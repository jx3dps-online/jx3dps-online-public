import type { 加速阈值配置, 加速阈值分组 } from '@/@types/加速阈值'
import { 解析加速阈值 } from '@/工具函数/加速阈值'

export const 标准GCD阈值: 加速阈值分组[] = [24, 16].map((原始帧数) => {
  const 配置: 加速阈值配置 = {
    标识: `标准GCD${原始帧数}`,
    名称: `公共调息${原始帧数 === 16 ? ` (1秒)` : ``}`,
    类型: '公共调息',
    原始帧数,
  }
  return { 配置, 标准GCD: true, 档位: 解析加速阈值(配置) }
})

export const 获取心法加速阈值 = (心法: {
  基础GCD?: number
  加速阈值?: 加速阈值配置[]
}): 加速阈值分组[] => {
  const 标识列表 = [
    ...标准GCD阈值.map((组) => 组.配置.标识),
    ...(心法.加速阈值 || []).map((配置) => 配置.标识),
  ]
  if (new Set(标识列表).size !== 标识列表.length) throw new Error('心法加速阈值标识重复')
  return [
    标准GCD阈值[心法.基础GCD === 1 ? 1 : 0],
    ...(心法.加速阈值 || []).map((配置) => ({ 配置, 标准GCD: false, 档位: 解析加速阈值(配置) })),
  ]
}

export const 获取主要加速阈值 = (分组: 加速阈值分组[]): 加速阈值分组[] => {
  const 主要分组 = 分组.filter((组) => 组.配置.主要)
  return 主要分组.length ? 主要分组 : 分组.filter((组) => 组.标准GCD)
}
