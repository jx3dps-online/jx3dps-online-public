import { 属性类型 } from '@/@types/属性'
import { 装备特效增益数据, 装备增益可选类型类型 } from '@/@types/装备'

/**
 * 装备特效数值集中维护
 * 数值统一为「档位 → 值」map：能拿到触发等级的（副本/试炼/橙武/水风特效）直接用触发等级做 key
 * 没有触发等级的走 registry 档位规则（如副本品级），见 装备特效判断.ts
 * Generator 无对应数值的条目先写 0 并标 待确认
 */

export type 装备特效档位规则 = '触发等级' | '副本品级'

export interface 装备特效算法参数 {
  /** 固定加成数值（适应、40791） */
  加成数值?: Record<number, number>
  每层所需属性?: Record<number, number>
  最大层数?: Record<number, number>
}

export interface 装备特效加速增益 {
  加成数值: Record<number, number>
  冷却帧数: number
  持续时间分段: { 加速等级: number; 持续帧数: number }[]
}

export interface 装备特效技能数据 {
  技能ID: string
  技能名称: string
  统计名称?: string
  真实伤害: number
}

export interface 装备特效触发技能 {
  /** 触发间隔（秒） */
  间隔: number
  /** 数据档位 → 技能档位，缺省按数据档位直接取 */
  档位映射?: Record<number, number>
  /** 技能档位 → 技能数据 */
  技能: Record<number, 装备特效技能数据>
}

export interface 装备特效描述 {
  描述: string
  /** 占位符 → 表现等级 → 展示值 */
  数值: Record<string, Record<number, number | string>>
}

export interface 装备特效数据项 {
  名称: string
  来源?: string
  限定部位?: string[]
  档位规则?: 装备特效档位规则
  常驻数值?: 装备特效增益数据[]
  算法参数?: 装备特效算法参数
  加速增益?: 装备特效加速增益
  触发技能?: 装备特效触发技能
  描述?: 装备特效描述
  待确认?: boolean
}

