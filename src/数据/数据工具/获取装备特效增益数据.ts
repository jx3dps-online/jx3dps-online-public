import { 装备叠加表现, 装备增益数据类型 } from '@/@types/装备'

const 获取装备特效增益数据 = (
  增益名称: string,
  特效表现: number | 装备叠加表现,
  装备增益数据: 装备增益数据类型,
  覆盖率 = 1,
) => {
  if (装备增益数据?.[增益名称]) {
    return 装备增益数据?.[增益名称]?.map((增益) => {
      let 数值 = 0
      if (typeof 特效表现 === 'object') {
        // 按件数叠加：每个触发等级分别查表乘件数后求和，支持不同等级混搭
        数值 = Object.entries(特效表现).reduce(
          (累计, [等级, 件数]) => 累计 + (增益?.值?.[+等级] || 0) * 件数,
          0,
        )
      } else {
        const 叠加层数 = 增益?.可叠加 ? 特效表现 || 1 : 1
        数值 = (增益?.值?.[特效表现] || 0) * 叠加层数
      }
      return {
        属性: 增益?.属性,
        值: 数值 * 覆盖率,
      }
    })
  } else {
    return []
  }
}

export default 获取装备特效增益数据
