export type 缓存映射类型 = typeof 缓存映射枚举

// 用于保存在浏览器的各属性键值
export const 获取缓存映射 = (心法): 缓存映射类型 => {
  // 防御：心法名为空说明调用时序异常（应在 初始化心法数据 设置「当前心法名」之后再调用），
  // 否则会生成 `undefined_xxx` 这类错误 key。
  if (!心法) {
    console.warn('[获取缓存映射] 心法名为空，localStorage key 可能错误，请检查初始化时序')
  }
  const res = {}
  Object.keys(缓存映射枚举).forEach((key) => {
    res[key] = 缓存映射枚举[key]?.replace(`{{心法}}`, 心法)
  })
  return res as 缓存映射类型
}
