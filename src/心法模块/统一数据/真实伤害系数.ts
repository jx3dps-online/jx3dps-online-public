import type { 技能基础数据模型 } from '@/@types/技能'
import 装备特效数据 from '@/数据/装备/装备增益数据/装备特效数据'

const 获取装备特效真实伤害技能 = (): 技能基础数据模型[] =>
  Object.values(装备特效数据).flatMap((特效数据) =>
    Object.values(特效数据?.触发技能?.技能 || {}).map((技能) => ({
      技能ID: 技能.技能ID,
      技能名称: 技能.技能名称,
      ...(技能.统计名称 ? { 统计名称: 技能.统计名称 } : null),
      真实伤害: 技能.真实伤害,
    })),
  )

// 逐云寒蕊由团队增益「飘黄」触发，真实伤害按装分计算，不属于装备特效
const 真实伤害系数: 技能基础数据模型[] = [
  // scripts\Include\NewSkill.luad
  // ====================
  {
    技能ID: '29541',
    技能名称: '逐云寒蕊',
    伤害计算次数: 1,
    真实伤害: 1,
    // 伤害计算类型标记: [计算公式计算类型.真实伤害, 计算公式计算类型.等级减伤, 计算公式计算类型.易伤],
  },
  ...获取装备特效真实伤害技能(),
]

export default 真实伤害系数
