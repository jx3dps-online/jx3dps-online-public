import type { 计算结果技能列表类型, 技能统计数据类型, 技能统计处理函数 } from '@/@types/输出'

const 技能统计处理: 技能统计处理函数 = (技能列表, 原始技能列表, 合并同名技能) => {
  if (!合并同名技能) return 技能列表
  const 诛邪分段 = 原始技能列表.filter((技能) =>
    ['诛邪镇魔·日', '诛邪镇魔·月'].includes(技能.技能名称),
  )
  if (!诛邪分段.length) return 技能列表

  const 结果 = 技能列表.filter((技能) => !['诛邪镇魔·日', '诛邪镇魔·月'].includes(技能.技能名称))
  const 分组 = new Map<string, 计算结果技能列表类型[]>()
  诛邪分段.forEach((技能) => {
    const 键 = `${技能.技能等级 || 1}_${技能.伤害层数 || 1}`
    分组.set(键, [...(分组.get(键) || []), 技能])
  })
  const 完整施展: 技能统计数据类型[] = []
  分组.forEach((技能) => {
    const 日次数 = 技能
      .filter((项) => 项.技能名称 === '诛邪镇魔·日')
      .reduce((总数, 项) => 总数 + 项.技能数量, 0)
    const 月次数 = 技能
      .filter((项) => 项.技能名称 === '诛邪镇魔·月')
      .reduce((总数, 项) => 总数 + 项.技能数量, 0)
    if (!日次数 || 日次数 !== 月次数) {
      结果.push(...技能)
      return
    }
    完整施展.push({
      技能名称: '诛邪镇魔',
      统计名称: '诛邪镇魔',
      技能等级: 技能[0].技能等级,
      伤害层数: 技能[0].伤害层数,
      技能数量: 日次数,
      技能总输出: 技能.reduce((总伤, 项) => 总伤 + 项.技能总输出, 0),
      会心几率:
        技能.reduce((总数, 项) => 总数 + (项.会心几率 || 0) * 项.技能数量, 0) / (日次数 * 2),
      伤害分段: 技能,
    })
  })
  if (完整施展.length) {
    const 技能数量 = 完整施展.reduce((总数, 技能) => 总数 + 技能.技能数量, 0)
    结果.push({
      技能名称: '诛邪镇魔',
      统计名称: '诛邪镇魔',
      技能数量,
      技能总输出: 完整施展.reduce((总伤, 技能) => 总伤 + 技能.技能总输出, 0),
      会心几率:
        完整施展.reduce((总数, 技能) => 总数 + (技能.会心几率 || 0) * 技能.技能数量, 0) / 技能数量,
      伤害分段: 完整施展.flatMap((技能) => 技能.伤害分段 || []),
    })
  }
  return 结果
}

export default 技能统计处理
