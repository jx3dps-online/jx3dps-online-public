import type { 循环数据 } from '@/@types/循环'
import type { 技能增益列表类型 } from '@/@types/技能'
import { 属性类型 } from '@/@types/属性'

// 发版默认循环的人工补偿：0 不补偿，0.025 补约 0.5 个百分点的通用增伤。
// 这是额外一份分星增益的强度比例，不修改原分星系数或 JCL 覆盖记录。
export const 分星内功增伤微调乘数 = 0
export const 分星微调增益名称 = '分星内功增伤全局微调入口'

export const 分星微调增益: 技能增益列表类型 = {
  增益名称: 分星微调增益名称,
  依赖奇穴: '擘两分星',
  增益所在位置: '奇穴',
  // 由默认循环为全部技能次数携带；不能无条件全局启用，否则会影响用户导入循环。
  增益类型: '部分启用',
  增益集合: [{ 属性: 属性类型.通用增伤, 值: (205 / 1024) * 分星内功增伤微调乘数 }],
}

/** 仅为内置默认循环全覆盖此增益，保留其他增益组合及原始数据。 */
export const 添加默认循环分星微调 = (循环: 循环数据): 循环数据 => {
  if (循环.类型 !== '默认') return 循环
  return {
    ...循环,
    循环详情: 循环.循环详情.map((详情) => ({
      ...详情,
      技能详情: 详情.技能详情.map((技能) => {
        const 增益列表 = (技能.技能增益列表 || []).map((增益) => ({
          ...增益,
          增益名称: [
            ...new Set([...增益.增益名称.split(',').filter(Boolean), 分星微调增益名称]),
          ].join(','),
        }))
        const 未分组次数 =
          技能.技能数量 - 增益列表.reduce((总数, 增益) => 总数 + 增益.增益技能数, 0)
        if (未分组次数 > 0) {
          增益列表.push({ 增益名称: 分星微调增益名称, 增益技能数: 未分组次数 })
        }
        return { ...技能, 技能增益列表: 增益列表 }
      }),
    })),
  }
}
