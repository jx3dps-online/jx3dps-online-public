// 角色默认基础属性缓存：按当前心法名缓存，切心法后自动失效。
// 避免在秒伤/寻优等热路径里每次调用都 spread 出约 20 个字段的新对象。
let 角色默认基础属性缓存: { 心法名: string | undefined; 值: 角色基础属性类型 } | null = null

// 动态取当前心法的角色默认基础属性（切心法后基础属性被动值变化）
export const 获取角色默认基础属性 = (): 角色基础属性类型 => {
  const 心法名 = 获取当前心法名()
  if (角色默认基础属性缓存 && 角色默认基础属性缓存.心法名 === 心法名) {
    return 角色默认基础属性缓存.值
  }

  const { 基础属性 = {} } = 获取当前数据()
  const 值: 角色基础属性类型 = {
    基础攻击: 0,
    破防等级: 0,
    无双等级: 0,
    会心等级: 0,
    会心效果等级: 0,
    全能等级: 0,
    武器伤害_最小值: 0,
    武器伤害_最大值: 0,
    力道: 17,
    元气: 17,
    身法: 18,
    根骨: 18,
    体质: 18,
    // 基础气血上限: 52285,
    基础气血上限: 3956,
    额外气血上限: 0,
    加速等级: 0,
    ...基础属性,
  }

  角色默认基础属性缓存 = { 心法名, 值 }
  return 值
}

