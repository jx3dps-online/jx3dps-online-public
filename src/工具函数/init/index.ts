/**
 * 页面初始化数据模块
 */

import type { 数据模块类型 } from '@/store/data'
import type { 系统模块类型 } from '@/store/system'
import { 获取当前心法名 } from '@/数据/数据工具/获取当前数据'
import { 解析当前角色 } from '@/角色/注册表'
import { 创建默认角色状态, 读取角色状态 } from '@/角色/状态'
import {
  加载缓存团队增益轴,
  加载缓存当前输出计算目标名称,
  加载缓存网络延迟,
  加载缓存背景图片显示状态,
  加载缓存网页设置,
  加载缓存背景图选择,
  加载缓存自定义背景图,
  加载缓存自定义循环数据,
  加载缓存副本事件方案列表,
  加载缓存增益启用,
  加载缓存特殊配置,
  合成增益数据,
} from './缓存函数'

export const 获取数据默认值 = () => {
  const 心法 = 获取当前心法名()
  const 角色 = 心法 ? 解析当前角色(心法) : undefined
  const { 状态, 读取错误 } = 角色 ? 读取角色状态(角色) : { 状态: undefined, 读取错误: undefined }
  const 默认状态 = 状态 || 创建默认角色状态()
  const 默认数据: 数据模块类型 = {
    当前角色: 角色,
    角色更新时间: 状态?.更新时间 || 0,
    角色读取错误: 读取错误,
    角色基础属性: 默认状态.装备信息?.装备基础属性,
    装备信息: 默认状态.装备信息,
    当前计算循环名称: 默认状态.当前计算循环名称,
    当前奇穴信息: 默认状态.当前奇穴信息,
    当前秘籍信息: 默认状态.当前秘籍信息,
    增益数据: 合成增益数据(默认状态.角色增益),
    增益启用: 加载缓存增益启用(),
    特殊配置: 加载缓存特殊配置(心法),
    当前输出计算目标名称: 加载缓存当前输出计算目标名称(),
    网络延迟: 加载缓存网络延迟(),
    团队增益轴: 加载缓存团队增益轴(),
    副本事件方案列表: 加载缓存副本事件方案列表(),
    自定义循环列表: 加载缓存自定义循环数据(),
    当前计算结果: { 秒伤: 0, 总伤: 0, 秒伤计算时间: 0, 计算结果技能列表: [] },
  }
  return 默认数据
}

export const 获取系统默认值 = () => {
  const 默认系统配置: 系统模块类型 = {
    新手引导流程状态: false,
    背景图片显示状态: 加载缓存背景图片显示状态(),
    背景图选择: 加载缓存背景图选择(),
    自定义背景图: 加载缓存自定义背景图(),
    增益面板显示状态: false,
    当前引导步骤: 0,
    配装器弹窗显示状态: false,
    网页设置: 加载缓存网页设置(),
  }
  return 默认系统配置
}
