export interface 增益收益条目 {
  标识: string
  增益: 技能增益列表类型
  秘籍技能: string
  关联技能: string[]
  效果列表: { 属性列表: 属性加成[]; 适用技能: string[] }[]
  已启用: boolean
  秒伤差值: number
  秒伤比例: number | null
}

const 获取增益标识 = (增益: 技能增益列表类型, 技能: 技能基础数据模型) =>
  JSON.stringify([
    增益.增益所在位置,
    增益.增益名称,
    增益.增益类型,
    增益.依赖奇穴,
    增益.依赖装备增益,
    增益.依赖团队增益,
    增益.依赖阵眼增益,
    增益.增益所在位置 === '秘籍' ? 技能.秘籍依赖技能 || 技能.技能名称 : '',
  ])

