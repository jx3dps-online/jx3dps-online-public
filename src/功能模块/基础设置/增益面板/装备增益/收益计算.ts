import type { 技能总伤害计算入参类型 } from '@/@types/计算'
import type { 装备信息数据类型 } from '@/@types/装备'
import type { 角色基础属性类型 } from '@/@types/角色'
import { 根据装备格式化技能基础数据 } from '@/计算模块/统一工具函数/技能增益启用计算/技能装备计算'
import 循环秒伤计算 from '@/计算模块/循环秒伤计算'
import { INT } from '@/工具函数/help'
import { 应用装备特效开关, type 装备收益来源 } from './属性来源'

export interface 装备收益结果 extends 装备收益来源 {
  秒伤差值: number
  秒伤比例: number
}

export const 计算装备收益秒伤 = (入参: 技能总伤害计算入参类型) =>
  INT(循环秒伤计算(入参).总伤 / 入参.战斗时间)

export const 获取装备收益入参 = (
  入参: 技能总伤害计算入参类型,
  装备信息: 装备信息数据类型,
): 技能总伤害计算入参类型 => ({
  ...入参,
  装备信息,
  技能数据映射: new Map(
    根据装备格式化技能基础数据([...入参.技能数据映射.values()], 装备信息.装备增益).map((技能) => [
      技能.技能名称,
      技能,
    ]),
  ),
})

export const 获取装备收益基准 = (
  入参: 技能总伤害计算入参类型,
  来源: 装备收益来源[],
  包含特效: boolean,
) => 获取装备收益入参(入参, 应用装备特效开关(入参.装备信息, 来源, 包含特效))

export const 获取移除装备来源后的入参 = (
  入参: 技能总伤害计算入参类型,
  来源: 装备收益来源,
  包含特效: boolean,
) => {
  const 装备基础属性 = { ...入参.装备信息.装备基础属性 }
  Object.entries(来源.属性).forEach(([字段, 值]) => {
    const 键 = 字段 as keyof 角色基础属性类型
    if (键 !== '加速等级') 装备基础属性[键] = (装备基础属性[键] || 0) - 值
  })
  const 装备信息 = {
    ...入参.装备信息,
    装备基础属性,
    装备增益: {
      ...入参.装备信息.装备增益,
      ...(包含特效 || 来源.分类 !== '装备' ? 来源.移除后增益 : {}),
    },
  }
  return 获取装备收益入参(入参, 装备信息)
}

export const 计算装备来源收益 = (
  入参: 技能总伤害计算入参类型,
  来源: 装备收益来源,
  基准秒伤: number,
  包含特效: boolean,
): 装备收益结果 => {
  const 秒伤差值 = 基准秒伤 - 计算装备收益秒伤(获取移除装备来源后的入参(入参, 来源, 包含特效))
  return { ...来源, 秒伤差值, 秒伤比例: 基准秒伤 ? (秒伤差值 / 基准秒伤) * 100 : 0 }
}
