import type { 技能总伤害计算入参类型 } from '@/@types/计算'
import type { 技能增益列表类型 } from '@/@types/技能'
import type { 装备增益类型 } from '@/@types/装备'
import 装备特效数据 from '@/数据/装备/装备增益数据/装备特效数据'

const 排除增益 = new Set<keyof 装备增益类型>([
  '大附魔_伤腰',
  '套装技能',
  '小橙武特效_会心',
  '龙门飞剑武器',
  '郭氏力道',
  '郭氏身法',
  '郭氏元气',
  '郭氏根骨',
  ...Object.entries(装备特效数据)
    .filter(([, 数据]) => 数据?.触发技能 || 数据?.待确认)
    .map(([键]) => 键 as keyof 装备增益类型),
])

export const 过滤属性效用增益 = (增益: 装备增益类型): 装备增益类型 =>
  Object.fromEntries(
    Object.entries(增益).map(([键, 值]) => [键, 排除增益.has(键 as keyof 装备增益类型) ? 0 : 值]),
  )

export const 获取属性效用入参 = (入参: 技能总伤害计算入参类型): 技能总伤害计算入参类型 => {
  // 风特效破防快照可折算容量；保留它及“橙武孤锋”等技能增益，仅清空装备技能增伤。
  const 过滤技能增益 = (列表?: 技能增益列表类型[]) =>
    列表?.map((增益) =>
      增益.增益所在位置 === '装备' && 增益.快照类型 !== '风特效' ? { ...增益, 增益集合: [] } : 增益,
    )
  return {
    ...入参,
    装备信息: {
      ...入参.装备信息,
      装备增益: 过滤属性效用增益(入参.装备信息.装备增益),
    },
    计算循环: 入参.计算循环.filter((技能) => 技能.技能名称 !== '剑风'),
    技能数据映射: new Map(
      [...入参.技能数据映射].map(([名称, 技能]) => [
        名称,
        {
          ...技能,
          技能增益列表: 过滤技能增益(技能.技能增益列表),
          技能等级数据: 技能.技能等级数据
            ? Object.fromEntries(
                Object.entries(技能.技能等级数据).map(([等级, 数据]) => [
                  等级,
                  { ...数据, 技能增益列表: 过滤技能增益(数据.技能增益列表) },
                ]),
              )
            : undefined,
        },
      ]),
    ),
  }
}
