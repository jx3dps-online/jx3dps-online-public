export interface 同部位对比参数 {
  入参: 技能总伤害计算入参类型
  来源: 装备收益来源
  包含特效: boolean
  平均单位容量收益: number
}

export interface 候选效用结果 extends 装备收益来源 {
  id: number
  装备数据: 装备属性信息模型
  当前装备: boolean
  装备类型: string
  精炼等级: number
  总容量: number
  普通容量: number
  加速容量: number
  特效容量: number
  非加速容量: number
  属性秒伤贡献: number
  普通属性秒伤: number
  特效秒伤: number
  相比当前: number
  效用系数: number | null
  不可比较原因: string[]
}

export const 准备同部位对比 = (参数: 同部位对比参数) => {
  const { 入参, 来源, 包含特效 } = 参数
  const 当前装备 = 根据部位索引获取装备(入参.装备信息.装备列表, 来源.标识)!
  const 候选装备 = 获取当前数据()
    .装备数据[当前装备.装备部位].filter((项) => 项.id && (!项.重复装备id || 项.id === 当前装备.id))
    .sort(
      (a, b) =>
        Number(b.id === 当前装备.id) - Number(a.id === 当前装备.id) || b.装备品级 - a.装备品级,
    )
  const 移除后入参 = 获取移除装备来源后的入参(
    入参,
    { ...来源, 移除后增益: 过滤属性效用增益(来源.移除后增益) },
    包含特效,
  )
  return {
    ...参数,
    当前装备,
    候选装备,
    移除后入参,
    移除后秒伤: 计算装备收益秒伤(移除后入参),
    当前秒伤: 计算装备收益秒伤(入参),
  }
}

export const 获取候选装备属性 = (
  基准: ReturnType<typeof 准备同部位对比>,
  候选: 装备属性信息模型,
) => {
  const { 入参, 当前装备, 移除后入参, 来源, 包含特效 } = 基准
  const 选择装备: 选择装备数据类型 = {
    ...当前装备,
    id: 候选.id,
    装备部位索引: 当前装备.装备部位索引 || (来源.标识 as 选择装备数据类型['装备部位索引']),
    当前精炼等级: Math.min(当前装备.当前精炼等级, 获取最大精炼等级(候选)),
    附魔: undefined,
    镶嵌孔数组: [],
  }
  const 单件 = 根据装备信息获取基础属性({
    ...入参.装备信息,
    装备列表: [选择装备],
    五彩石: '',
    装备增益: {},
  })
  const 候选来源 = 获取装备收益来源(单件).find((项) => 项.标识 === 来源.标识)!
  const 装备列表 = 入参.装备信息.装备列表.map((项) =>
    项 === 当前装备 ? { ...选择装备, 附魔: 项.附魔, 镶嵌孔数组: 项.镶嵌孔数组 } : 项,
  )
  const 替换后增益 = 根据装备信息获取基础属性({
    ...入参.装备信息,
    装备列表,
    五彩石: '',
    装备增益: {},
  }).装备增益
  const 装备基础属性 = { ...移除后入参.装备信息.装备基础属性 }
  Object.entries(候选来源.属性).forEach(([字段, 值]) => {
    const 键 = 字段 as keyof 角色基础属性类型
    if (键 !== '加速等级') 装备基础属性[键] = (装备基础属性[键] || 0) + 值
  })
  // 只替换该件装备的特效键；套装、附魔、镶嵌和五彩石始终沿用当前基准。
  const 特效键 = Object.keys(候选来源.移除后增益)
  const 装备信息 = {
    ...移除后入参.装备信息,
    装备列表,
    装备基础属性,
    装备增益: {
      ...移除后入参.装备信息.装备增益,
      ...(包含特效
        ? 过滤属性效用增益(Object.fromEntries(特效键.map((键) => [键, 替换后增益[键]])))
        : {}),
    },
  }
  候选来源.移除后增益 = Object.fromEntries(
    特效键.map((键) => [键, 移除后入参.装备信息.装备增益[键] || 0]),
  )
  return { 装备信息, 候选来源, 精炼等级: 选择装备.当前精炼等级 }
}

export const 计算候选装备效用 = (
  基准: ReturnType<typeof 准备同部位对比>,
  候选: 装备属性信息模型,
): 候选效用结果 => {
  const { 装备信息, 候选来源, 精炼等级 } = 获取候选装备属性(基准, 候选)
  const 候选入参 = 获取装备收益入参(基准.移除后入参, 装备信息)
  const 候选秒伤 = 计算装备收益秒伤(候选入参)
  const 无特效秒伤 =
    基准.包含特效 && Object.keys(候选来源.移除后增益).length
      ? 计算装备收益秒伤(获取移除装备来源后的入参(候选入参, { ...候选来源, 属性: {} }, true))
      : 候选秒伤
  const 容量 = 计算装备容量分布(装备信息, 基准.包含特效, [候选来源], true).条目[0]
  const 属性秒伤贡献 = 候选秒伤 - 基准.移除后秒伤
  const 不可比较原因 = [
    ...容量.效用未折算,
    ...(容量.非加速容量 <= 0 ? ['无可比较的非加速容量'] : []),
    ...(基准.平均单位容量收益 <= 0 ? ['当前配装没有有效的平均单位容量收益'] : []),
  ]
  return {
    ...候选来源,
    id: 候选.id!,
    装备数据: 候选,
    当前装备: 候选.id === 基准.当前装备.id,
    装备类型: 候选.装备类型,
    精炼等级,
    总容量: 容量.容量,
    普通容量: 容量.基础容量 - 容量.基础加速容量,
    加速容量: 容量.加速容量,
    特效容量: 容量.特效容量 - (容量.加速容量 - 容量.基础加速容量),
    非加速容量: 容量.非加速容量,
    属性秒伤贡献,
    普通属性秒伤: 无特效秒伤 - 基准.移除后秒伤,
    特效秒伤: 候选秒伤 - 无特效秒伤,
    相比当前: 候选秒伤 - 基准.当前秒伤,
    效用系数: 不可比较原因.length ? null : 属性秒伤贡献 / 容量.非加速容量 / 基准.平均单位容量收益,
    不可比较原因,
  }
}
