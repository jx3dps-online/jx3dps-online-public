import type { 装备属性信息模型, 装备信息数据类型 } from '@/@types/装备'
import 根据表单选项获取装备信息 from '../../../属性录入/配装器/工具函数/根据表单选项获取装备信息'
import { 装备信息转表单值 } from '../../../属性录入/配装器/工具函数/装备表单转换'
import { 生成装备表单值 } from '../../../属性录入/配装器/头部组件/全局寻优/候选粗排'
import type { 候选效用结果 } from './计算'

export interface 同部位对比结果 extends 候选效用结果 {
  实际秒伤差: number | null
  实际秒伤说明: string
}

export const 准备实际秒伤对比 = (
  装备信息: 装备信息数据类型,
  部位索引: string,
  计算秒伤: (装备信息: 装备信息数据类型) => number,
) => {
  const 表单 = 装备信息转表单值(装备信息)
  const 当前秒伤 = 计算秒伤(根据表单选项获取装备信息(表单))
  return (候选: 装备属性信息模型): Pick<同部位对比结果, '实际秒伤差' | '实际秒伤说明'> => {
    if (!当前秒伤) {
      return { 实际秒伤差: null, 实际秒伤说明: '当前配装没有可用的秒伤计算结果' }
    }
    try {
      const 候选装备信息 = 根据表单选项获取装备信息({
        ...表单,
        [部位索引]: 生成装备表单值(候选, 表单[部位索引], 部位索引, 8),
      })
      const 候选秒伤 = 计算秒伤(候选装备信息)
      return 候选秒伤
        ? { 实际秒伤差: 候选秒伤 - 当前秒伤, 实际秒伤说明: '' }
        : {
            实际秒伤差: null,
            实际秒伤说明: '当前所选循环在候选装备条件下没有可用的秒伤结果，请检查加速要求',
          }
    } catch (异常) {
      return {
        实际秒伤差: null,
        实际秒伤说明: 异常 instanceof Error ? 异常.message : '候选装备实际秒伤计算失败',
      }
    }
  }
}
