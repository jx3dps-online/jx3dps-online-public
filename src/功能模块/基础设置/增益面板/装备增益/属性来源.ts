export interface 装备收益来源 {
  标识: string
  名称: string
  说明: string
  装备品级?: number
  特征属性?: string[]
  分类: '装备' | '套装' | '附魔' | '镶嵌' | '五彩石'
  属性: Partial<角色基础属性类型>
  移除后增益: 装备增益类型
}

const 套装分组: [string, (keyof 装备增益类型)[]][] = [
  ['门派两件套', ['常驻套装会心会效', '套装会心会效']],
  ['门派四件套', ['套装技能']],
  ['切糕两件套（普通）', ['切糕会心']],
  ['切糕四件套（普通）', ['切糕无双']],
  ['切糕两件套（英雄）', ['切糕会心_英雄']],
  ['切糕四件套（英雄）', ['切糕无双_英雄']],
  ['冬至套装', ['冬至套装']],
]
const 套装增益键 = new Set(套装分组.flatMap(([, 键]) => 键))

export const 应用装备特效开关 = (
  装备信息: 装备信息数据类型,
  来源: 装备收益来源[],
  包含特效: boolean,
): 装备信息数据类型 => {
  if (包含特效) return 装备信息
  const 装备增益 = { ...装备信息.装备增益 }
  来源.filter((项) => 项.分类 === '装备').forEach((项) => {
    Object.keys(项.移除后增益).forEach((键) => {
      装备增益[键] = 0
    })
  })
  return { ...装备信息, 装备增益 }
}

export const 获取属性差值 = (
  当前: 角色基础属性类型,
  原始: 角色基础属性类型,
): Partial<角色基础属性类型> =>
  Object.fromEntries(
    (Object.keys(原始) as (keyof 角色基础属性类型)[])
      .filter((键) => 键 !== '装分' && 键 !== '面板攻击')
      .map((键) => [键, (当前[键] || 0) - (原始[键] || 0)]),
  )

export const 获取装备收益来源 = (装备信息: 装备信息数据类型): 装备收益来源[] => {
  const { 装备数据, 镶嵌孔 } = 获取当前数据()
  const 默认属性 = 获取角色默认基础属性()
  const 计算属性 = (装备列表: 装备信息数据类型['装备列表']) =>
    根据装备信息获取基础属性({ ...装备信息, 装备列表, 五彩石: '', 装备增益: {} })
  const 本体列表 = 装备信息.装备列表.map((装备) => ({ ...装备, 附魔: undefined, 镶嵌孔数组: [] }))
  const 本体属性 = 计算属性(本体列表).装备基础属性
  const 来源: 装备收益来源[] = []
  const 镶嵌等级数量 = new Map<number, number>()
  Object.keys(装备位置部位枚举).forEach((部位索引) => {
    const 装备 = 根据部位索引获取装备(装备信息.装备列表, 部位索引)
    if (!装备?.id) return
    const 数据 = 装备数据[装备.装备部位].find((项) => 项.id === 装备.id)
    if (!数据) throw new Error(`找不到${装备.装备部位}的装备资料，请重新选择装备后计算。`)
    const 单件 = 计算属性([{ ...装备, 附魔: undefined, 镶嵌孔数组: [] }])
    const 其余装备 = 计算属性(装备信息.装备列表.filter((项) => 项 !== 装备))
    const 移除后增益: 装备增益类型 = {}
    Object.keys(单件.装备增益).forEach((键) => {
      if (!套装增益键.has(键 as keyof 装备增益类型) && 装备信息.装备增益[键]) {
        移除后增益[键] = 其余装备.装备增益[键] || 0
      }
    })
    来源.push({
      标识: 部位索引,
      名称: 装备.装备部位 === '戒指' ? `戒指${部位索引 === '_9' ? '一' : '二'}` : 装备.装备部位,
      说明: 数据.装备名称,
      装备品级: 数据.装备品级,
      特征属性: [
        ...(数据.装备特效 === 装备特效枚举.大橙武特效 ? ['大橙武'] : []),
        ...(数据.装备特效 === 装备特效枚举.小橙武特效 ? ['小橙武'] : []),
        ...(数据.装备类型 === 装备类型枚举.门派套装 ? ['套装'] : []),
        ...获取装备数据描述(数据),
      ],
      分类: '装备',
      属性: 获取属性差值(单件.装备基础属性, 默认属性),
      移除后增益,
    })
    装备.镶嵌孔数组?.forEach((孔) => {
      if (
        !镶嵌孔.some(
          (项) =>
            孔.镶嵌类型 && (孔.镶嵌类型 === 项.镶嵌类型 || 项.镶嵌索引?.includes(孔.镶嵌类型)),
        )
      )
        return
      const 等级 = 孔.镶嵌宝石等级 || 1
      镶嵌等级数量.set(等级, (镶嵌等级数量.get(等级) || 0) + 1)
    })
  })
  套装分组.forEach(([名称, 键]) => {
    if (!键.some((项) => 装备信息.装备增益[项])) return
    来源.push({
      标识: 名称,
      名称,
      说明: '套装效果',
      分类: '套装',
      属性: {},
      移除后增益: Object.fromEntries(键.map((项) => [项, 0])),
    })
  })
  来源.push({
    标识: '普通附魔',
    名称: '普通附魔',
    说明: '全部普通附魔的属性',
    分类: '附魔',
    属性: 获取属性差值(
      计算属性(装备信息.装备列表.map((项) => ({ ...项, 镶嵌孔数组: [] }))).装备基础属性,
      本体属性,
    ),
    移除后增益: {},
  })
  来源.push({
    标识: '大附魔',
    名称: '大附魔',
    说明: '属性加成与触发效果',
    分类: '附魔',
    属性: {},
    移除后增益: Object.fromEntries(
      Object.keys(装备信息.装备增益)
        .filter((键) => 键.startsWith('大附魔_') && 装备信息.装备增益[键])
        .map((键) => [键, 0]),
    ),
  })
  来源.push({
    标识: '镶嵌',
    名称: '所有镶嵌',
    说明: [...镶嵌等级数量]
      .sort(([等级一], [等级二]) => 等级二 - 等级一)
      .map(([等级, 数量]) => `${等级}级×${数量}`)
      .join('、'),
    分类: '镶嵌',
    属性: 获取属性差值(
      计算属性(装备信息.装备列表.map((项) => ({ ...项, 附魔: undefined }))).装备基础属性,
      本体属性,
    ),
    移除后增益: {},
  })
  if (装备信息.五彩石) {
    const 五彩石 = 五彩石计算(装备信息.五彩石, { ...默认属性 })
    const 百分比 = 判断五彩石郭氏增益(五彩石.五彩石郭氏增益, {})
    来源.push({
      标识: '五彩石',
      名称: '五彩石',
      说明: 装备信息.五彩石,
      分类: '五彩石',
      属性: 获取属性差值(五彩石.计算后属性, 默认属性),
      移除后增益: Object.fromEntries(
        Object.entries(百分比)
          .filter(([, 值]) => 值)
          .map(([键, 值]) => [键, (装备信息.装备增益[键] || 0) - Number(值)]),
      ),
    })
  }
  const 字段 = Object.keys(获取属性差值(默认属性, 默认属性)) as (keyof 角色基础属性类型)[]
  if (
    !装备信息.装备列表.length ||
    字段.some(
      (键) =>
        Math.abs(
          (默认属性[键] || 0) +
            来源.reduce((和, 项) => 和 + (项.属性[键] || 0), 0) -
            (装备信息.装备基础属性[键] || 0),
        ) > 1e-7,
    )
  )
    throw new Error('当前面板与装备明细不一致，无法按来源拆分收益。请先在配装器中确认装备。')
  return 来源.filter(
    (项) => Object.values(项.属性).some((值) => 值 !== 0) || Object.keys(项.移除后增益).length,
  )
}
