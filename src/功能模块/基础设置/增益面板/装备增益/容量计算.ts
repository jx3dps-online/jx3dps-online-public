const 属性名称 = Object.fromEntries(Object.entries(属性类型).map(([名称, 键]) => [键, 名称]))

const 获取来源特效 = (装备信息: 装备信息数据类型, 来源: 装备收益来源): 装备增益类型 =>
  Object.fromEntries(
    Object.entries(来源.移除后增益).map(([键, 剩余]) => {
      const 原值 = 装备信息.装备增益[键]
      return [
        键,
        typeof 原值 === 'object'
          ? Object.fromEntries(
              Object.entries(原值).map(([等级, 数量]) => [
                等级,
                Number(数量) - (剩余?.[等级] || 0),
              ]),
            )
          : (原值 || 0) - Number(剩余),
      ]
    }),
  )

const 获取动态特效属性 = (装备信息: 装备信息数据类型) => {
  const 计算属性 = 计算增益加成后最终计算属性({
    装备基础属性: 装备信息.装备基础属性,
    增益集合: 获取装备增益(装备信息, []),
    当前目标: {} as 目标属性类型,
  })
  const 已启用: 装备增益类型 = {}
  const 结果 = new Map<string, Map<属性类型, number>>()
  let 前面板 = 获取属性加成后的面板(计算属性).计算人物面板
  // 沿用统一工具函数/装备特效加成.ts 的顺序，将每一步新增属性归给触发它的装备。
  const 顺序 = ['特效_38934', '特效_38946', '特效_38945', '特效_46727', '特效_40791'] as const
  顺序.forEach((键) => {
    if (!装备信息.装备增益[键]) return
    已启用[键] = 装备信息.装备增益[键]
    const 面板 = 获取属性加成后的面板(计算属性, false, undefined, 已启用).计算人物面板
    结果.set(键, new Map(容量属性.map(([字段, 属性]) => [属性, 面板[字段]! - 前面板[字段]!])))
    前面板 = 面板
  })
  return 结果
}

const 获取特效容量属性 = (
  装备信息: 装备信息数据类型,
  来源增益: 装备增益类型,
  动态特效属性: Map<string, Map<属性类型, number>>,
  未折算: Set<string>,
  仅属性: boolean,
) => {
  const 属性数值 = new Map<属性类型, number>()
  获取装备增益({ ...装备信息, 装备增益: 来源增益 }, []).forEach(({ 属性, 值 }) => {
    if (!值 || 属性 === 属性类型.体质 || 属性 === 属性类型.郭氏体质) return
    const 名称 = 属性名称[属性] || 属性
    const 归并属性 = 装备和附魔属性转换(属性)
    if (
      !名称.startsWith('郭氏') &&
      !名称.includes('百分比') &&
      (容量属性.some(([, 键]) => 键 === 归并属性) || 属性 === 属性类型.武器伤害)
    ) {
      属性数值.set(归并属性, (属性数值.get(归并属性) || 0) + 值)
    } else 未折算.add(名称)
  })
  Object.entries(来源增益).forEach(([键, 值]) => {
    if (!值) return
    动态特效属性.get(键)?.forEach((数值, 属性) => {
      属性数值.set(属性, (属性数值.get(属性) || 0) + 数值)
    })
    const 数据 = 装备特效数据[键]
    if (数据?.触发技能) 未折算.add(`${数据.名称}的触发伤害`)
    if (数据?.待确认) 未折算.add(`${数据.名称}中尚未确认的数值`)
  })
  if (来源增益.套装技能) 未折算.add('门派四件套技能增伤')
  if (来源增益.大橙武特效 && !仅属性) 未折算.add('大橙武技能增伤')
  if (来源增益.小橙武特效_会心) 未折算.add('小橙武技能会心')
  if (来源增益.龙门飞剑武器) 未折算.add('剑风伤害')
  return 属性数值
}

export const 计算装备容量分布 = (
  装备信息: 装备信息数据类型,
  包含特效: boolean,
  来源列表 = 获取装备收益来源(装备信息),
  仅属性 = false,
): 装备容量结果 => {
  let 当前装备 = 应用装备特效开关(装备信息, 来源列表, 包含特效)
  if (仅属性) 当前装备 = { ...当前装备, 装备增益: 过滤属性效用增益(当前装备.装备增益) }
  const 基准表 = 获取容量系数表()
  基准表[属性类型.全会心效果等级] = 基准表[属性类型.全会心等级]
  const 动态特效属性 = 获取动态特效属性(当前装备)
  const 条目: 装备容量条目[] = 来源列表.map((来源) => {
    const 未折算 = new Set<string>()
    const 原来源增益 = 获取来源特效(当前装备, 来源)
    const 来源增益 = 仅属性 ? 过滤属性效用增益(原来源增益) : 原来源增益
    const 特效属性 =
      包含特效 || 来源.分类 !== '装备'
        ? 获取特效容量属性(当前装备, 来源增益, 动态特效属性, 未折算, 仅属性)
        : new Map<属性类型, number>()
    const 百分比属性 = ['郭氏力道', '郭氏根骨', '郭氏身法', '郭氏元气'] as const
    if (来源.分类 === '五彩石' && 百分比属性.some((键) => 来源增益[键])) {
      未折算.add('五彩石百分比主属性')
    }
    const 效用未折算 = new Set(未折算)
    let 加速容量 = 0
    const 折算容量 = (属性: 属性类型, 数值: number, 名称: string) => {
      if (!数值) return 0
      const 基准 = 基准表[属性]
      if (!基准) {
        const 原因 = `${名称}（无附魔基准）`
        未折算.add(原因)
        if (属性 !== 属性类型.加速等级) 效用未折算.add(原因)
        return 0
      }
      const 容量 = (数值 / 基准) * 分数放大系数
      if (属性 === 属性类型.加速等级) 加速容量 += 容量
      return 容量
    }
    let 基础容量 = 容量属性.reduce(
      (和, [字段, 属性, 名称]) => 和 + 折算容量(属性, 来源.属性[字段] || 0, 名称),
      0,
    )
    if (获取当前数据().功法 === '外功') {
      基础容量 += 折算容量(
        属性类型.武器伤害,
        ((来源.属性.武器伤害_最小值 || 0) + (来源.属性.武器伤害_最大值 || 0)) / 2,
        '武器伤害',
      )
    }
    const 基础加速容量 = 加速容量
    const 特效容量 = [...特效属性].reduce(
      (和, [属性, 数值]) => 和 + 折算容量(属性, 数值, 属性名称[属性] || 属性),
      0,
    )
    return {
      ...来源,
      基础容量,
      基础加速容量,
      加速容量,
      特效容量,
      容量: 基础容量 + 特效容量,
      非加速容量: 基础容量 + 特效容量 - 加速容量,
      未折算: [...未折算],
      效用未折算: [...效用未折算],
      比例: 0,
    }
  })
  const 总容量 = 条目.reduce((和, 项) => 和 + 项.容量, 0)
  return {
    总容量,
    条目: 条目
      .map((项) => ({ ...项, 比例: 总容量 ? (项.容量 / 总容量) * 100 : 0 }))
      .sort((a, b) => b.容量 - a.容量),
    未折算: [...new Set(条目.flatMap((项) => 项.未折算))],
  }
}
