import type { 装备容量条目 } from './容量计算'
import type { 装备收益结果 } from './收益计算'

export interface 装备效用条目 extends 装备收益结果 {
  非加速容量: number
  秒伤占比: number
  容量占比: number
  效用系数: number | null
  不可比较原因: string[]
}

export const 计算装备效用 = (收益: 装备收益结果[], 容量: 装备容量条目[]) => {
  const 容量映射 = new Map(容量.map((项) => [项.标识, 项]))
  const 条目: 装备效用条目[] = 收益.map((项) => {
    const 对应容量 = 容量映射.get(项.标识)!
    return {
      ...项,
      非加速容量: 对应容量.非加速容量,
      秒伤占比: 0,
      容量占比: 0,
      效用系数: null,
      不可比较原因: [
        ...对应容量.效用未折算,
        ...(对应容量.非加速容量 <= 0 ? ['无可比较的非加速容量'] : []),
      ],
    }
  })
  const 可比较 = 条目.filter((项) => !项.不可比较原因.length)
  const 总秒伤损失 = 可比较.reduce((和, 项) => 和 + 项.秒伤差值, 0)
  const 总容量 = 可比较.reduce((和, 项) => 和 + 项.非加速容量, 0)
  可比较.forEach((项) => {
    if (总秒伤损失 <= 0) {
      项.不可比较原因.push('可比较项目的秒伤损失合计不大于零')
      return
    }
    项.秒伤占比 = 项.秒伤差值 / 总秒伤损失
    项.容量占比 = 项.非加速容量 / 总容量
    项.效用系数 = 项.秒伤占比 / 项.容量占比
  })
  return {
    可比较条目: 条目.filter((项) => 项.效用系数 !== null).sort((a, b) => b.效用系数! - a.效用系数!),
    不可比较条目: 条目.filter((项) => 项.效用系数 === null),
    总秒伤损失,
    总容量,
  }
}
