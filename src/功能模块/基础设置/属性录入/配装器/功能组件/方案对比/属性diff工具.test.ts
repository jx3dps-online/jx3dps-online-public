declare const describe: (name: string, suite: () => void) => void
declare const test: (name: string, assertion: () => void) => void
declare const expect: any
declare const jest: any

import { 装备信息数据类型, 装备位置部位枚举, 选择装备数据类型 } from '@/@types/装备'
import { 获取装备差异, 生成装备信息签名, 装备信息转表单值 } from './属性diff工具'

jest.mock('@/功能模块/基础设置/面板信息/工具', () => ({
  获取角色需要展示的面板数据: () => ({}),
}))
jest.mock('@/数据/装备', () => ({ 根据id获取装备数据: () => undefined }))
jest.mock('@/数据/数据工具/获取当前数据', () => ({
  __esModule: true,
  default: () => ({}),
}))

const 创建装备 = (
  装备部位: 装备位置部位枚举,
  id: number | undefined,
  附魔?: number,
): 选择装备数据类型 => ({
  id,
  装备部位,
  当前精炼等级: id ? 6 : 0,
  镶嵌孔数组: [],
  附魔,
})

const 创建装备信息 = (装备列表: 选择装备数据类型[]): 装备信息数据类型 =>
  ({ 装备列表, 五彩石: '', 装备增益: {} }) as 装备信息数据类型

describe('方案对比按装备部位还原槽位', () => {
  test('历史列表乱序时，相同装备的差异和签名保持一致', () => {
    const 帽子 = 创建装备(装备位置部位枚举._1, 1)
    const 暗器 = 创建装备(装备位置部位枚举._11, 11, 101)
    const 武器 = 创建装备(装备位置部位枚举._12, 12, 102)
    const 基准 = 创建装备信息([帽子, 暗器, 武器])
    const 对比 = 创建装备信息([武器, 帽子, 暗器])

    expect(获取装备差异(基准, 对比)).toEqual([])
    expect(生成装备信息签名(基准)).toBe(生成装备信息签名(对比))
  })

  test('前方部位缺失时仍能定位暗器、武器及其附魔变化', () => {
    const 暗器 = 创建装备(装备位置部位枚举._11, 11, 101)
    const 武器 = 创建装备(装备位置部位枚举._12, 12, 102)
    const 新武器 = { ...武器, 附魔: 103 }
    const 基准 = 创建装备信息([暗器, 武器])
    const 对比 = 创建装备信息([新武器, 暗器])

    expect(获取装备差异(基准, 对比)).toEqual([
      { 部位索引: '_12', 部位名: '武器', 基准装备: 武器, 对比装备: 新武器 },
    ])
    expect(生成装备信息签名(基准)).not.toBe(生成装备信息签名(对比))
  })

  test('两个戒指独立比较，其他部位顺序不会影响第二个戒指', () => {
    const 戒指一 = 创建装备(装备位置部位枚举._9, 9)
    const 戒指二 = 创建装备(装备位置部位枚举._10, 10)
    const 新戒指二 = { ...戒指二, 附魔: 104 }
    const 武器 = 创建装备(装备位置部位枚举._12, 12)
    const 基准 = 创建装备信息([武器, 戒指一, 戒指二])
    const 对比 = 创建装备信息([戒指一, 新戒指二, 武器])

    expect(获取装备差异(基准, 对比)).toEqual([
      { 部位索引: '_10', 部位名: '戒指', 基准装备: 戒指二, 对比装备: 新戒指二 },
    ])
    expect(装备信息转表单值(对比)).toMatchObject({ _9: 戒指一, _10: 新戒指二 })
  })

  test('第一个戒指为空时保留第二个戒指的位置', () => {
    const 空戒指 = 创建装备(装备位置部位枚举._9, undefined)
    const 戒指 = 创建装备(装备位置部位枚举._10, 10)
    const 基准 = 创建装备信息([空戒指, 戒指])
    const 对比 = 创建装备信息([戒指, 空戒指])

    expect(获取装备差异(基准, 对比).map((差异) => 差异.部位索引)).toEqual(['_9', '_10'])
    expect(生成装备信息签名(基准)).not.toBe(生成装备信息签名(对比))
    expect(装备信息转表单值(基准)._10).toEqual(戒指)
  })

  test('仅保存第二个戒指时使用已记录的槽位，不误判为第一个戒指', () => {
    const 戒指 = { ...创建装备(装备位置部位枚举._10, 10), 装备部位索引: '_10' as const }
    const 基准 = 创建装备信息([])
    const 对比 = 创建装备信息([戒指])

    expect(获取装备差异(基准, 对比)).toEqual([
      { 部位索引: '_10', 部位名: '戒指', 基准装备: undefined, 对比装备: 戒指 },
    ])
    expect(装备信息转表单值(对比)._9).toBeUndefined()
    expect(装备信息转表单值(对比)._10).toEqual(戒指)
  })

  test('空装备占位与缺少该部位等价，清除实际装备仍产生差异', () => {
    const 武器 = 创建装备(装备位置部位枚举._12, 12)
    const 空武器 = 创建装备(装备位置部位枚举._12, undefined)
    const 空列表 = 创建装备信息([])
    const 空占位 = 创建装备信息([空武器])

    expect(获取装备差异(空列表, 空占位)).toEqual([])
    expect(生成装备信息签名(空列表)).toBe(生成装备信息签名(空占位))
    expect(获取装备差异(创建装备信息([武器]), 空列表)).toEqual([
      { 部位索引: '_12', 部位名: '武器', 基准装备: 武器, 对比装备: undefined },
    ])
  })

  test('应用缺位方案时显式清除表单中上一个方案的暗器和武器', () => {
    const 暗器 = 创建装备(装备位置部位枚举._11, 11)
    const 武器 = 创建装备(装备位置部位枚举._12, 12)
    const 新表单值 = 装备信息转表单值(创建装备信息([]))
    const 合并后的表单值 = { _11: 暗器, _12: 武器, ...新表单值 }

    expect(Object.prototype.hasOwnProperty.call(新表单值, '_11')).toBe(true)
    expect(Object.prototype.hasOwnProperty.call(新表单值, '_12')).toBe(true)
    expect(合并后的表单值._11).toBeUndefined()
    expect(合并后的表单值._12).toBeUndefined()
  })
})
