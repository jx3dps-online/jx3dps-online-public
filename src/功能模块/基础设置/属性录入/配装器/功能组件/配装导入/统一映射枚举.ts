import 五彩石转换数据 from '@/数据/常量/五彩石转换.json'

export const 五彩石转换: Record<string, string> = 五彩石转换数据

// 按·分段精确替换元素词，天罗诡道保留原始名称
export const 归一五彩石名称 = (五彩石名称: string, 功法?: string): string => {
  if (!五彩石名称 || 功法 === '天罗诡道') return 五彩石名称
  return 五彩石名称
    .split('·')
    .map((词) => {
      const 元素词 = Object.keys(五彩石转换).find((key) => 词.startsWith(key))
      return 元素词 ? 词.replace(元素词, 五彩石转换[元素词]) : 词
    })
    .join('·')
}

