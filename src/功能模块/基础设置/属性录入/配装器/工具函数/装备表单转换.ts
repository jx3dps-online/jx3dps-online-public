import { 装备位置部位枚举, 装备信息数据类型, 选择装备数据类型 } from '@/@types/装备'

const 部位索引列表 = Object.keys(装备位置部位枚举) as (keyof typeof 装备位置部位枚举)[]

export const 根据部位索引获取装备 = (
  装备列表: 选择装备数据类型[] | undefined,
  部位索引: string,
): 选择装备数据类型 | undefined => {
  const 部位 = 装备位置部位枚举[部位索引]
  if (!部位) return undefined

  const 同部位索引 = 部位索引列表.filter((key) => 装备位置部位枚举[key] === 部位)
  const 同部位装备 = (装备列表 || []).filter((装备) => 装备?.装备部位 === 部位)
  const 已定位装备 = 同部位装备.find((装备) => 装备.装备部位索引 === 部位索引)
  if (已定位装备) return 已定位装备

  // 兼容旧缓存：单一部位按名称恢复，两枚戒指按原列表中的先后顺序恢复。
  // 已记录槽位的装备不再参与分配，避免只有第二枚戒指时被重复回填到第一枚。
  const 未定位装备 = 同部位装备.filter(
    (装备) => !同部位索引.some((key) => key === 装备.装备部位索引),
  )
  const 未占用槽位 = 同部位索引.filter(
    (key) => !同部位装备.some((装备) => 装备.装备部位索引 === key),
  )
  return 未定位装备[未占用槽位.findIndex((key) => key === 部位索引)]
}

export const 表单值转装备列表 = (表单值: Record<string, any>): 选择装备数据类型[] =>
  部位索引列表
    .filter((部位索引) => !!表单值[部位索引])
    .map((部位索引) => ({
      ...表单值[部位索引],
      装备部位: 装备位置部位枚举[部位索引],
      装备部位索引: 部位索引,
    }))

export const 装备信息转表单值 = (装备信息: 装备信息数据类型) => {
  const 表单值: Record<string, any> = {
    五彩石: 装备信息?.五彩石,
    大附魔_伤帽: 装备信息?.装备增益?.大附魔_伤帽 || 0,
    大附魔_伤衣: 装备信息?.装备增益?.大附魔_伤衣 || 0,
    大附魔_伤腰: 装备信息?.装备增益?.大附魔_伤腰 || 0,
    大附魔_伤腕: 装备信息?.装备增益?.大附魔_伤腕 || 0,
    大附魔_伤鞋: 装备信息?.装备增益?.大附魔_伤鞋 || 0,
  }
  部位索引列表.forEach((部位索引) => {
    const 装备 = 根据部位索引获取装备(装备信息?.装备列表, 部位索引)
    // setFieldsValue 会合并旧值，空槽和已移除的附魔都必须显式清空。
    表单值[部位索引] = 装备 ? { ...装备, 附魔: 装备.附魔 } : undefined
  })
  return 表单值
}
