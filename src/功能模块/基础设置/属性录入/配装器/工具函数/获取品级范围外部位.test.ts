declare const describe: (name: string, suite: () => void) => void
declare const test: (name: string, assertion: () => void) => void
declare const expect: any

import { 装备属性信息模型, 装备类型枚举 } from '@/@types/装备'
import { 获取品级范围外部位索引 } from './获取品级范围外部位'

const 创建装备 = (
  id: number,
  装备品级: number,
  装备类型: 装备类型枚举 = 装备类型枚举.普通,
): 装备属性信息模型 => ({
  id,
  装备名称: `测试装备${id}`,
  装备品级,
  装备主属性: '通用',
  装备类型,
  装备增益: [],
})

const 装备数据 = {
  帽子: [创建装备(1, 1000), 创建装备(2, 1300)],
  武器: [创建装备(3, 900), 创建装备(4, 1500, 装备类型枚举.橙武)],
}

describe('获取品级范围外部位索引', () => {
  test('品级范围为空或未设置时不做判断', () => {
    expect(获取品级范围外部位索引({ _1: { id: 1 } }, [], 装备数据)).toEqual([])
    expect(获取品级范围外部位索引({ _1: { id: 1 } }, undefined, 装备数据)).toEqual([])
  })

  test('装备都在品级范围内时不返回', () => {
    expect(
      获取品级范围外部位索引({ _1: { id: 1 }, _12: { id: 3 } }, [900, 1100], 装备数据),
    ).toEqual([])
  })

  test('装备高于范围上限时返回对应部位', () => {
    expect(
      获取品级范围外部位索引({ _1: { id: 2 }, _12: { id: 3 } }, [900, 1100], 装备数据),
    ).toEqual(['_1'])
  })

  test('装备低于范围下限时返回对应部位', () => {
    expect(
      获取品级范围外部位索引({ _1: { id: 2 }, _12: { id: 3 } }, [1200, 1500], 装备数据),
    ).toEqual(['_12'])
  })

  test('武器部位的橙武与候选池规则一致，始终视为范围内', () => {
    expect(获取品级范围外部位索引({ _12: { id: 4 } }, [900, 1100], 装备数据)).toEqual([])
  })

  test('空槽与找不到数据的装备不返回', () => {
    expect(
      获取品级范围外部位索引({ _1: undefined, _12: { id: 999 } }, [900, 1100], 装备数据),
    ).toEqual([])
  })
})
