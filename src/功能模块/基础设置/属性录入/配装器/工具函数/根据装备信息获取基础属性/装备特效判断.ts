/**
 * 装备特效档位判定
 * 触发等级直接用原始等级做值 map 的 key，其余按品级规则
 */

import { 装备属性信息模型 } from '@/@types/装备'
import { 本赛季普通品级, 本赛季英雄品级 } from '@/数据/常量/装备常量'
import 装备特效数据 from '@/数据/装备/装备增益数据/装备特效数据'

/**
 * 副本特效增益表现
 * 有触发等级直接用；否则按品级区域：英雄 3、普通 2、其余 1
 */
export const 获取副本特效增益表现 = (品级: number, 特效等级?: string | undefined) => {
  if (特效等级) {
    return +特效等级
  }
  return 品级 >= 本赛季英雄品级 ? 3 : 品级 >= 本赛季普通品级 ? 2 : 1
}

/**
 * 装备增益表现（值 map 的 key）
 * 按 registry 的档位规则统一判定：触发等级直接用原始等级，其余按品级规则
 */
export const 获取装备增益表现 = (装备属性: 装备属性信息模型): number => {
  const 档位规则 = 装备属性?.装备特效 && 装备特效数据[装备属性.装备特效]?.档位规则
  switch (档位规则) {
    case '触发等级':
      return 装备属性.特效等级 ? +装备属性.特效等级 : 1
    case '副本品级':
      return 获取副本特效增益表现(装备属性.装备品级, 装备属性.特效等级 || undefined)
    default:
      return 1
  }
}
