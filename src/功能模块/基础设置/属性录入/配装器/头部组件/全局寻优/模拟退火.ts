const 获取套装件数 = (表单值: Record<string, any>) => {
  const { 装备数据 } = 获取当前数据()
  let 件数 = 0
  Object.keys(装备位置部位枚举).forEach((部位索引) => {
    const 部位值 = 表单值?.[部位索引]
    if (!部位值?.id) return
    const 装备 = 装备数据?.[装备位置部位枚举[部位索引]]?.find((a) => a?.id === 部位值?.id)
    if (装备?.装备特效 === 装备特效枚举.门派套装) {
      件数++
    }
  })
  return 件数
}

// 秒伤随加速呈阶梯变化：加速等级分界与循环的加速值范围分界之间，秒伤只取决于其他属性。
// 逐部位坐标下降无法跨越分界（单件换装跨不过去时秒伤只降不升），因此按区间分别寻优再比较。
const 获取加速区间列表 = (当前循环信息?: 循环数据): 加速区间[] => {
  const 分界集合 = new Set<number>(获取加速等级分界())
  ;(当前循环信息?.循环详情 || []).forEach((详情) => {
    ;(详情?.循环加速值范围 || []).forEach((值) => {
      const 数值 = Number(值)
      if (数值 > 0 && Number.isFinite(数值)) {
        分界集合.add(数值)
      }
    })
  })
  const 分界列表 = [0, ...Array.from(分界集合).sort((a, b) => a - b), Infinity]
  return 分界列表.slice(0, -1).map((下限, index) => ({ 下限, 上限: 分界列表[index + 1] }))
}

const 优于 = (a: 评估结果, b: 评估结果) => {
  if (a.有效 !== b.有效) {
    return a.有效
  }
  if (a.有效) {
    return a.秒伤 > b.秒伤
  }
  for (let i = 0; i < Math.min(a.差距.length, b.差距.length); i++) {
    if (a.差距[i] !== b.差距[i]) {
      return a.差距[i] < b.差距[i]
    }
  }
  return false
}

export const 执行模拟退火 = async (props: 模拟退火入参): Promise<模拟退火输出> => {
  const { 装备数据 } = 获取当前数据()
  const {
    初始表单值,
    配置,
    装备选择范围,
    默认镶嵌宝石等级,
    增益数据,
    增益启用,
    允许规划增益 = true,
    当前循环信息,
    计算秒伤,
    是否取消,
    onProgress,
  } = props

  const 随机 = mulberry32(20240512)
  const 轮数 = 配置.迭代次数 || 10
  const 循环轮数 = 配置.循环轮数 ?? 5
  const 装备扰动数量 = 配置.装备扰动数量 ?? 3
  const 锁定部位 = 配置?.锁定部位 || []
  const 加速值范围 = 配置.约束.加速值范围
  const 套装件数约束 = 配置?.约束?.套装件数 ?? undefined
  const 装分上限 = 配置?.约束?.装分上限 ?? undefined
  const 沿用当前精炼镶嵌 = 装分上限 !== undefined
  const 排除附魔类型 = 配置.参与小附魔 ? 配置.排除附魔类型 || [] : []
  const 初始状态: 寻优状态 = { 表单值: 初始表单值, 增益数据 }
  const 五彩石数据 = 获取当前数据().五彩石
  const 全部五彩石 = 五彩石数据[5].concat(五彩石数据[6])
  const 潮生要求 = 当前循环信息?.额外配置信息?.潮生每秒回复 || 0
  const 初始潮生匹配 = 五彩石满足潮生要求(
    全部五彩石.find((石头) => 石头.五彩石名称 === 初始表单值.五彩石),
    当前循环信息,
  )

  const 候选表: Record<string, 装备属性信息模型[]> = {}
  Object.keys(装备位置部位枚举).forEach((部位索引) => {
    const 部位名 = 装备位置部位枚举[部位索引]
    if (!候选表[部位名]) {
      let 候选 = 获取部位候选装备(部位名, 装备选择范围)
      if (部位名 === '武器') {
        候选 = 候选?.filter((装备) => 装备?.装备特效 !== 装备特效枚举.大橙武特效)
      }
      if (配置.不使用橙武) {
        候选 = 候选?.filter((装备) => 装备?.装备类型 !== 装备类型枚举.橙武)
      }
      候选表[部位名] = 候选
    }
  })

  const 排除部位 = new Set<string>(锁定部位)
  const 武器部位索引 = Object.keys(装备位置部位枚举).find(
    (索引) => 装备位置部位枚举[索引] === '武器',
  ) as string
  const 当前武器 = 初始表单值?.[武器部位索引]
  const 当前武器装备 = 装备数据?.['武器']?.find((a) => a?.id === 当前武器?.id)
  if (当前武器装备?.装备特效 === 装备特效枚举.大橙武特效) {
    排除部位.add(武器部位索引)
  }

  const 未锁定部位索引 = Object.keys(装备位置部位枚举).filter((索引) => !排除部位.has(索引))
  const 附魔增益候选列表 = 创建附魔增益候选(配置, 未锁定部位索引, 增益启用 && 允许规划增益)
  type 搜索项 = { 类型: '装备'; 部位: string } | { 类型: '镶嵌'; 部位: string } | 附魔增益候选
  // 装分上限下镶嵌等级是贴近上限的主要手段，不设上限时保持原搜索空间
  const 非装备项列表: 搜索项[] = [
    ...附魔增益候选列表,
    ...(沿用当前精炼镶嵌 ? 未锁定部位索引.map((部位) => ({ 类型: '镶嵌' as const, 部位 })) : []),
  ]
  const 搜索项列表: 搜索项[] = [
    ...未锁定部位索引.map((部位) => ({ 类型: '装备' as const, 部位 })),
    ...非装备项列表,
  ]
  const 打乱搜索项 = (列表: 搜索项[] = 搜索项列表) => {
    const 结果 = [...列表]
    for (let i = 结果.length - 1; i > 0; i--) {
      const j = Math.floor(随机() * (i + 1))
      ;[结果[i], 结果[j]] = [结果[j], 结果[i]]
    }
    return 结果
  }

  const 全部区间 = 获取加速区间列表(当前循环信息)
  const 搜索区间列表 = 加速值范围
    ? 全部区间
        .map((区间) => ({
          下限: Math.max(区间.下限, 加速值范围[0]),
          上限: Math.min(区间.上限, 加速值范围[1]),
        }))
        .filter((区间) => 区间.下限 < 区间.上限)
    : 全部区间

  // 粗排后每次局部搜索的实际评估数不可预估，进度按搜索步骤计：每个加速区间、每次扰动各一步
  const 每轮步骤数 = 搜索区间列表.length + 轮数
  const 总步骤数 = 循环轮数 * 每轮步骤数

  const 让出主线程 = 创建时间片让出器()
  const 获取粗排候选 = 创建候选粗排({
    默认镶嵌宝石等级,
    沿用当前精炼镶嵌,
    计算秒伤,
    让出主线程,
    是否取消,
  })

  const 获取部位装分 = (表单值: Record<string, any>, 部位索引: string) =>
    装备列表装分计算(表单值转装备列表({ [部位索引]: 表单值[部位索引] }), 表单值.五彩石)

  // 装备、附魔、大附魔、五彩石、小吃和阵眼共同决定搜索状态，签名必须覆盖所有可变项。
  // 加速值与套装件数先算，秒伤只在满足区间约束时才计算，未达区间的修正步骤不做整次秒伤计算。
  type 状态基础 = {
    加速值: number
    套装件数: number
    装分: number
    部位约束数: number
    装备信息?: 装备信息数据类型
    秒伤?: number
  }
  const 基础缓存 = new Map<string, 状态基础 | null>()
  const 状态签名 = ({ 表单值, 增益数据 }: 寻优状态) => {
    const 装备签名 = Object.keys(装备位置部位枚举)
      .map((部位索引) => {
        const 部位值 = 表单值?.[部位索引]
        const 镶嵌 = 部位值?.镶嵌孔数组?.map((孔) => 孔?.镶嵌宝石等级)?.join(',') || ''
        return `${部位值?.id || 0}:${部位值?.附魔 || 0}:${部位值?.当前精炼等级 || 0}:${镶嵌}`
      })
      .join('|')
    const 大附魔签名 = ['大附魔_伤帽', '大附魔_伤衣', '大附魔_伤腰', '大附魔_伤腕', '大附魔_伤鞋']
      .map((键) => 表单值?.[键] || 0)
      .join(',')
    return `${装备签名}|${大附魔签名}|${表单值?.五彩石 || ''}|${JSON.stringify(增益数据.小吃)}|${增益数据.阵眼 || ''}`
  }

  const 计算部位约束数 = (表单值: Record<string, any>) =>
    未锁定部位索引.reduce((合计, 部位索引) => {
      const 部位值 = 表单值?.[部位索引]
      const 装备 = 装备数据?.[装备位置部位枚举[部位索引]]?.find((a) => a?.id === 部位值?.id)
      const 附魔 = 根据附魔ID获取附魔数据(部位值?.附魔)
      return (
        合计 +
        Number(!!配置.不使用橙武 && 装备?.装备类型 === 装备类型枚举.橙武) +
        Number(!!附魔 && 排除附魔类型.includes(附魔.附魔类型))
      )
    }, 0)

  const 获取基础 = (状态: 寻优状态) => {
    const 签名 = 状态签名(状态)
    if (基础缓存.has(签名)) {
      return 基础缓存.get(签名)
    }
    let 基础: 状态基础 | null
    try {
      const 装备信息 = 根据表单选项获取装备信息(状态.表单值)
      基础 = {
        加速值:
          (装备信息?.装备基础属性?.加速等级 || 0) +
          (增益启用 ? 计算增益数据中加速值(状态.增益数据) : 0),
        套装件数: 获取套装件数(状态.表单值),
        装分: 装分上限 === undefined ? 0 : 总装分计算(装备信息),
        部位约束数: 计算部位约束数(状态.表单值),
        装备信息,
      }
    } catch {
      基础 = null
    }
    基础缓存.set(签名, 基础)
    return 基础
  }

  const 评估 = (状态: 寻优状态, 区间: 加速区间): 评估结果 => {
    if (
      !五彩石满足潮生要求(
        全部五彩石.find((石头) => 石头.五彩石名称 === 状态.表单值.五彩石),
        当前循环信息,
      )
    ) {
      return { 有效: false, 秒伤: 0, 差距: [1, 0, 0, 0] }
    }
    const 基础 = 获取基础(状态)
    if (!基础) {
      return { 有效: false, 秒伤: 0, 差距: [Infinity] }
    }
    const 套装差距 = 套装件数约束 === undefined ? 0 : Math.max(0, 套装件数约束 - 基础.套装件数)
    const 加速差距 =
      基础.加速值 < 区间.下限
        ? 区间.下限 - 基础.加速值
        : 基础.加速值 >= 区间.上限
          ? 基础.加速值 - 区间.上限 + 1
          : 0
    const 装分差距 = 装分上限 === undefined ? 0 : Math.max(0, 基础.装分 - 装分上限)
    if (基础.部位约束数 || 套装差距 || 加速差距 || 装分差距) {
      return { 有效: false, 秒伤: 0, 差距: [基础.部位约束数, 套装差距, 加速差距, 装分差距] }
    }
    if (基础.秒伤 === undefined) {
      基础.秒伤 = 计算秒伤(基础.装备信息 as 装备信息数据类型, true, 状态.增益数据)
      基础.装备信息 = undefined
    }
    return { 有效: 基础.秒伤 > 0, 秒伤: 基础.秒伤, 差距: [0, 0, 0, 0, 基础.秒伤 > 0 ? 0 : 1] }
  }

  const 生成候选装备表单值 = (状态: 寻优状态, 装备: 装备属性信息模型, 部位索引: string) =>
    生成装备表单值(装备, 状态.表单值[部位索引], 部位索引, 默认镶嵌宝石等级, 沿用当前精炼镶嵌)

  const 获取候选状态 = async (状态: 寻优状态, 项: 搜索项, 有效: boolean) => {
    if (项.类型 === '镶嵌') {
      return 生成镶嵌候选状态(状态, 项.部位)
    }
    if (项.类型 !== '装备') {
      if (项.类型 === '附魔' && !状态.表单值[项.部位]?.id) return []
      return 项.候选值.map((值) => 生成附魔增益状态(状态, 项, 值))
    }
    let 全部候选 = 候选表[装备位置部位枚举[项.部位]] || []
    // 满足约束后粗排只看属性收益，先剔除换上即超装分上限的装备，避免入选候选全部无效
    if (有效 && 装分上限 !== undefined) {
      const 其余装分 = (获取基础(状态)?.装分 || 0) - 获取部位装分(状态.表单值, 项.部位)
      全部候选 = 全部候选.filter(
        (装备) =>
          其余装分 +
            获取部位装分(
              { [项.部位]: 生成候选装备表单值(状态, 装备, 项.部位), 五彩石: 状态.表单值.五彩石 },
              项.部位,
            ) <=
          装分上限,
      )
    }
    const 使用候选 = 有效
      ? await 获取粗排候选(全部候选, 状态.表单值, 项.部位, 状态.增益数据)
      : 全部候选
    return 使用候选
      .filter((装备) => 装备.id !== 状态.表单值[项.部位]?.id)
      .map((装备) => ({
        ...状态,
        表单值: { ...状态.表单值, [项.部位]: 生成候选装备表单值(状态, 装备, 项.部位) },
      }))
  }

  const 生成扰动状态 = async (当前状态: 寻优状态, 区间: 加速区间) => {
    let 新状态 = 当前状态
    let 已扰动装备数 = 0
    const 装备项 = 打乱搜索项(搜索项列表.filter((项) => 项.类型 === '装备'))
    const 附魔增益项 = 打乱搜索项(非装备项列表).slice(0, 1 + Math.floor(随机() * 3))
    // 装备单独计数，组合替换完成后再做局部搜索，允许中间状态跨越加速和套装约束。
    for (const 项 of [...装备项, ...附魔增益项]) {
      if (是否取消?.()) break
      if (项.类型 === '装备' && 已扰动装备数 >= 装备扰动数量) continue
      let 使用候选 = await 获取候选状态(新状态, 项, 评估(新状态, 区间).有效)
      if (项.类型 === '装备' && 套装件数约束 !== undefined && 随机() < 0.5) {
        const 套装候选 = 使用候选.filter((状态) =>
          候选表[装备位置部位枚举[项.部位]].some(
            (装备) =>
              装备.id === 状态.表单值[项.部位].id && 装备.装备特效 === 装备特效枚举.门派套装,
          ),
        )
        if (套装候选.length) {
          使用候选 = 套装候选
        }
      }
      if (使用候选.length) {
        新状态 = 使用候选[Math.floor(随机() * 使用候选.length)]
        if (项.类型 === '装备') 已扰动装备数++
      }
      await 让出主线程()
    }
    return 新状态
  }

  const 初始区间 = 全部区间.find((区间) => 评估(初始状态, 区间).差距[2] === 0) || 全部区间[0]
  const 初始评估 = 评估(初始状态, 初始区间)
  const 替换前秒伤 =
    初始评估.有效 && (!加速值范围 || 搜索区间列表.some((区间) => 评估(初始状态, 区间).有效))
      ? 初始评估.秒伤
      : 0
  let 最优状态 = 初始状态
  if (!初始潮生匹配 && 配置.参与五彩石 && !锁定部位.includes(武器部位索引)) {
    const 潮生五彩石 = 全部五彩石.find((石头) => 五彩石满足潮生要求(石头, 当前循环信息))
    最优状态 = { ...初始状态, 表单值: { ...初始表单值, 五彩石: 潮生五彩石!.五彩石名称 } }
  }
  let 最优秒伤 = 替换前秒伤
  let 已搜索总数 = 0
  let 当前循环轮次 = 0
  let 已完成步骤 = 0
  let 当前阶段: 模拟退火进度['当前阶段'] = '加速区间搜索'
  let 阶段序号 = 0
  let 阶段总数 = 搜索区间列表.length

  const 上报进度 = () => {
    onProgress?.({
      已搜索: 已搜索总数,
      已完成步骤,
      总步骤数,
      当前阶段,
      阶段序号,
      阶段总数,
      当前最优秒伤: 最优秒伤,
      迭代次数: 轮数,
      当前循环轮次,
      循环轮数,
      初始秒伤: 替换前秒伤,
    })
  }

  // 未满足约束时遍历完整候选修正差距，满足后仅精算属性粗排入选的装备。
  const 局部搜索 = async (起点: 寻优状态, 区间: 加速区间) => {
    let 状态 = 起点
    let 结果 = 评估(状态, 区间)
    if (结果.有效 && 结果.秒伤 > 最优秒伤) {
      最优状态 = 状态
      最优秒伤 = 结果.秒伤
    }
    for (let 轮次 = 0; 轮次 < 局部搜索最大轮次 && !是否取消?.(); 轮次++) {
      let 有改进 = false
      for (const 项 of 打乱搜索项()) {
        if (是否取消?.()) break
        const 使用候选 = await 获取候选状态(状态, 项, 结果.有效)
        for (const 候选状态 of 使用候选) {
          if (是否取消?.()) break
          const 候选结果 = 评估(候选状态, 区间)
          已搜索总数++
          if (优于(候选结果, 结果)) {
            状态 = 候选状态
            结果 = 候选结果
            有改进 = true
          }
          await 让出主线程()
        }
        if (结果.有效 && 结果.秒伤 > 最优秒伤) {
          最优状态 = 状态
          最优秒伤 = 结果.秒伤
        }
        上报进度()
      }
      if (!有改进) break
    }
    return { 状态, 结果 }
  }

  // 超出装分上限过多时逐件替换难以回到上限内，先用背包求一个上限内的起点
  let 搜索起点 = 最优状态
  if (装分上限 !== undefined && (获取基础(搜索起点)?.装分 || 0) > 装分上限) {
    const 起点表单值 = await 构造贴分起点({
      初始表单值: 搜索起点.表单值,
      装分上限,
      候选表,
      未锁定部位索引,
      小附魔候选: 附魔增益候选列表.reduce<Record<string, (string | number)[]>>((表, 项) => {
        if (项.类型 === '附魔') 表[项.部位] = 项.候选值
        return 表
      }, {}),
      排除附魔类型,
      参与大附魔: !!配置.参与大附魔,
      不使用橙武: !!配置.不使用橙武,
      默认镶嵌宝石等级,
      让出主线程,
      是否取消,
    })
    if (起点表单值) {
      搜索起点 = { ...初始状态, 表单值: 起点表单值 }
    }
  }

  type 区间结果 = { 区间: 加速区间; 状态: 寻优状态; 结果: 评估结果 }
  const 区间最优列表: 区间结果[] = []
  // 所有区间都没有可行解时，从违反约束最少的状态继续扰动，避免每轮都从同一起点空转
  let 最少违约: 区间结果 | undefined
  for (let 循环轮次 = 0; 循环轮次 < 循环轮数 && !是否取消?.(); 循环轮次++) {
    当前循环轮次 = 循环轮次 + 1
    const 本轮起点 = 最优秒伤 > 0 ? 最优状态 : 最少违约?.状态 || 搜索起点
    const 起点加速值 = 获取基础(本轮起点)?.加速值
    const 起点区间 = 搜索区间列表.find(
      (区间) => 起点加速值 !== undefined && 起点加速值 >= 区间.下限 && 起点加速值 < 区间.上限,
    )
    const 区间搜索顺序 = [
      ...搜索区间列表.filter((区间) => 区间 === 起点区间),
      ...搜索区间列表.filter((区间) => 区间 !== 起点区间),
    ]
    当前阶段 = '加速区间搜索'
    阶段总数 = 区间搜索顺序.length
    上报进度()
    for (let 序号 = 0; 序号 < 区间搜索顺序.length; 序号++) {
      if (是否取消?.()) break
      const 区间 = 区间搜索顺序[序号]
      阶段序号 = 序号 + 1
      const 局部结果 = await 局部搜索(本轮起点, 区间)
      if (局部结果.结果.有效) {
        const 历史最优 = 区间最优列表.find((项) => 项.区间 === 区间)
        if (!历史最优) {
          区间最优列表.push({ 区间, ...局部结果 })
        } else if (优于(局部结果.结果, 历史最优.结果)) {
          历史最优.状态 = 局部结果.状态
          历史最优.结果 = 局部结果.结果
        }
      } else if (!最少违约 || 优于(局部结果.结果, 最少违约.结果)) {
        最少违约 = { 区间, ...局部结果 }
      }
      已完成步骤++
      上报进度()
    }

    const 精搜列表 = 区间最优列表.length
      ? 区间最优列表.sort((a, b) => b.结果.秒伤 - a.结果.秒伤).slice(0, 精搜区间数)
      : 最少违约
        ? [最少违约]
        : []
    当前阶段 = '扰动搜索'
    阶段总数 = 轮数
    for (let 轮 = 0; 轮 < 轮数 && 精搜列表.length; 轮++) {
      if (是否取消?.()) break
      阶段序号 = 轮 + 1
      const 目标 = 精搜列表[轮 % 精搜列表.length]
      const 扰动状态 = await 生成扰动状态(目标.状态, 目标.区间)
      const 局部结果 = await 局部搜索(扰动状态, 目标.区间)
      if (优于(局部结果.结果, 目标.结果)) {
        目标.状态 = 局部结果.状态
        目标.结果 = 局部结果.结果
      }
      已完成步骤++
      上报进度()
    }
    if (!是否取消?.()) {
      已完成步骤 = 当前循环轮次 * 每轮步骤数
    }
  }

  const 当前五彩石: string | undefined = 最优状态.表单值?.五彩石
  if (配置.参与五彩石 && 最优秒伤 > 0 && 当前五彩石 && !锁定部位.includes(武器部位索引)) {
    // 五彩石可能带加速与装分，按候选所在加速区间重新校验约束
    const 五彩石列表 = (
      潮生要求 ? 全部五彩石 : 五彩石数据[当前五彩石.includes('陆') ? 6 : 5]
    ).filter((石头) => 五彩石满足潮生要求(石头, 当前循环信息))
    const 起点 = 最优状态
    for (const 五彩石 of 五彩石列表) {
      if (是否取消?.()) break
      const 候选状态 = { ...起点, 表单值: { ...起点.表单值, 五彩石: 五彩石?.五彩石名称 } }
      const 加速值 = 获取基础(候选状态)?.加速值
      const 区间 = 搜索区间列表.find(
        (项) => 加速值 !== undefined && 加速值 >= 项.下限 && 加速值 < 项.上限,
      )
      if (!区间) continue
      const 结果 = 评估(候选状态, 区间)
      已搜索总数++
      if (结果.有效 && 结果.秒伤 > 最优秒伤) {
        最优状态 = 候选状态
        最优秒伤 = 结果.秒伤
      }
      await 让出主线程()
    }
  }
  上报进度()

  const 替换前装备信息 = 根据表单选项获取装备信息(初始表单值)
  const 替换后装备信息 = 根据表单选项获取装备信息(最优状态.表单值)
  const 变更动作列表: 变更动作[] = 获取附魔增益变更(初始状态, 最优状态, 附魔增益候选列表)
  Object.keys(装备位置部位枚举).forEach((部位索引) => {
    const 旧值 = 初始表单值?.[部位索引]
    const 新值 = 最优状态.表单值[部位索引]
    if (旧值?.id !== 新值?.id) {
      变更动作列表.push({
        类型: '装备',
        部位: 部位索引,
        目标值: 新值?.id,
        预估秒伤增益: 0,
        预估成本铜: 0,
      })
    }
  })
  变更动作列表.push(...获取镶嵌变更(初始状态, 最优状态))
  if ((初始表单值?.五彩石 || '') !== (最优状态.表单值?.五彩石 || '')) {
    变更动作列表.push({
      类型: '五彩石',
      目标值: 最优状态.表单值?.五彩石,
      预估秒伤增益: 0,
      预估成本铜: 0,
    })
  }

  // 初始配装不满足约束时 替换前秒伤 记为 0 以便接受任意可行解，展示时仍用实际秒伤
  const 当前秒伤 = 初始潮生匹配 ? 替换前秒伤 || 计算秒伤(替换前装备信息, true, 增益数据) : 0
  return {
    结果: {
      替换前装备信息,
      替换后装备信息,
      替换前增益数据: 初始状态.增益数据,
      替换后增益数据: 最优状态.增益数据,
      变更动作列表,
      秒伤提升: 最优秒伤 - 当前秒伤,
      有效: 最优秒伤 > 0,
      替换前装分: 总装分计算(替换前装备信息),
      替换后装分: 总装分计算(替换后装备信息),
    },
    最优表单值: 最优状态.表单值,
    替换前秒伤: 当前秒伤,
    替换后秒伤: 最优秒伤,
  }
}
