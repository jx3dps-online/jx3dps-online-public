export interface 寻优状态 {
  表单值: Record<string, any>
  增益数据: 增益选项数据类型
}

export interface 附魔增益候选 {
  类型: '附魔' | '大附魔' | '药品' | '食品' | '家园酒品' | '阵眼'
  /** 附魔为部位索引，大附魔为表单键（如 大附魔_伤帽），小吃为小吃部位，阵眼固定为「阵眼」 */
  部位: string
  候选值: (string | number)[]
}

const 获取最高档候选 = <T extends { 增益集合: { 属性: 属性类型; 值: number }[] }>(
  列表: T[],
  获取品质: (项: T) => 附魔类型 | '金',
): T[] => {
  const 品质等级 = { 蓝: 0, 紫: 1, 精: 2, 挑: 2, 金: 2 }
  const 分组 = new Map<string, { 项: T; 品质: number; 属性值: Record<string, number> }[]>()
  for (const 项 of 列表) {
    const 属性值: Record<string, number> = {}
    项.增益集合.forEach(({ 属性, 值 }) => {
      属性值[属性] = (属性值[属性] || 0) + 值
    })
    const 属性列表 = Object.keys(属性值).sort()
    const 键 = 属性列表.join('|')
    const 品质 = 品质等级[获取品质(项)]
    let 同组 = 分组.get(键) || []
    if (同组.length && 品质 < 同组[0].品质) continue
    if (同组.length && 品质 > 同组[0].品质) 同组 = []
    if (同组.some((候选) => 属性列表.every((属性) => 候选.属性值[属性] >= 属性值[属性]))) continue
    同组 = 同组.filter((候选) => !属性列表.every((属性) => 属性值[属性] >= 候选.属性值[属性]))
    同组.push({ 项, 品质, 属性值 })
    分组.set(键, 同组)
  }
  return Array.from(分组.values()).flatMap((列表) => 列表.map(({ 项 }) => 项))
}

export const 创建附魔增益候选 = (
  配置: 全局寻优配置,
  未锁定部位: string[],
  允许搜索增益: boolean,
): 附魔增益候选[] => {
  const { 附魔, 小药小吃, 主属性, 阵眼 } = 获取当前数据()
  const 候选: 附魔增益候选[] = []
  if (配置.参与小附魔) {
    const 非输出属性 = [属性类型.体质, 属性类型.基础气血上限, 属性类型.额外气血上限]
    const 排除附魔类型 = 配置.排除附魔类型 || []
    未锁定部位.forEach((部位) => {
      const 列表 = 附魔.filter(
        (项) =>
          项.附魔支持部位.includes(装备位置部位枚举[部位]) &&
          !排除附魔类型.includes(项.附魔类型) &&
          !项.增益集合.some(({ 属性 }) => 非输出属性.includes(属性)),
      )
      const 最高档 = 获取最高档候选(列表, (项) => 项.附魔类型)
      if (最高档.length) 候选.push({ 类型: '附魔', 部位, 候选值: 最高档.map((项) => 项.id) })
    })
  }
  if (配置.参与大附魔) {
    未锁定部位.forEach((部位) => {
      const 大附魔键 = 大附魔部位枚举[装备位置部位枚举[部位]]
      if (大附魔键) 候选.push({ 类型: '大附魔', 部位: 大附魔键, 候选值: [0, 1, 2] })
    })
  }
  if (允许搜索增益) {
    const 主属性列表 = [属性类型.力道, 属性类型.身法, 属性类型.元气, 属性类型.根骨]
    const 槽位 = [
      ...(配置.参与药品 ? [小吃类型枚举.药品增强, 小吃类型枚举.药品辅助] : []),
      ...(配置.参与食品 ? [小吃类型枚举.食品增强, 小吃类型枚举.食品辅助] : []),
      ...(配置.参与家园酒品 ? [小吃类型枚举.家园酒品] : []),
    ]
    槽位.forEach((部位) => {
      const 列表 = 小药小吃.filter(
        (项) =>
          项.小吃部位 === 部位 &&
          项.增益集合.every(({ 属性 }) => !主属性列表.includes(属性) || 属性 === 属性类型[主属性]),
      )
      const 最高档 = 获取最高档候选(列表, (项) => 项.小吃品级)
      if (最高档.length) {
        候选.push({
          类型:
            部位 === 小吃类型枚举.家园酒品
              ? '家园酒品'
              : 部位 === 小吃类型枚举.食品增强 || 部位 === 小吃类型枚举.食品辅助
                ? '食品'
                : '药品',
          部位,
          候选值: 最高档.map((项) => 项.小吃名称),
        })
      }
    })
    if (配置.参与阵眼 && 阵眼?.length) {
      候选.push({ 类型: '阵眼', 部位: '阵眼', 候选值: 阵眼.map((项) => 项.阵眼名称) })
    }
  }
  return 候选
}

export const 生成附魔增益状态 = (
  状态: 寻优状态,
  候选: 附魔增益候选,
  值: string | number,
): 寻优状态 => {
  if (候选.类型 === '附魔') {
    return {
      ...状态,
      表单值: { ...状态.表单值, [候选.部位]: { ...状态.表单值[候选.部位], 附魔: 值 } },
    }
  }
  if (候选.类型 === '大附魔') {
    return { ...状态, 表单值: { ...状态.表单值, [候选.部位]: 值 } }
  }
  if (候选.类型 === '阵眼') {
    return { ...状态, 增益数据: { ...状态.增益数据, 阵眼: String(值) } }
  }
  return {
    ...状态,
    增益数据: {
      ...状态.增益数据,
      小吃: 合并小吃数据(状态.增益数据.小吃, [{ 名称: String(值), 类型: 候选.部位 }]),
    },
  }
}

export const 获取槽位小吃 = (增益数据: 增益选项数据类型 | undefined, 部位: string) => {
  const { 小药小吃 } = 获取当前数据()
  return (增益数据?.小吃 || []).filter(
    (名称) => 小药小吃.find((项) => 项.小吃名称 === 名称)?.小吃部位 === 部位,
  )
}

export const 获取附魔增益变更 = (
  初始状态: 寻优状态,
  最优状态: 寻优状态,
  候选列表: 附魔增益候选[],
): 变更动作[] => {
  const 变更: 变更动作[] = []
  const 取值 = (状态: 寻优状态, 类型: 附魔增益候选['类型'], 部位: string) =>
    类型 === '附魔'
      ? 状态.表单值[部位]?.附魔
      : 类型 === '大附魔'
        ? 状态.表单值[部位] || 0
        : 类型 === '阵眼'
          ? 状态.增益数据.阵眼 || ''
          : 获取槽位小吃(状态.增益数据, 部位).join('、')
  候选列表.forEach(({ 类型, 部位 }) => {
    const 新值 = 取值(最优状态, 类型, 部位)
    if (取值(初始状态, 类型, 部位) !== 新值) {
      变更.push({ 类型, 部位, 目标值: 新值, 预估秒伤增益: 0, 预估成本铜: 0 })
    }
  })
  return 变更
}

export const 获取镶嵌等级文本 = (部位值: any) =>
  (部位值?.镶嵌孔数组 || []).map((孔) => 孔?.镶嵌宝石等级 ?? 0).join('/')

export const 生成镶嵌候选状态 = (状态: 寻优状态, 部位: string): 寻优状态[] => {
  const 部位值 = 状态.表单值[部位]
  if (!部位值?.id) return []
  const 结果: 寻优状态[] = []
  ;(部位值.镶嵌孔数组 || []).forEach((孔, 孔索引) => {
    for (let 等级 = 0; 等级 <= 8; 等级++) {
      if (等级 === (孔?.镶嵌宝石等级 ?? 0)) continue
      const 镶嵌孔数组 = 部位值.镶嵌孔数组.map((项, i) =>
        i === 孔索引 ? { ...项, 镶嵌宝石等级: 等级 } : 项,
      )
      结果.push({ ...状态, 表单值: { ...状态.表单值, [部位]: { ...部位值, 镶嵌孔数组 } } })
    }
  })
  return 结果
}

/** 装备未更换但镶嵌等级变化的部位；更换的装备在装备变更里展示 */
export const 获取镶嵌变更 = (初始状态: 寻优状态, 最优状态: 寻优状态): 变更动作[] =>
  Object.keys(装备位置部位枚举)
    .filter((部位) => {
      const 旧值 = 初始状态.表单值[部位]
      const 新值 = 最优状态.表单值[部位]
      return !!新值?.id && 旧值?.id === 新值.id && 获取镶嵌等级文本(旧值) !== 获取镶嵌等级文本(新值)
    })
    .map(
      (部位): 变更动作 => ({
        类型: '镶嵌',
        部位,
        目标值: 获取镶嵌等级文本(最优状态.表单值[部位]),
        预估秒伤增益: 0,
        预估成本铜: 0,
      }),
    )
