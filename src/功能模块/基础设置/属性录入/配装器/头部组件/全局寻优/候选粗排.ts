/** 沿用当前精炼镶嵌：装分上限下精炼不参与搜索，已搜到的 0 级镶嵌也要保留 */
export const 生成装备表单值 = (
  装备: 装备属性信息模型,
  当前部位值: any,
  部位索引: string,
  默认镶嵌宝石等级: number,
  沿用当前精炼镶嵌 = false,
) => {
  const 当前镶嵌等级数组 = 当前部位值?.镶嵌孔数组?.map((item) => item?.镶嵌宝石等级) || []
  const 最大精炼等级 = 获取最大精炼等级(装备)
  return {
    ...当前部位值,
    镶嵌孔数组: 装备?.镶嵌孔数组?.map((孔, index) => ({
      ...孔,
      镶嵌宝石等级: 沿用当前精炼镶嵌
        ? (当前镶嵌等级数组?.[index] ?? 默认镶嵌宝石等级)
        : 当前镶嵌等级数组?.[index] || 默认镶嵌宝石等级,
    })),
    当前精炼等级: 沿用当前精炼镶嵌
      ? Math.min(当前部位值?.当前精炼等级 ?? 最大精炼等级, 最大精炼等级)
      : 最大精炼等级,
    id: 装备?.id,
    装备部位: 装备位置部位枚举[部位索引],
  }
}

interface 粗排配置 {
  默认镶嵌宝石等级: number
  沿用当前精炼镶嵌: boolean
  计算秒伤: (
    装备信息: 装备信息数据类型,
    是否郭氏计算?: boolean,
    增益数据?: 增益选项数据类型,
  ) => number
  让出主线程: () => Promise<void>
  是否取消?: () => boolean
}

const 计算当前属性收益 = async (
  当前状态: Record<string, any>,
  配置: 粗排配置,
  增益数据?: 增益选项数据类型,
) => {
  const 装备信息 = 根据表单选项获取装备信息(当前状态)
  const 旧秒伤 = 配置.计算秒伤(装备信息, false, 增益数据)
  const 收益列表 = 获取单点属性收益列表()
  收益列表.push({ 收益: '全能', 值: 收益列表[0].值 })
  const 属性收益: Record<string, number> = {}
  for (const { 收益, 值 } of 收益列表) {
    await 配置.让出主线程()
    if (配置.是否取消?.()) return 属性收益
    const 新秒伤 = 配置.计算秒伤(
      {
        ...装备信息,
        装备基础属性: 收益增益属性计算(收益, 值, 装备信息.装备基础属性),
      },
      false,
      增益数据,
    )
    属性收益[收益] = (新秒伤 - 旧秒伤) / 值
  }
  return 属性收益
}

export const 创建候选粗排 = (配置: 粗排配置) => {
  const { 主属性 } = 获取当前数据()
  const 默认属性 = 获取角色默认基础属性()
  const 属性字段: Record<string, keyof 角色基础属性类型> = {
    [主属性]: 主属性,
    攻击: '基础攻击',
    会心: '会心等级',
    会效: '会心效果等级',
    破防: '破防等级',
    无双: '无双等级',
    全能: '全能等级',
  }
  const 装备属性缓存 = new Map<string, 角色基础属性类型>()
  let 收益状态: Record<string, any> | undefined
  let 收益增益: 增益选项数据类型 | undefined
  let 属性收益: Record<string, number> = {}

  return async (
    全部候选: 装备属性信息模型[],
    当前状态: Record<string, any>,
    部位索引: string,
    增益数据?: 增益选项数据类型,
  ) => {
    if (!全部候选.length) return []
    if (收益状态 !== 当前状态 || 收益增益 !== 增益数据) {
      属性收益 = await 计算当前属性收益(当前状态, 配置, 增益数据)
      收益状态 = 当前状态
      收益增益 = 增益数据
    }
    const 评分列表: { 装备: 装备属性信息模型; 评分: number }[] = []
    for (const 装备 of 全部候选) {
      await 配置.让出主线程()
      if (配置.是否取消?.()) return []
      const 部位值 = 生成装备表单值(
        装备,
        当前状态[部位索引],
        部位索引,
        配置.默认镶嵌宝石等级,
        配置.沿用当前精炼镶嵌,
      )
      const 签名 = JSON.stringify([
        部位索引,
        部位值.id,
        部位值.当前精炼等级,
        部位值.附魔,
        部位值.镶嵌孔数组?.map((孔) => 孔.镶嵌宝石等级),
      ])
      let 属性 = 装备属性缓存.get(签名)
      if (!属性) {
        属性 = 根据表单选项获取装备信息({ [部位索引]: 部位值 }).装备基础属性
        装备属性缓存.set(签名, 属性)
      }
      let 评分 = Object.keys(属性字段).reduce((总分, 名称) => {
        const 字段 = 属性字段[名称]
        return 总分 + 属性收益[名称] * ((属性[字段] || 0) - (默认属性[字段] || 0))
      }, 0)
      评分 +=
        (属性收益.武伤 *
          (属性.武器伤害_最小值 +
            属性.武器伤害_最大值 -
            默认属性.武器伤害_最小值 -
            默认属性.武器伤害_最大值)) /
        2
      评分列表.push({ 装备, 评分 })
    }
    评分列表.sort((a, b) => b.评分 - a.评分)
    const 保留数量 = Math.max(1, Math.ceil(评分列表.length * 0.1))
    return 评分列表
      .filter(({ 装备 }, 索引) => 索引 < 保留数量 || !!装备.装备特效)
      .map(({ 装备 }) => 装备)
  }
}
