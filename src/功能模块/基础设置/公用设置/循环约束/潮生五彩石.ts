import { 属性类型 } from '@/@types/属性'
import { 五彩石数据类型 } from '@/@types/五彩石'
import { 循环数据 } from '@/@types/循环'

export const 五彩石满足潮生要求 = (五彩石: 五彩石数据类型 | undefined, 循环?: 循环数据) =>
  !循环?.额外配置信息?.潮生每秒回复 ||
  !!五彩石?.装备增益.some((增益) => 增益.增益类型 === 属性类型.每秒内力恢复)

export const 获取潮生要求提示 = () =>
  '当前循环要求潮生五彩石，请更换五彩石或使用对应条件重新生成循环。'
