// 斩刀·悟：10秒调息，释放后降低阵云结晦·悟调息1秒；
// 绝篇(16997)命中时为目标添加1层[流血]；
// 秘章(16996)命中眩晕3秒，下个刀系招式返还调息（清绝刀CD，斩绝绝）
class 斩刀悟 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)

    this.初始化技能运行数据()
  }

  命中() {
    // 刀系招式命中消耗1层[血怒·悟]（碎甲·悟下不消耗）
    this.消耗血怒一层()
    // 秘籍「命中附加流血」(16997)：命中时为目标添加1层[流血]
    if (this.是否选中秘籍('斩刀·悟', '【绝篇】添加流血')) {
      this.模拟循环.技能类实例集合?.流血?.获得和刷新流血?.()
    }
    // 降低阵云结晦·悟调息1秒（基础机制）
    this.降低阵云调息()
    // 天下宏愿特效：对阵招式几率降低阵云调息
    this.尝试橙武降低阵云调息(16)
    // 秘籍「命中眩晕并返还刀系调息」(16996)：命中眩晕3秒，并标记——
    // 下次刀系招式施放时立即返还其调息时间（斩绝绝：斩刀后重置绝刀）
    this.斩刀秘章命中标记()
  }

  造成伤害() {
    this.触发伤害行为('斩刀·悟', 1, this.获取橙武额外增伤(true))
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
      底部标识: this.技能释放时血怒 || undefined,
    }
  }
}

export default 斩刀悟
