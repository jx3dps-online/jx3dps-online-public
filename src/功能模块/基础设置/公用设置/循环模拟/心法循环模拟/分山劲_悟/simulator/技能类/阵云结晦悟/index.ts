import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 阵云结晦·悟 壹式：命中后自身伤害提高15%（持续10秒），施展后替换为贰式；
// 施放即获得3层[血怒·悟]（技能102366 施放3次血怒子技能102251）
class 阵云结晦悟 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)

    this.初始化技能运行数据()
  }

  命中() {
    // 命中目标使自身伤害提高15%，持续10秒（70161 Lv15=154/1024，技能102366；先添加，BUFF栏里显示在二段需求标记之前）
    this.模拟循环.添加buff?.({ 名称: '阵云增伤', 对象: '自身', 新增层数: 1 })
    // 天下宏愿特效：释放阵云结晦·悟后自身伤害提高15%，持续30秒
    if (this.模拟循环?.大橙武模拟) {
      this.模拟循环.添加buff?.({ 名称: '橙武·阵云增伤', 对象: '自身', 新增层数: 1 })
    }
    // 施放获得3层[血怒·悟]
    this.模拟循环.添加buff?.({ 名称: '血怒·悟', 对象: '自身', 新增层数: 3 })
    // 释放一段后获得无界阵云结晦二段需求(71508)，持续10秒，替换为贰式
    this.模拟循环.添加buff?.({ 名称: '阵云结晦贰式标记', 对象: '自身', 新增层数: 1 })
  }

  造成伤害() {
    this.触发伤害行为('阵云结晦·悟')
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
    }
  }
}

export default 阵云结晦悟
export const 阵云结晦悟类型 = typeof 阵云结晦悟
