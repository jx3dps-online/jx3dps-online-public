import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 盾刀·悟·叁式：叁式标记存在时才可释放
class 盾刀悟叁式 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  释放() {
    const 有标记 = this.模拟循环.当前自身buff列表?.['盾刀叁式标记']?.当前层数
    if (!有标记) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.BUFF错误,
      }
    }
    return { 可以释放: true }
  }

  命中() {
    // 消耗叁式标记
    this.模拟循环.卸除buff?.({ 名称: '盾刀叁式标记', 对象: '自身', 卸除层数: 1 })
    // 秘籍「命中流血目标伤害提高20%」(16987)：叁式命中时施放流血（CastSkill 101171）
    if (this.是否选中秘籍('盾刀·悟', '【绝篇】添加流血')) {
      this.模拟循环.技能类实例集合?.流血?.获得和刷新流血?.()
    }
  }

  造成伤害() {
    // 秘籍「伤害提高30%」由计算层按勾选常驻生效；
    // 秘籍「【绝篇】添加流血」(16987)为条件型：命中自身[流血]目标时本击提高20%
    const 有流血 =
      (this.模拟循环.技能类实例集合?.流血?.当前层数?.() || 0) > 0 &&
      this.是否选中秘籍('盾刀·悟', '【绝篇】添加流血')
    this.触发伤害行为('盾刀·悟·叁式', 1, [
      ...(有流血 ? ['【绝篇】添加流血'] : []),
      ...this.获取橙武额外增伤(),
    ])
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
    }
  }
}

export default 盾刀悟叁式
export const 盾刀悟叁式类型 = typeof 盾刀悟叁式
