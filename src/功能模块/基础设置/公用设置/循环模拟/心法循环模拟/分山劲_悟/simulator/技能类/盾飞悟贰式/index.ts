import { ERROR_ACTION } from '../../utils'
import 技能统一类 from '../../通用类/技能统一类'

// 盾飞·悟·贰式（盾回）：提前收回盾牌，切回擎盾；
// 盾飞持续10秒后也会自动收盾（参考旗舰端盾飞/盾回写法）
class 盾飞悟贰式 extends 技能统一类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  释放() {
    const 有盾飞 = this.模拟循环?.当前自身buff列表?.['盾飞·悟']?.当前层数
    if (!有盾飞) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.BUFF错误,
      }
    }
    return { 可以释放: true }
  }

  命中() {
    // 降低阵云结晦·悟调息1秒（基础机制）
    this.降低阵云调息()
    // 天下宏愿特效：盾回亦为对阵招式，释放后几率降低阵云调息（配方17451 tag64）
    this.尝试橙武降低阵云调息(16)
    // 收盾：卸除盾飞·悟与擎刀标记，切回擎盾
    this.模拟循环?.技能类实例集合?.['盾飞·悟']?.收盾?.()
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀', '盾飞·悟']),
    }
  }
}

export default 盾飞悟贰式
export const 盾飞悟贰式类型 = typeof 盾飞悟贰式
