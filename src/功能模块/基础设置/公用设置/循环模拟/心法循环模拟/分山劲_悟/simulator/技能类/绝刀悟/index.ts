import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 绝刀·悟：8秒调息，释放后降低阵云结晦·悟调息1秒；
// 绝篇(17001)命中流血目标时按流血层数触发绝刀·破
class 绝刀悟 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)

    this.初始化技能运行数据()
  }

  命中() {
    // 斩刀秘章：返还本次调息时间
    this.尝试斩刀秘章返还()
    // 刀系招式命中消耗1层[血怒·悟]（碎甲·悟下不消耗）
    this.消耗血怒一层()
    // 降低阵云结晦·悟调息1秒（基础机制）
    this.降低阵云调息()
    // 天下宏愿特效：对阵招式几率降低阵云调息
    this.尝试橙武降低阵云调息(16)
  }

  造成伤害() {
    // 斩杀判定：目标五十血以下选项直接生效；
    // 模拟斩杀时间选项按隐藏BUFF「斩杀时间预估」判断——BUFF存在为非斩杀期，消失即进入斩杀
    // const 是否斩杀 =
    //   this.模拟循环.目标五十血以下 ||
    const 是否斩杀 =
      this.模拟循环.斩杀模拟 && !this.模拟循环.当前自身buff列表?.['斩杀时间预估']?.当前层数
    const 斩杀增益: string[] = []
    if (是否斩杀) {
      // 基础斩杀：目标50%血以下绝刀伤害提高50%（游戏脚本 绝刀/铁骨衣_绝刀 对50%血目标无条件 +512，非秘籍效果）
      斩杀增益.push('绝刀基础斩杀')
      // 秘籍「【秘章】额外斩杀」(17000)：勾选后再提高50%（普通绝刀.lua 判 IsSkillRecipeActive(17000) 再 +512）
      if (this.是否选中秘籍('绝刀·悟', '【秘章】额外斩杀')) {
        斩杀增益.push('【秘章】额外斩杀')
      }
    }
    this.触发伤害行为('绝刀·悟', 1, [...斩杀增益, ...this.获取橙武额外增伤(true)])

    // 秘籍「按流血层数追击绝刀·破」(17001)：按[流血]层数触发绝刀·破
    if (this.是否选中秘籍('绝刀·悟', '【绝篇】额外伤害')) {
      const 流血层数 = this.模拟循环.技能类实例集合?.流血?.当前层数?.() || 0
      if (流血层数 > 0) {
        this.触发伤害行为('绝刀·破', 流血层数)
      }
    }
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
      底部标识: this.技能释放时血怒 || undefined,
    }
  }
}

export default 绝刀悟
export const 绝刀悟类型 = typeof 绝刀悟
