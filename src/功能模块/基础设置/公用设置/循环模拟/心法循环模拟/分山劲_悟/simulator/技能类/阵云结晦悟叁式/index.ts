import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 阵云结晦·悟 叁式：三段链收尾（血怒·悟已在壹式施放时获得3层，技能102366）
class 阵云结晦悟叁式 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  释放() {
    const 有标记 = this.模拟循环.当前自身buff列表?.['阵云结晦叁式标记']?.当前层数
    if (!有标记) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.BUFF错误,
      }
    }
    return { 可以释放: true }
  }

  命中() {
    // 命中目标使自身伤害提高20%，持续15秒（70161 Lv20=205/1024，与壹/贰式异源实例共存，技能102368）
    this.模拟循环.添加buff?.({ 名称: '阵云增伤·叁', 对象: '自身', 新增层数: 1 })
    // 天下宏愿特效：释放阵云结晦·悟·叁式后自身伤害提高15%，持续30秒
    if (this.模拟循环?.大橙武模拟) {
      this.模拟循环.添加buff?.({ 名称: '橙武·阵云增伤', 对象: '自身', 新增层数: 1 })
    }
    // 释放三段：删除无界阵云结晦三段需求(71509)
    this.模拟循环.卸除buff?.({ 名称: '阵云结晦叁式标记', 对象: '自身', 卸除层数: 1 })
    // 命中附加施放流血（CastSkill 101171）：非玩家目标1次，血狱·悟(101245)下共3次
    this.模拟循环.技能类实例集合?.流血?.获得和刷新流血?.()
    if (this.模拟循环?.校验奇穴是否存在?.('血狱·悟')) {
      this.模拟循环.技能类实例集合?.流血?.获得和刷新流血?.()
      this.模拟循环.技能类实例集合?.流血?.获得和刷新流血?.()
    }
  }

  造成伤害() {
    this.触发伤害行为('阵云结晦·悟·叁式')
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
    }
  }
}

export default 阵云结晦悟叁式
export const 阵云结晦悟叁式类型 = typeof 阵云结晦悟叁式
