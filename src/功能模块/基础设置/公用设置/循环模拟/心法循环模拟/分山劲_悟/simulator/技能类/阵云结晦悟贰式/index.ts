import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 阵云结晦·悟 贰式：贰式标记存在时才可释放，施展后替换为叁式
class 阵云结晦悟贰式 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  释放() {
    const 有标记 = this.模拟循环.当前自身buff列表?.['阵云结晦贰式标记']?.当前层数
    if (!有标记) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.BUFF错误,
      }
    }
    return { 可以释放: true }
  }

  命中() {
    // 命中目标使自身伤害提高15%，持续10秒（70161 Lv15，与壹式异源实例共存，技能102367）
    this.模拟循环.添加buff?.({ 名称: '阵云增伤·贰', 对象: '自身', 新增层数: 1 })
    // 天下宏愿特效：释放阵云结晦·悟·贰式后自身伤害提高15%，持续30秒
    if (this.模拟循环?.大橙武模拟) {
      this.模拟循环.添加buff?.({ 名称: '橙武·阵云增伤', 对象: '自身', 新增层数: 1 })
    }
    // 释放二段：删除无界阵云结晦二段需求(71508)，获得无界阵云结晦三段需求(71509)
    this.模拟循环.卸除buff?.({ 名称: '阵云结晦贰式标记', 对象: '自身', 卸除层数: 1 })
    this.模拟循环.添加buff?.({ 名称: '阵云结晦叁式标记', 对象: '自身', 新增层数: 1 })
  }

  造成伤害() {
    this.触发伤害行为('阵云结晦·悟·贰式')
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
    }
  }
}

export default 阵云结晦悟贰式
export const 阵云结晦悟贰式类型 = typeof 阵云结晦悟贰式
