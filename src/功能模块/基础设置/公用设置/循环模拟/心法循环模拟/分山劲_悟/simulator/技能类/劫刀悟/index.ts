import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 劫刀·悟：擎刀姿态下替换盾刀·悟；目标每层[流血]伤害提高4%；
// 盾飞绝篇(17254)对盾阵范围内目标伤害提高100%
// （劫刀不消耗[血怒·悟]：技能描述与游戏脚本均无消耗逻辑，勿按刀系招式类推）
class 劫刀悟 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  释放() {
    // 仅盾飞·悟持续期间可释放劫刀
    if (!this.模拟循环?.当前自身buff列表?.['盾飞·悟']?.当前层数) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.无盾飞,
      }
    }
    return { 可以释放: true }
  }

  造成伤害() {
    // 盾飞秘籍「调息增加5秒并清除刀系调息」(17254)勾选时：对盾阵范围内目标伤害提高100%
    const 盾飞绝篇增益 = this.是否选中秘籍('盾飞·悟', '【绝篇】重置调息')
      ? ['盾飞绝篇劫刀增伤']
      : []
    this.触发伤害行为('劫刀·悟', 1, ['劫刀流血增伤', ...盾飞绝篇增益, ...this.获取橙武额外增伤()])
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
    }
  }
}

export default 劫刀悟
export const 劫刀悟类型 = typeof 劫刀悟
