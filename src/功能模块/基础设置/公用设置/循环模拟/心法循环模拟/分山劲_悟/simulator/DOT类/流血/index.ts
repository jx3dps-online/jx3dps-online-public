import 通用DOT类 from '../../通用类/通用DOT类'

// 流血：每2秒造成1次伤害，持续16秒，血狱·悟后最多叠加3层
class 流血 extends 通用DOT类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  获得和刷新流血() {
    const 当前最后一跳流血数据 =
      this?.DOT运行数据?.待生效数据?.[this?.DOT运行数据?.待生效数据?.length - 1] || {}
    const 当前流血层数 = 当前最后一跳流血数据?.当前层数 || 0
    const 流血最大层数 = this?.模拟循环?.Buff和Dot数据?.流血?.最大层数 || 1
    const 添加流血层数 = 1
    const 新流血层数 = Math.min(当前流血层数 + 添加流血层数, 流血最大层数)
    const 数据 = this.获取当前DOT数据('流血')
    this.更新待生效数据(新流血层数, 数据)
    // 陷阵·悟(71095，奇穴101248)：施加流血时获得1层（游戏脚本 移动端_苍云通用_流血.lua 判定
    // GetSkillLevel(101248)==1 后 AddBuff 71095），最多2层，持续240帧
    if (this.模拟循环.校验奇穴是否存在?.('陷阵·悟')) {
      this.模拟循环.添加buff?.({ 名称: '陷阵·悟', 对象: '自身', 新增层数: 1 })
    }
  }

  结算流血伤害() {
    const 待生效数据 = this.结算并更新运行数据()

    待生效数据.forEach((数据) => {
      const 层数 = 数据.当前层数 || 1
      const 生效时间 = 数据.生效时间 || 0
      if (生效时间) {
        // 按当前层数选择对应的伤害结算（层数越多单跳伤害计算次数越多）
        const 层数名称 = ['一', '二', '三'][Math.min(层数, 3) - 1] || '一'
        this.触发伤害行为(`流血·悟·${层数名称}`, 1, [], 生效时间, true)
      }
    })
  }
}

export default 流血

export const 流血DOT类型 = typeof 流血
