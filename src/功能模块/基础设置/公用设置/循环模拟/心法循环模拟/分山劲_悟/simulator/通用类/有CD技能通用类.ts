import { 技能运行数据类型 } from '../type'
import 技能统一类 from './技能统一类'

class 有CD技能通用类 extends 技能统一类 {
  技能运行数据: 技能运行数据类型 = {
    待充能时间点: [],
  }

  constructor(模拟循环) {
    super(模拟循环)
  }

  初始化技能运行数据() {
    this.技能运行数据.待充能时间点 = []
  }

  // 减少13秒
  减少调息时间(减少帧数) {
    const 待充能时间点 = this.技能运行数据.待充能时间点
    if (待充能时间点?.length) {
      const 新待充能时间点 = 待充能时间点
        .map((item) => {
          return item - 减少帧数
        })
        ?.filter((item) => {
          return item > (this.模拟循环.当前时间 || 0)
        })
      this.更新技能运行数据({ 待充能时间点: 新待充能时间点 })
    }
  }

  // 斩刀秘章：斩刀·悟命中后标记，下次刀系招式施放时返还其调息时间
  斩刀秘章命中标记() {
    if (this.是否选中秘籍('斩刀·悟', '【秘章】返还调息')) {
      this.模拟循环.添加buff?.({ 名称: '绝返·悟', 对象: '自身', 新增层数: 1 })
    }
  }

  尝试斩刀秘章返还() {
    if ((this.模拟循环?.当前自身buff列表?.['绝返·悟']?.当前层数 || 0) > 0) {
      this.模拟循环.卸除buff?.({ 名称: '绝返·悟', 对象: '自身', 卸除层数: 1 })
      this.重置调息时间()
      return true
    }
    return false
  }

  重置调息时间() {
    this.更新技能运行数据({ 待充能时间点: [] })
  }

  更新技能运行数据(新数据) {
    this.技能运行数据 = {
      ...this.技能运行数据,
      ...新数据,
    }
  }
}

export default 有CD技能通用类
