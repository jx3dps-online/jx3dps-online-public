import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 闪刀·悟：施展后替换为贰式，降低阵云结晦·悟调息1秒；
// 绝篇(16999)使自身伤害提高10%、无双等级提高15%，持续15秒
class 闪刀悟 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)

    this.初始化技能运行数据()
  }

  // 闪刀绝篇无双的4个独立槽位（多实例：每次施放新增一个，各自倒计时，与原始Buff数据、通用增益名一一对应）
  static 无双槽位列表 = ['闪刀无双', '闪刀无双·2', '闪刀无双·3', '闪刀无双·4']

  命中() {
    // 斩刀秘章：返还本次调息时间
    this.尝试斩刀秘章返还()
    // 刀系招式命中消耗1层[血怒·悟]（碎甲·悟下不消耗）
    this.消耗血怒一层()
    // 替换为贰式
    this.模拟循环.添加buff?.({ 名称: '闪刀贰式标记', 对象: '自身', 新增层数: 1 })
    // 秘籍「【绝篇】增伤无双」(16999)：
    // 伤害提高10%（70161 Lv10）为重刷语义——重复施放只刷新持续时间
    // 无双等级提高15%（71624 Lv15）为多实例语义——每次施放新增一个独立实例，4个槽位全满时新的获得无效
    if (this.是否选中秘籍('闪刀·悟', '【绝篇】增伤无双')) {
      this.模拟循环.添加buff?.({ 名称: '闪刀增伤', 对象: '自身', 新增层数: 1 })
      const 空闲槽位 = 闪刀悟.无双槽位列表.find(
        (名称) => !this.模拟循环?.当前自身buff列表?.[名称]?.当前层数,
      )
      if (空闲槽位) {
        this.模拟循环.添加buff?.({ 名称: 空闲槽位, 对象: '自身', 新增层数: 1 })
      }
    }
    // 降低阵云结晦·悟调息1秒（基础机制）
    this.降低阵云调息()
    // 天下宏愿特效：对阵招式几率降低阵云调息
    this.尝试橙武降低阵云调息(16)
  }

  造成伤害() {
    this.触发伤害行为('闪刀·悟', 1, this.获取橙武额外增伤(true))
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀']),
    }
  }
}

export default 闪刀悟
export const 闪刀悟类型 = typeof 闪刀悟
