import { 获取实际技能数据 } from '../../../通用/通用函数'
import 循环主类类型 from '../main'
import { 循环基础技能数据类型, 技能释放记录结果 } from '../type'

class 技能统一类 {
  模拟循环: Partial<循环主类类型> = {}
  本次释放记录: 技能释放记录结果 = {}
  本次释放延迟: number | 'GCD' = 0
  技能释放时血怒 = 0

  constructor(模拟循环) {
    this.模拟循环 = 模拟循环
    return
  }

  获取实际GCD(当前技能?: 循环基础技能数据类型) {
    if (!当前技能) {
      return 0
    }
    const 应校验GCD组: string[] = 当前技能?.检测GCD组 || []
    let 最大GCD = 0
    应校验GCD组.forEach((GCD组) => {
      let 实际GCD = 0
      if (GCD组 === '自身') {
        实际GCD = this.模拟循环.GCD组?.[当前技能?.技能名称]
      } else {
        实际GCD = this.模拟循环.GCD组?.[GCD组]
      }
      if (实际GCD > 最大GCD) {
        最大GCD = 实际GCD
      }
    })
    return 最大GCD
  }

  检查GCD(索引, 当前技能?: 循环基础技能数据类型) {
    const 后一个技能 = this.模拟循环?.测试循环?.[索引 + 1]
    let GCD = this.获取实际GCD(当前技能)
    let 等待GCD = 0
    if (this.本次释放延迟) {
      if (this.本次释放延迟 === 'GCD' && 后一个技能) {
        const 下一个技能实际数据: any = 获取实际技能数据(后一个技能)
        const 下一个技能 = this?.模拟循环?.技能基础数据?.find(
          (item) => item?.技能名称 === 下一个技能实际数据?.实际技能名称,
        )
        if (下一个技能 && (下一个技能?.检测GCD组 || 下一个技能?.技能GCD组)) {
          if (
            (下一个技能?.检测GCD组?.length || 下一个技能?.技能GCD组) &&
            下一个技能实际数据?.额外信息?.延迟 !== 'GCD'
          ) {
            const 技能实例 = this?.模拟循环?.技能类实例集合?.[下一个技能?.技能名称]
            const 后一个技能GCD = this.模拟循环?.检查GCD?.(下一个技能, 技能实例, 索引 + 1) || 0
            等待GCD = 后一个技能GCD
          } else {
            const 再下一个技能实际名称 = 获取实际技能数据(
              this.模拟循环?.测试循环?.[索引 + 2],
            )?.实际技能名称
            const 再下一个技能 = this?.模拟循环?.技能基础数据?.find(
              (item) => item?.技能名称 === 再下一个技能实际名称,
            )
            if (再下一个技能 && (再下一个技能?.检测GCD组?.length || 再下一个技能?.技能GCD组)) {
              const 技能实例 = this?.模拟循环?.技能类实例集合?.[再下一个技能?.技能名称]
              const 后一个技能GCD = this.模拟循环?.检查GCD?.(再下一个技能, 技能实例, 索引 + 2) || 0
              等待GCD = 后一个技能GCD
            }
          }
        }
      } else {
        等待GCD = Number(this.本次释放延迟)
      }
      if (等待GCD) {
        GCD = Math.max(等待GCD, GCD)
      }
    }

    this.本次释放延迟 = 0
    return GCD
  }

  统一初始化(额外信息) {
    if (额外信息?.延迟) {
      this.本次释放延迟 = 额外信息?.延迟
    }
    // 重置释放记录
    this.本次释放记录 = {}
    this.技能释放时血怒 = this.模拟循环?.当前自身buff列表?.['血怒·悟']?.当前层数 || 0
  }

  触发伤害行为(
    伤害名称,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    触发伤害时间: number | undefined = undefined,
    DOT伤害 = false,
    技能等级 = 1,
  ) {
    this.模拟循环.技能造成伤害?.(伤害名称, 伤害次数, 额外增益列表, 触发伤害时间, DOT伤害, 技能等级)
  }

  // 判断某技能的某本秘籍是否被勾选（秘籍数据来自秘籍设置抽屉，键为技能名、值为增益名列表）
  是否选中秘籍(技能名称: string, 秘籍名称: string) {
    return this.模拟循环.秘籍?.[技能名称]?.includes(秘籍名称) || false
  }

  // 刀系招式命中消耗1层[血怒·悟]并回复2%气血（回复不模拟）。
  // 碎甲·悟(101249)点出后刀系不再消耗（游戏脚本 消耗血怒.lua 的 101249 判定），定版必点碎甲故常态不触发
  消耗血怒一层() {
    if (this.模拟循环?.校验奇穴是否存在?.('碎甲·悟')) {
      return
    }
    if ((this.模拟循环?.当前自身buff列表?.['血怒·悟']?.当前层数 || 0) > 0) {
      this.模拟循环.卸除buff?.({ 名称: '血怒·悟', 对象: '自身', 卸除层数: 1 })
    }
  }

  // 绝技降调息（基础机制，无条件生效）：斩刀·悟/绝刀·悟/闪刀·悟（一段）/盾飞·悟·贰式（盾回）
  // 释放后降低绝技（阵云结晦·悟）调息1秒。按两份实测战斗记录核对：60秒基础调息下，
  // 紫武每轮阵云间隔约扣18~19秒（实测均值41.2秒）、橙武约扣14秒（实测均值46.3秒），
  // 与该技能集合的施放频次严丝合缝；血刀/劫刀/盾刀不在降低集合内
  降低阵云调息(帧数 = 16) {
    this.模拟循环?.技能类实例集合?.['阵云结晦·悟']?.减少调息时间?.(帧数)
  }

  // 无界橙武特效：释放对阵招式后一定几率使绝技（阵云结晦·悟）调息时间降低1秒。
  // 几率来源：装备效果脚本 移动端_装备效果_释放对阵招式降低绝技调息（hd 20260907 数据核对）
  // `Random(1, 10000) < 3000 --暂定30%`，官方注释即30%；配方行 17451（tag64=对阵触发）
  static 橙武降CD几率 = 0.3

  // 仅在大橙武模拟开启时生效。两种实现方式（橙武降CD方式，见 main.ts SimulatorCycleProps）：
  // 期望（默认）：每次施放固定降低 帧数×几率（16×0.3=4.8帧=0.3秒），无随机、同循环每次模拟结果一致
  // 概率：按游戏内实现，阵云在调息中时每次施放30%几率降低1秒；随机值按「固定种子+循环位置」
  //   哈希逐位确定（与施放顺序无关）：拖动/编辑某位置技能只会重新计算该位置及之后
  // 阵云不在调息中时降低无意义：不掷骰、不折算，判定只影响后续的阵云状态
  static 橙武随机种子 = 987654321

  尝试橙武降低阵云调息(帧数 = 16) {
    if (!this.模拟循环?.大橙武模拟) {
      return
    }
    const 阵云实例 = this.模拟循环?.技能类实例集合?.['阵云结晦·悟']
    const 阵云在调息中 =
      (阵云实例?.技能运行数据?.待充能时间点 || []).some(
        (帧) => 帧 > (this.模拟循环.当前时间 || 0),
      ) || false
    if (!阵云在调息中) {
      return
    }
    if (this.模拟循环?.橙武降CD方式 === '期望') {
      阵云实例?.减少调息时间?.(帧数 * 技能统一类.橙武降CD几率)
      return
    }
    // 概率：按位置哈希取随机值（Math.imul 32位整数运算精确），位置不变则判定结果不变
    let 哈希 =
      (技能统一类.橙武随机种子 ^ Math.imul((this.模拟循环?.当前循环位置 ?? 0) + 1, 2654435761)) >>>
      0
    哈希 = Math.imul(哈希 ^ (哈希 >>> 15), 2246822519) >>> 0
    哈希 = Math.imul(哈希 ^ (哈希 >>> 13), 3266489917) >>> 0
    哈希 = (哈希 ^ (哈希 >>> 16)) >>> 0
    if (哈希 / 4294967296 < 技能统一类.橙武降CD几率) {
      阵云实例?.减少调息时间?.(帧数)
    }
  }

  // 无界橙武增伤：傍身招式（盾刀/劫刀/盾击/隐刀）伤害+2%（配方17447 DamageAddPercent=21/1024，
  // 表驱动无几率）；对阵招式+2% 为用户提供的武器描述（脚本无此行）。大橙武模拟开启时挂载，
  // 计算层按 依赖装备增益「大橙武特效」门控
  获取橙武额外增伤(对阵 = false) {
    if (!this.模拟循环?.大橙武模拟) {
      return []
    }
    return [对阵 ? '橙武·对阵增伤' : '橙武·盾刀增伤']
  }

  获取技能释放记录结果() {
    return {
      ...this.本次释放记录,
    }
  }

  获取当前重要buff列表(技能依赖自身buff列表: string[] = [], 技能依赖目标buff列表: string[] = []) {
    const 重要buff列表: string[] = []
    // 重点BUFF公共项：闪刀无双（多实例槽位）与阵云增伤（壹/贰/叁式异源实例），
    // 与各技能自带依赖项合并去重，仅实际存留的条目会展示在技能悬停列表里
    const 合并列表 = [
      ...new Set([
        '闪刀无双',
        '闪刀无双·2',
        '闪刀无双·3',
        '闪刀无双·4',
        '阵云增伤',
        '阵云增伤·贰',
        '阵云增伤·叁',
        ...技能依赖自身buff列表,
      ]),
    ]
    合并列表.forEach((buff) => {
      if (this.模拟循环.当前自身buff列表?.[buff]?.当前层数) {
        重要buff列表.push(buff)
      }
    })
    技能依赖目标buff列表.forEach((buff) => {
      if (this.模拟循环.当前目标buff列表?.[buff]?.当前层数) {
        重要buff列表.push(buff)
      }
    })
    return 重要buff列表 || []
  }
}

export default 技能统一类
