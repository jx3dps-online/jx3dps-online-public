import { 每秒郭氏帧 } from '@/数据/常量'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

// 盾飞·悟：获得1层[血怒·悟]与[擎刀]（持续10秒，即盾阵存在时间），
// 盾阵每秒造成伤害；10秒后自动收盾切回擎盾；
// 绝篇(17254)：调息时间增加5秒（simulator/utils按勾选处理），清除刀系调息时间；
// 秘章(17253)：盾飞招式（盾阵）伤害提高35%
class 盾飞悟 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)

    this.初始化技能运行数据()
  }

  释放() {
    // 获得擎刀增益（持续10秒，与盾飞·悟标记同步）
    this.模拟循环.添加buff?.({ 名称: '擎刀', 对象: '自身', 新增层数: 1 })
    this.模拟循环.添加buff?.({ 名称: '盾飞·悟', 对象: '自身', 新增层数: 1 })
    // 获得1层[血怒·悟]
    this.模拟循环.添加buff?.({ 名称: '血怒·悟', 对象: '自身', 新增层数: 1 })
    // 天下宏愿特效：释放对阵招式后几率使阵云结晦·悟调息降低1秒
    this.尝试橙武降低阵云调息(16)
    // 切换擎刀后傍身招式替换为劫刀·悟，清除未完成的盾刀连段标记（同一键位互斥）
    ;['盾刀贰式标记', '盾刀叁式标记'].forEach((标记) => {
      if (this.模拟循环?.当前自身buff列表?.[标记]?.当前层数) {
        this.模拟循环.卸除buff?.({ 名称: 标记, 对象: '自身', 卸除层数: 1 })
      }
    })
    // 秘籍「调息增加5秒并清除刀系调息」(17254)：清除刀系招式调息时间（CD增加5秒已在simulator/utils按勾选处理）
    if (this.是否选中秘籍('盾飞·悟', '【绝篇】重置调息')) {
      ;['斩刀·悟', '绝刀·悟', '闪刀·悟'].forEach((技能名称) => {
        this.模拟循环?.技能类实例集合?.[技能名称]?.重置调息时间?.()
      })
    }
    // 盾飞持续10秒后自动收盾（技能替换为盾飞·悟·贰式）
    const 盾飞结束 = (this.模拟循环.当前时间 || 0) + 每秒郭氏帧 * 10
    this.模拟循环.添加待生效事件队列?.([
      {
        事件时间: 盾飞结束,
        事件名称: '盾飞收盾',
        事件备注: { 技能名称: '盾飞·悟' },
      },
    ])
    this.保存释放记录()
  }

  // 收盾：先结算盾飞·悟·结算伤害（手动盾回与10秒自动收盾都会触发），再卸除标记切回擎盾
  收盾() {
    if (!this.模拟循环?.当前自身buff列表?.['盾飞·悟']?.当前层数) {
      return
    }
    this.触发伤害行为('盾飞·悟·结算', 1)
    this.模拟循环.卸除buff?.({ 名称: '盾飞·悟', 对象: '自身', 卸除层数: 1 })
    if (this.模拟循环?.当前自身buff列表?.['擎刀']?.当前层数) {
      this.模拟循环.卸除buff?.({ 名称: '擎刀', 对象: '自身', 卸除层数: 1 })
    }
  }

  // 10秒到期自动收盾
  强制收盾() {
    this.收盾()
  }

  盾飞持续伤害() {
    const 有盾飞 = this.模拟循环?.当前自身buff列表?.['盾飞·悟']?.当前层数
    if (!有盾飞) {
      return
    }
    // 盾阵每秒对范围内目标造成伤害；秘籍「伤害提高35%」由计算层按勾选常驻生效
    // DOT伤害=true：神兵·无双气劲等命中叠层效果不吃盾阵每跳
    this.触发伤害行为('盾阵(DOT)', 1, [], undefined, true)
    const 当前时间 = this.模拟循环?.当前时间 || 0
    const 盾飞刷新时间 = this.模拟循环?.当前自身buff列表?.['盾飞·悟']?.刷新时间 || 0
    const 盾飞持续时间 = this.模拟循环?.当前自身buff列表?.['盾飞·悟']?.最大持续时间 || 0
    const 盾飞剩余时间 = 盾飞刷新时间 + 盾飞持续时间 - 当前时间

    if (盾飞剩余时间 > 每秒郭氏帧) {
      const 盾飞持续伤害 = 当前时间 + 每秒郭氏帧
      this.模拟循环?.添加待生效事件队列?.([
        {
          事件时间: 盾飞持续伤害,
          事件名称: '盾飞持续伤害',
        },
      ])
    }
  }

  释放后() {
    // 立即造成一次盾阵伤害，后续每秒一次
    this.盾飞持续伤害()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒·悟', '擎刀', '盾飞·悟']),
    }
  }
}

export default 盾飞悟
export const 盾飞悟类型 = typeof 盾飞悟
