import { 获取实际技能数据 } from '../../../通用/通用函数'
import 循环主类类型 from '../main'
import { 循环基础技能数据类型, 技能释放记录结果 } from '../type'

class 技能统一类 {
  模拟循环: 循环主类类型
  本次释放记录: 技能释放记录结果 = {}
  本次释放延迟: number | 'GCD' = 0
  本次消耗满灵?: '日' | '月'
  本次光明相生效 = false
  技能等级 = 1
  constructor(模拟循环) {
    this.模拟循环 = 模拟循环
  }
  检查GCD(索引, 当前技能?: 循环基础技能数据类型) {
    const GCD组 = 当前技能?.技能GCD组 === '自身' ? 当前技能?.技能名称 : 当前技能?.技能GCD组 || ''
    let GCD = this.模拟循环?.GCD组?.[GCD组] || 0
    let 等待GCD = 0

    if (this.本次释放延迟) {
      if (GCD组 === '公共' && typeof this.本次释放延迟 === 'number') {
        GCD = GCD + this.本次释放延迟
      } else if (this.本次释放延迟 === 'GCD') {
        等待GCD = this.查找下一个有效技能GCD(索引)
      } else {
        等待GCD = Number(this.本次释放延迟)
      }

      if (等待GCD) {
        GCD = Math.max(等待GCD, GCD)
      }
    }

    this.本次释放延迟 = 0
    return GCD
  }

  /**
   * 从当前索引往后扫描（最多5步），找到第一个满足条件的技能并获取其GCD。
   * 用于处理需要推进时间到后续技能 GCD 前释放的场景。
   * 跳过的技能：不存在、额外延迟为 'GCD'、无GCD组且无检测GCD组。
   */
  查找下一个有效技能GCD(当前索引: number): number {
    const 最大向前步数 = 5

    for (let 步数 = 1; 步数 <= 最大向前步数; 步数++) {
      const 目标技能 = this.模拟循环?.测试循环?.[当前索引 + 步数]
      if (!目标技能) continue

      const 目标技能实际数据: any = 获取实际技能数据(目标技能)
      // 延迟为 'GCD' 的技能本身也会处理 GCD 推进，跳过
      if (目标技能实际数据?.额外信息?.延迟 === 'GCD') continue

      const 目标基础技能 = this?.模拟循环?.技能基础数据?.find(
        (item) => item?.技能名称 === 目标技能实际数据?.实际技能名称,
      )

      if (目标基础技能?.技能GCD组 === '自身') continue

      if (目标基础技能 && 目标基础技能?.技能GCD组) {
        const 技能实例 = this?.模拟循环?.技能类实例集合?.[目标基础技能?.技能名称]
        return this.模拟循环?.检查GCD?.(目标基础技能, 技能实例, 当前索引 + 步数) || 0
      }
    }

    return 0
  }

  释放前初始化(额外信息) {
    this.本次释放延迟 = 额外信息?.延迟 || 0
    this.本次释放记录 = {}
    this.本次消耗满灵 = undefined
    this.本次光明相生效 = false
  }
  触发伤害行为(
    伤害名称,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    触发伤害时间: number | undefined = undefined,
    DOT伤害 = false,
    技能等级 = this.技能等级,
  ) {
    this.模拟循环.技能造成伤害(伤害名称, 伤害次数, 额外增益列表, 触发伤害时间, DOT伤害, 技能等级)
  }
  检查满灵() {
    const 状态 = this.模拟循环.角色状态信息
    if (状态.满灵) return
    if (状态.月魂 >= 100) 状态.满灵 = '月'
    else if (状态.日灵 >= 100) 状态.满灵 = '日'
  }
  回复灵力(日灵: number, 月魂: number, 来源: string, 强制 = false) {
    const 状态 = this.模拟循环.角色状态信息
    if (状态.满灵 && !强制) return
    状态.日灵 = Math.min(100, 状态.日灵 + 日灵)
    状态.月魂 = Math.min(100, 状态.月魂 + 月魂)
    this.检查满灵()
    this.模拟循环.添加战斗日志({
      日志: 来源 + '回复灵力，日灵【' + 状态.日灵 + '】月魂【' + 状态.月魂 + '】',
      日志类型: '回复灵力',
    })
  }
  添加储备(颜色: '日' | '月') {
    if (!this.模拟循环.校验奇穴是否存在('日月同辉')) return
    const 名称 = 颜色 === '日' ? '日珥' : '月芒'
    const 异色 = 颜色 === '日' ? '月芒' : '日珥'
    const Buff = this.模拟循环.当前自身buff列表
    const 层数 = Buff[异色]?.当前层数 || 0
    if (层数) {
      this.模拟循环.添加buff({ 名称: '光明相', 对象: '自身', 新增层数: 层数 + 1 })
      this.模拟循环.卸除buff({ 名称: 异色, 对象: '自身', 卸除层数: 层数 })
      if (this.模拟循环.校验奇穴是否存在('日月齐光') && (Buff.光明相?.当前层数 || 0) >= 5) {
        this.模拟循环.添加buff({ 名称: '日月齐光', 对象: '自身' })
        const 状态 = this.模拟循环.角色状态信息
        if (!状态.满灵)
          this.回复灵力(
            状态.日灵 > 状态.月魂 ? 100 : 0,
            状态.月魂 >= 状态.日灵 ? 100 : 0,
            '日月齐光',
          )
      }
    } else if (!Buff.光明相?.当前层数) {
      this.模拟循环.添加buff({ 名称, 对象: '自身' })
    }
  }
  消耗满灵(生死劫 = false) {
    const 状态 = this.模拟循环.角色状态信息
    const 颜色 = 状态.满灵!
    this.本次消耗满灵 = 颜色
    const 储备 = 颜色 === '日' ? '日珥' : '月芒'
    if (
      this.模拟循环.校验奇穴是否存在('明焰续夜') &&
      (this.模拟循环.当前自身buff列表[储备]?.当前层数 || 0) >= 2
    ) {
      this.模拟循环.技能类实例集合.驱夜断愁.重置调息时间()
    }
    状态[颜色 === '日' ? '日灵' : '月魂'] = 0
    状态.满灵 = undefined
    this.模拟循环.添加战斗日志({ 日志: '消耗满' + 颜色, 日志类型: '消耗灵力' })
    if (生死劫 && this.模拟循环.校验奇穴是否存在('双曜转辉')) this.添加储备(颜色)
    this.本次光明相生效 = !!this.模拟循环.当前自身buff列表.光明相?.当前层数
    if (this.本次光明相生效) {
      this.回复灵力(颜色 === '月' ? 100 : 0, 颜色 === '日' ? 100 : 0, '光明相', true)
      if (this.模拟循环.校验奇穴是否存在('崇光斩恶'))
        this.触发伤害行为(
          !生死劫 && 颜色 === '月' ? '崇光斩恶·月破魔' : '崇光斩恶',
          1,
          [],
          undefined,
          false,
          2,
        )
    }
    if (this.模拟循环.当前自身buff列表.橙武?.当前层数) {
      this.回复灵力(颜色 === '月' ? 100 : 0, 颜色 === '日' ? 100 : 0, '橙武', true)
    }
    if (生死劫 && this.模拟循环.校验奇穴是否存在('双曜转辉')) {
      const 层数 = this.模拟循环.当前自身buff列表[储备]?.当前层数 || 0
      if (层数) {
        this.模拟循环.卸除buff({ 名称: 储备, 对象: '自身', 卸除层数: 层数 })
        this.模拟循环.添加buff({
          名称: 颜色 === '日' ? '月芒' : '日珥',
          对象: '自身',
          新增层数: 层数,
        })
        this.回复灵力(颜色 === '月' ? 100 : 0, 颜色 === '日' ? 100 : 0, '双曜转辉', true)
      }
    }
  }
  诛邪镇魔(生死劫 = false) {
    if (!this.模拟循环.校验奇穴是否存在('诛邪镇魔')) return
    const 颜色 = this.本次消耗满灵!
    const 名称 = '诛邪镇魔·' + 颜色
    const 异色 = '诛邪镇魔·' + (颜色 === '日' ? '月' : '日')
    const Buff = this.模拟循环.当前目标buff列表
    if (Buff[异色]?.当前层数) {
      const 日劫 = 颜色 === '日' ? 生死劫 : Buff[异色].生死劫标记
      const 月劫 = 颜色 === '月' ? 生死劫 : Buff[异色].生死劫标记
      this.模拟循环.卸除buff({ 名称: 异色, 对象: '目标' })
      const 等级 = 1 + (日劫 ? 2 : 0) + (月劫 ? 1 : 0)
      this.触发伤害行为('诛邪镇魔·日', 1, [], undefined, false, 等级)
      this.触发伤害行为('诛邪镇魔·月', 1, [], undefined, false, 等级)
    } else {
      const 生死劫标记 = 生死劫 || Buff[名称]?.生死劫标记
      this.模拟循环.添加buff({ 名称, 对象: '目标' })
      Buff[名称].生死劫标记 = 生死劫标记
    }
  }
  满灵技能结束() {
    if (this.本次光明相生效) {
      this.模拟循环.卸除buff({
        名称: '光明相',
        对象: '自身',
        buff刷新时间: this.模拟循环.当前自身buff列表.光明相?.刷新时间,
      })
    }
    if (!this.模拟循环.当前自身buff列表.光明相?.当前层数)
      this.模拟循环.卸除buff({ 名称: '日月齐光', 对象: '自身' })
    this.检查满灵()
  }
  获取技能释放记录结果() {
    const { 日灵, 月魂 } = this.模拟循环.角色状态信息
    return {
      ...this.本次释放记录,
      背景容器: this.本次光明相生效 || !!this.模拟循环.当前自身buff列表.光明相?.当前层数,
      底部标识: '日' + 日灵 + '/月' + 月魂,
    }
  }
}
export default 技能统一类
