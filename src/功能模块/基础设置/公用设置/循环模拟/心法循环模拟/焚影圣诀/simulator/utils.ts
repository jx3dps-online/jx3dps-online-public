export const 根据奇穴修改buff数据 = (_奇穴: string[], _加速值: number) =>
  Object.fromEntries(Object.entries(原始Buff数据).map(([名称, 数据]) => [名称, { ...数据 }]))
export const 根据奇穴秘籍修改技能数据 = (
  奇穴: string[],
  秘籍: 选中秘籍信息,
): 循环基础技能数据类型[] =>
  循环模拟技能基础数据.map((技能) => {
    const 名称 = 技能.技能原始名称 || 技能.技能名称
    let 技能CD = 技能.技能CD || 0
    let 最大充能层数 = 技能.最大充能层数 || 1
    if (['烈日斩', '银月斩'].includes(名称) && 奇穴.includes('日月同辉')) {
      技能CD = 每秒郭氏帧 * 15
      最大充能层数 = 3
    } else if (名称 === '生死劫' && 奇穴.includes('双曜转辉')) {
      技能CD = 每秒郭氏帧 * 15
      最大充能层数 = 2
    } else if (名称 === '光明相' && 奇穴.includes('夷数神光')) {
      技能CD += 每秒郭氏帧 * 25
    }
    技能CD -= 判断秘籍减冷却(名称, 秘籍)
    return { ...技能, 技能CD, 最大充能层数 }
  })
