import type { 循环数据, 循环详情 } from '@/@types/循环'
import 计算循环 from '@/心法模块/心法/焚影圣诀/计算循环'
import 默认秘籍 from '@/心法模块/心法/焚影圣诀/默认数据/秘籍.json'

export default (网络延迟: number): Partial<循环数据>[] =>
  计算循环.flatMap((循环) => {
    const 各档循环 = 循环.循环详情 as (循环详情 & { 技能序列?: string[] })[]
    const 当前档位 = 各档循环.find((详情) => Number(详情.循环延迟要求) === 网络延迟)
    if (各档循环.some((详情) => 详情.技能序列) && !当前档位) return []

    return [
      {
        名称: 循环.标题,
        标题: 循环.标题,
        类型: '默认',
        奇穴: 循环.奇穴,
        秘籍: { 光明相: 默认秘籍.光明相, ...循环.秘籍 },
        技能序列: 当前档位?.技能序列 || 循环.技能序列,
        起手Buff配置: {},
        额外配置信息: { 起手日灵: 0, 起手月魂: 0, 背后攻击: true },
      },
    ]
  })
