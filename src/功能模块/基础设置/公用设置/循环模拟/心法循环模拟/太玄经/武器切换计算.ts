interface 武器计算入参 {
  完整日志: 循环日志数据类型[]
  武器装备: 武器装备类型
  奇穴信息: string[]
  秘籍信息: 选中秘籍信息
  增益启用: boolean
}

const 准备装备计算 = (装备: 装备信息数据类型, 全场基础, 参数, dispatch, getState) => {
  const 基础 = 获取秒伤计算基础(dispatch, getState, {
    ...参数,
    更新装备信息: 装备,
    更新快照计算: 全场基础.团队快照计算列表,
    更新计算循环详情: 全场基础.实际计算循环详情,
  })
  let 增益集合 = 获取装备增益(装备, 基础.团队快照计算列表, 基础.实际计算循环详情?.覆盖率)
  const 团队增益结合: string[] = []
  if (基础.增益启用) {
    增益集合 = 增益集合.concat(
      根据增益选项获取增益集合(基础.增益数据, undefined, 基础.团队快照计算列表),
    )
    基础.增益数据.团队增益.forEach((增益) => {
      if (增益.启用) 团队增益结合.push(增益.增益名称)
    })
    if (基础.增益数据.阵眼) 团队增益结合.push(基础.增益数据.阵眼)
  }
  const 首次属性 = 计算增益加成后最终计算属性({
    装备基础属性: 装备.装备基础属性,
    增益集合,
    当前目标: 基础.当前目标,
  })
  return { 基础, 首次属性, 团队增益结合 }
}

type 装备计算类型 = ReturnType<typeof 准备装备计算>

const 计算技能 = (循环: 循环技能详情, 装备计算: 装备计算类型, 战斗时间: number, 详情: boolean) => {
  const { 基础, 首次属性, 团队增益结合 } = 装备计算
  return 计算循环内某技能总伤害(
    循环,
    基础.当前装备信息.装备增益,
    基础.当前目标,
    基础.技能数据映射,
    true,
    基础.团队快照计算列表,
    首次属性,
    战斗时间,
    团队增益结合,
    详情,
  )
}

const 按持有时段分组 = (日志: 循环日志数据类型[]) => {
  const 分组 = new Map<string, 循环日志数据类型[]>()
  for (const 条目 of 日志) {
    if (条目.日志类型 !== '造成伤害') continue
    const key = `${条目.装备ID}_${条目.武器持有序号}`
    const 当前组 = 分组.get(key) ?? []
    当前组.push(条目)
    分组.set(key, 当前组)
  }
  return [...分组.values()]
}

const 合并计算结果 = (
  列表: 计算结果技能列表类型[],
  行: 计算结果技能列表类型 & { DOT跳数?: number },
) => {
  const 已有 = 列表.find(
    (item: 计算结果技能列表类型 & { DOT跳数?: number }) =>
      item.技能名称 === 行.技能名称 &&
      item.技能等级 === 行.技能等级 &&
      item.技能ID === 行.技能ID &&
      item.统计名称 === 行.统计名称 &&
      item.伤害层数 === 行.伤害层数 &&
      item.DOT跳数 === 行.DOT跳数,
  )
  if (!已有) {
    列表.push(行)
    return
  }
  const 会心数量 = (已有.总会心个数 ?? 0) + (行.总会心个数 ?? 0)
  if (行.技能数量 > 0) {
    已有.技能最终详情 =
      已有.技能数量 > 0 ? 处理技能最终详情(已有.技能最终详情, 行.技能最终详情) : 行.技能最终详情
  }
  已有.技能数量 += 行.技能数量
  已有.技能总输出 += 行.技能总输出
  已有.总会心个数 = 会心数量
  已有.会心几率 = 已有.技能数量 ? 会心数量 / 已有.技能数量 : 0
}

const 汇总循环伤害 = (
  分组: { 循环: 循环技能详情[]; 装备计算: 装备计算类型 }[],
  战斗时间: number,
  详情: boolean,
): 当前计算结果类型 => {
  const 列表: 计算结果技能列表类型[] = []
  let 总伤 = 0
  for (const { 循环, 装备计算 } of 分组) {
    for (const 技能 of 循环) {
      const 结果 = 计算技能(技能, 装备计算, 战斗时间, 详情)
      总伤 += 结果.总伤
      合并计算结果(列表, {
        技能名称: 技能.技能名称,
        技能等级: 技能.技能等级 as any,
        技能ID: 结果.当前技能属性?.技能ID,
        统计名称: 结果.当前技能属性?.统计名称,
        伤害层数: 技能.伤害层数,
        DOT跳数: 技能.DOT跳数,
        技能数量: 结果.计算数量,
        技能总输出: 结果.总伤,
        总会心个数: 结果.总会心数量,
        会心几率: 结果.计算数量 ? 结果.总会心数量 / 结果.计算数量 : 0,
        技能最终详情: 结果.技能最终详情,
      })
    }
  }
  return {
    总伤,
    秒伤: 战斗时间 > 0 ? INT(总伤 / 战斗时间) : 0,
    秒伤计算时间: 战斗时间,
    计算结果技能列表: 列表,
  }
}

const 计算单事件详情 = (组: 循环日志数据类型[], 装备计算: 装备计算类型, 战斗时间: number) => {
  const 技能组 = getDpsCycle(组)
  return 组.map((日志) => {
    const 单循环 = getDpsCycle([日志])[0]
    const 完整技能 = 技能组.find(
      (技能) => 技能.技能名称 === 单循环.技能名称 && 技能.技能等级 === 单循环.技能等级,
    )!
    const 同技能日志 = 组.filter(
      (条目) =>
        条目.日志 === 日志.日志 &&
        (条目.其他数据?.技能等级 ?? 1) === (日志.其他数据?.技能等级 ?? 1),
    )
    const buff键 = (条目: 循环日志数据类型) => [...(条目.buff列表 ?? [])].sort().join(',')
    const 同buff日志 = 同技能日志.filter((条目) => buff键(条目) === buff键(日志))
    const 原次数 = 同buff日志.reduce((数量, 条目) => 数量 + (条目.其他数据?.伤害次数 ?? 1), 0)
    const 原全部次数 = 同技能日志.reduce((数量, 条目) => 数量 + (条目.其他数据?.伤害次数 ?? 1), 0)
    const 本次原次数 = 日志.其他数据?.伤害次数 ?? 1
    const buff项 = 完整技能.技能增益列表?.find(
      (项) => 项.增益名称.split(',').sort().join(',') === buff键(日志),
    )
    const 剩余次数 =
      完整技能.技能数量 -
      (完整技能.技能增益列表 ?? []).reduce((数量, 项) => 数量 + 项.增益技能数, 0)
    const 有无buff日志 = 同技能日志.some((条目) => !条目.buff列表?.length)
    const 本次次数 = 日志.buff列表?.length
      ? ((buff项?.增益技能数 ?? 0) * 本次原次数) / 原次数
      : (剩余次数 * 本次原次数) / 原次数
    const 结果 = 计算技能(
      {
        ...完整技能,
        技能数量: 本次次数,
        技能增益列表: 完整技能.技能增益列表?.map((项) => ({
          ...项,
          增益技能数: 项 === buff项 ? 本次次数 : 0,
        })),
      },
      装备计算,
      战斗时间,
      false,
    )
    // 原汇总对总次数和增益次数分别取整；无空 buff 日志时也保留其余项。
    const 余项 =
      !有无buff日志 && 剩余次数 !== 0
        ? 计算技能(
            { ...完整技能, 技能数量: (剩余次数 * 本次原次数) / 原全部次数, 技能增益列表: [] },
            装备计算,
            战斗时间,
            false,
          )
        : undefined
    const 总会心数量 = 结果.总会心数量 + (余项?.总会心数量 ?? 0)
    const 数量 = 本次次数 + (余项?.计算数量 ?? 0)
    return {
      日志顺序: 日志.日志顺序,
      名称: 日志.日志,
      时间: 日志.日志时间 ?? 0,
      增益: 日志.buff列表 ?? [],
      伤害: 结果.总伤 + (余项?.总伤 ?? 0),
      会心期望: 数量 ? 总会心数量 / 数量 : 0,
    }
  })
}

export const 准备武器切换计算 = (props: 武器计算入参) => (dispatch, getState) => {
  const { 完整日志, 武器装备, 奇穴信息, 秘籍信息, 增益启用 } = props
  const 完整循环 = getDpsCycle(完整日志)
  const 参数 = {
    更新循环技能列表: 完整循环,
    更新奇穴数据: 奇穴信息,
    更新秘籍信息: 秘籍信息,
    更新增益启用: 增益启用,
  }
  const 起手装备 = 武器装备.装备集合[武器装备.起手武器ID]
  const 全场基础 = 获取秒伤计算基础(dispatch, getState, { ...参数, 更新装备信息: 起手装备 })
  const 禁止原因 =
    增益启用 && 全场基础.增益数据.团队增益.some((项) => 项.增益名称 === '飘黄' && 项.启用)
      ? '首版混合武器计算需关闭飘黄，尚无逐次触发时点规则'
      : 起手装备.装备增益.特效_42767
        ? '首版混合武器计算暂不支持速震特效'
        : 起手装备.装备增益.龙门飞剑武器
          ? '首版混合武器计算暂不支持龙门特效起手'
          : undefined
  const 装备计算集合 = new Map<number, 装备计算类型>()
  for (const [id, 装备] of Object.entries(武器装备.装备集合)) {
    装备计算集合.set(Number(id), 准备装备计算(装备, 全场基础, 参数, dispatch, getState))
  }
  const 起手计算 = 装备计算集合.get(武器装备.起手武器ID)!
  const 计算结果 = (日志: 循环日志数据类型[], 时间帧: number, 详情 = true) => {
    if (禁止原因 || 时间帧 <= 0 || !完整循环.length) {
      return { 总伤: 0, 秒伤: 0, 秒伤计算时间: 时间帧 / 每秒郭氏帧, 计算结果技能列表: [] }
    }
    const 战斗时间 = 时间帧 / 每秒郭氏帧
    const 明确循环 = getDpsCycle(日志)
    const 最终循环 = 根据增益修改最终循环(起手装备, 明确循环, 战斗时间, 起手计算.首次属性)
    const 有效技能名称 = new Set(最终循环.map((技能) => 技能.技能名称))
    const 分组 = 按持有时段分组(日志).map((组) => ({
      循环: getDpsCycle(组).filter((技能) => 有效技能名称.has(技能.技能名称)),
      装备计算: 装备计算集合.get(组[0].装备ID!)!,
    }))
    const 补充循环 = 最终循环.filter((技能) => !明确循环.includes(技能))
    分组.push({ 循环: 补充循环, 装备计算: 起手计算 })
    return 汇总循环伤害(分组, 战斗时间, 详情)
  }
  const 获取单事件详情 = (时间帧: number) =>
    禁止原因
      ? []
      : 按持有时段分组(完整日志)
          .flatMap((组) =>
            计算单事件详情(组, 装备计算集合.get(组[0].装备ID!)!, 时间帧 / 每秒郭氏帧),
          )
          .sort((a, b) => a.时间 - b.时间 || a.日志顺序! - b.日志顺序!)
  return { 计算结果, 获取单事件详情, 禁止原因 }
}
