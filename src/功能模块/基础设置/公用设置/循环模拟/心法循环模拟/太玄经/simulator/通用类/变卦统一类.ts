import 有CD技能通用类 from './有CD技能通用类'
import { ERROR_ACTION } from '../utils'

class 变卦统一类 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
  }

  卦象清除() {
    this.模拟循环.卸除buff({ 名称: `卦象_水坎`, 对象: '自身' })
    this.模拟循环.卸除buff({ 名称: `卦象_山艮`, 对象: '自身' })
    this.模拟循环.卸除buff({ 名称: `卦象_火离`, 对象: '自身' })
    this.模拟循环.角色状态信息.鬼遁强化水坎 = false
  }

  获取变卦星运消耗() {
    return this.模拟循环.秘籍['变卦']?.includes('顺序变卦') ? 50 : 40
  }

  是否为鬼遁免费变卦() {
    return (
      this.模拟循环.校验奇穴是否存在('鬼遁') &&
      (this.模拟循环.角色状态信息.鬼遁免费变卦次数 || 0) > 0
    )
  }

  释放() {
    const 星运消耗 = this.获取变卦星运消耗()
    if (!this.是否为鬼遁免费变卦() && (this.模拟循环.角色状态信息.星运 || 0) < 星运消耗) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.星运不足,
      }
    }
    return { 可以释放: true }
  }

  结算变卦星运(来源) {
    if (this.是否为鬼遁免费变卦()) {
      const 剩余次数 = Math.max(0, (this.模拟循环.角色状态信息.鬼遁免费变卦次数 || 0) - 1)
      this.模拟循环.角色状态信息.鬼遁免费变卦次数 = 剩余次数
      this.模拟循环.卸除buff({ 名称: '免费变卦', 对象: '自身' })
      this.模拟循环.添加战斗日志?.({
        日志: `鬼遁 触发 ${来源} 不消耗星运，剩余${剩余次数}次`,
        日志类型: '技能释放结果',
      })
    } else {
      this.消耗星运(this.获取变卦星运消耗(), 来源)
    }
  }

  统一变卦生效(当前存在祝由释放允许) {
    // 变卦无法主动获得，只能刷新
    if (当前存在祝由释放允许) {
      this.模拟循环.添加buff({ 名称: '祝由释放允许', 对象: '自身' })
    }
    if (this.模拟循环.校验奇穴是否存在('荧入白')) {
      this.模拟循环.添加buff({ 名称: '荧入白', 对象: '自身' })
    }
    // 太玄经新赛季技改：鬼遁不再在变卦后返还 20 点星运，原逻辑注释保留
    // if (this.模拟循环.校验奇穴是否存在('鬼遁')) {
    //   this.获得星运(20, '鬼遁')
    // }
  }

  保存释放记录() {
    const 造成buff数据 = this.获取施加重要buff信息('荧入白')
    this.本次释放记录 = 造成buff数据 ? { 造成buff数据 } : {}
  }
}

export default 变卦统一类

export const 变卦类型 = typeof 变卦统一类
