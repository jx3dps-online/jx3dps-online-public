import 循环模拟技能基础数据 from '../../../constant/skill'
import { 待生效事件 } from '../../type'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 苍棘缚地悟 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '苍棘缚地·悟')
  static 基础攻击次数 = 9
  static 首次间隔 = 16 // 延迟1s出第一次伤害
  static 攻击间隔 = 16 // 每秒1跳
  static 最大额外攻击 = 2
  额外攻击次数 = 0
  下个攻击时间 = 0

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
    苍棘缚地悟.技能数据 = 模拟循环?.技能基础数据?.find((item) => item.技能名称 === '苍棘缚地·悟')
  }

  命中() {
    if (this.模拟循环.大橙武模拟) {
      this.模拟循环.添加buff?.({ 名称: '烬灭', 对象: '自身' })
    }
    this.保存释放记录('苍棘缚地·悟')
    this.额外攻击次数 = 0
    this.下个攻击时间 = 0
    this.创建苍棘缚地攻击()
  }

  创建苍棘缚地攻击(额外攻击 = 0) {
    const 待生效事件队列: 待生效事件[] = []
    const 基础时间 = this.下个攻击时间 || this.模拟循环.当前时间
    const 攻击次数 = 额外攻击 || 苍棘缚地悟.基础攻击次数

    for (let i = 0; i < 攻击次数; i++) {
      const 延迟 = 额外攻击 ? 0 : 苍棘缚地悟.首次间隔
      const 攻击时间 = 基础时间 + 延迟 + 苍棘缚地悟.攻击间隔 * (i + 1)
      if (额外攻击) {
        this.下个攻击时间 = 攻击时间
      }
      待生效事件队列.push({
        事件名称: '苍棘缚地攻击',
        事件时间: 攻击时间,
        事件备注: {
          技能名称: '苍棘缚地·悟',
        },
      })
    }

    if (!额外攻击) {
      this.下个攻击时间 = 基础时间 + 苍棘缚地悟.首次间隔 + 苍棘缚地悟.攻击间隔 * 攻击次数
    }

    this.模拟循环.添加待生效事件队列(待生效事件队列)
  }

  沾衣触发额外攻击() {
    if (this.额外攻击次数 >= 苍棘缚地悟.最大额外攻击) return
    this.额外攻击次数++

    // 从事件队列中找到最后一个苍棘缚地攻击事件，在其后追加
    const 当前队列 = this.模拟循环.待生效事件队列 || []
    let 最后攻击时间 = this.模拟循环.当前时间
    for (let i = 当前队列.length - 1; i >= 0; i--) {
      if (
        当前队列[i]?.事件名称 === '苍棘缚地攻击' &&
        当前队列[i]?.事件备注?.技能名称 === '苍棘缚地·悟'
      ) {
        最后攻击时间 = 当前队列[i].事件时间 || 0
        break
      }
    }

    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '苍棘缚地攻击',
        事件时间: 最后攻击时间 + 苍棘缚地悟.攻击间隔,
        事件备注: {
          技能名称: '苍棘缚地·悟',
        },
      },
    ])
  }

  苍棘缚地攻击() {
    this.触发伤害行为('苍棘缚地·悟', 1)
    // 苍棘攻击后消耗并蒂增伤BUFF（并蒂下一跳会重新补上）
    this.模拟循环.卸除buff?.({ 名称: '并蒂增伤', 对象: '自身', 卸除层数: 1 })
  }

  保存释放记录(名称) {
    this.本次释放记录 = {
      实际伤害技能: 名称,
      重要buff列表: this.获取当前重要buff列表([]),
    }
  }
}

export default 苍棘缚地悟

export const 苍棘缚地悟类型 = typeof 苍棘缚地悟
