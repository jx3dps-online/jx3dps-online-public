import { 获取倒读条实际帧数分布, 获取实际帧数 } from '@/工具函数/data'
import 循环模拟技能基础数据 from '../../../constant/skill'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 待生效事件 } from '../../type'
import { 数组求和 } from '@/工具函数/help'

class 川乌射罔悟 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '川乌射罔·悟')
  static 作用总间隔 = 41 // 2.56s * 16fps ≈ 41 frames
  static 作用间隔帧 = 10
  static 默认作用次数 = 4
  static 当前作用次数 = 4 // 可被断读条修改

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
    川乌射罔悟.技能数据 = 模拟循环?.技能基础数据?.find((item) => item.技能名称 === '川乌射罔·悟')
  }

  释放前初始化(额外信息) {
    // 断读条：从额外信息读取作用次数，默认4跳
    川乌射罔悟.当前作用次数 = 额外信息?.作用次数 || 川乌射罔悟.默认作用次数
  }

  获取读条时间() {
    // 根据加速计算完整读条时间，断读条时按截断后的跳数裁切
    let 读条持续时间 = 获取实际帧数(川乌射罔悟.作用总间隔, this.模拟循环.加速值)

    if (川乌射罔悟.当前作用次数 < 川乌射罔悟.默认作用次数) {
      const 实际作用分布 = this.获取川乌作用分布()
      读条持续时间 = 数组求和(实际作用分布)
    }

    return 读条持续时间
  }

  获取川乌作用分布() {
    const 循环加速值 = this.模拟循环.加速值 || 0
    const 作用分布 = 获取倒读条实际帧数分布(
      川乌射罔悟.作用总间隔,
      川乌射罔悟.作用间隔帧,
      循环加速值,
      0,
      0,
      川乌射罔悟.默认作用次数,
    ).reverse()
    // 截断：只取前 当前作用次数 跳
    return 作用分布?.filter((_, index) => index < 川乌射罔悟.当前作用次数)
  }

  读条(读条开始时间) {
    this.对阵招式橙武减少绝技技能CD()
    this.减少苍棘缚地CD(32)
    this.读条川乌射罔悟(读条开始时间)
    this.保存释放记录('川乌射罔·悟')
  }

  读条川乌射罔悟(读条开始时间) {
    const 待生效事件队列: 待生效事件[] = []
    const 作用分布 = this.获取川乌作用分布()
    let 已读条时间 = 0
    for (let i = 0; i < 作用分布.length; i++) {
      待生效事件队列.push({
        事件名称: '技能读条',
        事件时间: 读条开始时间 + 已读条时间 + 作用分布[i],
        事件备注: {
          技能名称: '川乌射罔·悟',
          是否为最后一跳: 作用分布.length - 1 === i,
        },
      })
      已读条时间 = 已读条时间 + 作用分布[i]
    }
    this.模拟循环.添加待生效事件队列(待生效事件队列)
  }

  读条命中(事件备注) {
    this.改变温寒(1, '川乌射罔·悟')
    this.触发伤害行为('川乌射罔·悟')
  }

  保存释放记录(名称) {
    this.本次释放记录 = {
      实际伤害技能: 名称,
      重要buff列表: this.获取当前重要buff列表(['钩吻追加']),
    }
  }
}

export default 川乌射罔悟

export const 川乌射罔悟类型 = typeof 川乌射罔悟
