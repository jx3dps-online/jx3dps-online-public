import { 获取实际帧数 } from '@/工具函数/data'
import 循环模拟技能基础数据 from '../../../constant/skill'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 待生效事件 } from '../../type'

class 青圃着尘悟 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '青圃着尘·悟')
  static 跳数 = 6
  // 0加速下6跳间隔：0, 10, 10, 10, 10, 9（总计49帧≈3.06s）
  static 基础间隔序列 = [0, 10, 10, 10, 10, 9]
  static 基础总帧数 = 49

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
    青圃着尘悟.技能数据 = 模拟循环?.技能基础数据?.find((item) => item.技能名称 === '青圃着尘·悟')
  }

  获取读条时间() {
    return 获取实际帧数(青圃着尘悟.基础总帧数, this.模拟循环.加速值)
  }

  读条(读条开始时间) {
    this.对阵招式橙武减少绝技技能CD()
    this.减少苍棘缚地CD(48)
    this.读条青圃着尘悟(读条开始时间)
    this.保存释放记录('青圃着尘·悟')
  }

  读条青圃着尘悟(读条开始时间) {
    const 待生效事件队列: 待生效事件[] = []
    const 循环加速值 = this.模拟循环.加速值 || 0
    // 加速只影响总帧数，减少量从右往左分配：优先减右端高于最小值的间隔
    const 加速后总帧数 = 获取实际帧数(青圃着尘悟.基础总帧数, 循环加速值)
    let 剩余减少量 = 青圃着尘悟.基础总帧数 - 加速后总帧数
    const 实际间隔序列 = [...青圃着尘悟.基础间隔序列]
    while (剩余减少量 > 0) {
      // 找到当前非零间隔中的最小值（首跳0帧除外）
      const 非零间隔 = 实际间隔序列.slice(1)
      const 当前最小值 = Math.min(...非零间隔)
      // 从右往左找第一个大于当前最小值的非零间隔
      let 已减少 = false
      for (let i = 实际间隔序列.length - 1; i >= 1; i--) {
        if (实际间隔序列[i] > 当前最小值 && 剩余减少量 > 0) {
          实际间隔序列[i] -= 1
          剩余减少量 -= 1
          已减少 = true
        }
      }
      // 所有非零值已相等，剩余减少量从右往左逐个减
      if (!已减少) {
        for (let i = 实际间隔序列.length - 1; i >= 1 && 剩余减少量 > 0; i--) {
          if (实际间隔序列[i] > 0) {
            实际间隔序列[i] -= 1
            剩余减少量 -= 1
          }
        }
      }
    }

    let 累计时间 = 0
    for (let i = 0; i < 实际间隔序列.length; i++) {
      累计时间 = 累计时间 + 实际间隔序列[i]
      待生效事件队列.push({
        事件名称: '技能读条',
        事件时间: 读条开始时间 + 累计时间,
        事件备注: {
          技能名称: '青圃着尘·悟',
          是否为最后一跳: 实际间隔序列.length - 1 === i,
        },
      })
    }
    this.模拟循环.添加待生效事件队列(待生效事件队列)
  }

  读条命中(事件备注) {
    this.引爆中毒()
    this.改变温寒(-1, '青圃着尘·悟')
    this.触发伤害行为('青圃着尘·悟')
  }

  引爆中毒() {
    const 中毒实例 = this.模拟循环.技能类实例集合?.中毒
    if (!中毒实例) return
    const 待生效数据 = 中毒实例?.DOT运行数据?.待生效数据 || []
    const 当前时间 = this.模拟循环.当前时间
    // 统计尚未生效的中毒跳数（含当前时间）
    const 剩余跳数 = 待生效数据.filter((item) => (item.生效时间 || 0) >= 当前时间).length
    if (剩余跳数 <= 0) return

    // 立即结算剩余跳数的中毒伤害（合并为1次统计）
    const 额外增益列表 = this.模拟循环.当前自身buff列表?.['钩吻断肠绝章']?.当前层数
      ? ['钩吻断肠绝章']
      : []
    this.触发伤害行为('中毒(DOT)', 1, 额外增益列表, undefined, 剩余跳数)
    // 清除中毒DOT待生效数据（引爆后DOT消失）
    中毒实例.DOT运行数据.待生效数据 = []
    this.模拟循环.卸除buff?.({ 名称: '中毒', 对象: '目标', 卸除层数: 1 })
  }

  保存释放记录(名称) {
    this.本次释放记录 = {
      实际伤害技能: 名称,
      重要buff列表: this.获取当前重要buff列表(['钩吻追加']),
    }
  }
}

export default 青圃着尘悟

export const 青圃着尘悟类型 = typeof 青圃着尘悟
