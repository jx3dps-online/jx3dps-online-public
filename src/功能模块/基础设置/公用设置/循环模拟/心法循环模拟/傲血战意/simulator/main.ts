  // 造成伤害
  技能造成伤害(
    来源,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    造成时间 = this.当前时间,
    隐藏日志 = false,
    技能等级 = 1,
    快照检测Buff列表: string[] = [],
  ) {
    const 当前技能数据 = 技能系数?.find((item) => item.技能名称 === 来源)
    const 技能增益列表 = 当前技能数据?.技能增益列表 || []

    const 有关的buff列表 =
      技能增益列表
        ?.filter((item) => {
          const 当前增益数据 = 转化buff和增益名称(item.增益名称, this.当前自身buff列表)
          if (当前增益数据) {
            if (造成时间 !== undefined) {
              const 增益消失时间 = (当前增益数据?.刷新时间 || 0) + (当前增益数据?.最大持续时间 || 0)
              const 增益获得时间 = 当前增益数据?.刷新时间 || 0
              return 造成时间 <= 增益消失时间 && !!当前增益数据 && 造成时间 >= 增益获得时间
            } else {
              return !!当前增益数据?.当前层数
            }
          } else {
            return false
          }
        })
        ?.map((item) => item.增益名称)
        ?.filter((item) => {
          if (快照检测Buff列表?.length) {
            return !快照检测Buff列表?.includes(item)
          } else {
            return true
          }
        })
        ?.filter((item) => !额外增益列表?.includes(item)) || []

    let 总增益列表 = 有关的buff列表.concat(额外增益列表)

    const 目标破甲 = this.当前目标buff列表['破甲']
    if (
      目标破甲?.当前层数 &&
      造成时间 >= (目标破甲.刷新时间 || 0) &&
      造成时间 < (目标破甲.刷新时间 || 0) + 目标破甲.最大持续时间! &&
      技能增益列表.some((增益) => 增益.增益名称 === '破甲')
    ) {
      总增益列表.push('破甲')
    }

    if (this.启用团队增益快照) {
      const 团队增益buff列表 = this.副本事件实例列表?.length
        ? 判断副本事件快照Buff(this.副本事件实例列表, this.当前时间 || 0)
        : 判断团队增益快照Buff({
            团队增益轴: this.团队增益轴,
            判定帧: this.当前时间 || 0,
          })
      if (团队增益buff列表?.length) {
        总增益列表 = 总增益列表?.concat(团队增益buff列表)
      }
    }

    if (!隐藏日志) {
      this.添加战斗日志({
        日志: 来源,
        日志类型: '造成伤害',
        日志时间: 造成时间,
        buff列表: 总增益列表 || [],
        其他数据: {
          伤害次数: 伤害次数,
          技能等级: 技能等级,
        },
      })
    }
  }

  检查GCD(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    if (技能实例?.检查GCD) {
      GCD = 技能实例?.检查GCD?.(i, 当前技能)
    } else {
      GCD = this.技能释放前检查GCD统一方法(当前技能)
    }
    return GCD
  }

  // 判断GCD，技能CD等
  技能释放前(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    let 等待CD = 0

    // 判断是否为当前箭袋第一个技能
    if (i >= 0) {
      // 判断上一个技能对于本技能是否有GCD限制
      if (当前技能?.技能GCD组) {
        GCD = this.检查GCD(当前技能, 技能实例, i)
      }
      // 判断技能CD，如果存在CD。增加等待时间
      if (当前技能?.技能CD) {
        等待CD = this.技能释放前检查运行数据(当前技能, 技能实例, GCD)
      }
    }

    const 是否为GCD技能 = !!当前技能?.技能GCD组 && 当前技能.技能释放后添加GCD > 0
    let 延迟等待 = 0
    if (是否为GCD技能 && this.已释放GCD技能数 > 0) {
      延迟等待 = this.网络延迟
      if (this.周期性忽略延迟 > 0) {
        const 衔接索引 = this.已释放GCD技能数 - 1
        const 免延迟比例 = 1 / (this.周期性忽略延迟 + 1)
        if (Math.ceil((衔接索引 + 1) * 免延迟比例) > Math.ceil(衔接索引 * 免延迟比例)) {
          延迟等待 = 0
        }
      }
    }
    const 技能计划释放时间 = this.当前时间 + GCD + 延迟等待
    const 破楼兰标记 = this.当前自身buff列表.破楼兰标记
    if (当前技能.技能名称 === '灭' && 破楼兰标记?.当前层数) {
      const 标记到期时间 = 破楼兰标记.刷新时间! + 破楼兰标记.最大持续时间!
      if (技能计划释放时间 >= 标记到期时间) {
        等待CD = Math.max(等待CD, 标记到期时间 + 当前技能.技能CD! - 技能计划释放时间)
      }
    }
    return {
      技能计划释放时间: 技能计划释放时间,
      技能预估释放时间: 技能计划释放时间 + 等待CD,
      等待CD,
    }
  }

  // 增加技能GCD
  增加技能GCD(当前技能: 循环基础技能数据类型) {
    // GCD处理
    if (当前技能?.技能GCD组) {
      let 实际添加GCD = 获取实际帧数(当前技能?.技能释放后添加GCD, this.加速值)
      // if (当前技能?.最小GCD) {
      //   实际添加GCD = Math.max(实际添加GCD, 当前技能?.最小GCD)
      // }
      let 待更新GCD组: string = 当前技能.技能GCD组 as string
      if (当前技能.技能GCD组 === '自身') {
        待更新GCD组 = 当前技能?.技能名称
      }
      if (待更新GCD组) {
        this.GCD组[待更新GCD组] = (this.GCD组[待更新GCD组] || 0) + 实际添加GCD
      }
    }
  }

  // 增加技能CD
  增加技能CD(当前技能: 循环基础技能数据类型, 技能实例) {
    // 技能CD处理
    if (当前技能?.技能CD) {
      if (技能实例?.技能释放后更新运行数据) {
        技能实例.技能释放后更新运行数据?.()
      } else {
        this.技能释放后更新运行数据(当前技能, 技能实例)
      }
    }
  }

  技能成功开始释放(当前技能: 循环基础技能数据类型, 技能实例, 是否为读条技能) {
    this.增加技能GCD(当前技能)
    if (当前技能.技能名称 === '饮羽簇') {
      // 读条引在读条结束以后进入CD
      if (!this.当前自身buff列表?.['橙武']?.当前层数 && !是否为读条技能) {
        this.增加技能CD(当前技能, 技能实例)
      }
    } else {
      this.增加技能CD(当前技能, 技能实例)
    }
  }

  // 判断添加GCD等
  技能释放后(
    当前技能: 循环基础技能数据类型,
    计划释放时间: number,
    开始读条时间,
    开始释放时间,
    是否为读条技能,
    技能实例,
    释放时标鹄层数: number,
  ) {
    const 技能释放记录结果 = 技能实例?.获取技能释放记录结果?.() || {}

    // 技能释放记录
    this.技能释放记录.push({
      技能名称: 当前技能?.技能名称,
      计划释放时间,
      实际释放时间: 开始释放时间,
      开始读条时间: 开始读条时间,
      是否为读条技能: 是否为读条技能,
      技能释放记录结果: {
        ...技能释放记录结果,
        释放时标鹄层数,
      },
    })
    if (当前技能.技能GCD组 && 当前技能.技能释放后添加GCD > 0) {
      this.已释放GCD技能数 += 1
    }
  }

  清空buff调用函数(对象: '自身' | '目标') {
    const buff列表 = 对象 === '自身' ? this.当前自身buff列表 : this.当前目标buff列表

    // 更新目标buff
    Object.keys(buff列表).forEach((key) => {
      const buff对象 = buff列表[key]
      const buff应该消失时间 = (buff对象?.刷新时间 || 0) + (buff对象?.最大持续时间 || 0)
      const 消失层数 = buff对象?.自然消失失去层数 || buff对象?.最大层数
      const 是否破楼兰标记 = 对象 === '自身' && key === '破楼兰标记'
      if (
        buff对象.最大持续时间 !== undefined &&
        (buff应该消失时间 < this.当前时间 ||
          (是否破楼兰标记 && buff应该消失时间 === this.当前时间))
      ) {
        this.卸除buff({ 名称: key, 对象, 事件时间: buff应该消失时间, 卸除层数: 消失层数 })
        if (是否破楼兰标记) {
          const 灭技能数据 = this.技能基础数据.find((技能) => 技能.技能名称 === '灭')!
          this.技能类实例集合.灭!.更新技能运行数据({
            待充能时间点: [buff应该消失时间 + 灭技能数据.技能CD!],
          })
        }
      }
    })
  }

