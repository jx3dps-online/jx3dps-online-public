  // ----------------- 通用函数 start----------------- //
  重置循环执行结果() {
    this.循环执行结果 = '成功'
    this.循环异常信息 = { 异常索引: 0, 异常信息: '' }
  }

  记录起手Buff() {
    for (const 对象 of ['自身', '目标'] as const) {
      const 列表 = 对象 === '自身' ? this.当前自身buff列表 : this.当前目标buff列表
      for (const [名称, buff] of Object.entries(列表)) {
        if (
          !buff.当前层数 ||
          (buff.最大持续时间 !== undefined && (buff.刷新时间 || 0) + buff.最大持续时间 <= 0)
        ) {
          delete 列表[名称]
          continue
        }
        this.添加战斗日志({
          日志: `${对象}获得${名称}`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 0,
        })
      }
    }
  }

