    this.当前目标buff列表 = { ...获取起手Buff配置(props?.起手Buff配置, this.Buff和Dot数据, '目标') }
    delete this.当前目标buff列表['流血']
    this.角色状态信息 = {
      战意: 5,
      体态: this.当前自身buff列表['骑御']?.当前层数 ? '骑乘' : '站立',
    }
    delete this.当前自身buff列表['骑御']
    this.待生效事件队列 = []
    // 模拟初始化
