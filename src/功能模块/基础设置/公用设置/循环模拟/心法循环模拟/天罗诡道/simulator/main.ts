  添加神机每秒回复事件(初始时间 = 16) {
    if (this.已添加每秒神机回复事件){
      return
    }
    let 当前时间 = this.当前时间 || 0

    // 如果是第一次添加，为了错位，提前设置8帧
    if (当前时间 === 0) {
      当前时间 = -(每秒郭氏帧 - 初始时间)
    }
    const 待生效事件 = 按数字生成数组(1000).map((次数) => {
      return {
        事件名称: `神机每秒回复`,
        事件时间: 当前时间 + 每秒郭氏帧 * 次数,
      }
    })
    this.添加待生效事件队列(待生效事件)
    this.已添加每秒神机回复事件 =true
  }

  神机值变化(来源?: any) {
    // 检查神机值是否足够
    const 当前神机值 = this.角色状态信息?.神机值 || 100
    const 消耗神机值 = 来源.消耗神机值! ?? 0

    let 变化量 = 10
    let 技能名称 = 来源
    if (来源 === '每秒' && this.当前自身buff列表?.['心无旁骛']?.当前层数) {
      变化量 = 20
    }
    if (消耗神机值) {
      变化量 = -消耗神机值
    }
    if (来源 !== '每秒' && 来源 !== '连弩'){
      技能名称 = 来源?.技能名称
    }
    // 执行神机值变化
    const 回复后神机值 = Math.min(100, 当前神机值 + 变化量!)
    const 实际回复值 = 回复后神机值 - 当前神机值
    if (实际回复值 != 0) {
      this.角色状态信息.神机值 = 回复后神机值

      // 神机值buff监控逻辑
      if (回复后神机值 > 20) {
        this.添加buff({ 名称: '神机好穷陷阱增伤', 对象: '自身' })
      } else {
        this.卸除buff({ 名称: '神机好穷陷阱增伤', 对象: '自身' })
      }

      if (回复后神机值 < 80) {
        this.添加buff({ 名称: '神机好穷内攻增伤', 对象: '自身' })
      } else {
        this.卸除buff({ 名称: '神机好穷内攻增伤', 对象: '自身' })
      }
    }

    const 变化值 = Math.abs(实际回复值)
    if (变化值 > 0) {
      this?.添加战斗日志({
        日志: `【${技能名称}】${实际回复值 > 0 ? '回复' : '消耗'}${变化值}点神机值，当前神机值：${回复后神机值}`,
        日志类型: '技能释放结果',
        日志时间: this.当前时间,
      })
    }
  }

