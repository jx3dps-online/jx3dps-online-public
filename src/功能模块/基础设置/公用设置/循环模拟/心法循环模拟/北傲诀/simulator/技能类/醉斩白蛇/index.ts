import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 获取倒读条实际帧数分布 } from '@/工具函数/data'

class 醉斩白蛇 extends 有CD技能通用类 {
  本次作用次数?: number
  constructor(模拟循环) {
    super(模拟循环)
    this.技能数据 = 模拟循环.技能基础数据.find((技能) => 技能.技能名称 === '醉斩白蛇')
  }

  释放() {
    if (this.模拟循环.角色状态信息.气劲 < this.获取消耗数量()) {
      return { 可以释放: false, 异常信息: ERROR_ACTION.资源不足 }
    }
    return { 可以释放: true }
  }

  获取跳数() {
    const 上限 = this.模拟循环.奇穴.includes('化蛟') ? 8 : 4
    return Math.max(1, Math.min(上限, Math.floor(this.本次作用次数 ?? 上限)))
  }

  释放前初始化(额外信息) {
    super.释放前初始化(额外信息)
    this.本次作用次数 = 额外信息?.作用次数
  }

  获取消耗数量() {
    if (this.模拟循环.当前自身buff列表.橙武) return 0
    return this.模拟循环.当前自身buff列表.绝期 ? 60 : this.技能数据.消耗数量!
  }

  技能释放后更新运行数据() {
    if (!this.模拟循环.当前自身buff列表.橙武) super.技能释放后更新运行数据()
  }
  获取跳时刻() {
    const 即时首跳 = this.模拟循环.奇穴.includes('化蛟')
    // 按用户确认的化蛟加速阈值匹配完整引导帧数，2024 以上不再细分。
    const 化蛟加速档位 = [10, 297, 603, 928, 1274, 1639, 2024].filter(
      (加速值) => this.模拟循环.加速值 >= 加速值,
    ).length
    const 化蛟引导帧数 = [40, 35, 34, 33, 32, 31, 30, 29][化蛟加速档位]
    const 分布 = 即时首跳
      ? 获取倒读条实际帧数分布(化蛟引导帧数, 化蛟引导帧数 / 7, 0, 0, 0, 7)
      : 获取倒读条实际帧数分布(21, 5.25, this.模拟循环.加速值)
    let 时间 = 0
    const 时刻 = 分布.map((间隔) => (时间 += 间隔))
    return (即时首跳 ? [0, ...时刻] : 时刻).slice(0, this.获取跳数())
  }
  读条时间() {
    const 时刻 = this.获取跳时刻()
    return Math.max(1, 时刻[时刻.length - 1])
  }

  命中() {
    this.模拟循环.变更资源('气劲', -this.获取消耗数量(), '醉斩白蛇')
    this.模拟循环.开始战斗()
    const 模拟 = this.模拟循环
    模拟.卸除buff({ 名称: '绝期·醉斩', 对象: '自身' })
    if (模拟.奇穴.includes('荡岳')) 模拟.添加buff({ 名称: '蓄势', 对象: '自身' })
  }

  读条(开始时间: number) {
    this.模拟循环.添加待生效事件队列(
      this.获取跳时刻().map((时刻) => ({
        事件名称: '醉斩技能读条',
        事件时间: 开始时间 + 时刻,
        事件备注: { 技能名称: this.技能数据.技能名称 },
      })),
    )
    this.本次释放记录.伤害段数 = this.获取跳数()
  }

  读条伤害() {
    const 模拟 = this.模拟循环
    if (模拟.当前自身buff列表.绝期) {
      模拟.卸除buff({ 名称: '绝期', 对象: '自身' })
      模拟.添加buff({ 名称: '绝期·醉斩', 对象: '自身' })
    }
    const 蓄势层数 = 模拟.当前自身buff列表.蓄势?.当前层数
    this.触发伤害行为('醉斩白蛇', 1, 蓄势层数 ? [`蓄势·${蓄势层数}`] : [])
    if (this.模拟循环.奇穴.includes('化蛟'))
      (['狂意', '刀魂', '气劲'] as const).forEach((资源) => this.模拟循环.变更资源(资源, 1, '化蛟'))
  }
}

export default 醉斩白蛇
