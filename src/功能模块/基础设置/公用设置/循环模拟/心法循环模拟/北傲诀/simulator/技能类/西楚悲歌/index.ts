import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 西楚悲歌 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
    this.技能数据 = 模拟循环.技能基础数据.find((技能) => 技能.技能名称 === '西楚悲歌')
  }

  释放() {
    if (!this.模拟循环.校验奇穴是否存在('疏狂')) {
      return { 可以释放: false, 异常信息: { 信息: '未启用奇穴：疏狂' } }
    }
    return { 可以释放: true }
  }

  命中() {
    this.模拟循环.开始战斗()
    this.模拟循环.添加待生效事件队列([
      {
        事件时间: this.模拟循环.当前时间 + 2,
        事件名称: '疏狂刀气',
        事件备注: { 技能名称: this.技能数据.技能名称 },
      },
    ])
    this.模拟循环.添加buff({ 名称: '疏狂_自我', 对象: '自身' })
    // 实战确认疏狂13秒：NPC第192帧仍刷新一次11456，持续至第208帧。
    this.模拟循环.添加待生效事件队列(
      Array.from({ length: 48 }, (_, i) => ({
        事件时间: this.模拟循环.当前时间 + (i + 1) * 4,
        事件名称: '疏狂领域刷新',
        事件备注: { 技能名称: this.技能数据.技能名称, 刷新增益: true },
      })),
    )
  }

  领域生效(刷新增益: boolean) {
    if (刷新增益) this.模拟循环.添加buff({ 名称: '疏狂_自我', 对象: '自身' })
    else this.触发伤害行为('西楚悲歌', 1, [], undefined, 2)
  }
}

export default 西楚悲歌
