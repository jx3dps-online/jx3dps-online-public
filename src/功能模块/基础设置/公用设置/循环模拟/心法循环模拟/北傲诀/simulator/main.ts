  普通攻击结算() {
    // 霜风刀法从0秒开始，每1.5秒（24帧造成一次伤害）
    const 霜风刀法间隔 = 获取实际帧数(24, this.加速值)
    if (this.霜风刀法上次造成伤害时间 !== undefined) {
      if (this.霜风刀法上次造成伤害时间 + 霜风刀法间隔 <= this.当前时间) {
        const 本次应该造成霜风刀法伤害序列: number[] = [
          this.霜风刀法上次造成伤害时间 + 霜风刀法间隔,
        ]
        while (
          本次应该造成霜风刀法伤害序列?.[本次应该造成霜风刀法伤害序列.length - 1] + 霜风刀法间隔 <=
          this.当前时间
        ) {
          本次应该造成霜风刀法伤害序列.push(
            本次应该造成霜风刀法伤害序列?.[本次应该造成霜风刀法伤害序列.length - 1] + 霜风刀法间隔,
          )
        }
        for (let i = 0; i < 本次应该造成霜风刀法伤害序列.length; i++) {
          // 三种体态的霜风刀法系数一致，这里直接用大刀的
          this.技能造成伤害('霜风刀法·大刀', undefined, undefined, 本次应该造成霜风刀法伤害序列[i])
          if (i === 本次应该造成霜风刀法伤害序列.length - 1) {
            this.霜风刀法上次造成伤害时间 = 本次应该造成霜风刀法伤害序列[i]
          }
        }
      }
    } else {
      this.技能造成伤害('霜风刀法·大刀')
      this.霜风刀法上次造成伤害时间 = 0
    }
  }

