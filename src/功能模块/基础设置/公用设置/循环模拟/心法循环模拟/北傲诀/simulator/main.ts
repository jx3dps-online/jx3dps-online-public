  待生效事件结算(结算判断时间 = this.当前时间) {
    while (this.待生效事件队列[0]?.事件时间 <= 结算判断时间) {
      const 当前事件 = this.待生效事件队列.shift()!
      this.增加时间(当前事件.事件时间 - this.当前时间)
      this.清空已经消失的buff()
      this.对所有有CD技能检查和充能()
      this.添加战斗日志({
        日志: `事件【${当前事件.事件名称}】触发`,
        日志类型: '技能释放结果',
      })
      if (当前事件.事件名称.includes('技能读条')) {
        this.技能类实例集合[当前事件.事件备注.技能名称].读条伤害()
      } else if (当前事件.事件名称.includes('卸除buff')) {
        this.卸除buff({
          名称: 当前事件.事件备注.buff名称,
          对象: 当前事件.事件备注.buff对象,
          卸除层数: 当前事件.事件备注.卸除层数,
        })
      } else if (当前事件.事件名称 === '临江召唤伤害') {
        this.技能类实例集合.上将军印.召唤伤害(当前事件.事件备注.段数, 当前事件.事件备注.触发见尘)
      } else if (当前事件.事件名称 === '坚壁清野直伤' || 当前事件.事件名称 === '坚壁清野残留') {
        this.技能类实例集合.坚壁清野.延迟伤害(!!当前事件.事件备注.直伤)
      } else if (当前事件.事件名称 === '疏狂刀气' || 当前事件.事件名称 === '疏狂领域刷新') {
        this.技能类实例集合.西楚悲歌.领域生效(!!当前事件.事件备注.刷新增益)
      } else if (当前事件.事件名称 === '擒龙一式转二式') {
        this.技能类实例集合.擒龙六斩.一式转二式()
      } else if (当前事件.事件名称 === '烽河持续伤害') {
        this.技能类实例集合.烽河.造成伤害()
      } else if (当前事件.事件名称 === '资源恢复') {
        const 当前资源 = { 秀明尘身: '狂意', 松烟竹雾: '刀魂', 雪絮金屏: '气劲' }[
          this.角色状态信息.体态
        ]
        ;(['狂意', '刀魂', '气劲'] as const).forEach((资源) => {
          if (资源 !== 当前资源) this.变更资源(资源, 1, '体态恢复')
        })
        this.添加待生效事件队列([{ ...当前事件, 事件时间: this.当前时间 + 16 }])
      }
    }
  }

  开始战斗() {
    if (this.已进入战斗) return
    this.已进入战斗 = true
    this.添加待生效事件队列([{ 事件名称: '资源恢复', 事件时间: this.当前时间 + 16 }])
  }

  添加待生效事件队列(传入数据: 待生效事件[], 事件覆盖 = false) {
    let 新待生效事件队列: 待生效事件[] = []
    // 把原来事件中的同名事件修改时间
    if (事件覆盖) {
      if (this.待生效事件队列?.some((item) => item.事件名称 === 传入数据?.[0]?.事件名称)) {
        新待生效事件队列 = this.待生效事件队列.map((item) => {
          if (item.事件名称 === 传入数据?.[0]?.事件名称) {
            return 传入数据?.[0]
          } else {
            return item
          }
        })
      } else {
        新待生效事件队列 = (this.待生效事件队列 || []).concat(传入数据 || [])
      }
    } else {
      新待生效事件队列 = (this.待生效事件队列 || []).concat(传入数据 || [])
    }
    // 由于不确定待生效事件时间分布，重新排序
    新待生效事件队列.sort((a, b) => {
      return (a?.事件时间 || 0) - (b?.事件时间 || 0)
    })
    this.待生效事件队列 = [...新待生效事件队列]
  }

  删除待生效事件队列(事件名称) {
    const 新待生效事件队列: 待生效事件[] = [...(this.待生效事件队列 || [])].filter(
      (item) => item.事件名称 !== 事件名称,
    )
    // 由于不确定待生效事件时间分布，重新排序
    新待生效事件队列.sort((a, b) => {
      return (a?.事件时间 || 0) - (b?.事件时间 || 0)
    })
    this.待生效事件队列 = [...新待生效事件队列]
  }

  // 按实际套路体态校验
  体态校验(当前技能: 循环基础技能数据类型) {
    if (当前技能?.技能类型 && ['秀明尘身', '松烟竹雾', '雪絮金屏']?.includes(当前技能?.技能类型)) {
      if (this.角色状态信息?.体态 !== 当前技能?.技能类型) {
        return {
          可以释放: false,
          异常信息: ERROR_ACTION.体态错误,
        }
      } else {
        return { 可以释放: true }
      }
    } else {
      return { 可以释放: true }
    }
  }

  // ----------------- 时间、GCD、CD相关算法 start----------------- //
  /**
   *
   * @param 增加时间方法
   * @description 每次增加时间方法都要同步推进GCD
   */
  增加时间(time) {
    if (time > 0) {
      this.跳过全部GCD时间(time)
      this.当前时间 += time
      this.DOT结算与更新()
      this.清空已经消失的buff()
    }
  }

  跳过全部GCD时间(time) {
    // 减少GCD剩余时间
    const 新GCD组: 技能GCD组 = {}
    Object.keys(this.GCD组).map((key) => {
      新GCD组[key] = Math.max((this.GCD组[key] || 0) - time, 0)
    })
    this.GCD组 = { ...新GCD组 }
  }

  更新碎江天GCD() {
    const 碎江天 = this.技能基础数据.find((技能) => 技能.技能名称 === '碎江天')!
    碎江天.技能GCD组 = this.当前自身buff列表.龙息 ? '碎江天' : '公共'
  }

  获取技能GCD组(当前技能: 循环基础技能数据类型) {
    return 当前技能.技能GCD组 === '自身' ? 当前技能.技能名称 : 当前技能.技能GCD组
  }

  技能释放前检查GCD统一方法(当前技能: 循环基础技能数据类型) {
    const 校验GCD组 = this.获取技能GCD组(当前技能)
    if (校验GCD组) {
      // 大部分技能只检查自己的GCD
      const GCD = this.GCD组[校验GCD组]
      // 增加GCD
      return GCD || 0
    }
    return 0
  }

  // 对所有有CD技能检查和充能
  对所有有CD技能检查和充能() {
    Object.keys(this.技能类实例集合).forEach((key) => {
      const 实例 = this.技能类实例集合[key]
      if (实例?.技能运行数据) {
        const 运行数据: 技能运行数据类型 = 实例?.技能运行数据
        const 待充能时间点 = 运行数据?.待充能时间点
        if (待充能时间点?.length) {
          const 新待充能时间点 = 待充能时间点?.filter((item) => item > this.当前时间)
          实例?.更新技能运行数据({ 待充能时间点: 新待充能时间点 })
        }
      }
    })
  }

  技能释放前检查运行数据(当前技能: 循环基础技能数据类型, 技能实例: 检查运行数据实例类型, GCD) {
    let 等待CD时间 = 0
    const 可以释放时间 = this.当前时间 + GCD || 0
    if (技能实例?.技能运行数据) {
      const 待充能时间点 = 技能实例?.技能运行数据?.待充能时间点
      if (待充能时间点?.length >= (当前技能?.最大充能层数 || 1)) {
        const 可释放时间 = 待充能时间点?.[0]
        // 当前没有层数可用，需要等待充能
        if (可释放时间 > 可以释放时间) {
          等待CD时间 = 可释放时间 - 可以释放时间
        }
      }
    }
    return 等待CD时间
  }

