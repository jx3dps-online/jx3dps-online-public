import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 上将军印 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
    this.技能数据 = 模拟循环.技能基础数据.find((技能) => 技能.技能名称 === '上将军印')
  }

  释放() {
    if (!this.模拟循环.校验奇穴是否存在('临江')) {
      return { 可以释放: false, 异常信息: { 信息: '未启用奇穴：临江' } }
    }
    if (this.模拟循环.角色状态信息.狂意 < this.技能数据.消耗数量!) {
      return { 可以释放: false, 异常信息: ERROR_ACTION.资源不足 }
    }
    return { 可以释放: true }
  }

  命中() {
    this.模拟循环.变更资源('狂意', -this.技能数据.消耗数量!, '上将军印')
    this.模拟循环.开始战斗()
    const 模拟 = this.模拟循环
    模拟.添加buff({ 名称: '临江', 对象: '自身' })
    if (模拟.奇穴.includes('斩狂枭')) {
      模拟.结束斩狂枭()
      const 秒数 = Math.floor(模拟.角色状态信息.狂意 / 10)
      if (秒数 > 0) {
        模拟.变更资源('狂意', -秒数 * 10, '斩狂枭')
        模拟.添加buff({ 名称: '斩狂枭', 对象: '自身' })
        模拟.当前自身buff列表.斩狂枭.最大持续时间 = 秒数 * 16
      }
    }
    // 28883 → 召唤上将每跳伤害：分疆7击，常规5击；召唤物切态后仍继续命中。
    const 时刻 = 模拟.奇穴.includes('分疆') ? [4, 8, 12, 16, 20, 24, 28] : [4, 12, 20, 24, 28]
    const 触发见尘 =
      模拟.奇穴.includes('见尘') &&
      !!模拟.技能类实例集合['闹须弥(DOT)'].DOT运行数据.待生效数据.length
    模拟.添加待生效事件队列(
      时刻.map((时间, 段数) => ({
        事件名称: '临江召唤伤害',
        事件时间: 模拟.当前时间 + 时间,
        事件备注: { 技能名称: this.技能数据.技能名称, 段数, 触发见尘 },
      })),
    )
  }

  召唤伤害(段数: number, 触发见尘: boolean) {
    this.触发伤害行为(段数 ? '上将军印·连续' + 段数 : '上将军印')
    if (触发见尘) this.触发伤害行为('上将军印·见尘')
  }
}

export default 上将军印
