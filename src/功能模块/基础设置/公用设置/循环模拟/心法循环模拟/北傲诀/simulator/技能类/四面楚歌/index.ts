import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 四面楚歌 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
    this.技能数据 = 模拟循环.技能基础数据.find((技能) => 技能.技能名称 === '四面楚歌')
  }

  命中() {
    this.模拟循环.开始战斗()
  }

  读条时间() {
    return 48
  }

  读条(开始时间: number) {
    // 42433 的五次延迟子技能；562/69、33515 将动作锁定到第 48 帧。
    this.模拟循环.添加待生效事件队列(
      [2, 18, 30, 40, 47].map((时刻) => ({
        事件名称: '四面楚歌技能读条',
        事件时间: 开始时间 + 时刻,
        事件备注: { 技能名称: this.技能数据.技能名称 },
      })),
    )
    this.本次释放记录.伤害段数 = 5
  }

  读条伤害() {
    this.触发伤害行为('霜云')
  }
}

export default 四面楚歌
