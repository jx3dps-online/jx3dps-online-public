// import 循环主类 from '../main'
import { 获取实际帧数, 获取倒读条实际帧数分布 } from '@/工具函数/data'
import 循环模拟技能基础数据 from '../../../constant/skill'
import { 待生效事件 } from '../../type'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 每秒郭氏帧 } from '@/数据/常量'

class 兵主逆 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '兵主逆')

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  获取读条时间() {
    // 根据加速修改实际读条帧
    const 读条持续时间 = 获取实际帧数(每秒郭氏帧 * 3, this.模拟循环.加速值)
    return 读条持续时间
  }

  释放() {
    // 兵主逆按下时就进入CD并减少绝技调息时间
    const 倒读条开始时间 = this.模拟循环.当前时间 || 0

    // 在兵主逆释放时减少列宿游1秒调息时间
    const 列宿游实例 = this.模拟循环.技能类实例集合?.['列宿游']
    if (列宿游实例?.减少绝技技能CD) {
      列宿游实例.减少绝技技能CD(每秒郭氏帧 * 1)
    }

    // 启动倒读条，3秒内分3跳
    this.倒读条(倒读条开始时间)
  }

  倒读条(倒读条开始时间) {
    const 待生效事件队列: 待生效事件[] = []
    const 循环加速值 = this.模拟循环.加速值 || 0
    const 作用总间隔 = 每秒郭氏帧 * 3 // 3秒倒读条
    const 作用间隔帧 = 每秒郭氏帧 * 1 // 每跳1秒
    const 作用次数 = 3 // 明确指定3次伤害

    // 使用获取倒读条实际帧数分布来计算每跳的实际时间（考虑加速）
    const 作用分布 = 获取倒读条实际帧数分布(作用总间隔, 作用间隔帧, 循环加速值, 0, 0, 作用次数)
    let 已读条时间 = 0

    // 记录累计后的三跳时间点（便于排查是否丢跳/错序）
    const 累计时间点列表: number[] = []
    let 计划累计时间 = 0
    for (let i = 0; i < (作用分布 || []).length; i++) {
      计划累计时间 += 作用分布[i]
      累计时间点列表.push(倒读条开始时间 + 计划累计时间)
    }

    this.模拟循环.添加战斗日志?.({
      日志: `兵主逆倒读条计划：${累计时间点列表.join(',')}`,
      日志类型: '技能释放结果',
      日志时间: 倒读条开始时间,
    })

    // 三跳伤害和堙灭buff触发
    for (let i = 0; i < 作用分布.length; i++) {
      const 事件时间 = 倒读条开始时间 + 已读条时间 + 作用分布[i]
      已读条时间 = 已读条时间 + 作用分布[i]

      待生效事件队列.push({
        事件名称: `兵主逆伤害${i + 1}`,
        事件时间: 事件时间,
        事件备注: {
          技能名称: '兵主逆',
          跳数: i + 1,
        },
      })
    }

    // 倒读条结束事件
    待生效事件队列.push({
      事件名称: `兵主逆倒读条结束`,
      事件时间: 倒读条开始时间 + 已读条时间,
      事件备注: {
        技能名称: '兵主逆',
      },
    })

    this.模拟循环.添加待生效事件队列?.(待生效事件队列)
  }

  造成伤害(跳数) {
    // 倒读条技能：只在有跳数参数时触发伤害（由倒读条事件触发），不在释放时立即触发
    if (!跳数) {
      return
    }

    this.模拟循环.添加战斗日志?.({
      日志: `兵主逆倒读条伤害触发：第${跳数}跳`,
      日志类型: '技能释放结果',
      日志时间: this.模拟循环.当前时间,
    })

    // 每一跳都触发一次堙灭BUFF
    this.模拟循环.添加buff?.({ 名称: '堙灭', 对象: '自身' })

    // 触发兵主逆伤害，附带15%会心和15%会心效果（仅兵主逆读条伤害享受）
    // 堙灭增伤会通过通用增益列表中的无界_通用增伤_5·X自动匹配（通过转化函数映射到堙灭BUFF）
    this.触发伤害行为('兵主逆·悟', 1, ['无界_通用内功会心_15·1', '无界_通用内功会效_15·1'])

    // 每一跳都会附带一次辰星·悟
    this.触发伤害行为('辰星·悟', 1)

    // 如果是第三跳，完全释放结束后获得持续12秒的15%无界通用伤害加成
    if (跳数 === 3) {
      this.模拟循环.添加buff?.({ 名称: '兵主逆增伤', 对象: '自身' })
      this.保存释放记录()
    }
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['兵主逆增伤', '堙灭·悟', '大橙武增伤', '灵灯·悟']),
    }
  }
}

export default 兵主逆

export const 兵主逆类型 = typeof 兵主逆
