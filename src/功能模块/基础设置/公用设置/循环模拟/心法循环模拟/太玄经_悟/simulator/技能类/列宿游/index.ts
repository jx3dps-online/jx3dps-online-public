import 循环模拟技能基础数据 from '../../../constant/skill'
import { 每秒郭氏帧 } from '@/数据/常量'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 列宿游 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '列宿游·悟')

  constructor(模拟循环) {
    super(模拟循环)
    列宿游.技能数据 = 模拟循环?.技能基础数据?.find((item) => item.技能名称 === '列宿游·悟')
    this.初始化技能运行数据()
  }

  释放() {
    // 列宿游在有明灯·悟的时候再次释放会立即减少5秒
    // 需要在释放时检查，因为命中()会添加明灯buff，不要自己减自己
    const 明灯buff = this.模拟循环?.当前自身buff列表?.['明灯']
    if (明灯buff?.当前层数) {
      // 减少5秒调息时间
      this.减少绝技技能CD(每秒郭氏帧 * 5)
    }
  }

  命中() {
    // 先添加BUFF，再触发伤害，确保BUFF在伤害计算时已经存在
    this.模拟循环.添加buff?.({ 名称: '明灯', 对象: '自身' })
    this.添加灵灯Buff()
    this.触发伤害行为('列宿游·悟', 1)
    this.保存释放记录()
  }

  添加灵灯Buff() {
    // 灵灯·悟无法重复叠加，上限为25秒，每次刷新后固定为25秒持续时间
    const 灵灯buff = this.模拟循环?.当前自身buff列表?.['灵灯']
    const 当前时间 = this.模拟循环?.当前时间 || 0
    const 目标持续时间 = 每秒郭氏帧 * 25 // 刷新后固定为25秒

    if (灵灯buff) {
      // 如果已经存在灵灯BUFF，计算剩余时间
      const 刷新时间 = 灵灯buff.刷新时间 || 0
      const 当前最大持续时间 = 灵灯buff.最大持续时间 || 0
      const 延长时间 = 灵灯buff.延长时间 || 0
      const 应该消失时间 = 刷新时间 + 当前最大持续时间 + 延长时间
      const 剩余时间 = Math.max(0, 应该消失时间 - 当前时间)

      // 需要延长到25秒的时间 = 25秒 - 剩余时间
      const 需要延长时间 = 目标持续时间 - 剩余时间

      if (需要延长时间 > 0) {
        // 延长到25秒
        this.模拟循环.延长Buff?.({
          名称: '灵灯',
          对象: '自身',
          来源: '列宿游·悟',
          延长时间: 需要延长时间,
        })
      }
      // 如果剩余时间已经达到或超过25秒，不需要操作
    } else {
      // 如果不存在，直接添加新BUFF
      this.模拟循环.添加buff?.({ 名称: '灵灯', 对象: '自身' })
      // 添加后立即延长到25秒（因为BUFF系统添加的默认持续时间可能不是25秒）
      // 需要在下一个事件循环中处理，这里先添加BUFF
      // 由于添加BUFF后立即检查可能无法获取到，这里暂时依赖BUFF配置的最大持续时间限制
      // 如果需要确保第一次也是25秒，可能需要延迟处理或使用其他方式
    }
  }

  保存释放记录() {
    const 明灯buff数据 = this.获取施加重要buff信息('明灯')
    const 灵灯buff数据 = this.获取施加重要buff信息('灵灯')
    this.本次释放记录 = { 明灯: 明灯buff数据, 灵灯: 灵灯buff数据 } as any
  }
}

export default 列宿游

export const 列宿游类型 = typeof 列宿游
