// import 循环主类 from '../main'
import { 每秒郭氏帧 } from '@/数据/常量'
import 循环模拟技能基础数据 from '../../../constant/skill'
import { 待生效事件 } from '../../type'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 杀星在尾 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '杀星在尾')

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  获取读条时间() {
    // 杀星在尾会读条1秒（16帧）
    return 16
  }

  读条(读条开始时间) {
    // 添加读条结束事件
    const 读条时间 = this.获取读条时间()
    const 读条结束时间 = 读条开始时间 + 读条时间

    this.模拟循环.添加待生效事件队列?.([
      {
        事件名称: '技能读条',
        事件时间: 读条结束时间,
        事件备注: {
          技能名称: '杀星在尾',
        },
      },
    ])
  }

  读条结束后() {
    // 读条完毕后立即获得6%无界通用增伤持续15秒
    this.模拟循环.添加buff?.({ 名称: '无界_通用增伤_6', 对象: '自身' })

    // 开始五秒内每秒造成两次伤害共10次，读条完毕不立即造成伤害
    this.启动持续伤害()
  }

  启动持续伤害() {
    const 待生效事件队列: 待生效事件[] = []
    const 当前时间 = this.模拟循环.当前时间 || 0
    const 总伤害次数 = 10 // 固定10次伤害：5秒 × 每秒钟2次 = 10次

    // 在1、2、3、4、5秒时各一次性触发两次伤害，读条完毕不立即造成伤害，总共固定10次伤害
    let 伤害序号 = 1
    for (let 秒数 = 1; 秒数 <= 5 && 伤害序号 <= 总伤害次数; 秒数++) {
      const 事件时间 = 当前时间 + 每秒郭氏帧 * 秒数

      // 每个整秒时一次性触发两次伤害，确保总共固定10次
      for (let 次数 = 1; 次数 <= 2 && 伤害序号 <= 总伤害次数; 次数++) {
        待生效事件队列.push({
          事件名称: `杀星在尾伤害${伤害序号}`,
          事件时间: 事件时间,
          事件备注: {
            技能名称: '杀星在尾',
            跳数: 伤害序号,
          },
        })
        伤害序号++
      }
    }

    this.模拟循环.添加待生效事件队列?.(待生效事件队列)
  }

  造成伤害(跳数) {
    // 只在有有效跳数时触发伤害，避免主循环无参数调用导致额外伤害
    // 跳数应该为1-10之间，对应我们在启动持续伤害中生成的10次伤害事件
    if (跳数 && 跳数 >= 1 && 跳数 <= 10) {
      this.触发伤害行为('杀星在尾·悟', 1)
    }
  }

  释放后() {
    this.保存释放记录()

    // 杀星在尾减少2秒绝技调息时间
    this.减少绝技技能CD(每秒郭氏帧 * 2)
    this.对阵招式橙武减少绝技技能CD()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['大橙武增伤', '返闭惊魂无双', '灵灯·悟', '堙灭·悟']),
    }
  }
}

export default 杀星在尾

export const 杀星在尾类型 = typeof 杀星在尾
