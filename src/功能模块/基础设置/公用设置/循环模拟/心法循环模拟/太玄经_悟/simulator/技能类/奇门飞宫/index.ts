// import 循环主类 from '../main'
import { 每秒郭氏帧 } from '@/数据/常量'
import 循环模拟技能基础数据 from '../../../constant/skill'
import { 待生效事件 } from '../../type'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 奇门飞宫 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '奇门飞宫')

  static 全局伤害事件名称 = '奇门飞宫全局伤害'

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  释放() {
    // 奇门飞宫是放置类技能，施展后获得一次奇门飞宫·贰的机会
    this.保存释放记录()

    // 启动持续伤害：全局每5秒最多结算一次伤害（多个奇门飞宫不叠加频率）
    const 当前时间 = this.模拟循环.当前时间 || 0
    const 间隔 = 每秒郭氏帧 * 5
    const 持续结束时间 = 当前时间 + 每秒郭氏帧 * 30

    const 循环实例: any = this.模拟循环 as any
    循环实例.奇门飞宫持续伤害结束时间 = Math.max(
      循环实例.奇门飞宫持续伤害结束时间 || 0,
      持续结束时间,
    )

    const 已计划下次伤害时间 = 循环实例.奇门飞宫下次伤害时间 || 0
    const 下次伤害时间 = Math.max(已计划下次伤害时间, 当前时间 + 间隔)
    循环实例.奇门飞宫下次伤害时间 = 下次伤害时间

    const 待生效事件: 待生效事件 = {
      事件名称: 奇门飞宫.全局伤害事件名称,
      事件时间: 下次伤害时间,
      事件备注: {
        技能名称: '奇门飞宫',
        跳数: 1,
      },
    }

    this.模拟循环.添加待生效事件队列?.([待生效事件], true)
  }

  造成伤害(跳数) {
    // 触发奇门飞宫伤害
    this.触发伤害行为('奇门飞宫·悟', 1)

    // 继续安排下一跳（全局每5秒一次，直到持续结束）
    const 循环实例: any = this.模拟循环 as any
    const 当前时间 = this.模拟循环.当前时间 || 0
    const 间隔 = 每秒郭氏帧 * 5
    const 持续结束时间 = 循环实例.奇门飞宫持续伤害结束时间 || 0
    const 下次伤害时间 = 当前时间 + 间隔

    if (下次伤害时间 <= 持续结束时间) {
      循环实例.奇门飞宫下次伤害时间 = 下次伤害时间
      const 待生效事件: 待生效事件 = {
        事件名称: 奇门飞宫.全局伤害事件名称,
        事件时间: 下次伤害时间,
        事件备注: {
          技能名称: '奇门飞宫',
          跳数: (跳数 || 0) + 1,
        },
      }
      this.模拟循环.添加待生效事件队列?.([待生效事件], true)
    }
  }

  释放后() {
    // 奇门飞宫减少3秒绝技调息时间
    this.减少绝技技能CD(每秒郭氏帧 * 3)

    // 清除奇门飞宫·贰的调息时间
    const 奇门飞宫贰实例 = this.模拟循环.技能类实例集合?.['奇门飞宫贰']
    if (奇门飞宫贰实例?.重置调息时间) {
      奇门飞宫贰实例.重置调息时间()
    }
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['大橙武增伤', '灵灯·悟']),
    }
  }
}

export default 奇门飞宫

export const 奇门飞宫类型 = typeof 奇门飞宫
