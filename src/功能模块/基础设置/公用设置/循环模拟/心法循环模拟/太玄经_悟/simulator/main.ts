  添加buff({ 名称, 对象 = '目标', 事件时间 = this.当前时间, 新增层数 = 1, 只添加日志 = false }) {
    const 当前Buff对象 = 对象 === '自身' ? this.当前自身buff列表[名称] : this.当前目标buff列表[名称]
    const 当前层数 = 当前Buff对象?.当前层数

    const buff数据 = this.Buff和Dot数据[名称]
    if (!buff数据) {
      console.warn(`Buff数据不存在: ${名称}`)
      return
    }

    const 新buff对象 = {
      ...buff数据,
      当前层数: Math.min((当前层数 || 0) + 新增层数, buff数据.最大层数 || 1),
      刷新时间: 事件时间,
      延长时间: 名称 === '兵主逆增伤' && 当前Buff对象?.当前层数 ? 0 : 当前Buff对象?.延长时间 || 0,
      已延长次数:
        名称 === '兵主逆增伤' && 当前Buff对象?.当前层数 ? 0 : 当前Buff对象?.已延长次数 || 0,
    }
    if (新buff对象.当前层数 !== 当前层数 && 新buff对象.当前层数 !== 1) {
      this.添加战斗日志({
        日志: `${名称}层数变为【${新buff对象.当前层数}】`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    } else {
      this.添加战斗日志({
        日志: `${对象}获得${名称}`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    }

    if (!只添加日志) {
      if (对象 === '自身') {
        this.当前自身buff列表[名称] = { ...新buff对象 }
      } else {
        this.当前目标buff列表[名称] = { ...新buff对象 }
      }
    }
  }

  延长Buff({ 名称, 延长时间, 对象 = '目标', 来源 = '技能' }) {
    const 当前Buff对象 = 对象 === '自身' ? this.当前自身buff列表[名称] : this.当前目标buff列表[名称]
    if (当前Buff对象 && 当前Buff对象.当前层数) {
      if (
        this.Buff和Dot数据?.[名称]?.最多延长次数 &&
        当前Buff对象.已延长次数 &&
        当前Buff对象.已延长次数 >= this.Buff和Dot数据[名称]?.最多延长次数
      ) {
        return
      }
      const 新buff对象 = {
        ...当前Buff对象,
        延长时间: (当前Buff对象.延长时间 || 0) + 延长时间,
        已延长次数: (当前Buff对象.已延长次数 || 0) + 1,
      }
      this.添加战斗日志({
        日志: `${来源} 触发 ${名称} 延长【${延长时间}】帧`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: this.当前时间,
      })
      if (对象 === '自身') {
        this.当前自身buff列表[名称] = { ...新buff对象 }
      } else {
        this.当前目标buff列表[名称] = { ...新buff对象 }
      }
    }
  }

  卸除buff({
    名称,
    buff刷新时间 = 0,
    对象 = '目标',
    事件时间 = this.当前时间,
    卸除层数 = 1,
    只添加日志 = false,
  }) {
    const 当前层数 =
      对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数

    if (当前层数 && 当前层数 >= 0) {
      if (当前层数 - 卸除层数 > 0) {
        this.添加战斗日志({
          日志: `${名称}层数变为【${当前层数 - 卸除层数}】`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 事件时间,
        })
        if (!只添加日志) {
          const 新buff对象 = {
            ...this.Buff和Dot数据[名称],
            当前层数: 当前层数 - 卸除层数,
            刷新时间: buff刷新时间 || 事件时间,
          }
          if (对象 === '自身') {
            this.当前自身buff列表[名称] = { ...新buff对象 }
          } else {
            this.当前目标buff列表[名称] = { ...新buff对象 }
          }
        }
      } else {
        this.添加战斗日志({
          日志: `${对象}失去${名称}`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 事件时间,
        })
        if (!只添加日志) {
          if (对象 === '自身') {
            delete this.当前自身buff列表[名称]
          } else {
            delete this.当前目标buff列表[名称]
          }
        }
      }
    } else if (只添加日志) {
      this.添加战斗日志({
        日志: `${对象}失去${名称}`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    }
  }

