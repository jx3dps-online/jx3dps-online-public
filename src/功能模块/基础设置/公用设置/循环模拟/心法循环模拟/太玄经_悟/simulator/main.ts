  // ----------------- 时间、GCD、CD相关算法 start----------------- //
  /**
   *
   * @param 增加时间方法
   * @description 每次增加时间方法都要同步推进GCD
   */
  增加时间(time) {
    this.跳过全部GCD时间(time)
    // 增加时间
    this.当前时间 = this.当前时间 + (time > 0 ? time : 0 || 0)
    this.DOT结算与更新()
    this.清空已经消失的buff()
  }

  跳过全部GCD时间(time) {
    // 减少GCD剩余时间
    const 新GCD组: 技能GCD组 = { 公共: 0 }
    Object.keys(this.GCD组).map((key) => {
      新GCD组[key] = Math.max((this.GCD组[key] || 0) - time, 0)
    })
    this.GCD组 = { ...新GCD组 }
  }

  技能释放前检查GCD统一方法(当前技能: 循环基础技能数据类型) {
    let 校验GCD组: string | string[] = 当前技能.技能GCD组 as any
    if (typeof 校验GCD组 === 'object') {
      if (校验GCD组?.length) {
        // 大部分技能只检查自己的GCD
        const GCD = Math.max(this.GCD组[校验GCD组?.[0]] || 0, this.GCD组[校验GCD组?.[1]] || 0)
        // 武学助手的无GCD技能自带多-1段加速
        // if (当前技能.技能GCD组 === '自身' && this.开启武学助手) {
        //   GCD = GCD + 0
        // }
        // 增加GCD
        return GCD || 0
      }
    } else {
      if (当前技能.技能GCD组 === '自身') {
        校验GCD组 = 当前技能?.技能名称
      }
      if (校验GCD组) {
        // 大部分技能只检查自己的GCD
        const GCD = this.GCD组[校验GCD组]
        // 武学助手的无GCD技能自带多-1段加速
        // if (当前技能.技能GCD组 === '自身' && this.开启武学助手) {
        //   GCD = GCD + 0
        // }
        // 增加GCD
        return GCD || 0
      }
    }
    return 0
  }

  // 对所有有CD技能检查和充能
  对所有有CD技能检查和充能() {
    Object.keys(this.技能类实例集合).forEach((key) => {
      const 实例 = this.技能类实例集合[key]
      if (实例?.技能运行数据) {
        const 运行数据: 技能运行数据类型 = 实例?.技能运行数据
        const 待充能时间点 = 运行数据?.待充能时间点
        if (待充能时间点?.length) {
          const 新待充能时间点 = 待充能时间点?.filter((item) => item > this.当前时间)
          实例?.更新技能运行数据({ 待充能时间点: 新待充能时间点 })
        }
      }
    })
  }

  技能释放前检查运行数据(当前技能: 循环基础技能数据类型, 技能实例: 检查运行数据实例类型, GCD) {
    let 等待CD时间 = 0
    const 可以释放时间 = this.当前时间 + GCD || 0
    if (技能实例?.技能运行数据) {
      const 待充能时间点 = 技能实例?.技能运行数据?.待充能时间点
      if (待充能时间点?.length >= (当前技能?.最大充能层数 || 1)) {
        const 可释放时间 = 待充能时间点?.[0]
        // 当前没有层数可用，需要等待充能
        if (可释放时间 > 可以释放时间) {
          等待CD时间 = 可释放时间 - 可以释放时间
        }
      }
    }
    return 等待CD时间
  }

  技能释放后更新运行数据(
    当前技能: 循环基础技能数据类型,
    技能实例: 检查运行数据实例类型,
    增加CD?: number,
  ) {
    const 实际增加CD = 增加CD || 当前技能?.技能CD || 0
    if (技能实例?.技能运行数据) {
      const 待充能时间点 = 技能实例?.技能运行数据?.待充能时间点 || []
      const 本次释放充能 =
        (待充能时间点?.[待充能时间点.length - 1] || this.当前时间) + (实际增加CD || 0)
      const 新待充能时间点 = [...待充能时间点, 本次释放充能]
      技能实例?.更新技能运行数据?.({ 待充能时间点: 新待充能时间点 })
    }
  }

