  // 造成伤害
  技能造成伤害(
    来源,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    造成时间: number | undefined = undefined,
    DOT伤害 = false,
  ) {
    // 战斗未开始前不造成任何伤害
    if (this.战斗开始时间 === undefined) {
      return
    }
    // 如果没有传入造成时间，使用当前时间
    const 实际造成时间 = 造成时间 !== undefined ? 造成时间 : this.当前时间
    const 对应技能 = 技能系数?.find((item) => item.技能名称 === 来源)
    const 技能增益列表 = 获取技能信息(对应技能)?.技能增益列表 || []

    const 有关的buff列表 =
      技能增益列表
        ?.filter((item) => {
          let 判定增益名称 = item.增益名称
          let 增益层数: number | undefined = undefined

          // 只分割"·"后面是数字的情况（如"无界_通用增伤_5·1"），不分割"·"后面是非数字的情况（如"明灯·悟"）
          if (item.增益名称?.includes('·')) {
            const 分割结果 = item.增益名称?.split('·')
            const 后半部分 = 分割结果?.[1]
            // 检查后半部分是否是纯数字
            if (后半部分 && /^\d+$/.test(后半部分)) {
              判定增益名称 = 分割结果?.[0]
              增益层数 = +后半部分
            }
          }

          const 当前增益数据 = 转化buff和增益名称(判定增益名称, this.当前自身buff列表, 增益层数)

          // 全局启用类型的增益：如果有BUFF数据则检查BUFF，如果没有BUFF数据则直接生效（如非侠、无视防御）
          if (item.增益类型 === '全局启用') {
            if (当前增益数据) {
              // 有BUFF数据，需要检查BUFF是否存在且有效
              if (造成时间 !== undefined) {
                const 增益消失时间 =
                  (当前增益数据?.刷新时间 || 0) +
                  (当前增益数据?.最大持续时间 || 0) +
                  (当前增益数据?.延长时间 || 0)
                const 增益获得时间 = 当前增益数据?.刷新时间 || 0
                // 允许造成时间等于或略早于增益获得时间（容差1帧），以处理BUFF刚添加的情况
                return 造成时间 <= 增益消失时间 && !!当前增益数据 && 造成时间 >= 增益获得时间 - 1
              } else {
                // 没有传入时间参数，直接检查BUFF层数（适用于BUFF刚添加的情况）
                return !!当前增益数据?.当前层数
              }
            } else {
              // 没有BUFF数据（如非侠、无视防御），直接生效
              return true
            }
          }

          // 部分启用类型的增益：必须有BUFF数据才能生效
          if (当前增益数据) {
            if (造成时间 !== undefined) {
              const 增益消失时间 =
                (当前增益数据?.刷新时间 || 0) +
                (当前增益数据?.最大持续时间 || 0) +
                (当前增益数据?.延长时间 || 0)
              const 增益获得时间 = 当前增益数据?.刷新时间 || 0
              // 允许造成时间等于或略早于增益获得时间（容差1帧），以处理BUFF刚添加的情况
              return 造成时间 <= 增益消失时间 && !!当前增益数据 && 造成时间 >= 增益获得时间 - 1
            } else {
              // 没有传入时间参数，直接检查BUFF层数（适用于BUFF刚添加的情况）
              return !!当前增益数据?.当前层数
            }
          } else {
            return false
          }
        })
        ?.map((item) => {
          // DOT伤害实时部分buff吃快照，由额外增益列表传入
          if (
            (['灭影追风·悟', '大橙武增伤']?.includes(item?.增益名称) ||
              item?.增益名称?.includes('披靡·悟')) &&
            DOT伤害
          ) {
            return ''
          } else {
            return item.增益名称
          }
        })
        .filter((item) => !!item) || []

    let 总增益列表 = 有关的buff列表.concat(额外增益列表)

    if (this.启用团队增益快照) {
      const 团队增益buff列表 = 判断团队增益快照Buff({
        团队增益轴: this.团队增益轴,
        判定帧: this.当前时间 || 0,
      })
      if (团队增益buff列表?.length) {
        总增益列表 = 总增益列表?.concat(团队增益buff列表)
      }
    }

    this.添加战斗日志({
      日志: 来源,
      日志类型: '造成伤害',
      日志时间: 实际造成时间,
      buff列表: 总增益列表 || [],
      其他数据: {
        伤害次数: 伤害次数,
      },
    })
  }

  检查GCD(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    if (技能实例?.检查GCD) {
      GCD = 技能实例?.检查GCD?.(i)
    } else {
      GCD = this.技能释放前检查GCD统一方法(当前技能)
    }
    return GCD
  }

  // 判断GCD，技能CD等
  技能释放前(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    let 等待CD = 0

    // 判断是否为当前箭袋第一个技能
    if (i >= 0) {
      // 判断上一个技能对于本技能是否有GCD限制
      if (当前技能?.技能GCD组) {
        GCD = this.检查GCD(当前技能, 技能实例, i)
      }
      // 判断技能CD，如果存在CD。增加等待时间
      if (当前技能?.技能CD) {
        等待CD = this.技能释放前检查运行数据(当前技能, 技能实例, GCD)
      }
    }
    const 延迟等待 = this.当前时间 ? this.网络延迟 : 0
    const 技能计划释放时间 = this.当前时间 + GCD + 延迟等待
    return {
      技能计划释放时间: 技能计划释放时间,
      技能预估释放时间: 技能计划释放时间 + 等待CD,
      等待CD,
    }
  }

  技能GCD和CD处理(
    等待CD,
    技能预估释放时间,
    当前技能: 循环基础技能数据类型,
    技能实例: 检查运行数据实例类型,
  ) {
    // 判断在处理完特殊事件以后，剩余的待定时间还有多少
    const 时间差 = 技能预估释放时间 - this.当前时间
    if (时间差 && 时间差 > 0) {
      this.增加时间(时间差)
    }
    if (等待CD) {
      this.添加战斗日志({
        日志: `【${当前技能?.技能名称}】等技能CD【${等待CD}】帧`,
        日志类型: '等CD',
        日志时间: 技能预估释放时间,
      })
      // const 当前层数 = 技能实例?.技能运行数据?.当前层数
      // const 新层数 = Math.min(当前层数 + 1, 当前技能?.最大充能层数 || 1)
      // 技能实例?.更新技能运行数据({ 当前层数: 新层数 })
    }
    const 待充能时间点 = 技能实例?.技能运行数据?.待充能时间点
    const 新待充能时间点 = 待充能时间点?.filter((item) => item > 技能预估释放时间)
    技能实例?.更新技能运行数据?.({ 待充能时间点: 新待充能时间点 })
  }

  // 增加技能GCD
  增加技能GCD(当前技能: 循环基础技能数据类型) {
    // GCD处理
    if (当前技能?.技能GCD组) {
      let 实际添加GCD = 获取实际帧数(当前技能.技能释放后添加GCD, this.加速值)
      if (当前技能?.最小GCD) {
        实际添加GCD = Math.max(实际添加GCD, 当前技能?.最小GCD)
      }
      let 待更新GCD组: string | string[] = 当前技能.技能GCD组 as any
      if (typeof 待更新GCD组 === 'object') {
        if (待更新GCD组?.length) {
          待更新GCD组?.forEach((key) => {
            this.GCD组[key] = (this.GCD组[key] || 0) + 实际添加GCD
          })
        }
      } else {
        if (当前技能.技能GCD组 === '自身') {
          待更新GCD组 = 当前技能?.技能名称
        }
        if (待更新GCD组) {
          this.GCD组[待更新GCD组] = (this.GCD组[待更新GCD组] || 0) + 实际添加GCD
        }
      }
    }
  }

  技能成功开始释放(当前技能: 循环基础技能数据类型, 技能实例) {
    this.增加技能GCD(当前技能)
    this.增加技能CD(当前技能, 技能实例)
  }

