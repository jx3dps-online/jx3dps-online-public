import 技能统一类 from '../../通用类/技能统一类'

class 风矢 extends 技能统一类 {
  static 攻击间隔 = 24
  停手开始时间 = 0
  停手结束时间 = 0

  风矢检查() {
    const 当前时间 = this.模拟循环.当前时间
    const 正在停手 = 当前时间 > this.停手开始时间 && 当前时间 < this.停手结束时间
    if (!正在停手) {
      this.触发伤害行为('风矢')
    }
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '风矢检查',
        事件时间: 正在停手 ? this.停手结束时间 : 当前时间 + 风矢.攻击间隔,
      },
    ])
  }
}

export default 风矢
