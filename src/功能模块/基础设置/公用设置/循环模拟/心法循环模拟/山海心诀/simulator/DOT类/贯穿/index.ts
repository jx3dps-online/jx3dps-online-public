import 通用DOT类 from '../../通用类/通用DOT类'
import { 箭形态枚举 } from '../../../constant/enum'

class 贯穿 extends 通用DOT类 {
  审固触发次数 = 0
  /**
   * 乌烬累计层数与当前贯穿实际生效的增伤必须分开记录。
   * 来源：jx3-package 的 scripts/skill/万灵山庄/山海心诀子技能/ 下，
   * 万灵山庄_通用上一层贯穿.luad 与 万灵山庄_映日强化层数记录.luad。
   *
   * Lua 用隐藏 Buff 34489 记录乌烬层数；只要自身施加的贯穿 26856 还存在，
   * 记录 Buff 就会自动续期，贯穿消失时才清除。续期不会重新赋值贯穿的伤害系数。
   * 上贯穿入口先处理贯穿，再检查当前箭袋首箭是否为金乌状态（2 或 4，即红箭或紫箭）；
   * 满足条件才叠加记录层数，并将贯穿的 fDamageCoefficient 写为 1 + 层数 * 0.2。
   *
   * 玩家反馈桑柘下非金乌箭触发标鹄后，贯穿增伤会丢失。与此吻合的原因是普通上贯穿
   * 调用 AddBuff 刷新了贯穿的伤害系数，而非金乌状态没有重新写入乌烬增伤。
   * AddBuff 重置系数为 1 属于引擎行为，未在上述 Lua 中显式实现；本修复按反馈建模，
   * 仍需游戏伤害记录确认，不能将模拟器自测通过视为该引擎行为已得到验证。
   * 原实现直接用累计乌烬层数结算所有自然跳和引爆，漏掉增伤失效，因而会高估这段伤害。
   *
   * 桑柘仍走 AddBuff，标鹄引爆还会额外上一层贯穿；审固已满 6 层时只延长跳数，
   * 两次延长用尽后也不会重新 AddBuff，所以保留原增伤。审固未满 6 层仍走普通刷新。
   * 因此只在普通刷新时清空乌烬增伤层数，金乌条件满足时再按累计层数写回。
   * 不能在非金乌分支直接将乌烬层数归零：这会误清审固满层时应保留的增伤，且让后续
   * 金乌从 1 层重新累计。例如已有 2 层，非金乌刷新后再触发金乌，应累计到 3 层而非 1 层。
   */
  乌烬层数 = 0
  乌烬增伤层数 = 0
  constructor(模拟循环) {
    super(模拟循环)
  }

  获得和刷新贯穿(来源?) {
    this.结算贯穿伤害()
    const 审固 = this.模拟循环.校验奇穴是否存在('审固')
    // const 贯穿buff数据 = this.模拟循环.当前目标buff列表?.['贯穿']
    const 当前最后一跳贯穿数据 =
      this?.DOT运行数据?.待生效数据?.[this?.DOT运行数据?.待生效数据?.length - 1] || {}
    const 当前贯穿层数 = 当前最后一跳贯穿数据?.当前层数 || 0
    const 贯穿最大层数 = this?.模拟循环?.Buff和Dot数据?.贯穿?.最大层数 || 6
    const 新贯穿层数 = Math.min(当前贯穿层数 + 1, 贯穿最大层数)
    const 原始数据 = this.获取当前DOT数据('贯穿')
    const 贯穿待生效数据 = [...this.DOT运行数据.待生效数据]

    const 贯穿刷新 = () => {
      this.乌烬增伤层数 = 0
      this.模拟循环.添加buff?.({
        名称: '贯穿',
        对象: '目标',
        新增层数: 1,
        只添加日志: true,
      })
      this.更新待生效数据(新贯穿层数, 原始数据)
    }

    if (审固) {
      if (当前贯穿层数 === 6 && this.审固触发次数 < 2) {
        // 增加审固次数
        this.审固触发次数 += 1
        // 更新dot序列
        const 原最后一次生效时间 = 贯穿待生效数据[贯穿待生效数据?.length - 1]?.生效时间 || 0
        // 审固延长4秒等于延长8跳
        for (let i = 0; i < 8; i++) {
          贯穿待生效数据.push({
            当前层数: 新贯穿层数,
            生效时间: 原最后一次生效时间 + 原始数据.伤害频率 * (i + 1),
          })
        }
        this.更新DOT运行数据({
          待生效数据: [...(贯穿待生效数据 || [])],
        })
        // 添加审固日志
        this.模拟循环.添加战斗日志({
          日志: `触发审固，贯穿延长4秒，本次贯穿已触发${this.审固触发次数}次`,
          日志类型: '自身buff变动',
          日志时间: this.模拟循环.当前时间,
        })
      } else if ((当前贯穿层数 || 0) < 6) {
        贯穿刷新()
        this.审固触发次数 = 0
      }
    } else {
      贯穿刷新()
    }
    const 箭形态 = this.模拟循环.角色状态信息.箭袋信息[0]?.箭形态
    // Lua 在公共上贯穿入口读取当前箭袋，而不是延迟命中的箭矢快照。
    if (
      this.模拟循环.校验奇穴是否存在('乌烬') &&
      (箭形态 === 箭形态枚举.红箭 || 箭形态 === 箭形态枚举.紫箭)
    ) {
      this.乌烬层数 = Math.min(this.乌烬层数 + 1, 4)
      this.乌烬增伤层数 = this.乌烬层数
      this.模拟循环.添加战斗日志({
        日志: `乌烬层数变为【${this.乌烬层数}】`,
        日志类型: '目标buff变动',
      })
    }
    this.模拟循环.添加待生效事件队列(
      [
        {
          事件名称: '卸除buff-贯穿',
          事件时间: this.DOT运行数据.待生效数据[this.DOT运行数据.待生效数据.length - 1].生效时间!,
          事件备注: { buff名称: '贯穿', buff对象: '目标', 卸除层数: 6 },
        },
      ],
      true,
    )
    if (来源) {
      this.模拟循环.添加战斗日志?.({
        日志: `${来源}`,
        日志类型: '上贯穿',
        日志时间: this.模拟循环.当前时间,
      })
    }
  }

  结算贯穿伤害(事件时间 = this.模拟循环.当前时间) {
    const { 结算数组: 待生效数据 } = this.结算并更新运行数据(事件时间)
    待生效数据.forEach((数据) => {
      const 层数 = 数据.当前层数 || 1
      const 生效时间 = 数据.生效时间 || 0
      if (生效时间) {
        this.触发伤害行为(
          `贯穿·${[层数]}`,
          1,
          this.乌烬增伤层数 ? [`乌烬·${this.乌烬增伤层数}`] : [],
          生效时间,
        )
      }
    })
    if (!this.DOT运行数据.待生效数据.length) {
      this.乌烬层数 = 0
      this.乌烬增伤层数 = 0
      this.审固触发次数 = 0
    }
  }

  引爆贯穿逻辑(来源, 类型: '棘矢' | '于狩') {
    // 获取当前剩余的贯穿
    let 待生效数据: any[] = [...(this.DOT运行数据.待生效数据 || [])]
    this.模拟循环.添加战斗日志({
      日志: `${来源}`,
      日志类型: `${类型}引爆贯穿`,
      日志时间: this.模拟循环.当前时间,
    })
    if (待生效数据?.length) {
      const 引爆跳数 = Math.min(待生效数据?.length, 3)
      const 当前贯穿层数 = 待生效数据[待生效数据?.length - 1]?.当前层数 || 0
      this.模拟循环.添加战斗日志({
        日志: `贯穿【${当前贯穿层数}】- 引爆【${引爆跳数}】跳`,
        日志类型: '技能释放结果',
        日志时间: this.模拟循环.当前时间,
      })
      this.模拟循环.技能造成伤害(
        `贯穿·${当前贯穿层数 * 引爆跳数}`,
        1,
        this.乌烬增伤层数 ? [`乌烬·${this.乌烬增伤层数}`] : [],
        this.模拟循环.当前时间,
      )
      // 引爆贯穿，减少3跳
      if (待生效数据.length > 3) {
        待生效数据.splice(待生效数据.length - 3)
      } else {
        待生效数据 = []
        this.乌烬层数 = 0
        this.乌烬增伤层数 = 0
        this.审固触发次数 = 0
        this.模拟循环.卸除buff({ 名称: '贯穿', 卸除层数: 6, 只添加日志: true })
      }
      // }
      this.更新DOT运行数据({
        待生效数据: [...(待生效数据 || [])],
      })
    } else {
      this.模拟循环.添加战斗日志({
        日志: `${来源}触发【${类型}】失败，当前无可引爆贯穿`,
        日志类型: '技能释放结果',
        日志时间: this.模拟循环.当前时间,
      })
    }
  }
}

export default 贯穿

export const 贯穿DOT类型 = typeof 贯穿
