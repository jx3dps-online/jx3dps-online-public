import type { 原生模拟器, 原生特殊规则, 原技能数据, 原技能实例 } from './类型'

type 查询模拟器 = Omit<原生模拟器, '技能成功开始释放'> & {
  技能成功开始释放: (技能: 原技能数据, 实例: 原技能实例, 是否读条: boolean, 索引: number) => void
  技能GCD和CD处理: (等待CD: number, 时间: number, 技能: 原技能数据, 实例: 原技能实例) => void
}

// 仅供已核对相同生命周期的心法显式接入；外层负责隔离查询或完整恢复。
export const 查询非读条释放: NonNullable<原生特殊规则['查询释放']> = (模拟, 名称, 索引, 截止) => {
  const 原 = 模拟 as unknown as 查询模拟器
  const 技能 = 原.技能基础数据.find((项) => 项.技能名称 === 名称)
  const 实例 = 原.技能类实例集合[名称]
  if (!技能 || !实例 || 实例.获取读条时间 || 实例.读条 || '读条时间' in 实例) return undefined
  实例.释放前初始化?.({ 宏执行: 1 })
  const 计划 = 原.技能释放前(技能, 实例, 索引)
  if (截止 !== undefined && 计划.技能预估释放时间 > 截止 + 0.000001)
    return { 可以释放: false, 时间: 计划.技能预估释放时间 }
  原.待生效事件结算(计划.技能预估释放时间)
  原.技能GCD和CD处理(计划.等待CD, 计划.技能预估释放时间, 技能, 实例)
  原.技能成功开始释放(技能, 实例, false, 索引)
  // 复演原循环当前只向原校验转发这两个参数，保持同一查询口径。
  const 结果 = 原.技能释放校验(实例, 技能)
  原.清空已经消失的buff()
  return { 可以释放: 结果.可以释放, 时间: 原.当前时间 }
}
