import type { 心法耦合表 } from './类型'

// 只有状态绑定与经过核对的别名留在心法表中，通用默认值在这里维护。
export const 创建耦合表 = (
  配置: Pick<心法耦合表, '名称' | '资源' | '资源显示' | '示例'> & Partial<心法耦合表>,
): 心法耦合表 => ({
  技能: {},
  自身增益: {},
  目标增益: {},
  增益体态: {},
  状态增益别名: {},
  DOT: [],
  字段: {},
  体态字段: '',
  体态名称: {},
  体态别名: {},
  禁用体态: {},
  补充规则: {},
  连招: {},
  资源下限字段: {},
  引导: {},
  沿用技能: true,
  环境字段: {},
  ...配置,
  排除技能: ['换行', '触发橙武', '点掉橙武', '进入斩杀', '删除丹青', ...(配置.排除技能 || [])],
})

export const 通用环境字段: 心法耦合表['环境字段'] = {
  mana: { 名称: '固定内力比例', 默认值: 1, 最大值: 1 },
  npclevel: { 名称: '固定目标 NPC 强度', 默认值: 6, 最大值: 6, 最小值: 1 },
  nearby_enemy: { 名称: '固定附近敌人数', 默认值: 1, 最大值: 100 },
}

export const 读取资源路径 = (角色: Record<string, unknown>, 路径: string): number => {
  const 值 = 路径
    .split('.')
    .reduce<unknown>((对象, 字段) => (对象 as Record<string, unknown>)?.[字段], 角色)
  if (typeof 值 !== 'number' || !Number.isFinite(值))
    throw new Error('原模拟器没有有效的资源状态：' + 路径)
  return 值
}
