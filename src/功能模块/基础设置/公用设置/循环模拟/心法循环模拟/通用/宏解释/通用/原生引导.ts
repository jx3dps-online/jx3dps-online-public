export interface 原生引导 {
  技能: string
  结束帧: number
  跳时刻: number[]
}

const 可以续演前缀 = (
  已有: 原生复演缓存['记录'],
  输入: string[],
  随机记录: number[],
  等待时刻: (number | undefined)[],
) => {
  const 全部输入 = [...输入, '']
  return !!(
    已有 &&
    已有.前缀.length <= 输入.length - 1 &&
    已有.前缀.every((项, i) => 项 === 输入[i]) &&
    已有.等待前缀.every((项, i) => 项 === 等待时刻[i]) &&
    [...已有.未来].every(([i, 项]) => 全部输入[i] === 项) &&
    已有.随机.every((项, i) => 项 === 随机记录[i])
  )
}

export const 可以续演原循环 = (
  已有: 原生复演缓存['记录'],
  输入: string[],
  随机记录: number[],
  等待时刻: (number | undefined)[],
) => 已有?.前缀.length === 输入.length - 1 && 可以续演前缀(已有, 输入, 随机记录, 等待时刻)

// 只暂停原模拟()的读条末尾结算；启动、校验、每跳效果仍由原技能执行。
export const 复演原循环 = (
  初始模拟: 原生模拟器 | (() => 原生模拟器),
  输入: string[],
  随机记录: number[],
  表: 心法耦合表,
  暂停时刻?: number,
  缓存?: 原生复演缓存,
  等待时刻: (number | undefined)[] = [],
  标注等待 = false,
  保存提交快照 = true,
) => {
  const 索引 = 输入.length - 1
  const 全部输入 = [...输入, '']
  const 时间线 = [...等待时刻]
  const 已有 = 缓存?.记录
  // 后续技能依赖使最新前缀失效时，退到最近的兼容快照，只重算受影响的后段。
  const 命中 = [已有, ...(缓存?.历史 || []).slice().reverse()]
    .filter((项): 项 is NonNullable<typeof 项> => !!项)
    .sort((左, 右) => 右.前缀.length - 左.前缀.length)
    .find((项) => 可以续演前缀(项, 输入, 随机记录, 时间线))
  const 起始索引 = 命中?.前缀.length || 0
  const 模拟 = 命中?.模拟 || (typeof 初始模拟 === 'function' ? 初始模拟() : 初始模拟)
  const 版本 = 缓存 ? ++缓存.版本 : 0
  const 名称 = 获取实际技能数据(输入[索引]).实际技能名称
  const 原释放前 = 模拟.技能释放前
  const 原结算 = 模拟.待生效事件结算
  const 原校验 = 模拟.技能释放校验
  const 原开始 = 模拟.本轮模拟开始前
  const 原结束 = 模拟.本轮模拟结束后
  const 原网络延迟 = 模拟.网络延迟
  let 拒绝: ((当前: 原生模拟器) => boolean) | undefined
  const 原随机 = Math.random
  const 随机 = [...随机记录]
  const 暂停 = Symbol('原生引导暂停')
  let 随机索引 = 0
  let 当前索引 = -1
  let 预估 = Infinity
  let 自然就绪时间: number | undefined
  let GCD就绪时间: number | undefined
  let 网络等待: number | undefined
  let 当前预估 = Infinity
  let 开始 = 0
  let 引导: 原生引导 | undefined
  let 已暂停 = false
  const 引导记录: 原生读条记录 = { ...命中?.引导记录 }
  const 未来 = new Map<number, string>(命中?.未来)
  let 提交记录: 原生复演缓存['记录']
  let 省略提交快照 = false
  let 轮次 = 起始索引 - 1
  let 正在执行 = false
  let 观察释放计划 = true
  const 忽略 = new Map<object, Set<PropertyKey>>([
    [
      模拟,
      new Set([
        '技能释放前',
        '待生效事件结算',
        '添加战斗日志',
        '技能释放校验',
        '本轮模拟开始前',
        '本轮模拟结束后',
        '测试循环',
      ]),
    ],
  ])
  const 读条时间 = new Map<string, number>()
  const 原读条方法 = Object.entries(模拟.技能类实例集合).flatMap(([名, 实例]) => {
    const 排除 = new Set<PropertyKey>()
    忽略.set(实例, 排除)
    const 原方法 = 实例.获取读条时间
    if (!原方法) return []
    排除.add('获取读条时间')
    实例.获取读条时间 = (...参数) => {
      const 持续 = 原方法.apply(实例, 参数)
      读条时间.set(名, 持续)
      return 持续
    }
    return [{ 实例, 原方法 }]
  })
  const 观察输入 = new Proxy(全部输入, {
    get(目标, 属性, 接收者) {
      const 值 = Reflect.get(目标, 属性, 接收者)
      if (
        缓存 &&
        正在执行 &&
        观察释放计划 &&
        轮次 <= 索引 &&
        typeof 属性 === 'string' &&
        /^\d+$/.test(属性) &&
        Number(属性) > 轮次
      )
        未来.set(Number(属性), 值)
      return 值
    },
  })
  模拟.本轮模拟开始前 = () => {
    轮次++
    正在执行 = true
    if (命中 && 轮次 === 起始索引) {
      命中.恢复()
      模拟.测试循环 = 观察输入
      随机索引 = 命中.随机.length
    } else if (
      缓存 &&
      索引 > 0 &&
      轮次 === 索引 &&
      模拟.技能释放记录.length === 索引 &&
      随机索引 <= 随机记录.length
    ) {
      缓存.记录 = {
        模拟,
        前缀: 输入.slice(0, 索引),
        等待前缀: 输入.slice(0, 索引).map((_, i) => 时间线[i]),
        未来: new Map([...未来].filter(([i]) => i >= 索引)),
        随机: 随机.slice(0, 随机索引),
        引导记录: { ...引导记录 },
        恢复: 创建原生快照(模拟, 忽略),
      }
    }
    if (
      缓存 &&
      轮次 === 输入.length &&
      模拟.技能释放记录.length === 输入.length &&
      暂停时刻 !== undefined &&
      Math.abs(预估 - 暂停时刻) < 0.000001
    ) {
      if (保存提交快照)
        提交记录 = {
          模拟,
          前缀: [...输入],
          等待前缀: 输入.map((_, i) => 时间线[i]),
          未来: new Map([...未来].filter(([i]) => i > 索引)),
          随机: 随机.slice(0, 随机索引),
          引导记录: { ...引导记录 },
          恢复: 创建原生快照(模拟, 忽略),
        }
      else 省略提交快照 = true
    }
    const 限流时间 = 读取复制宏限流时间(模拟.技能释放记录, 全部输入, 轮次)
    if (限流时间 > 模拟.当前时间) {
      原结算.call(模拟, 限流时间)
      if (限流时间 > 模拟.当前时间) 模拟.增加时间(限流时间 - 模拟.当前时间)
    }
    模拟.网络延迟 = 原网络延迟
    const 原索引 = 当前索引
    const 原预估 = 当前预估
    const 原最后预估 = 预估
    const 原开始时间 = 开始
    const 原计划 = 读取宏网络计划(模拟, 全部输入[轮次], 轮次, 标注等待 && 轮次 === 索引)
    if (轮次 === 索引) {
      自然就绪时间 = 原计划?.就绪时间
      GCD就绪时间 = 原计划?.GCD就绪时间
      网络等待 = 原计划?.网络等待
    }
    const 计划 = 原网络延迟 ? 原计划 : undefined
    当前索引 = 原索引
    当前预估 = 原预估
    预估 = 原最后预估
    开始 = 原开始时间
    const { 额外信息 } = 获取实际技能数据(全部输入[轮次]) as {
      额外信息: Record<string, number> | null
    }
    模拟.网络延迟 = 额外信息?.宏执行 === 1 ? 0 : 原网络延迟
    const 相对等待 = 额外信息?.宏执行 === 1 ? 额外信息.宏等待 || 0 : 0
    const 等待 =
      Math.max(
        模拟.当前时间 + 相对等待,
        时间线[轮次] ?? 模拟.当前时间,
        计划?.就绪时间 ?? 模拟.当前时间,
      ) + (计划?.网络等待 ?? 0)
    if (等待 !== undefined && 等待 > 模拟.当前时间) {
      原结算.call(模拟, 等待)
      if (等待 > 模拟.当前时间) 模拟.增加时间(等待 - 模拟.当前时间)
    }
    原开始.call(模拟)
  }
  模拟.本轮模拟结束后 = () => {
    原结束.call(模拟)
    正在执行 = false
  }
  模拟.技能释放前 = (...参数) => {
    当前索引 = 参数[2] as number
    观察释放计划 =
      缓存?.释放计划依赖后续技能?.(参数[1] as 原技能实例, 参数[0] as 原技能数据) !== false
    let 计划: ReturnType<typeof 原释放前>
    try {
      计划 = 原释放前.apply(模拟, 参数)
    } finally {
      观察释放计划 = true
    }
    当前预估 = 计划.技能预估释放时间
    if (当前索引 === 索引) {
      预估 = 计划.技能预估释放时间
      开始 = 模拟.当前时间
    }
    return 计划
  }
  模拟.技能释放校验 = (实例, 技能) => {
    if (当前索引 !== 索引) return 原校验.call(模拟, 实例, 技能)
    const 校验 = 记录原生拒绝(模拟, 原校验, 实例, 技能)
    拒绝 = 校验.拒绝
    return 校验.结果
  }
  模拟.待生效事件结算 = (时间 = 模拟.当前时间) => {
    let 本次记录: (typeof 引导记录)[number] | undefined
    const 当前名 = 获取实际技能数据(输入[当前索引]).实际技能名称
    const 当前配置 = 表.引导[当前名]
    if (读条时间.get(当前名) && 时间 > 当前预估 && !引导记录[当前索引]) {
      const 跳时刻 = 当前配置
        ? 模拟.待生效事件队列
            .filter(
              (项) =>
                项.事件名称.includes(当前配置.事件名称标记) && 项.事件备注?.技能名称 === 当前名,
            )
            .map((项) => 项.事件时间)
        : []
      引导记录[当前索引] = {
        跳数: 当前配置 ? 跳时刻.length : undefined,
        开始帧: 当前预估,
        结束帧: 时间,
      }
      if (当前配置) {
        本次记录 = 引导记录[当前索引]
      }
      if (跳时刻.length) {
        if (当前索引 === 索引) 引导 = { 技能: 名称, 结束帧: 时间, 跳时刻 }
      }
      if (当前索引 === 索引 && 引导 && 暂停时刻 !== undefined && 暂停时刻 < 时间) {
        const 截止 = Math.max(预估, 暂停时刻)
        原结算.call(模拟, 截止)
        if (截止 > 模拟.当前时间) 模拟.增加时间(截止 - 模拟.当前时间)
        已暂停 = true
        throw 暂停
      }
    }
    原结算.call(模拟, 时间)
    if (本次记录) 本次记录.结束帧 = 模拟.当前时间
  }
  Math.random = () => {
    if (随机索引 >= 随机.length) 随机.push(原随机())
    return 随机[随机索引++]
  }
  try {
    模拟.测试循环 = 观察输入
    模拟.模拟(起始索引)
  } catch (错误) {
    if (错误 !== 暂停) throw 错误
  } finally {
    Math.random = 原随机
    模拟.技能释放前 = 原释放前
    模拟.待生效事件结算 = 原结算
    模拟.技能释放校验 = 原校验
    模拟.本轮模拟开始前 = 原开始
    模拟.本轮模拟结束后 = 原结束
    模拟.网络延迟 = 原网络延迟
    for (const { 实例, 原方法 } of 原读条方法) 实例.获取读条时间 = 原方法
  }
  const 记录 = 模拟.技能释放记录[模拟.技能释放记录.length - 1]
  return {
    模拟,
    恢复模拟: (): 原生模拟器 => {
      // 候选只保留试放结果；真正选中时沿记录随机序列重跑，在原位置保存续接快照。
      if (缓存 && (缓存.版本 !== 版本 || 省略提交快照))
        return 复演原循环(缓存.创建, 输入, 随机, 表, 暂停时刻, 缓存, 时间线, 标注等待).恢复模拟()
      if (缓存) {
        缓存.记录 = 提交记录 || 缓存.记录
        if (提交记录) {
          const 历史 = (缓存.历史 ??= [])
          历史.push(提交记录)
          if (历史.length > 6) 历史.splice(0, 历史.length - 6)
        }
        缓存.版本++
      }
      return 模拟
    },
    随机,
    预估,
    自然就绪时间,
    GCD就绪时间,
    网络等待,
    开始,
    引导: 已暂停 ? 引导 : undefined,
    跳时刻: 引导?.跳时刻 || [],
    引导记录,
    成功: 已暂停 || 模拟.循环执行结果 === '成功',
    拒绝,
    释放时间: 已暂停 ? 预估 : (记录?.开始读条时间 ?? 记录?.实际释放时间),
  }
}

export const 截断引导输入 = (输入: string[], 引导: 原生引导, 时间: number, 表: 心法耦合表) => {
  const 配置 = 表.引导[引导.技能]
  const 跳数 = 引导.跳时刻.filter((帧) => 帧 <= 时间).length
  if (跳数 < 配置.最少回填跳数) return undefined
  // 原输入可能还有显式延迟，回填跳数时一并保留。
  const { 实际技能名称, 额外信息 } = 获取实际技能数据(输入[输入.length - 1])
  const 额外 = { ...(额外信息 as Record<string, number> | null), [配置.次数字段]: 跳数 }
  const 编码 = 生成实际技能序列([{ 技能名称: 实际技能名称, 额外信息: 额外 }])[0]
  return { 输入: [...输入.slice(0, -1), 编码], 额外, 跳数 }
}
