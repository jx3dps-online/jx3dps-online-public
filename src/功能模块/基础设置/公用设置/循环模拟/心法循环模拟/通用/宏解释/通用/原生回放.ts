// Worker 内复用模块，但每个候选必须从同一空状态开始；new 实例不会重置技能类静态字段。
const 恢复心法基线 = new Map<string, () => void>()

const 推进原时间 = (模拟: 原生模拟器, 时间: number) => {
  模拟.待生效事件结算(时间)
  if (时间 > 模拟.当前时间) 模拟.增加时间(时间 - 模拟.当前时间)
  模拟.本轮模拟开始前()
  模拟.本轮模拟结束后()
}

// 候选从原生前缀状态独立复演，校验失败的资源、CD、副作用不会污染当前状态。
// 效果与心法分支全部由原模拟()执行；这里仅保存宏的输入及等待时刻。
export const 创建原生宏接口 = async (
  表: 心法耦合表,
  特殊: 原生特殊规则,
  参数: Record<string, unknown>,
  气血: number,
  环境: Record<string, number>,
): Promise<心法运行接口> => {
  await 初始化工作线程数据(表.名称)
  const 构造 = await 特殊.加载构造器()
  恢复心法基线.get(表.名称)?.()
  const 输入 = 读取续接循环(参数)
  const 决策时刻: (number | undefined)[] = 输入.map(() => undefined)
  const 等待时刻: (number | undefined)[] = 输入.map(() => undefined)
  // 固定参数复制后共享，不冻结调用方或编辑器的数据。
  const 只读参数 = {
    奇穴: 复制快照只读数据(参数.奇穴),
    秘籍: 复制快照只读数据(参数.秘籍),
    团队增益轴: 复制快照只读数据(参数.团队增益轴),
    副本事件实例列表: 复制快照只读数据(参数.副本事件实例列表),
  }
  const 创建 = () => {
    const 模拟 = 构造({ ...参数, ...只读参数, 测试循环: [] })
    共享原生固定配置(模拟, 表.名称)
    return 模拟
  }
  const 初始模拟 = 创建()
  const 禁用原生续演 =
    typeof 特殊.禁用原生续演 === 'function' ? 特殊.禁用原生续演(初始模拟.奇穴) : 特殊.禁用原生续演
  const 复演缓存: 原生复演缓存 | undefined = 禁用原生续演
    ? undefined
    : {
        创建,
        版本: 0,
        局部有效技能索引: 特殊.局部有效技能索引,
        释放计划依赖后续技能: 特殊.释放计划依赖后续技能,
      }
  const 接入: 引擎接入 = {
    模拟: 初始模拟,
    体态允许: () => true,
    读取特殊资源: () => ({
      ...读取特殊资源(接入.模拟.角色状态信息, 表),
      ...特殊.读取特殊资源?.(接入.模拟),
    }),
  }
  // 在续接循环、教师回放及候选执行之前保存一次，包含技能类及继承链的静态数据。
  if (!恢复心法基线.has(表.名称)) 恢复心法基线.set(表.名称, 创建原生快照(接入.模拟, new Map()))
  for (const 项 of 输入) {
    const 名称 = 获取实际技能数据(项).实际技能名称
    if (!接入.模拟.技能类实例集合[名称]) throw new Error('原模拟器不支持当前循环动作：' + 名称)
  }
  const 表含DOT = {
    ...表,
    DOT: Object.keys(接入.模拟.技能类实例集合).filter(
      (名) => !!接入.模拟.技能类实例集合[名].DOT运行数据,
    ),
  }
  const 说明 = 创建心法说明(接入.模拟, 表含DOT, 获取当前数据().奇穴数据)
  const 未学习技能 = new Map<string, string>()
  for (const [名称, 规则] of Object.entries(说明.释放规则)) {
    for (const 条件 of 规则) {
      if (条件.类型 === '奇穴' && !接入.模拟.奇穴.includes(条件.名称)) {
        未学习技能.set(名称, 条件.名称)
        break
      }
    }
  }
  const 校验循环奇穴 = (名称: string, 索引: number) => {
    const 奇穴 = 未学习技能.get(名称)
    if (奇穴)
      throw new Error(`当前循环第 ${索引 + 1} 个动作「${名称}」不可释放：未选择奇穴「${奇穴}」`)
  }
  输入.forEach((项, 索引) => 校验循环奇穴(获取实际技能数据(项).实际技能名称, 索引))
  说明.支持打断 = Object.keys(表.引导).length > 0
  const 读取 = 创建状态读取(接入, 表含DOT, 说明.技能, 气血, 环境)
  let 上个技能 = typeof 参数.宏上个技能 === 'string' ? 参数.宏上个技能 : ''
  const 续接 = 输入.length ? 复演原循环(接入.模拟 as 原生模拟器, 输入, [], 表) : undefined
  if (续接 && !续接.成功) {
    const { 异常索引, 异常信息 } = 续接.模拟.循环异常信息
    const 原因 = typeof 异常信息 === 'string' ? 异常信息 : 异常信息?.信息
    throw new Error(`当前循环第 ${异常索引} 个动作无法续接：${原因}`)
  }
  let 随机记录 = 续接?.随机 || []
  let 循环引导记录 = 续接?.引导记录 || {}
  let 引导: 原生引导 | undefined
  let 引导缓存: 原生复演缓存 | undefined
  let 当前状态 = 读取(上个技能)
  let 上次动作结束时间 = 当前状态.时间
  const 宏限流等待帧 = 当前状态.每秒帧 * 0.01
  let 上次宏释放毫秒 = -Infinity
  let 同毫秒宏释放次数 = 0
  let 下次宏释放时间 = -Infinity
  const 记录宏释放 = (时间: number) => {
    const 毫秒 = Math.floor((时间 * 1000) / 当前状态.每秒帧)
    同毫秒宏释放次数 = 毫秒 === 上次宏释放毫秒 ? 同毫秒宏释放次数 + 1 : 1
    上次宏释放毫秒 = 毫秒
    下次宏释放时间 = 同毫秒宏释放次数 >= 5 ? 时间 + 宏限流等待帧 : -Infinity
  }
  if (续接) {
    for (let 索引 = 0; 索引 < 输入.length; 索引++) {
      const { 额外信息 } = 获取实际技能数据(输入[索引]) as {
        额外信息: Record<string, number> | null
      }
      if (额外信息?.宏执行 !== 1) continue
      const 记录 = 续接.模拟.技能释放记录[索引]
      记录宏释放(记录.开始读条时间 ?? 记录.实际释放时间)
    }
  }
  let 动作额外信息: Record<string, number> = {}
  let 恢复当前: (() => void) | undefined
  let 待回滚 = false
  const 回滚候选 = () => {
    if (!待回滚) return
    恢复当前!()
    if (复演缓存) 复演缓存.版本++
    待回滚 = false
  }
  const 截断 = () => {
    if (!引导) return undefined
    const 回填 = 截断引导输入(输入, 引导, 当前状态.时间, 表)
    if (!回填) return undefined
    恢复当前 ??= 创建原生快照(接入.模拟 as 原生模拟器, new Map())
    const 结果 = 复演原循环(创建, 回填.输入, 随机记录, 表, undefined, 引导缓存, 等待时刻)
    待回滚 = true
    // 原参数必须确实产生所要求的跳数，且包含原技能的打断损耗。
    if (!结果.成功 || 结果.跳时刻.length !== 回填.跳数) return undefined
    return { ...结果, ...回填 }
  }
  const 候选 = new Map<
    string,
    {
      实际技能: string
      释放时间: number
      自然就绪时间?: number
      GCD就绪时间?: number
      网络等待?: number
      原生?: ReturnType<typeof 复演>
    } | null
  >()
  const 原生拒绝 = new Map<string, (当前: 原生模拟器) => boolean>()
  let 截断计划: { 状态: typeof 当前状态; 输入: string[]; 时间: number } | undefined
  const 复演 = (
    名称: string,
    预检 = false,
    保存提交快照 = 参数.宏延后提交快照 !== true,
    提交 = false,
  ) => {
    回滚候选()
    if (!引导 && 原生拒绝.get(名称)?.(接入.模拟 as 原生模拟器)) return undefined
    // 已选中的动作立即提交，不会回滚成未释放；引导截断仍需保存当前状态。
    if (!提交 || 引导) 恢复当前 ??= 创建原生快照(接入.模拟 as 原生模拟器, new Map())
    let 结束 = 引导 && 截断计划?.状态 === 当前状态 ? 截断计划 : undefined
    if (引导 && !结束) {
      const 结果 = 截断()
      if (结果) {
        结束 = { 状态: 当前状态, 输入: 结果.输入, 时间: 结果.模拟.当前时间 }
        // 只复用已知随机序列下的输入和时刻，不共享截断模拟器或其可变状态。
        if (复演缓存 && 结果.随机.length === 随机记录.length) 截断计划 = 结束
      }
    }
    if (引导 && !结束) return undefined
    const 前缀 = 结束?.输入 || 输入
    const 目标时间 = Math.max(当前状态.时间, 结束?.时间 ?? 当前状态.时间)
    const 输入技能 = 生成实际技能序列([
      { 技能名称: 名称, 额外信息: { 宏执行: 1, ...(预检 && 参数.网络延迟 ? { 宏预检: 1 } : {}) } },
    ])[0]
    const 结果 = 复演原循环(
      创建,
      [...前缀, 输入技能],
      随机记录,
      表,
      目标时间,
      复演缓存,
      [...等待时刻, 目标时间],
      参数.宏等待标注 !== false,
      保存提交快照,
    )
    待回滚 = !提交
    if (
      !引导 &&
      结果.拒绝 &&
      结果.随机.length === 随机记录.length &&
      Math.abs(结果.预估 - 目标时间) < 0.000001
    )
      原生拒绝.set(名称, 结果.拒绝)
    const 可用 =
      结果.成功 &&
      结果.释放时间 !== undefined &&
      (预检 ? Math.abs(结果.释放时间 - 目标时间) < 0.000001 : 结果.释放时间 >= 目标时间 - 0.000001)
    return {
      ...结果,
      输入技能,
      可用,
      目标时间,
      实际技能: 名称,
    }
  }
  const 试释放 = (名称: string) => {
    if (当前状态.时间 < 下次宏释放时间) return null
    if (未学习技能.has(名称)) return null
    if (候选.has(名称)) return 候选.get(名称)
    let 结果: {
      实际技能: string
      释放时间: number
      自然就绪时间?: number
      GCD就绪时间?: number
      网络等待?: number
      原生?: ReturnType<typeof 复演>
    } | null = null
    for (const 动作 of 表.动作候选?.[名称] || [名称]) {
      回滚候选()
      if (未学习技能.has(动作)) continue
      if (!引导 && 原生拒绝.get(动作)?.(接入.模拟 as 原生模拟器)) continue
      const 资格 =
        !引导 &&
        // 共享调息动作的作用实例不同，保留原模拟器完整释放校验。
        !表.技能状态来源?.[动作] &&
        可以续演原循环(
          复演缓存?.记录,
          [...输入, 生成实际技能序列([{ 技能名称: 动作, 额外信息: { 宏执行: 1 } }])[0]],
          随机记录,
          等待时刻,
        )
          ? 预检原生释放(接入.模拟 as 原生模拟器, 输入, 动作, false, 特殊.预检浅恢复)
          : undefined
      if (资格 === false) continue
      if (特殊.查询释放 && 复演缓存 && (!引导 || 截断计划?.状态 === 当前状态)) {
        const 查询 = 查询原生资格(
          特殊.查询释放,
          复演缓存,
          引导 ? 截断计划!.输入 : 输入,
          动作,
          随机记录,
          等待时刻,
          Math.max(当前状态.时间, 引导 ? 截断计划!.时间 : 当前状态.时间),
          Number(参数.网络延迟 || 0),
          当前状态,
        )
        if (查询 === null) continue
        if (查询) {
          结果 = 查询
          break
        }
      }
      if (
        引导 &&
        截断计划?.状态 === 当前状态 &&
        复演缓存?.记录 &&
        可以续演原循环(
          复演缓存.记录,
          [
            ...截断计划.输入,
            生成实际技能序列([{ 技能名称: 动作, 额外信息: { 宏执行: 1, 宏预检: 1 } }])[0],
          ],
          随机记录,
          等待时刻,
        )
      ) {
        const 前缀 = 复演缓存.记录
        const 模拟 = 前缀.模拟
        const 恢复前缀 = 创建原生快照(模拟, new Map())
        let 时间可用: boolean | undefined
        恢复当前 ??= 创建原生快照(接入.模拟 as 原生模拟器, new Map())
        try {
          前缀.恢复()
          const 时间 = Math.max(当前状态.时间, 截断计划.时间)
          模拟.测试循环 = [...截断计划.输入, 动作, '']
          模拟.待生效事件结算(时间)
          if (时间 > 模拟.当前时间) 模拟.增加时间(时间 - 模拟.当前时间)
          模拟.本轮模拟开始前()
          时间可用 = 预检原生释放(模拟, 截断计划.输入, 动作, true, 特殊.预检浅恢复)
        } finally {
          恢复前缀()
          恢复当前()
          复演缓存.版本++
        }
        if (时间可用 === false) continue
      }
      let 首次: ReturnType<typeof 复演>
      if (资格 !== true) {
        首次 = 复演(动作, true)
        if (!首次?.可用) continue
      }
      // 当前资格不含网络等待；提交仍交给原网络规则，并允许实际释放晚于决策。
      const 实际 = 参数.网络延迟 ? 复演(动作) : 首次 || 复演(动作)
      if (实际?.可用) {
        结果 = {
          实际技能: 动作,
          释放时间: 实际.释放时间!,
          原生: 实际,
          自然就绪时间: 实际.自然就绪时间,
          GCD就绪时间: 实际.GCD就绪时间,
          网络等待: 实际.网络等待,
        }
        break
      }
    }
    候选.set(名称, 结果)
    return 候选.get(名称)
  }
  const 事件来源 = (): 等待来源[] => {
    回滚候选()
    const 来源: 等待来源[] = []
    if (下次宏释放时间 > 当前状态.时间) 来源.push({ 类型: '宏限流', 时间: 下次宏释放时间 })
    for (const 项 of 接入.模拟.待生效事件队列)
      if (项.事件时间 > 当前状态.时间)
        来源.push({ 类型: '原生事件', 时间: 项.事件时间, 名称: 项.事件名称 })
    for (const [名称, 剩余帧] of Object.entries(接入.模拟.GCD组))
      if (剩余帧 > 0)
        来源.push({
          类型: 'GCD',
          名称,
          剩余帧,
          时间: 正等待时刻(当前状态.时间, 剩余帧),
          浮点后继: 当前状态.时间 + 剩余帧 === 当前状态.时间,
        })
    return 来源
  }
  return {
    说明,
    奇穴: 接入.模拟.奇穴,
    获取状态: () => 当前状态,
    观察未来状态: (时间, 观察) => {
      回滚候选()
      const 恢复 = 创建原生快照({ 接入, 复演缓存, 候选, 原生拒绝 }, new Map())
      const 原状态 = 当前状态
      const 原恢复 = 恢复当前
      try {
        推进原时间(接入.模拟 as 原生模拟器, 时间)
        当前状态 = 读取(上个技能)
        恢复当前 = undefined
        候选.clear()
        原生拒绝.clear()
        if (复演缓存) 复演缓存.版本++
        return 观察(当前状态)
      } finally {
        回滚候选()
        恢复()
        当前状态 = 原状态
        恢复当前 = 原恢复
        待回滚 = false
      }
    },
    获取引导跳时刻: () => 引导?.跳时刻 || [],
    读取循环输入: (循环) =>
      循环.map((项, 索引) => {
        const { 实际技能名称, 额外信息 } = 获取实际技能数据(项)
        校验循环奇穴(实际技能名称, 索引)
        const 引导配置 = 表.引导[实际技能名称]
        return {
          技能: 实际技能名称,
          作用次数: 引导配置 ? 额外信息?.[引导配置.次数字段] : undefined,
        }
      }),
    获取主动等待: (循环, 索引) => {
      回滚候选()
      const { 实际技能名称, 额外信息 } = 获取实际技能数据(循环[索引]) as {
        实际技能名称: string
        额外信息: Record<string, number | 'GCD'> | null
      }
      // 宏等待是距上一动作结束的决策等待，包含切态前的择时；网络等待仍由释放计划计算。
      const 等待 = 额外信息?.宏等待
      const 宏等待 =
        额外信息?.宏执行 === 1 && typeof 等待 === 'number' && Number.isFinite(等待)
          ? Math.max(0, 等待)
          : 0
      const 前瞻等待 = 特殊.教师等待GCD技能?.includes(实际技能名称)
      if (!额外信息?.延迟 && !前瞻等待) return 宏等待
      const 模拟 = 接入.模拟 as 原生模拟器
      const 技能 = 模拟.技能基础数据.find((项) => 项.技能名称 === 实际技能名称)!
      const 实例 = 模拟.技能类实例集合[实际技能名称]
      const 恢复 = 创建原生快照(模拟, new Map())
      try {
        模拟.测试循环 = 循环
        实例.统一初始化?.(额外信息 ?? undefined)
        实例.释放前初始化?.(额外信息 ?? undefined)
        // 原技能内置的后续 GCD 等待也必须先成为真实决策，不能在后续复演时改写释放时间。
        const GCD等待 = 模拟.检查GCD!(技能, 实例, 索引)
        return 额外信息?.延迟 ? GCD等待 : Math.max(宏等待, GCD等待)
      } finally {
        恢复()
      }
    },
    获取循环记录: () => {
      回滚候选()
      const 结果 = 读取教师结果(接入.模拟 as 原生模拟器, 输入, 当前状态.每秒帧, 循环引导记录)
      return {
        ...结果,
        动作: 结果.动作.map((项, 索引) => ({ ...项, 决策时间: 决策时刻[索引] ?? 项.时间 })),
      }
    },
    可以释放技能: (名称) => !!试释放(名称),
    获取实际技能名称: (名称) => 试释放(名称)!.实际技能,
    获取技能释放时间: (名称) => 试释放(名称)!.释放时间,
    获取释放计划: (名称) => {
      const 计划 = 试释放(名称)
      return 计划
        ? {
            技能: 名称,
            实际技能: 计划.实际技能,
            决策时间: 当前状态.时间,
            释放时间: 计划.释放时间,
            自然就绪时间: 计划.自然就绪时间,
            GCD就绪时间: 计划.GCD就绪时间,
            网络等待: 计划.网络等待,
            依赖完整性: '部分',
          }
        : undefined
    },
    获取调度摘要: () => {
      回滚候选()
      const 模拟 = 接入.模拟
      return {
        时间: 当前状态.时间,
        GCD组: { ...模拟.GCD组 },
        充能时刻: Object.fromEntries(
          Object.entries(模拟.技能类实例集合).map(([名称, 实例]) => [
            名称,
            [...(实例.技能运行数据?.待充能时间点 || [])],
          ]),
        ),
        事件: 模拟.待生效事件队列.map((项) => ({
          名称: 项.事件名称,
          时间: 项.事件时间,
          技能: 项.事件备注?.技能名称,
        })),
        增益: (['自身', '目标'] as const).flatMap((对象) =>
          Object.entries(对象 === '自身' ? 模拟.当前自身buff列表 : 模拟.当前目标buff列表).map(
            ([名称, 项]) => ({
              对象,
              名称,
              层数: 项.当前层数 || 0,
              刷新时间: 项.刷新时间,
              失效时间:
                项.最大持续时间 === undefined ? undefined : (项.刷新时间 || 0) + 项.最大持续时间,
            }),
          ),
        ),
        引导: 引导 ? { 技能: 引导.技能, 结束帧: 引导.结束帧, 跳时刻: [...引导.跳时刻] } : undefined,
        依赖完整性: '部分',
      }
    },
    推进时间: (时间) => {
      回滚候选()
      if (引导) {
        const 结果 = 复演原循环(创建, 输入, 随机记录, 表, 时间, 引导缓存, 等待时刻)
        if (!结果.成功) throw new Error('原引导无法继续回放：' + 引导.技能)
        接入.模拟 = 结果.恢复模拟()
        随机记录 = 结果.随机
        循环引导记录 = 结果.引导记录
        // 读条到达末尾后，由结束读条统一提交结束效果。
      } else 推进原时间(接入.模拟 as 原生模拟器, 时间)
      当前状态 = 读取(上个技能, 引导 && { 技能: 引导.技能, 结束帧: 引导.结束帧 })
      恢复当前 = undefined
      候选.clear()
    },
    获取事件来源: 事件来源,
    下个事件时间: () => {
      let 时间 = Infinity
      for (const 项 of 事件来源()) 时间 = Math.min(时间, 项.时间)
      return 时间
    },
    释放技能: (名称) => {
      const 准备 = 试释放(名称)
      const 结果 = 准备 && (准备.原生 || 复演(准备.实际技能, false, true, true))
      if (!结果?.可用) throw new Error('原模拟器拒绝在当前时刻释放：' + 名称)
      动作额外信息 = {
        宏执行: 1,
        宏等待: Math.max(0, 结果.目标时间 - 上次动作结束时间),
        宏等待CD: Math.max(
          0,
          Math.min(结果.目标时间, 结果.自然就绪时间 ?? 结果.目标时间) -
            (结果.GCD就绪时间 ?? 结果.目标时间),
        ),
        宏额外等待: Math.max(0, 结果.目标时间 - (结果.自然就绪时间 ?? 结果.目标时间)),
      }
      决策时刻.push(结果.目标时间)
      输入.push(结果.输入技能)
      等待时刻.push(结果.目标时间)
      原生拒绝.clear()
      随机记录 = 结果.随机
      循环引导记录 = 结果.引导记录
      接入.模拟 = 结果.恢复模拟()
      待回滚 = false
      上个技能 = 名称
      记录宏释放(结果.释放时间!)
      引导 = 结果.引导
      引导缓存 =
        引导 && 复演缓存?.记录
          ? { ...复演缓存, 版本: 0, 历史: [...(复演缓存.历史 || [])] }
          : undefined
      当前状态 = 读取(上个技能, 引导 && { 技能: 引导.技能, 结束帧: 引导.结束帧 })
      上次动作结束时间 = 当前状态.时间
      恢复当前 = undefined
      候选.clear()
      return 动作额外信息
    },
    结束读条: (中断) => {
      回滚候选()
      if (!引导) return undefined
      const 时间 = 当前状态.时间
      const 回填 = 中断 ? 截断() : undefined
      if (中断 && !回填)
        throw new Error(引导.技能 + '：无法回填当前跳数；' + 表.引导[引导.技能].回填失败提示)
      const 结果 = 回填 || 复演原循环(创建(), 输入, 随机记录, 表, undefined, undefined, 等待时刻)
      if (!结果.成功) throw new Error('原引导结束回放失败：' + 引导.技能)
      if (回填) 输入.splice(0, 输入.length, ...回填.输入)
      接入.模拟 = 结果.模拟
      随机记录 = 结果.随机
      循环引导记录 = 结果.引导记录
      if (时间 > 接入.模拟.当前时间) 推进原时间(结果.模拟, 时间)
      引导 = undefined
      引导缓存 = undefined
      待回滚 = false
      原生拒绝.clear()
      当前状态 = 读取(上个技能)
      上次动作结束时间 = 当前状态.时间
      恢复当前 = undefined
      候选.clear()
      return { ...动作额外信息, ...回填?.额外 }
    },
    获取日志: () => {
      回滚候选()
      return 接入.模拟.战斗日志
        .map((项) => ({
          时间: 项.日志时间 || 0,
          类型: 项.日志类型 || '',
          内容: 项.日志,
          增益: 项.buff列表,
        }))
        .sort((左, 右) => 左.时间 - 右.时间)
    },
  }
}
