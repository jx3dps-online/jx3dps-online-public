export const 获取条件变化时间 = (条件: 宏条件 | undefined, 状态: 宏状态): number => {
  if (!条件) return Infinity
  const 待查 = [条件]
  let 最早 = Infinity
  while (待查.length) {
    const 当前 = 待查.pop()!
    if (当前.类型 === '且' || 当前.类型 === '或') {
      待查.push(当前.右, 当前.左)
      continue
    }
    if (当前.类型 !== '增益' || !当前.时间) continue
    for (const 增益 of 获取条件增益(当前, 状态)) {
      const 时间 = 状态.时间 + 增益.剩余帧 - 当前.值 * 状态.每秒帧
      for (const 偏移 of [-0.001 * 状态.每秒帧, 0, 0.001 * 状态.每秒帧]) {
        for (const 严格偏移 of [0, 0.000001]) {
          const 候选 = 时间 + 偏移 + 严格偏移
          if (候选 > 状态.时间 + 0.0000001 && 候选 < 最早) 最早 = 候选
        }
      }
    }
  }
  return 最早
}

export interface 运行观察 {
  选择?: (状态: 宏状态) => 技能宏语句 | undefined
  决策?: (状态: 宏状态, 选中: 技能宏语句 | undefined, 轨迹: 宏运行结果['轨迹']) => void
  下个时间?: (状态: 宏状态) => number
  打断读条?: (状态: 宏状态) => boolean
  等待?: (状态: 宏状态, 下个时间: number, 固有时间: number, 来源: 等待来源[]) => void
  释放后?: (轨迹: 宏运行结果['轨迹'][number]) => void
  停止?: () => boolean
  完成尾部读条?: boolean
  读条期间仅推进?: boolean
  生成范围?: boolean
  样本动作数?: number
  控制?: () => Promise<unknown>
}

export const 获取固有等待来源 = (状态: 宏状态, 接口: 心法运行接口, 截止时间: number) => {
  const 来源: 等待来源[] = [
    { 类型: '截止', 时间: 截止时间 },
    { 类型: '轮询', 时间: 状态.时间 + 1 },
  ]
  for (const [名称, 技能] of Object.entries(状态.技能)) {
    if (技能.阻塞帧 > 0)
      来源.push({
        类型: '技能阻塞',
        名称,
        时间: 正等待时刻(状态.时间, 技能.阻塞帧),
        剩余帧: 技能.阻塞帧,
        浮点后继: 状态.时间 + 技能.阻塞帧 === 状态.时间,
      })
  }
  if (接口.获取事件来源) {
    for (const 项 of 接口.获取事件来源()) 来源.push(项)
  } else 来源.push({ 类型: '原生事件', 时间: 接口.下个事件时间() })
  if (状态.读条) 来源.push({ 类型: '读条', 名称: 状态.读条.技能, 时间: 状态.读条.结束帧 })
  return 来源
}

export const 获取固有等待时间 = (状态: 宏状态, 接口: 心法运行接口, 截止时间: number) => {
  let 时间 = Infinity
  for (const 项 of 获取固有等待来源(状态, 接口, 截止时间)) 时间 = Math.min(时间, 项.时间)
  return 时间
}

export class 宏运行错误 extends Error {
  constructor(public 结果: 宏运行结果) {
    super(结果.结束.原始错误?.信息 || 结果.结束.原因)
    this.name = '宏运行错误'
  }
}

export const 选择宏语句 = (
  语句: 宏语句[],
  状态: 宏状态,
  接口: 心法运行接口,
  宏库 = new Map<string, 宏配置>(),
  已选择 = new Map<string, 技能宏语句 | undefined>(),
): 技能宏语句 | undefined => {
  if (语句.length && !状态.读条) {
    const 自动 = 接口.说明.自动技能?.find((项) => 状态.数值[项.资源] === 项.数值)
    if (自动)
      return (
        接口.可以释放技能
          ? 接口.可以释放技能(自动.技能)
          : !获取不可释放原因(自动.技能, 状态, 接口.说明.释放规则[自动.技能], 接口.奇穴)
      )
        ? { 行号: 语句[0].行号, 命令: 'cast', 技能: 自动.技能, 自动技能: true }
        : undefined
  }
  for (const 行 of 语句) {
    if (行.条件 && !判定条件(行.条件, 状态)) continue
    if (行.命令 === 'mcast') {
      if (!已选择.has(行.宏)) {
        已选择.set(
          行.宏,
          选择宏语句(选择宏页面(宏库.get(行.宏)!, 状态).语句, 状态, 接口, 宏库, 已选择),
        )
      }
      const 选中 = 已选择.get(行.宏)
      if (选中)
        return {
          ...选中,
          条件:
            行.条件 && 选中.条件
              ? { 类型: '且', 左: 行.条件, 右: 选中.条件 }
              : 行.条件 || 选中.条件,
        }
      continue
    }
    if (状态.读条 && 行.命令 !== 'fcast') continue
    const 连招 = 接口.说明.连招[行.技能]?.find((后续) => 状态.自身增益[后续.增益]?.层数 > 0)
    const 技能 = 连招?.技能 || 行.技能
    // 原生预检确认当前释放资格，网络等待由提交阶段按原规则处理。
    // 不能用通用等待估算提前排除，或提前选中尚未就绪的高优先级技能。
    if (
      接口.可以释放技能
        ? 接口.可以释放技能(技能)
        : !获取不可释放原因(技能, 状态, 接口.说明.释放规则[技能], 接口.奇穴)
    )
      return { ...行, 技能 }
  }
}

export const 选择宏页面 = (配置: 宏配置, 状态: 宏状态) =>
  配置.页.find((页) => 页.体态 === undefined || 页.体态 === (状态.翻页体态 ?? 状态.体态)) || {
    语句: [],
  }

function* 运行宏步骤(
  文本: string,
  秒数: number,
  接口: 心法运行接口,
  单次 = false,
  宏列表: 宏定义[] = [],
  观察?: 运行观察,
): Generator<void, 宏运行结果> {
  const 最长秒数 = 观察?.生成范围 ? 1200 : 300
  if (!Number.isFinite(秒数) || 秒数 <= 0 || 秒数 > 最长秒数)
    throw new Error(`模拟时长应在 0 到 ${最长秒数} 秒之间`)
  const { 配置, 宏库 } = 编译宏调用(文本, 接口.说明, 宏列表)
  const 等待读条结束 =
    !观察 &&
    ![配置, ...宏库.values()].some((宏) =>
      宏.页.some((页) => 页.语句.some((行) => 行.命令 === 'fcast')),
    )
  const 起点 = performance.now()
  const 轨迹: 宏运行结果['轨迹'] = []
  let 状态 = 接口.获取状态()
  const 起始帧 = 状态.时间
  const 截止时间 = 起始帧 + 秒数 * 状态.每秒帧
  const 结束: 运行结束 = {
    原因: '正常终点',
    起始帧,
    目标截止帧: 截止时间,
    最后决策帧: 起始帧,
    原生最终帧: 起始帧,
    决策区间已结束: false,
    尾部已结算: false,
    已提交动作数: 0,
  }
  let 循环次数 = 0
  let 片段开始 = performance.now()
  let 唤醒来源: 等待来源[] = []
  let 阶段 = '初态事件'
  try {
    接口.推进时间(状态.时间)
    状态 = 接口.获取状态()
    while (观察?.生成范围 ? 状态.时间 <= 截止时间 + 1e-7 * 状态.每秒帧 : 状态.时间 < 截止时间) {
      if (观察?.生成范围 && performance.now() - 片段开始 >= 16) {
        yield
        片段开始 = performance.now()
      }
      if (观察?.停止?.()) {
        结束.原因 = '观察停止'
        break
      }
      // 有限样本到此关闭新决策，已提交动作仍须完成原生结算。
      if (观察?.样本动作数 !== undefined && 轨迹.length >= 观察.样本动作数) break
      循环次数++
      if (!观察?.生成范围 && 循环次数 > 50000) {
        结束.原因 = '执行步数上限'
        break
      }
      阶段 = '读条结束'
      if (状态.读条 && (状态.时间 >= 状态.读条.结束帧 || 观察?.打断读条?.(状态))) {
        const 中断 = 状态.时间 < 状态.读条.结束帧
        const 额外信息 = 接口.结束读条(中断)
        if (中断) 轨迹[轨迹.length - 1].额外信息 = 额外信息
        状态 = 接口.获取状态()
        轨迹[轨迹.length - 1].释放后 = 状态
      }
      if (状态.读条 && (等待读条结束 || 观察?.读条期间仅推进)) {
        if (状态.时间 >= 截止时间) break
        阶段 = '读条推进'
        const 下个时间 = Math.min(状态.读条.结束帧, 截止时间, 观察?.下个时间?.(状态) ?? Infinity)
        if (!(下个时间 > 状态.时间)) {
          结束.原因 = '事件不推进'
          break
        }
        接口.推进时间(下个时间)
        状态 = 接口.获取状态()
        continue
      }
      阶段 = '选择动作'
      const 语句 = 选择宏页面(配置, 状态).语句
      const 选中 = 观察?.选择 ? 观察.选择(状态) : 选择宏语句(语句, 状态, 接口, 宏库)
      结束.最后决策帧 = 状态.时间
      观察?.决策?.(状态, 选中, 轨迹)
      if (观察?.停止?.()) {
        结束.原因 = '观察停止'
        break
      }
      if (选中) {
        阶段 = '释放计划'
        const 计划 = 接口.获取释放计划?.(选中.技能)
        const 实际技能 = 计划?.实际技能 || 接口.获取实际技能名称?.(选中.技能) || 选中.技能
        const 释放时间 = 计划?.释放时间 ?? 接口.获取技能释放时间?.(选中.技能) ?? 状态.时间
        if (观察?.生成范围 ? 释放时间 > 截止时间 + 1e-7 * 状态.每秒帧 : 释放时间 >= 截止时间) {
          接口.推进时间(截止时间)
          状态 = 接口.获取状态()
          break
        }
        if (!观察?.生成范围 && 轨迹.length >= 3000) {
          结束.原因 = '动作上限'
          break
        }
        const 决策前 = 状态
        const 调度前 = 接口.获取调度摘要?.()
        if (状态.读条) {
          阶段 = '打断读条'
          轨迹[轨迹.length - 1].额外信息 = 接口.结束读条(true)
          状态 = 接口.获取状态()
          轨迹[轨迹.length - 1].释放后 = 状态
          if (
            !接口.可以释放技能 &&
            ((选中.条件 && !判定条件(选中.条件, 状态)) ||
              获取不可释放原因(选中.技能, 状态, 接口.说明.释放规则[选中.技能], 接口.奇穴))
          )
            continue
        }
        阶段 = '提交释放'
        const 额外信息 = 接口.释放技能(选中.技能) || undefined
        const 释放后 = 接口.获取状态()
        轨迹.push({
          序号: 轨迹.length + 1,
          行号: 选中.行号,
          技能: 实际技能,
          ...(选中.自动技能 ? { 自动技能: true } : {}),
          额外信息,
          时间: 释放时间,
          决策前,
          释放后,
          诊断: {
            决策序号: 循环次数,
            决策时间: 决策前.时间,
            来源: 观察?.选择 ? '观察' : '宏',
            释放计划: 计划,
            唤醒来源,
            调度前,
            调度后: 接口.获取调度摘要?.(),
          },
        })
        唤醒来源 = []
        状态 = 释放后
        观察?.释放后?.(轨迹[轨迹.length - 1])
        if (单次) {
          结束.原因 = '单次完成'
          break
        }
        continue
      }
      if (观察?.生成范围 && 状态.时间 >= 截止时间) break
      阶段 = '等待计划'
      const 来源 = 获取固有等待来源(状态, 接口, 截止时间)
      let 固有时间 = Infinity
      for (const 项 of 来源) 固有时间 = Math.min(固有时间, 项.时间)
      const 添加条件 = (宏: 宏配置) => {
        for (const 行 of 选择宏页面(宏, 状态).语句) {
          const 时间 = 获取条件变化时间(行.条件, 状态)
          if (Number.isFinite(时间)) 来源.push({ 类型: '条件', 时间, 名称: String(行.行号) })
        }
      }
      添加条件(配置)
      for (const 宏 of 宏库.values()) 添加条件(宏)
      const 观察时间 = 观察?.下个时间?.(状态)
      if (观察时间 !== undefined) 来源.push({ 类型: '观察', 时间: 观察时间 })
      let 下个时间 = Infinity
      for (const 项 of 来源) 下个时间 = Math.min(下个时间, 项.时间)
      唤醒来源 = 来源.filter((项) => 项.时间 === 下个时间)
      观察?.等待?.(状态, 下个时间, 固有时间, 唤醒来源)
      if (!(下个时间 > 状态.时间)) {
        结束.原因 = '事件不推进'
        break
      }
      阶段 = '等待推进'
      接口.推进时间(下个时间)
      状态 = 接口.获取状态()
    }
    结束.决策区间已结束 = 结束.原因 === '正常终点'
    if (状态.读条 && ['正常终点', '单次完成', '观察停止'].includes(结束.原因)) {
      阶段 = '尾部引导'
      if (单次 || !观察 || (观察.完成尾部读条 && !观察.停止?.()) || 观察.生成范围) {
        接口.推进时间(Math.min(状态.读条.结束帧, 观察?.下个时间?.(状态) ?? Infinity))
        状态 = 接口.获取状态()
      }
      轨迹[轨迹.length - 1].额外信息 = 接口.结束读条(!!状态.读条 && 状态.时间 < 状态.读条.结束帧)
      状态 = 接口.获取状态()
      轨迹[轨迹.length - 1].释放后 = 状态
    }
    if (
      结束.原因 === '正常终点' &&
      观察?.样本动作数 !== undefined &&
      轨迹.length >= 观察.样本动作数 &&
      状态.时间 < 截止时间
    ) {
      阶段 = '样本尾部事件'
      接口.推进时间(截止时间)
      状态 = 接口.获取状态()
    }
    结束.尾部已结算 = !状态.读条 && ['正常终点', '单次完成', '观察停止'].includes(结束.原因)
  } catch (错误) {
    结束.原因 = '原生错误'
    结束.决策区间已结束 = false
    结束.尾部已结算 = false
    结束.原始错误 = {
      名称: 错误 instanceof Error ? 错误.name : 'Error',
      信息: 错误 instanceof Error ? 错误.message : String(错误),
      阶段,
    }
    状态 = 接口.获取状态()
  }
  结束.原生最终帧 = 状态.时间
  结束.已提交动作数 = 轨迹.length
  const 结果 = {
    轨迹,
    最终状态: 状态,
    日志: 接口.获取日志(),
    用时毫秒: performance.now() - 起点,
    结束,
  }
  if (!['正常终点', '单次完成', '观察停止'].includes(结束.原因)) throw new 宏运行错误(结果)
  return 结果
}

export const 运行宏 = (...参数: Parameters<typeof 运行宏步骤>): 宏运行结果 => {
  const 步骤 = 运行宏步骤(...参数)
  let 下个 = 步骤.next()
  while (!下个.done) 下个 = 步骤.next()
  return 下个.value
}

export const 分批运行宏 = async (
  文本: string,
  秒数: number,
  接口: 心法运行接口,
  单次 = false,
  宏列表: 宏定义[] = [],
  观察?: 运行观察,
): Promise<宏运行结果> => {
  const 控制 = 观察?.控制 ?? (() => new Promise((解决) => setTimeout(解决, 0)))
  const 步骤 = 运行宏步骤(文本, 秒数, 接口, 单次, 宏列表, 观察)
  try {
    let 下个 = 步骤.next()
    while (!下个.done) {
      await 控制()
      下个 = 步骤.next()
    }
    return 下个.value
  } finally {
    步骤.return(undefined as never)
  }
}
