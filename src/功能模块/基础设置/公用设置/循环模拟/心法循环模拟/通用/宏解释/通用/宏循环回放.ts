import { 获取实际技能数据 } from '../../通用函数'
import { 创建原生快照 } from './原生快照'
import { 创建原生查询检查点 } from './原生查询副本'
import type { 原生模拟器 } from './类型'
import { 每秒郭氏帧 } from '@/数据/常量'

interface 循环实例 {
  测试循环: string[]
  网络延迟: number
  当前时间: number
  技能释放记录: unknown[]
  模拟: () => void
  本轮模拟开始前: () => void
  待生效事件结算: (时间: number) => void
  增加时间: (时间: number) => void
}

export const 读取复制宏限流时间 = (记录列表: unknown[], 输入: string[], 索引: number) => {
  const 额外信息 = 获取实际技能数据(输入[索引]).额外信息 as Record<string, unknown> | null
  if (额外信息?.宏执行 !== 1 || 额外信息.宏复制 !== 1) return -Infinity
  let 输入索引 = 索引 - 1
  let 最新释放时间: number | undefined
  let 同毫秒次数 = 0
  // 沿用宏接口的 5 次/10ms 规则，只读取成功记录，避免资格查询消耗次数。
  for (let i = 记录列表.length - 1; i >= 0; i--) {
    const 记录 = 记录列表[i] as {
      自动插入?: boolean
      实际释放时间: number
      开始读条时间?: number
    }
    if (记录.自动插入) continue
    const 前项信息 = 获取实际技能数据(输入[输入索引--]).额外信息 as Record<string, unknown> | null
    if (前项信息?.宏执行 !== 1) continue
    const 时间 = 记录.开始读条时间 ?? 记录.实际释放时间
    最新释放时间 ??= 时间
    if (Math.floor((时间 * 1000) / 每秒郭氏帧) !== Math.floor((最新释放时间 * 1000) / 每秒郭氏帧))
      break
    if (++同毫秒次数 === 5) return 最新释放时间 + 每秒郭氏帧 * 0.01
  }
  return -Infinity
}

// 在动作起点查询原网络规则，避免宏先等到 GCD 结束后绕过衔接延迟分支。
export const 读取宏网络计划 = (模拟: 原生模拟器, 输入: string, 索引: number, 读取就绪 = false) => {
  const { 实际技能名称, 额外信息 } = 获取实际技能数据(输入) as {
    实际技能名称: string
    额外信息: Record<string, number> | null
  }
  if (额外信息?.宏执行 !== 1 || 额外信息.宏预检 === 1 || (!模拟.网络延迟 && !读取就绪))
    return undefined
  const 技能 = 模拟.技能基础数据.find((项) => 项.技能名称 === 实际技能名称)!
  const 实例 = 模拟.技能类实例集合[实际技能名称]
  const 检查点 = 创建原生查询检查点(模拟)
  const 恢复 =
    检查点?.恢复 || 创建原生快照({ 实例, 技能 }, new Map([[实例, new Set(['模拟循环'])]]))
  const 网络延迟 = 模拟.网络延迟
  try {
    实例.统一初始化?.(额外信息)
    实例.释放前初始化?.(额外信息)
    const 原计划 = 模拟.技能释放前(技能, 实例, 索引)
    if (!网络延迟)
      return {
        就绪时间: 原计划.技能预估释放时间,
        GCD就绪时间: 原计划.技能计划释放时间,
        网络等待: 0,
      }
    恢复()
    模拟.网络延迟 = 0
    实例.统一初始化?.(额外信息)
    实例.释放前初始化?.(额外信息)
    const 就绪计划 = 模拟.技能释放前(技能, 实例, 索引)
    return {
      就绪时间: 就绪计划.技能预估释放时间,
      GCD就绪时间: 就绪计划.技能计划释放时间,
      网络等待: Math.max(0, 原计划.技能预估释放时间 - 就绪计划.技能预估释放时间),
    }
  } finally {
    if (检查点) 检查点.结束()
    else 恢复()
    模拟.网络延迟 = 网络延迟
  }
}

export const 执行宏标记循环 = (模拟: 循环实例) => {
  const 输入 = 模拟.测试循环.map(
    (项) => 获取实际技能数据(项).额外信息 as Record<string, number> | null,
  )
  if (!输入.some((项) => 项?.宏执行 === 1)) return 模拟.模拟()
  const 原开始 = 模拟.本轮模拟开始前
  const 原延迟 = 模拟.网络延迟
  const 复制技能等待CD = new Map<number, number>()
  let 索引 = -1
  模拟.本轮模拟开始前 = () => {
    const 额外 = 输入[++索引]
    const 限流时间 = 读取复制宏限流时间(模拟.技能释放记录, 模拟.测试循环, 索引)
    if (限流时间 > 模拟.当前时间) {
      模拟.待生效事件结算(限流时间)
      if (限流时间 > 模拟.当前时间) 模拟.增加时间(限流时间 - 模拟.当前时间)
    }
    模拟.网络延迟 = 原延迟
    const 计划 = 读取宏网络计划(模拟 as 原生模拟器, 模拟.测试循环[索引], 索引)
    if (额外?.宏执行 === 1 && 额外.宏复制 === 1 && 计划) {
      复制技能等待CD.set(索引, Math.max(0, 计划.就绪时间 - 计划.GCD就绪时间))
    }
    模拟.网络延迟 = 额外?.宏执行 === 1 ? 0 : 原延迟
    const 宏等待 = 额外?.宏执行 === 1 && Number.isFinite(额外.宏等待) ? 额外.宏等待 : 0
    const 时间 =
      Math.max(模拟.当前时间 + 宏等待, 计划?.就绪时间 ?? 模拟.当前时间) + (计划?.网络等待 ?? 0)
    if (时间 > 模拟.当前时间) {
      模拟.待生效事件结算(时间)
      if (时间 > 模拟.当前时间) 模拟.增加时间(时间 - 模拟.当前时间)
    }
    原开始.call(模拟)
  }
  try {
    模拟.模拟()
    模拟.技能释放记录.forEach((记录, 索引) => {
      const 等待CD = 复制技能等待CD.get(索引)
      const 释放记录 = 记录 as { 计划释放时间: number }
      // 只补回预推进消耗的 CD 等待，保留正式释放阶段的显式延迟。
      if (等待CD !== undefined) 释放记录.计划释放时间 -= 等待CD
    })
  } finally {
    模拟.本轮模拟开始前 = 原开始
    模拟.网络延迟 = 原延迟
  }
}
