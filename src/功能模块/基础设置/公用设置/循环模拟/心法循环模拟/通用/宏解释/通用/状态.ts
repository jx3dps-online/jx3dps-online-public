import type { 增益状态, 宏状态, 技能状态 } from '../类型'
import type { 原增益数据, 引擎接入, 心法耦合表 } from './类型'
import { 每秒郭氏帧 } from '@/数据/常量'
import { 读取资源路径 } from './耦合默认值'
import { 读取通用调息, 读取冷却绑定 } from './调息查询'

const 提取增益 = (列表: Record<string, 原增益数据>, 时间: number): Record<string, 增益状态> => {
  return Object.fromEntries(
    Object.entries(列表).map(([名称, 增益]) => [
      名称,
      {
        层数: 增益.当前层数 || 0,
        剩余帧:
          增益.最大持续时间 !== undefined
            ? Math.max(0, (增益.刷新时间 || 0) + 增益.最大持续时间 + (增益.延长时间 || 0) - 时间)
            : Infinity,
      },
    ]),
  )
}

export const 创建状态读取 = (
  接入: 引擎接入,
  表: 心法耦合表,
  支持技能: string[],
  气血: number,
  环境: Record<string, number>,
) => {
  return (上个技能: string, 读条?: 宏状态['读条']): 宏状态 => {
    const { 模拟 } = 接入
    const 技能状态: Record<string, 技能状态> = {}
    for (const 技能 of 模拟.技能基础数据.filter((技能) => 支持技能.includes(技能.技能名称))) {
      const 名称 = 技能.技能名称
      const 状态名称 = 表.技能状态来源?.[名称] || 名称
      const 实例 = 模拟.技能类实例集合[状态名称]
      const 充能队列: number[] = 实例.技能运行数据?.待充能时间点 || []
      const 剩余充能 =
        (技能.最大充能层数 || 1) - 充能队列.filter((时间) => 时间 > 模拟.当前时间).length
      const 调息帧 = 剩余充能 > 0 ? 0 : Math.max(0, 充能队列[0] - 模拟.当前时间)
      const 状态技能 = 模拟.技能基础数据.find((项) => 项.技能名称 === 状态名称)!
      const GCD = 模拟.技能释放前检查GCD统一方法(状态技能)
      const 阻塞 = Math.max(GCD, 调息帧)
      技能状态[名称] = {
        调息帧,
        冷却帧: 读取冷却绑定(模拟, 表, 名称),
        充能: 表.技能充能?.[名称]
          ? 读取资源路径(模拟.角色状态信息, 表.技能充能[名称].路径)
          : Math.max(0, 剩余充能),
        最大充能: 表.技能充能?.[名称]?.最大值 || 技能.最大充能层数 || 1,
        阻塞帧: 阻塞,
        体态允许: 接入.体态允许(名称),
      }
    }
    Object.assign(技能状态, 读取通用调息(模拟, 表))
    const 自身增益 = 提取增益(模拟.当前自身buff列表, 模拟.当前时间)
    for (const [名称, 来源] of Object.entries(表.增益资源来源 || {})) {
      if (来源.奇穴 && !模拟.奇穴.includes(来源.奇穴)) continue
      const 层数 = 读取资源路径(模拟.角色状态信息, 来源.路径)
      if (层数 > 0) 自身增益[名称] = { 层数, 剩余帧: Infinity }
    }
    for (const [名称, 来源] of Object.entries(表.增益层数来源 || {})) {
      const 当前 = 来源.find((项) => 自身增益[项.名称]?.层数 > 0)
      if (当前) 自身增益[名称] = { ...自身增益[当前.名称], 层数: 当前.层数 }
    }
    for (const [名称, 别名] of Object.entries(表.状态增益别名)) {
      if (模拟.奇穴.includes(别名.奇穴)) {
        if (自身增益[别名.名称]) 自身增益[名称] = { ...自身增益[别名.名称] }
        else delete 自身增益[名称]
      }
    }
    const 体态 = 表.体态名称[String(模拟.角色状态信息[表.体态字段])] ?? 0
    for (const [名称, 值] of Object.entries(表.增益体态)) {
      if (体态 === 值) 自身增益[名称] = { 层数: 1, 剩余帧: Infinity }
    }
    const 目标增益 = 提取增益(模拟.当前目标buff列表, 模拟.当前时间)
    for (const 名称 of 表.DOT) {
      const DOT运行数据 = 模拟.技能类实例集合[名称].DOT运行数据!
      const 待生效 = DOT运行数据.待生效数据
      const 最后一跳 = 待生效[待生效.length - 1]
      if (最后一跳)
        目标增益[模拟.Buff和Dot数据[名称]?.名称 || 名称] = {
          层数: (最后一跳.当前层数 ?? DOT运行数据.当前层数)!,
          剩余帧: Math.max(0, 最后一跳.生效时间 - 模拟.当前时间),
        }
    }
    return {
      时间: 模拟.当前时间,
      每秒帧: 每秒郭氏帧,
      数值: {
        ...环境,
        ...Object.fromEntries(
          Object.entries(表.资源)
            .filter(([, 字段]) => !字段.startsWith('特殊:'))
            .map(([名称, 字段]) => [
              名称,
              读取资源路径(模拟.角色状态信息, 字段) * (表.资源倍率?.[名称] ?? 1),
            ]),
        ),
        ...接入.读取特殊资源?.(),
        life: 气血,
      },
      自身增益,
      目标增益,
      技能: 技能状态,
      上个技能,
      数值容差: { life: 0.001, mana: 0.001 },
      体态,
      翻页体态: 表.翻页体态映射?.[体态],
      奇穴: [...模拟.奇穴],
      已有技能: 支持技能.filter(
        (技能) =>
          模拟.技能基础数据.find((数据) => 数据.技能名称 === 技能)?.显示类型 !== '奇穴技能' ||
          模拟.奇穴.includes(
            模拟.技能基础数据.find((数据) => 数据.技能名称 === 技能)!.依赖奇穴名 || 技能,
          ),
      ),
      读条,
    }
  }
}
