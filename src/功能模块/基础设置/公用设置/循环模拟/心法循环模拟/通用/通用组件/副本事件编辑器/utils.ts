/**
 * 副本事件编辑器工具函数
 */
import { v4 as uuidV4 } from 'uuid'
import { 每秒郭氏帧 } from '@/数据/常量'
import {
  副本事件定义类型,
  副本事件实例类型,
  副本事件方案类型,
  副本事件阶段类型,
} from '@/@types/副本事件'

export const 副本事件方案版本 = '1.0.0'

// 内置默认方案：不可重命名/删除，内容为默认填充，只读
export const 默认方案名称 = '常规增益'
export const 默认方案总时间 = 每秒郭氏帧 * 60 * 10

// 未知事件（不在事件定义中）的兜底颜色
export const 默认事件颜色 = '#8c8c8c'

// 帧 → 分:秒(帧)
export const 帧转分秒帧 = (帧: number) => {
  const 总帧 = Math.max(0, Math.round(帧))
  const 分 = Math.floor(总帧 / (每秒郭氏帧 * 60))
  const 秒 = Math.floor((总帧 % (每秒郭氏帧 * 60)) / 每秒郭氏帧)
  const 剩余帧 = 总帧 % 每秒郭氏帧
  const 时分秒 = `${分}:${秒.toString().padStart(2, '0')}`
  return {
    分,
    秒,
    帧: 剩余帧,
    时分秒,
    文本: 剩余帧 > 0 ? `${时分秒}(${剩余帧})` : 时分秒,
  }
}

// 分:秒(帧) → 帧
export const 分秒帧转帧 = (分: number, 秒: number, 帧: number) => {
  return 分 * 60 * 每秒郭氏帧 + 秒 * 每秒郭氏帧 + 帧
}

// 实例总持续时间 = Σ阶段.持续时间
export const 获取实例总持续时间 = (实例: 副本事件实例类型) => {
  return (实例?.阶段列表 || []).reduce((sum, 阶段) => sum + (阶段?.持续时间 || 0), 0)
}

// 查找事件定义
export const 获取事件定义 = (事件名称: string, 事件定义列表: 副本事件定义类型[]) => {
  return 事件定义列表?.find((item) => item?.事件名称 === 事件名称)
}

// 深拷贝阶段列表
const 拷贝阶段列表 = (阶段列表: 副本事件阶段类型[]): 副本事件阶段类型[] => {
  return (阶段列表 || []).map((阶段) => ({ ...阶段 }))
}

// 根据事件定义创建一个实例
export const 创建副本事件实例 = (
  事件定义: 副本事件定义类型,
  释放时间: number,
): 副本事件实例类型 => {
  return {
    id: uuidV4(),
    事件名称: 事件定义?.事件名称,
    释放时间,
    阶段列表: 拷贝阶段列表(事件定义?.阶段列表),
  }
}

// 自动填充：可重复事件按 CD 连续铺满到总时间；一次性只加 1 个
export const 自动填充实例 = (
  事件定义: 副本事件定义类型,
  首次施放时间: number,
  总时间: number,
): 副本事件实例类型[] => {
  const 结果: 副本事件实例类型[] = []
  const 首次时间 = Math.max(0, 首次施放时间)
  if (!事件定义?.可重复 || 事件定义?.默认CD <= 0) {
    结果.push(创建副本事件实例(事件定义, 首次时间))
    return 结果
  }
  let 当前时间 = 首次时间
  while (当前时间 <= 总时间) {
    结果.push(创建副本事件实例(事件定义, 当前时间))
    当前时间 = 当前时间 + 事件定义.默认CD
  }
  return 结果
}

// 检测同一事件的重叠实例，返回重叠的实例 id 对
export const 检测重叠实例 = (实例列表: 副本事件实例类型[]) => {
  const 重叠对: { 实例A: 副本事件实例类型; 实例B: 副本事件实例类型 }[] = []
  const 按事件分组: { [key: string]: 副本事件实例类型[] } = {}
  ;(实例列表 || []).forEach((实例) => {
    if (!按事件分组[实例?.事件名称]) {
      按事件分组[实例?.事件名称] = []
    }
    按事件分组[实例?.事件名称].push(实例)
  })

  Object.keys(按事件分组).forEach((事件名称) => {
    const 组 = 按事件分组[事件名称]
    for (let i = 0; i < 组.length; i++) {
      for (let j = i + 1; j < 组.length; j++) {
        const A = 组[i]
        const B = 组[j]
        const A结束 = A.释放时间 + 获取实例总持续时间(A)
        const B结束 = B.释放时间 + 获取实例总持续时间(B)
        if (A.释放时间 < B结束 && B.释放时间 < A结束) {
          重叠对.push({ 实例A: A, 实例B: B })
        }
      }
    }
  })
  return 重叠对
}

// 判断某个新实例是否与已有同事件实例重叠
export const 判断实例是否重叠 = (实例列表: 副本事件实例类型[], 目标实例: 副本事件实例类型) => {
  const 目标结束 = 目标实例.释放时间 + 获取实例总持续时间(目标实例)
  return (实例列表 || []).some((实例) => {
    if (实例?.id === 目标实例?.id || 实例?.事件名称 !== 目标实例?.事件名称) {
      return false
    }
    const 结束 = 实例.释放时间 + 获取实例总持续时间(实例)
    return 目标实例.释放时间 < 结束 && 实例.释放时间 < 目标结束
  })
}

// 根据事件定义生成「默认填充」的实例列表：
// 对所有「默认参与」的事件，从 0 帧起按 CD 连续铺满到总时间；一次性事件只加 1 个。
// 相当于重置为最基础的默认轴。
export const 生成默认填充实例列表 = (
  事件定义列表: 副本事件定义类型[],
  总时间: number,
): 副本事件实例类型[] => {
  const 事件实例列表: 副本事件实例类型[] = []
  ;(事件定义列表 || []).forEach((定义) => {
    if (定义?.默认参与 === false) {
      return
    }
    // 号令三军等一次性事件：默认参与时也放在 0 帧释放一次
    if (!定义?.可重复 || 定义?.默认CD <= 0) {
      事件实例列表.push(创建副本事件实例(定义, 0))
      return
    }
    // 可重复事件：从 0 帧开始按 CD 铺满
    事件实例列表.push(...自动填充实例(定义, 0, 总时间))
  })
  return 事件实例列表
}

// 生成内置默认方案（内容 = 默认填充）
export const 生成默认方案 = (
  事件定义列表: 副本事件定义类型[],
  总时间: number = 默认方案总时间,
): 副本事件方案类型 => {
  return {
    方案名称: 默认方案名称,
    总时间,
    事件实例列表: 生成默认填充实例列表(事件定义列表, 总时间),
    版本: 副本事件方案版本,
  }
}

// 生成「事件名称 -> CD」映射（用于时间轴间隔提示）
export const 生成事件CD映射 = (
  事件定义列表: 副本事件定义类型[],
): { [事件名称: string]: number } => {
  const 映射: { [事件名称: string]: number } = {}
  ;(事件定义列表 || []).forEach((定义) => {
    if (定义?.默认CD > 0) {
      映射[定义.事件名称] = 定义.默认CD
    }
  })
  return 映射
}
