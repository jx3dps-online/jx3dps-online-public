/**
 * 战斗曲线 - 增益泳道类型与计算工具
 * 泳道区间统一使用「秒」为单位，与曲线 x 轴时间一致
 */

import { 每秒郭氏帧 } from '@/数据/常量'
import { 循环日志数据类型 } from '../../../../typs'
import { 副本事件实例类型, 副本事件定义类型 } from '@/@types/副本事件'
import { 团队增益轴类型 } from '@/@types/团队增益'
import 事件定义原始 from '../副本事件编辑器/事件定义.json'

const 事件定义列表 = 事件定义原始 as 副本事件定义类型[]

export interface 增益区间 {
  开始: number // 秒
  结束: number // 秒
  层数?: number // 覆盖区间内的层数（>1 时在滑块上展示）
}

export interface 增益泳道类型 {
  名称: string
  颜色: string
  图标?: string
  区间列表: 增益区间[]
}

// 监听增益描述（心法传入）
export interface 监听增益类型 {
  名称: string
  颜色?: string
  图标?: string
}

// 默认泳道颜色（当事件定义未提供颜色时兜底）
const 默认泳道颜色 = '#5B8FF9'

// 根据事件名称获取事件定义的颜色/图标
const 获取事件颜色图标 = (事件名称: string): { 颜色: string; 图标?: string } => {
  const 定义 = 事件定义列表?.find((item) => item?.事件名称 === 事件名称)
  return {
    颜色: 定义?.颜色 || 默认泳道颜色,
    图标: 定义?.图标,
  }
}

/**
 * 根据副本事件实例列表计算团队增益泳道（事件级）
 * 每个事件一个泳道，区间 = 实例释放时间 ~ 释放时间+总持续时间（多实例多区间）
 */
export const 计算副本事件泳道 = (事件实例列表: 副本事件实例类型[]): 增益泳道类型[] => {
  if (!事件实例列表?.length) {
    return []
  }

  const 泳道映射: { [key: string]: 增益泳道类型 } = {}

  ;(事件实例列表 || []).forEach((实例) => {
    if (!实例?.事件名称) {
      return
    }
    const 总持续时间 = (实例.阶段列表 || []).reduce((s, 阶段) => s + (阶段?.持续时间 || 0), 0)
    const 开始 = (实例.释放时间 || 0) / 每秒郭氏帧
    const 结束 = ((实例.释放时间 || 0) + 总持续时间) / 每秒郭氏帧
    if (结束 <= 开始) {
      return
    }

    if (!泳道映射[实例.事件名称]) {
      const { 颜色, 图标 } = 获取事件颜色图标(实例.事件名称)
      泳道映射[实例.事件名称] = {
        名称: 实例.事件名称,
        颜色,
        图标,
        区间列表: [],
      }
    }
    泳道映射[实例.事件名称].区间列表.push({ 开始, 结束 })
  })

  // 每个泳道内区间按时间排序
  return Object.values(泳道映射).map((泳道) => ({
    ...泳道,
    区间列表: [...泳道.区间列表].sort((a, b) => a.开始 - b.开始),
  }))
}

/**
 * 根据旧团队增益轴（释放时间点/平均间隔/持续时间）计算泳道
 */
export const 计算团队增益轴泳道 = (团队增益轴: 团队增益轴类型): 增益泳道类型[] => {
  if (!团队增益轴) {
    return []
  }

  const 泳道: 增益泳道类型[] = []

  Object.keys(团队增益轴).forEach((增益名称) => {
    const 增益数据 = 团队增益轴[增益名称]
    if (!增益数据) {
      return
    }
    const 区间列表: 增益区间[] = []
    const 持续时间 = 增益数据.持续时间 || 0
    const 释放时间点 = 增益数据.释放时间点 || []
    const 平均间隔 = 增益数据.平均间隔

    if (增益名称 === '号令三军') {
      // 号令三军：一次性，一鼓 + 二鼓（与伤害计算 判断团队增益快照Buff 一致）
      const 释放时间 = 释放时间点?.[0] || 0
      if (持续时间 > 0) {
        区间列表.push({
          开始: 释放时间 / 每秒郭氏帧,
          结束: (释放时间 + 持续时间) / 每秒郭氏帧,
        })
        区间列表.push({
          开始: (释放时间 + 持续时间) / 每秒郭氏帧,
          结束: (释放时间 + 持续时间 * 2) / 每秒郭氏帧,
        })
      }
    } else if (平均间隔 && 平均间隔 > 0) {
      // 初次释放时间 + n * 平均间隔 循环（与伤害计算 判断时间点是否在事件内 一致）
      const 初次释放时间 = 释放时间点?.[0] || 0
      const 最大次数 = 100
      for (let n = 0; n < 最大次数; n++) {
        const 开始帧 = 初次释放时间 + n * 平均间隔
        区间列表.push({
          开始: 开始帧 / 每秒郭氏帧,
          结束: (开始帧 + 持续时间) / 每秒郭氏帧,
        })
      }
    } else if (释放时间点?.length) {
      // 无平均间隔：按实际释放时间点一次性绘制
      释放时间点.forEach((时间点) => {
        if (持续时间 > 0) {
          区间列表.push({
            开始: 时间点 / 每秒郭氏帧,
            结束: (时间点 + 持续时间) / 每秒郭氏帧,
          })
        }
      })
    }

    if (区间列表.length) {
      const { 颜色, 图标 } = 获取事件颜色图标(增益名称)
      泳道.push({ 名称: 增益名称, 颜色, 图标, 区间列表 })
    }
  })

  return 泳道
}

/**
 * 从战斗日志中，根据监听增益列表计算增益泳道（同时支持自身/目标 buff）
 * 依据「自身buff变动/目标buff变动」日志的获得/失去/层数变为事件，精确判断 buff 存在与消失时间（含提前卸载），
 * 并在层数变化处拆分区间，记录每个子区间内的具体层数（便于在曲线上观察层数变化）。
 */
export const 计算自身增益泳道 = (
  日志信息: 循环日志数据类型[],
  监听列表: 监听增益类型[],
  总战斗用时帧: number,
): 增益泳道类型[] => {
  if (!日志信息?.length || !监听列表?.length) {
    return []
  }

  return (监听列表 || [])
    .map((监听) => {
      const 区间列表: 增益区间[] = []
      let 当前层数 = 0
      let 区间开始帧: number | null = null
      let 当前区间层数 = 0

      const 结束当前区间 = (结束帧: number) => {
        if (区间开始帧 != null && 结束帧 > 区间开始帧) {
          区间列表.push({
            开始: 区间开始帧 / 每秒郭氏帧,
            结束: 结束帧 / 每秒郭氏帧,
            层数: 当前区间层数,
          })
        }
        区间开始帧 = null
        当前区间层数 = 0
      }

      for (const 日志 of 日志信息) {
        if (日志?.日志类型 !== '自身buff变动' && 日志?.日志类型 !== '目标buff变动') {
          continue
        }
        const 文本 = 日志?.日志 || ''
        const 时间帧 = 日志?.日志时间 || 0
        let 新层数 = 当前层数

        if (文本.includes(`获得${监听.名称}`)) {
          // 「获得」既可能是新 buff（0→1），也可能是同层数刷新（层数不变）
          新层数 = 当前层数 === 0 ? 1 : 当前层数
        } else if (文本.includes(`失去${监听.名称}`)) {
          新层数 = 0
        } else if (文本.includes(`${监听.名称}层数变为`)) {
          const 匹配 = 文本.match(/层数变为【(\d+)】/)
          新层数 = 匹配 ? parseInt(匹配[1], 10) : 当前层数
        } else {
          continue
        }

        if (新层数 === 当前层数) {
          continue
        }

        if (当前层数 === 0 && 新层数 > 0) {
          // buff 开始存在
          区间开始帧 = 时间帧
          当前区间层数 = 新层数
        } else if (当前层数 > 0 && 新层数 === 0) {
          // buff 消失（含提前卸载）
          结束当前区间(时间帧)
        } else if (当前层数 > 0 && 新层数 > 0) {
          // 层数变化：拆分当前子区间，开启新子区间（记录变化后的层数）
          结束当前区间(时间帧)
          区间开始帧 = 时间帧
          当前区间层数 = 新层数
        }
        当前层数 = 新层数
      }

      // 战斗结束时仍未消失的 buff，用总战斗用时补齐结束时间
      if (区间开始帧 != null) {
        结束当前区间(总战斗用时帧 || 区间开始帧 + 每秒郭氏帧)
      }

      // 合并「相邻且同层数」的区间，避免重复展示（只合并真正相连的区间，不能把多次离散的覆盖并成一段）
      const 合并后区间: 增益区间[] = []
      for (const 区间 of 区间列表) {
        const 上一个 = 合并后区间[合并后区间.length - 1]
        if (上一个 && 上一个.层数 === 区间.层数 && 区间.开始 <= 上一个.结束) {
          上一个.结束 = Math.max(上一个.结束, 区间.结束)
        } else {
          合并后区间.push({ ...区间 })
        }
      }

      return {
        名称: 监听.名称,
        颜色: 监听.颜色 || 默认泳道颜色,
        图标: 监听.图标,
        区间列表: 合并后区间,
      }
    })
    .filter((泳道) => 泳道.区间列表?.length)
}
