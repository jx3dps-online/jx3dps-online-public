import 循环模拟技能基础数据 from '../../../constant/skill'
import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 血刀 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '血刀')
  static 消耗怒气 = 10

  释放() {
    const 当前怒气 = this.模拟循环.角色状态信息?.怒气 || 0
    if (当前怒气 < 血刀.消耗怒气) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.怒气不足,
      }
    }

    const 闪刀换血刀层数 = this.模拟循环.当前自身buff列表?.['闪刀换血刀']?.当前层数
    if (闪刀换血刀层数) {
      // 释放血刀，消耗一层闪刀换血刀；两层消耗完后buff移除，切回闪刀
      this.模拟循环.卸除buff?.({ 名称: '闪刀换血刀', 对象: '自身', 卸除层数: 1 })
    } else {
      return {
        可以释放: false,
        异常信息: '血刀不可释放，缺少闪刀换血刀',
      }
    }

    return { 可以释放: true }
  }

  造成伤害() {
    // 客户端按目标流血状态选择子技能：目标带31385三层流血或带自身的8249流血 → 13143，否则 13144（苍云_苍雪刀_血刀.lua）
    const 目标流血层数 = this.模拟循环.技能类实例集合?.流血?.当前层数?.() || 0
    if (目标流血层数 > 0) {
      this.触发伤害行为('血刀·有流血')
    } else {
      this.触发伤害行为('血刀')
    }
    // 血刀命中添加流血：血刀本身即可对目标添加流血（使用者确认），无条件铺层；DOT结算时按登锋奇穴自动区分常规流血与登锋流血
    this.模拟循环.技能类实例集合?.流血?.获得和刷新流血?.()
    this.触发消耗怒气(血刀.消耗怒气, 血刀.技能数据?.技能名称)
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒', '血怒_惊涌', '威压', '橙武']),
    }
  }

  获取技能释放记录结果() {
    return {
      ...this.本次释放记录,
    }
  }
}

export default 血刀
export const 血刀类型 = typeof 血刀
