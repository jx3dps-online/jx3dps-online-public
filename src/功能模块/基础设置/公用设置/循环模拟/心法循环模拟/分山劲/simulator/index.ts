/**
 * 定义模拟循环类
 */

import 循环主类, { SimulatorCycleProps } from './main'
import { 执行宏标记循环 } from '../../通用/宏解释/通用/宏循环回放'

const 模拟循环 = (props: SimulatorCycleProps) => {
  const 模拟实例 = new 循环主类(props)
  执行宏标记循环(模拟实例)

  模拟实例.日志排序()

  const 当前各技能运行状态 = 模拟实例.获取当前各技能的运行状态()
  const 当前DOT运行状态 = 模拟实例.获取各DOT的运行状态()

  // 盾飞/盾回的切体态是延迟事件：事件未触发时角色状态信息还是切换前的体态，
  // 暴露下一个将切换到的体态供 UI 判断技能可用性（盾飞后斩刀不应被禁用）
  const 待生效切体态事件 = 模拟实例.待生效事件队列?.find(
    (事件) =>
      ['盾飞切体态', '盾回切体态']?.includes(事件?.事件名称 || '') &&
      (事件?.事件时间 || 0) > 模拟实例.当前时间,
  )
  const 待生效体态切换 = 待生效切体态事件
    ? 待生效切体态事件.事件名称 === '盾飞切体态'
      ? ('擎刀' as const)
      : ('擎盾' as const)
    : undefined

  return {
    最终日志: 模拟实例.战斗日志,
    当前自身buff列表: 模拟实例.当前自身buff列表,
    当前目标buff列表: 模拟实例.当前目标buff列表,
    角色状态信息: 模拟实例.角色状态信息,
    待生效体态切换,
    当前时间: 模拟实例.当前时间,
    循环执行结果: 模拟实例.循环执行结果,
    循环异常信息: 模拟实例.循环异常信息,
    技能释放记录: 模拟实例.技能释放记录,
    当前各技能运行状态,
    当前DOT运行状态,
    当前GCD组: 模拟实例.GCD组,
    技能基础数据: 模拟实例.技能基础数据,
  }
}

export default 模拟循环
