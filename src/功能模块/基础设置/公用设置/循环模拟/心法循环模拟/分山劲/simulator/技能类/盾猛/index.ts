// import 循环主类 from '../main'
import { 每秒郭氏帧 } from '@/数据/常量'
import 循环模拟技能基础数据 from '../../../constant/skill'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 盾猛 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '盾猛')
  static 回复怒气 = 0
  // 释放时（消耗威压前）的自身威压层数，供「显示盾猛威压层数」开关渲染
  释放时威压层数 = 0

  constructor(模拟循环) {
    super(模拟循环)

    盾猛.回复怒气 = 15

    this.初始化技能运行数据()
  }

  释放() {
    // 盾飞施展后获得飞盾(8873)，0.5秒内无法施展盾猛
    if (this.模拟循环.当前自身buff列表?.['飞盾0.5秒无法使用盾猛']?.当前层数) {
      return {
        可以释放: false,
        异常信息: '飞盾0.5秒无法使用盾猛',
      }
    }
    return { 可以释放: true }
  }

  命中(_是否为最后一个技能: boolean, 循环位置: number) {
    // 盾压重置触发源：盾猛施放判定（35%概率/期望，见 技能统一类.尝试盾压重置）
    this.尝试盾压重置(循环位置)
  }

  造成伤害(_索引) {
    // 威压：盾猛消耗威压强化自身，最多消耗6层，每层伤害提高30%并返还1秒调息时间
    const 威压层数 = this.模拟循环.当前自身buff列表?.['威压']?.当前层数 || 0
    this.释放时威压层数 = 威压层数
    const 消耗层数 = Math.min(威压层数, 6)
    if (消耗层数) {
      this.模拟循环.卸除buff?.({ 名称: '威压', 对象: '自身', 卸除层数: 消耗层数 })
      this.触发伤害行为('盾猛', 1, [`威压·${消耗层数}`])
      this.减少调息时间?.(消耗层数 * 每秒郭氏帧)
    } else {
      this.触发伤害行为('盾猛')
    }
  }

  释放后() {
    // 残裂：盾猛命中敌人时额外回复20点怒气
    if (this.模拟循环.校验奇穴是否存在?.('残裂')) {
      this.触发回复怒气(盾猛.回复怒气 + 20, '残裂' + 盾猛.技能数据?.技能名称)
    } else {
      this.触发回复怒气(盾猛.回复怒气, 盾猛.技能数据?.技能名称)
    }
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒', '血怒_惊涌', '威压', '橙武']),
    }
  }

  获取技能释放记录结果() {
    return {
      ...this.本次释放记录,
      特殊标记: this.释放时威压层数 > 0 ? this.释放时威压层数 : undefined,
    }
  }
}

export default 盾猛
export const 盾猛类型 = typeof 盾猛
