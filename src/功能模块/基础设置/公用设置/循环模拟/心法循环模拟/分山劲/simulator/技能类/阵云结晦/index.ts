import 循环模拟技能基础数据 from '../../../constant/skill'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { ERROR_ACTION } from '../../utils'

class 阵云结晦 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '阵云结晦')
  // static 回复怒气 = 0
  // 苍生铸世技改：招式等级由消耗的暴怒值决定，并通过后续招式的可释放Buff层数传递
  本次释放等级 = 1

  constructor(模拟循环) {
    super(模拟循环)
    // 阵云结晦.回复怒气 = 15
  }
  释放() {
    const 后续连招未完成 = 阵云结晦.技能数据?.Buff存在不可释放?.some(
      (名称) => (this.模拟循环.当前自身buff列表?.[名称]?.当前层数 || 0) > 0,
    )
    if (后续连招未完成) {
      return {
        可以释放: false,
        异常信息: '阵云结晦不可释放，请先完成后续连招',
      }
    }

    const 当前暴怒值 = this.模拟循环.角色状态信息?.暴怒值 || 0
    if (当前暴怒值 < 40) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.暴怒值不足,
      }
    }

    const 本次消耗 = this.模拟循环.校验奇穴是否存在?.('积怒') && 当前暴怒值 >= 80 ? 80 : 40
    this.本次释放等级 = 本次消耗 === 80 ? 2 : 1
    this.模拟循环.消耗暴怒值?.(本次消耗, 阵云结晦.技能数据?.技能名称)
    this.模拟循环.添加buff?.({ 名称: '可释放月照连营', 对象: '自身', 新增层数: this.本次释放等级 })
    return { 可以释放: true }
  }
  命中() {
    // 阵云结晦伤害延迟0.625秒
    // 苍生铸世技改：伤害立即生效，注释保留
    // const 阵云结晦伤害延迟 = (this.模拟循环.当前时间 || 0) + 10
    // this.模拟循环.添加待生效事件队列?.([
    //   {
    //     事件时间: 阵云结晦伤害延迟,
    //     事件名称: '阵云结晦伤害延迟',
    //     事件备注: { 技能名称: '阵云结晦' },
    //   },
    // ])
  }
  // 阵云结晦伤害延迟() {
  //   this.触发伤害行为('阵云结晦', 1, [], undefined, false, this.本次释放等级)
  // }
  造成伤害(索引) {
    this.触发伤害行为('阵云结晦', 1, [], undefined, false, this.本次释放等级)
  }

  释放后() {
    // this.触发回复怒气(阵云结晦.回复怒气, 阵云结晦.技能数据?.技能名称)
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒', '血怒_惊涌', '威压', '橙武']),
    }
  }
  获取技能释放记录结果() {
    return {
      ...this.本次释放记录,
    }
  }
}

export default 阵云结晦
export const 阵云结晦类型 = typeof 阵云结晦
