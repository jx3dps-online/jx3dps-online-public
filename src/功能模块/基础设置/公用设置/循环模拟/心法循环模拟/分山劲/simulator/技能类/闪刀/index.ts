// import 循环主类 from '../main'
import 循环模拟技能基础数据 from '../../../constant/skill'
import { ERROR_ACTION } from '../../utils'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 闪刀 extends 有CD技能通用类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '闪刀')
  static 消耗怒气 = 0

  constructor(模拟循环) {
    super(模拟循环)

    闪刀.消耗怒气 = 15
  }
  释放() {
    const 当前怒气 = this.模拟循环.角色状态信息?.怒气 || 0
    if (当前怒气 < 闪刀.消耗怒气) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.怒气不足,
      }
    }

    return { 可以释放: true }
  }
  命中() {
    // 苍雪刀记录绝刀怒气用以判断触发的血誓怒气。
    this.记录绝刀怒气判定()
    // 用来在模拟器内显示援戈层数标记。
    this.记录释放时援戈层数()
  }

  造成伤害() {
    this.触发伤害行为('闪刀')
    this.触发血誓效果(闪刀.绝刀怒气判定?.绝返等级)
    this.模拟循环.技能类实例集合?.盾击?.触发援戈伤害?.()
    // 怒气结算要在触发麟光之前，否则会先回怒再消耗
    this.触发消耗怒气(闪刀.消耗怒气, 闪刀.技能数据?.技能名称)
    this.模拟循环.技能类实例集合?.业火麟光?.触发麟光玄甲伤害?.()

    //偃守孤旌期间斩刀、闪刀无调息时间
    if (this.模拟循环.当前自身buff列表?.['战绝']?.当前层数) {
      this.重置苍雪刀调息时间()
    }

    // 履刃奇穴效果：点出履刃且目标有3层流血时，重置斩刀调息时间
    if (this.模拟循环.校验奇穴是否存在?.('履刃')) {
      const 流血实例 = this.模拟循环.技能类实例集合?.流血
      if (流血实例 && typeof 流血实例.当前层数 === 'function') {
        const 当前流血层数 = 流血实例.当前层数()
        if (当前流血层数 >= 3) {
          this.重置斩刀调息时间()
        }
      }
    }
    // 崩血3层流血时，闪刀、劫刀消耗一层流血并触发崩血伤害
    if (this.模拟循环.校验奇穴是否存在?.('崩血')) {
      this.模拟循环.技能类实例集合?.流血?.崩血消耗流血()
    }
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒', '血怒_惊涌', '麟光玄甲', '援戈', '橙武']),
    }
  }

  获取技能释放记录结果() {
    const 援戈层数 = this.获取释放时援戈层数() || 0
    const 格式化标记 = this.格式化援戈标记(援戈层数)
    return {
      ...this.本次释放记录,
      特殊标记: 援戈层数 > 0 ? 格式化标记 : undefined,
      底部标识: this.技能释放时怒气 || 0,
    }
  }
}

export default 闪刀
export const 闪刀类型 = typeof 闪刀
