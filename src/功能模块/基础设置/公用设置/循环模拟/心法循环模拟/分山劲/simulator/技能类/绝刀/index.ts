// import 循环主类 from '../main'
import 循环模拟技能基础数据 from '../../../constant/skill'
import { ERROR_ACTION } from '../../utils'
import 技能统一类 from '../../通用类/技能统一类'

class 绝刀 extends 技能统一类 {
  // 苍云\套路及子技能\苍云_苍雪刀_绝刀.lua
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '绝刀')

  // 实例字段（不能放 static：秘籍差异与本次释放状态只属于当前模拟实例）
  本次释放消耗怒气 = 0
  本次释放绝破等级 = 0
  本次释放绝返等级 = 0
  最低消耗怒气 = 25
  最高消耗怒气 = 65

  constructor(模拟循环) {
    super(模拟循环)
    const 存在减少消耗怒气秘籍 = this.模拟循环.秘籍?.['绝刀']?.includes('怒气消耗-15')
    if (存在减少消耗怒气秘籍) {
      this.最低消耗怒气 = 10
      this.最高消耗怒气 = 50
    } else {
      this.最低消耗怒气 = 25
      this.最高消耗怒气 = 65
    }
  }

  释放() {
    const 当前怒气 = this.模拟循环.角色状态信息?.怒气 || 0
    if (当前怒气 < this.最低消耗怒气) {
      return {
        可以释放: false,
        异常信息: ERROR_ACTION.怒气不足,
      }
    }

    return { 可以释放: true }
  }

  判定绝刀怒气消耗() {
    // scripts\skill\苍云\90级奇穴\判定怒气提高绝刀伤害.lua
    const 当前怒气 = this.模拟循环.角色状态信息?.怒气 || 0
    const 消耗怒气等级 = Math.min(Math.floor((当前怒气 - this.最低消耗怒气) / 10), 4)
    // 吓魂为科研口径（按目标流血判定、不区分目标类型）：客户端要求目标带自身来源流血（8249/31385）才直接升到8/9档，
    // 模拟器以流血DOT存在近似「带自身来源流血」，不区分玩家/NPC；档位增幅维持+4的科研加法口径
    let 吓魂等级判定 = 0
    let 怒气附加等级 = 0
    const 目标有自身流血 = (this.模拟循环.技能类实例集合?.流血?.当前层数?.() || 0) > 0
    if (this.模拟循环.校验奇穴是否存在?.('吓魂') && 目标有自身流血) {
      吓魂等级判定 = 4
      if (this.模拟循环.校验奇穴是否存在?.('嗜血')) {
        怒气附加等级 = 1
      }
    }
    if (this.模拟循环.校验奇穴是否存在?.('嗜血') && 消耗怒气等级 === 4) {
      怒气附加等级 = 5
    }
    // 绝返增益只定义到9级（吓魂+嗜血满怒时等级会算到13，超出部分取9级封顶）
    const 最终绝反等级 = Math.min(消耗怒气等级 + 吓魂等级判定 + 怒气附加等级, 9)
    const 消耗怒气 = Math.min(this.最低消耗怒气 + 消耗怒气等级 * 10)
    const 绝破等级 = 消耗怒气等级 + 1
    return {
      绝返等级: 最终绝反等级,
      绝破等级: 绝破等级,
      消耗怒气: 消耗怒气,
    }
  }

  命中() {
    // 用来在模拟器内显示援戈层数标记。
    // 这个要写到前面不然会被橙武跳过。
    // 苍生铸世技改：援戈已从奇穴列表移除，注释保留
    // this.记录释放时援戈层数()

    this.本次释放消耗怒气 = 0
    this.本次释放绝破等级 = 0
    this.本次释放绝返等级 = 0

    const { 绝返等级, 绝破等级, 消耗怒气 } = this.判定绝刀怒气消耗()
    this.本次释放绝破等级 = 绝破等级
    this.本次释放绝返等级 = 绝返等级

    // 橙武特效期间不消耗怒气和狂绝
    const 有橙武BUFF = this.模拟循环.当前自身buff列表?.['橙武']?.当前层数
    if (有橙武BUFF) {
      this.模拟循环.技能类实例集合?.裂伤?.获得和刷新裂伤()
      return
    }

    // 有狂绝时不消耗怒气
    const 有狂绝 = this.模拟循环.当前自身buff列表?.['狂绝']?.当前层数
    if (有狂绝) {
      this.模拟循环.卸除buff?.({ 名称: '狂绝', 对象: '自身', 卸除层数: 1 })
    } else {
      // 没有橙武和狂绝时正常消耗怒气
      this.本次释放消耗怒气 = 消耗怒气
    }
  }

  造成伤害() {
    // 苍生铸世技改：惊涌不再提供满怒额外伤害与破招，血怒期间绝刀对非侠士目标伤害提高71%
    const 有血怒_惊涌 = this.模拟循环.当前自身buff列表?.['血怒_惊涌']?.当前层数
    // 点出嗜血时使用嗜血版绝返阶梯（每10点怒气增幅30%）
    const 绝返增益名 = this.模拟循环.校验奇穴是否存在?.('嗜血') ? '嗜血绝返' : '绝返'
    const 额外增益列表 = [
      ...(this.本次释放绝返等级 ? [`${绝返增益名}·${this.本次释放绝返等级}`] : []),
      ...(有血怒_惊涌 ? ['血怒_惊涌_绝刀'] : []),
    ]
    // 使用统一的绝刀技能，但通过倍率调整伤害，并添加绝返增益
    this.触发伤害行为('绝刀', 1, 额外增益列表, undefined, false, 1)
    // this.触发血誓效果(绝刀.本次释放绝返等级)
    // this.模拟循环.技能类实例集合?.盾击?.触发援戈伤害?.()
    // 结算怒气消耗
    if (this.本次释放消耗怒气) {
      this.模拟循环.消耗怒气?.(this.本次释放消耗怒气, '绝刀')
    }
    // 绝刀怒气结算要在触发麟光之前，否则会先回怒再消耗
    // this.模拟循环.技能类实例集合?.业火麟光?.触发麟光玄甲伤害?.()
    // 嗜血晚于绝刀伤害生效，只有点出嗜血奇穴时释放绝刀才获得嗜血增伤（客户端绝刀.lua 检查21281后才加17176）
    if (this.模拟循环.校验奇穴是否存在?.('嗜血')) {
      this.模拟循环.添加buff?.({ 名称: '嗜血', 对象: '自身', 新增层数: 1 })
    }
  }

  释放后() {
    this.保存释放记录()
  }

  保存释放记录() {
    this.本次释放记录 = {
      重要buff列表: this.获取当前重要buff列表(['血怒', '血怒_惊涌', '威压', '橙武']),
    }
  }

  获取技能释放记录结果() {
    // 苍生铸世技改：援戈已从奇穴列表移除，注释保留
    // const 援戈层数 = this.获取释放时援戈层数() || 0
    // const 格式化标记 = this.格式化援戈标记(援戈层数)
    return {
      ...this.本次释放记录,
      // 特殊标记: 援戈层数 > 0 ? 格式化标记 : undefined,
      // 伤害段数=绝破等级（怒气档位1-5），作为绝刀的怒气等级角标展示
      伤害段数: this.本次释放绝破等级,
    }
  }
}

export default 绝刀
export const 绝刀类型 = typeof 绝刀
