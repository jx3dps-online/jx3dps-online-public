// import 循环主类 from '../main'
import 循环模拟技能基础数据 from '../../../constant/skill'
import 技能统一类 from '../../通用类/技能统一类'

class 盾刀 extends 技能统一类 {
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '盾刀')
  static 回复怒气 = 0
  static 技能图标 = 'https://icon.jx3box.com/icon/6327.png'

  constructor(模拟循环) {
    super(模拟循环)

    // 苍生铸世技改：盾刀回怒提高到10点
    盾刀.回复怒气 = 10
  }

  // 盾刀一段产生并检查隐刀836，二、三段只产生并检查盾击804
  获取本次GCD组集(): { 触发GCD组: string[]; 检测GCD组: string[] } {
    const 已进入后续段数 =
      this.模拟循环.当前自身buff列表?.['盾刀二段标记']?.当前层数 ||
      this.模拟循环.当前自身buff列表?.['盾刀三段标记']?.当前层数
    if (已进入后续段数) {
      return { 触发GCD组: ['盾击804'], 检测GCD组: ['公共', '盾击804'] }
    }
    return { 触发GCD组: ['盾击804', '隐刀836'], 检测GCD组: ['公共', '盾击804', '隐刀836'] }
  }

  判断盾刀触发伤害() {
    const 盾刀二段标记 = this.模拟循环.当前自身buff列表?.['盾刀二段标记']?.当前层数
    const 盾刀三段标记 = this.模拟循环.当前自身buff列表?.['盾刀三段标记']?.当前层数
    if (!盾刀二段标记 && !盾刀三段标记) {
      this.触发伤害行为?.('盾刀·一')
      this.模拟循环.添加buff?.({ 名称: '盾刀二段标记', 对象: '自身' })
    } else if (盾刀二段标记) {
      this.触发伤害行为?.('盾刀·二')
      this.模拟循环.卸除buff?.({ 名称: '盾刀二段标记', 对象: '自身' })
      this.模拟循环.添加buff?.({ 名称: '盾刀三段标记', 对象: '自身' })
    } else if (盾刀三段标记) {
      this.触发伤害行为?.('盾刀·三')
      if (this?.模拟循环?.秘籍?.['盾刀']?.some((a) => a === '三段回怒')) {
        this.模拟循环?.回复怒气?.(5, '盾刀')
      }
      this.模拟循环.卸除buff?.({ 名称: '盾刀三段标记', 对象: '自身' })
    }
  }
  命中(_是否为最后一个技能: boolean, 循环位置: number) {
    // 盾压重置触发源：盾刀施放判定（35%概率/期望，见 技能统一类.尝试盾压重置）
    this.尝试盾压重置(循环位置)
    盾刀.技能图标 = this.判断盾刀图标()
    this.保存释放记录()
  }

  造成伤害() {
    this.判断盾刀触发伤害()
    // 威压：盾刀命中目标获得1层威压
    if (this.模拟循环.校验奇穴是否存在?.('威压')) {
      this.模拟循环.添加buff?.({ 名称: '威压', 对象: '自身', 新增层数: 1 })
    }
  }

  释放后() {
    this.触发回复怒气(盾刀.回复怒气, 盾刀.技能数据?.技能名称)
  }

  判断盾刀图标() {
    if (this.模拟循环?.当前自身buff列表?.['盾刀三段标记']?.当前层数) {
      return 'https://icon.jx3box.com/icon/6329.png'
    } else if (this.模拟循环?.当前自身buff列表?.['盾刀二段标记']?.当前层数) {
      return 'https://icon.jx3box.com/icon/6328.png'
    } else {
      return 'https://icon.jx3box.com/icon/6327.png'
    }
  }

  保存释放记录() {
    this.本次释放记录 = {
      实际图标: 盾刀.技能图标,
      重要buff列表: this.获取当前重要buff列表(['血怒', '血怒_惊涌', '威压', '橙武']),
    }
  }

  获取技能释放记录结果() {
    return {
      ...this.本次释放记录,
    }
  }
}

export default 盾刀
export const 盾刀类型 = typeof 盾刀
