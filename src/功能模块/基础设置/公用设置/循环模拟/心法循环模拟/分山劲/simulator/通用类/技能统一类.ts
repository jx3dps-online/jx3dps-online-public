  //   哈希逐位确定（与施放顺序无关）：拖动/编辑某位置技能只会重新计算该位置及之后，之前的盾压判定完全固定；
  // 期望（默认）=无随机的确定性等效：盾压在调息中时每次施放累计进度 1，攒满 1/几率 次必然重置一次，
  //   长期均值与概率版一致，同循环每次模拟结果完全一致；
  // 手动=不自动触发，由玩家手动插入「重置盾压」技能
  static 盾压重置几率 = 0.35
  static 盾压随机种子 = 987654321

  尝试盾压重置(循环位置 = 0) {
    const 模拟循环 = this.模拟循环
    if (模拟循环?.盾压重置方式 === '手动') {
      return
    }
    // 盾生锋：云城盾套路不再重置盾压调息时间（客户端盾牌攻击几率触发盾压.lua 检查46079后直接return）
    if (模拟循环?.校验奇穴是否存在?.('盾生锋')) {
      return
    }
    // 盾压不在调息中时重置无意义：不掷骰也不累计进度
    const 盾压实例 = 模拟循环?.技能类实例集合?.['盾压']
    const 盾压在调息中 =
      (盾压实例?.技能运行数据?.待充能时间点 || []).some((帧) => 帧 > (模拟循环.当前时间 || 0)) ||
      false
    if (!盾压在调息中) {
      return
    }
    const 盾压秘籍 = 模拟循环?.秘籍?.['盾压'] || []
    const 重置几率 =
      技能统一类.盾压重置几率 +
      (盾压秘籍?.includes('5%重置_1') ? 0.05 : 0) +
      (盾压秘籍?.includes('5%重置_2') ? 0.05 : 0)
    if (模拟循环?.盾压重置方式 === '期望') {
      模拟循环.盾压期望重置计数 = (模拟循环.盾压期望重置计数 ?? 0) + 1
      if (模拟循环.盾压期望重置计数 >= 1 / 重置几率) {
        模拟循环.盾压期望重置计数 -= 1 / 重置几率
        this.重置盾压调息时间()
      }
      return
    }
    // 按位置哈希取随机值（Math.imul 32位整数运算精确）：位置不变则判定结果不变，拖动技能只影响被编辑位置及之后
    let 哈希 = (技能统一类.盾压随机种子 ^ Math.imul(循环位置 + 1, 2654435761)) >>> 0
    哈希 = Math.imul(哈希 ^ (哈希 >>> 15), 2246822519) >>> 0
    哈希 = Math.imul(哈希 ^ (哈希 >>> 13), 3266489917) >>> 0
    哈希 = (哈希 ^ (哈希 >>> 16)) >>> 0
    if (哈希 / 4294967296 < 重置几率) {
      this.重置盾压调息时间()
    }
  }

