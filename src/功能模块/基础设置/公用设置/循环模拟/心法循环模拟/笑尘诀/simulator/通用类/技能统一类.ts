import { 获取实际技能数据 } from '../../../通用/通用函数'
import 循环主类类型 from '../main'
import { 循环基础技能数据类型, 技能释放记录结果 } from '../type'

class 技能统一类 {
  模拟循环: 循环主类类型
  本次释放记录: 技能释放记录结果 = {}
  本次释放延迟: number | 'GCD' = 0
  本次伤害结束时间 = 0
  技能名称 = ''

  constructor(模拟循环) {
    this.模拟循环 = 模拟循环
    return
  }

  检查GCD(索引, 当前技能?: 循环基础技能数据类型) {
    const GCD组 = 当前技能?.技能GCD组 === '自身' ? 当前技能?.技能名称 : 当前技能?.技能GCD组 || ''
    let GCD = 当前技能 ? this.模拟循环.技能释放前检查GCD统一方法(当前技能) : 0
    let 等待GCD = 0

    if (this.本次释放延迟) {
      if (GCD组 === '公共' || GCD组 === '江湖') {
        GCD = GCD + (this.本次释放延迟 === 'GCD' ? 0 : this.本次释放延迟)
      } else if (this.本次释放延迟 === 'GCD') {
        等待GCD = this.查找下一个有效技能GCD(索引)
      } else {
        等待GCD = Number(this.本次释放延迟)
      }

      if (等待GCD) {
        GCD = Math.max(等待GCD, GCD)
      }
    }

    this.本次释放延迟 = 0
    return GCD
  }

  /**
   * 从当前索引往后扫描（最多3步），找到第一个满足条件的技能并获取其GCD。
   * 用于处理"灭"等需要推进时间到后续技能GCD前释放的场景。
   * 跳过的技能：不存在、额外延迟为 'GCD'、无GCD组且无检测GCD组。
   */
  查找下一个有效技能GCD(当前索引: number): number {
    const 最大向前步数 = 5

    for (let 步数 = 1; 步数 <= 最大向前步数; 步数++) {
      const 目标技能 = this.模拟循环?.测试循环?.[当前索引 + 步数]
      if (!目标技能) continue

      const 目标技能实际数据: any = 获取实际技能数据(目标技能)
      // 延迟为 'GCD' 的技能本身也会处理 GCD 推进，跳过
      if (目标技能实际数据?.额外信息?.延迟 === 'GCD') continue

      const 目标基础技能 = this?.模拟循环?.技能基础数据?.find(
        (item) => item?.技能名称 === 目标技能实际数据?.实际技能名称,
      )

      if (目标基础技能?.技能GCD组 === ('自身' as any)) continue

      if (目标基础技能 && 目标基础技能?.技能GCD组) {
        const 技能实例 = this?.模拟循环?.技能类实例集合?.[目标基础技能?.技能名称]
        return this.模拟循环?.检查GCD?.(目标基础技能, 技能实例, 当前索引 + 步数) || 0
      }
    }

    return 0
  }

  释放前初始化(额外信息) {
    this.本次释放延迟 = 0
    if (额外信息?.延迟) {
      this.本次释放延迟 = 额外信息?.延迟
    }
    // 重置释放记录
    this.本次释放记录 = {}
    this.本次伤害结束时间 = 0
  }

  触发伤害行为(
    伤害名称,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    触发伤害时间: number | undefined = undefined,
    DOT伤害 = false,
    技能等级 = 1,
  ) {
    this.模拟循环.技能造成伤害?.(伤害名称, 伤害次数, 额外增益列表, 触发伤害时间, DOT伤害, 技能等级)
    const 连击技能 = [
      '拨狗朝天·真实',
      '横打双獒·一',
      '横打双獒·二',
      '恶狗拦路',
      '犬牙交错',
      '棒打狗头·一',
      '棒打狗头·二',
      '蜀犬吠日·一',
      '蜀犬吠日·二',
      '蜀犬吠日·三',
      '蜀犬吠日·四',
      '蛟龙翻江·一',
      '蛟龙翻江·二',
      '蛟龙翻江·三',
      '双龙取水',
      '龙游天地·一',
      '龙游天地·二',
      '龙游天地·三',
      '龙腾五岳',
      '龙战于野·一',
      '龙战于野·二',
      '龙战于野·三',
      '亢龙有悔·一',
      '亢龙有悔·二',
      '亢龙有悔·三',
      '亢龙有悔·四',
      '亢龙有悔·五',
      '亢龙有悔·六',
      '亢龙有悔·三分之一不翻倍',
      '亢龙有悔合一掌1',
      '龙跃于渊·一',
      '龙跃于渊·二',
      '龙跃于渊·三',
      '时乘六龙',
      '狂龙乱舞·一',
      '狂龙乱舞·二',
      '狂龙乱舞·三',
      '狂龙乱舞·四',
      '龙啸九天',
      '追远',
    ]
    if (连击技能.includes(伤害名称)) {
      for (let i = 0; i < 伤害次数; i++) {
        if (this.模拟循环.校验奇穴是否存在('祭湘君'))
          this.模拟循环.技能类实例集合.祭湘君?.获得连击()
        if (this.模拟循环.校验奇穴是否存在('坚冰')) this.模拟循环.技能类实例集合.坚冰?.获得连击()
      }
    }
  }

  登记伤害(伤害名称: string, 延迟 = 0, 伤害次数 = 1, 技能等级 = 1) {
    this.本次伤害结束时间 = Math.max(this.本次伤害结束时间, this.模拟循环.当前时间 + 延迟)
    if (!延迟) {
      this.触发伤害行为(伤害名称, 伤害次数, [], undefined, false, 技能等级)
      this.模拟循环.技能类实例集合[this.技能名称].延迟生效?.(伤害名称)
      return
    }
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '技能伤害',
        事件时间: this.模拟循环.当前时间 + 延迟,
        事件备注: { 技能名称: this.技能名称, 伤害名称, 伤害次数, 技能等级 },
      },
    ])
  }

  触发苍龙() {
    if (this.模拟循环.当前自身buff列表.苍龙) {
      this.触发伤害行为('苍龙')
    }
  }

  获取技能释放记录结果() {
    return { ...this.本次释放记录 }
  }

  保存释放记录() {
    this.本次释放记录.重要buff列表 = this.获取当前重要buff列表([
      '昊破',
      '越渊',
      '逍遥',
      '触类',
      '含弘·3',
      '贞固',
      '暴龙震江',
    ])
  }

  获取当前重要buff列表(技能依赖自身buff列表: string[] = [], 技能依赖目标buff列表: string[] = []) {
    const 重要buff列表: string[] = []
    技能依赖自身buff列表.forEach((buff) => {
      if (this.模拟循环.当前自身buff列表?.[buff]?.当前层数) {
        重要buff列表.push(buff)
      }
    })
    技能依赖目标buff列表.forEach((buff) => {
      if (this.模拟循环.当前目标buff列表?.[buff]?.当前层数) {
        重要buff列表.push(buff)
      }
    })
    return 重要buff列表 || []
  }

  获取施加重要buff信息(buff名称) {
    const 当前时间 = this.模拟循环.当前时间 || 0
    const buff对象 = this.模拟循环.Buff和Dot数据?.[buff名称]

    return buff对象
      ? {
          buff名称: buff名称,
          buff开始时间: 当前时间,
          buff结束时间: 当前时间 + (buff对象?.最大持续时间 || 0),
        }
      : null
  }
}

export default 技能统一类
