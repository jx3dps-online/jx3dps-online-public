  添加buff({ 名称, 对象 = '目标', 事件时间 = this.当前时间, 新增层数 = 1, 来源 = '' }) {
    const 当前层数 =
      对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数

    const 新buff对象 = {
      ...this.Buff和Dot数据[名称],
      当前层数: Math.min((当前层数 || 0) + 新增层数, this.Buff和Dot数据[名称].最大层数 || 1),
      刷新时间: 事件时间,
    }
    if (新buff对象.当前层数 !== 当前层数 && 新buff对象.当前层数 !== 1) {
      this.添加战斗日志({
        日志: `${名称}层数变为【${新buff对象.当前层数}】 ${来源 ? `—— 来源：【${来源}】` : ''}`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    } else {
      this.添加战斗日志({
        日志: `${对象}获得${名称} ${来源 ? `—— 来源：【${来源}】` : ''}`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    }

    if (对象 === '自身') {
      this.当前自身buff列表[名称] = { ...新buff对象 }
    } else {
      this.当前目标buff列表[名称] = { ...新buff对象 }
    }
    this.登记buff失效(名称, 对象 as '自身' | '目标')
  }

  登记buff失效(名称: string, 对象: '自身' | '目标') {
    const buff = (对象 === '自身' ? this.当前自身buff列表 : this.当前目标buff列表)[名称]
    if (buff.最大持续时间 !== undefined) {
      this.添加待生效事件队列(
        [
          {
            事件名称: `卸除buff-${对象}-${名称}`,
            事件时间: Math.max(0, (buff.刷新时间 || 0) + buff.最大持续时间),
            事件备注: { buff名称: 名称, buff对象: 对象, 卸除层数: buff.最大层数 },
          },
        ],
        true,
      )
    }
  }

  卸除buff({
    名称,
    buff刷新时间,
    对象 = '目标',
    事件时间 = this.当前时间,
    卸除层数 = 1,
    来源 = '',
  }: {
    名称: string
    buff刷新时间?: number
    对象?: '自身' | '目标'
    事件时间?: number
    卸除层数?: number
    来源?: string
  }) {
    const 当前层数 =
      对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数

    if (当前层数 && 当前层数 >= 0) {
      if (当前层数 - 卸除层数 > 0) {
        this.添加战斗日志({
          日志: `${名称}层数变为【${当前层数 - 卸除层数}】 ${来源 ? `—— 来源：【${来源}】` : ''}`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 事件时间,
        })
        const 新buff对象 = {
          ...this.Buff和Dot数据[名称],
          当前层数: 当前层数 - 卸除层数,
          刷新时间:
            buff刷新时间 ??
            (对象 === '自身'
              ? this.当前自身buff列表[名称]?.刷新时间
              : this.当前目标buff列表[名称]?.刷新时间) ??
            事件时间,
        }
        if (对象 === '自身') {
          this.当前自身buff列表[名称] = { ...新buff对象 }
        } else {
          this.当前目标buff列表[名称] = { ...新buff对象 }
        }
      } else {
        this.添加战斗日志({
          日志: `${对象}失去${名称} ${来源 ? `—— 来源：【${来源}】` : ''}`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 事件时间,
        })
        if (对象 === '自身') {
          delete this.当前自身buff列表[名称]
          if (名称 === '逍遥') this.切换角色体态('常态', '逍遥结束')
          if (名称 === '逍遥' && this.校验奇穴是否存在('越渊')) {
            this.添加buff({ 名称: '越渊', 对象: '自身' })
          }
        } else {
          delete this.当前目标buff列表[名称]
        }
        this.删除待生效事件队列(`卸除buff-${对象}-${名称}`)
      }
    }
  }

