  检查GCD(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    if (技能实例?.检查GCD) {
      GCD = 技能实例?.检查GCD?.(i, 当前技能)
    } else {
      GCD = this.技能释放前检查GCD统一方法(当前技能)
    }
    return GCD
  }

  // 判断GCD，技能CD等
  技能释放前(当前技能: 循环基础技能数据类型, 技能实例, i) {
    let GCD = 0
    let 等待CD = 0

    // 判断是否为当前箭袋第一个技能
    if (i >= 0) {
      // 判断上一个技能对于本技能是否有GCD限制
      if (当前技能?.技能名称 !== '换行') {
        GCD = Math.max(
          this.检查GCD(当前技能, 技能实例, i),
          当前技能.技能名称 === '苍龙戾天' ? 0 : this.僵直结束时间 - this.当前时间,
          this.读条结束时间 - this.当前时间,
        )
      }
      // 判断技能CD，如果存在CD。增加等待时间
      if (当前技能?.技能CD) {
        等待CD = this.技能释放前检查运行数据(当前技能, 技能实例, GCD)
      }
    }
    const 延迟等待 = i > 0 && GCD ? this.网络延迟 : 0
    const 技能计划释放时间 = this.当前时间 + GCD + 延迟等待
    return {
      技能计划释放时间: 技能计划释放时间,
      技能预估释放时间: 技能计划释放时间 + 等待CD,
      等待CD,
    }
  }

  技能GCD和CD处理(
    等待CD,
    技能预估释放时间,
    当前技能: 循环基础技能数据类型,
    技能实例: 检查运行数据实例类型,
  ) {
    // 判断在处理完特殊事件以后，剩余的待定时间还有多少
    const 时间差 = 技能预估释放时间 - this.当前时间
    if (时间差 && 时间差 > 0) {
      this.增加时间(时间差)
    }
    const 剩余GCD = this.技能释放前检查GCD统一方法(当前技能)
    if (剩余GCD) {
      const 释放时间 = this.当前时间 + 剩余GCD
      this.待生效事件结算(释放时间)
      this.增加时间(释放时间 - this.当前时间)
    }
    if (等待CD) {
      this.添加战斗日志({
        日志: `【${当前技能?.技能名称}】等技能CD【${等待CD}】帧`,
        日志类型: '等CD',
        日志时间: 技能预估释放时间,
      })
    }
    const 待充能时间点 = 技能实例?.技能运行数据?.待充能时间点
    const 新待充能时间点 = 待充能时间点?.filter((item) => item > this.当前时间)
    技能实例?.更新技能运行数据?.({ 待充能时间点: 新待充能时间点 })
  }

  // 增加技能GCD
  增加技能GCD(当前技能: 循环基础技能数据类型) {
    // GCD处理
    const { 触发GCD组 } = 获取本次GCD组集(当前技能, !!this.当前自身buff列表.逍遥)
    for (const 待更新GCD组 of 触发GCD组) {
      const 组数据 = GCD组基础帧[待更新GCD组]
      const 基础帧 = 组数据?.基础帧 ?? 当前技能.技能释放后添加GCD
      const 最小帧 = 组数据?.最小帧 ?? 当前技能.最小GCD
      let 实际添加GCD = (组数据 ? 组数据.不吃加速 : 当前技能.不吃加速)
        ? 基础帧
        : 获取实际帧数(基础帧, this.加速值)
      if (最小帧) {
        实际添加GCD = Math.max(实际添加GCD, 最小帧)
      }
      if (待更新GCD组) {
        const 新GCD = Math.max((this.GCD组[待更新GCD组] || 0) + 实际添加GCD, 0)
        this.GCD组[待更新GCD组] = 新GCD
      }
    }
  }

  技能成功开始释放(当前技能: 循环基础技能数据类型, 技能实例) {
    this.增加技能GCD(当前技能)
    this.增加技能CD(当前技能, 技能实例)
    if (当前技能.技能名称 !== '换行') {
      this.读条结束时间 = this.当前时间 + (技能实例.读条时间?.() || 0)
      this.僵直结束时间 =
        this.当前时间 +
        Math.max(
          (this.当前自身buff列表.逍遥 &&
            !(
              this.当前自身buff列表.贞固 && ['蜀犬吠日', '亢龙有悔'].includes(当前技能.技能名称)
            )) ||
            当前技能.技能名称 === '苍龙戾天'
            ? 当前技能.僵直时间 || 0
            : 0,
          this.读条结束时间 - this.当前时间,
        )
    }
  }

  // 增加技能CD
  增加技能CD(当前技能: 循环基础技能数据类型, 技能实例) {
    // 技能CD处理
    if (当前技能?.技能CD) {
      if (技能实例?.技能释放后更新运行数据) {
        技能实例.技能释放后更新运行数据?.()
      } else {
        this.技能释放后更新运行数据(当前技能, 技能实例)
      }
    }
  }

  // 判断添加GCD等
  技能释放后(当前技能: 循环基础技能数据类型, 计划释放时间: number, 开始释放时间: number, 技能实例) {
    const 技能释放记录结果 = 技能实例?.获取技能释放记录结果?.() || {}
    if (当前技能.技能名称 !== '换行' && this.僵直结束时间 > 开始释放时间) {
      this.添加战斗日志({
        日志: `【${当前技能.技能名称}】${技能实例?.读条时间?.() ? '读条' : '动作'}持续${this.僵直结束时间 - 开始释放时间}帧，结束于${this.僵直结束时间}帧`,
        日志类型: '技能释放结果',
        日志时间: 开始释放时间,
      })
    }
    // 技能释放记录
    this.技能释放记录.push({
      技能名称: 当前技能?.技能名称,
      计划释放时间,
      实际释放时间: 开始释放时间,
      是否为读条技能: !!技能实例?.读条时间?.(),
      技能释放记录结果: {
        ...技能释放记录结果,
      },
    })
  }

  清空buff调用函数(对象: '自身' | '目标') {
    const buff列表 = 对象 === '自身' ? this.当前自身buff列表 : this.当前目标buff列表

    // 更新目标buff
    Object.keys(buff列表).forEach((key) => {
      const buff对象 = buff列表[key]
      const buff应该消失时间 = (buff对象?.刷新时间 || 0) + (buff对象?.最大持续时间 || 0)
      const 消失层数 = buff对象?.自然消失失去层数 || buff对象?.最大层数
      if (buff对象.最大持续时间 !== undefined && buff应该消失时间 <= this.当前时间) {
        this.卸除buff({ 名称: key, 对象, 事件时间: buff应该消失时间, 卸除层数: 消失层数 })
      }
    })
  }

