  技能造成伤害(
    来源: string,
    伤害次数 = 1,
    额外增益列表: string[] = [],
    造成时间 = this.当前时间,
    DOT伤害 = false,
    技能等级 = 1,
  ) {
    const 对应技能 = 技能系数?.find((item) => item.技能名称 === 来源)
    const 技能增益列表 = 获取技能信息(对应技能, 技能等级)?.技能增益列表 || []

    const 有关的buff列表 =
      技能增益列表
        ?.filter((item) => {
          if (DOT伤害) return false
          const 当前增益数据 =
            this?.当前自身buff列表?.[item.增益名称] || this?.当前目标buff列表?.[item.增益名称]
          if (造成时间 && 当前增益数据?.最大持续时间 !== undefined) {
            const 增益消失时间 = (当前增益数据?.刷新时间 || 0) + 当前增益数据.最大持续时间
            const 增益获得时间 = 当前增益数据?.刷新时间 || 0
            return 造成时间 <= 增益消失时间 && 造成时间 >= 增益获得时间
          } else {
            return !!当前增益数据
          }
        })
        ?.map((item) => {
          return item.增益名称
        }) || []

    const 增益列表 = [...额外增益列表]
    if (DOT伤害 && this.当前自身buff列表.越渊) 增益列表.push('越渊_常驻')
    if (this.校验奇穴是否存在('饮江') && 来源.startsWith('亢龙有悔')) 增益列表.push('饮江')

    let 总增益列表 = 有关的buff列表.concat(增益列表)

    if (this.启用团队增益快照 && !DOT伤害) {
      const 团队增益buff列表 = this.副本事件实例列表?.length
        ? 判断副本事件快照Buff(this.副本事件实例列表, 造成时间 || 0)
        : 判断团队增益快照Buff({
            团队增益轴: this.团队增益轴,
            判定帧: 造成时间 || 0,
          })
      if (团队增益buff列表?.length) {
        总增益列表 = 总增益列表?.concat(团队增益buff列表)
      }
    }

    this.添加战斗日志({
      日志: 来源,
      日志类型: '造成伤害',
      日志时间: 造成时间,
      buff列表: 总增益列表 || [],
      其他数据: {
        伤害次数: 伤害次数,
        技能等级: 技能等级,
      },
    })
  }

