import 技能统一类 from '../../通用类/技能统一类'
import type 循环主类 from '../../main'
import 技能基础数据 from '../../../constant/skill'

class 天隼击 extends 技能统一类 {
  static 技能数据 = 技能基础数据.find((技能) => 技能.技能名称 === '天隼击')!
  技能名称 = '天隼击'

  constructor(模拟循环: 循环主类) {
    super(模拟循环)
  }

  已开启 = false
  下次攻击时间 = 0
  攻击次数 = 0

  命中() {
    this.保存释放记录()
    this.已开启 = !this.已开启
    this.模拟循环.删除待生效事件队列('天隼检查')
    this.模拟循环.添加战斗日志({
      日志: this.已开启 ? '开启天隼击' : '关闭天隼击',
      日志类型: '技能释放结果',
    })
    if (this.已开启) this.登记检查()
  }

  登记检查() {
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '天隼检查',
        事件时间: this.模拟循环.当前时间 + 16,
      },
    ])
  }
  天隼检查() {
    if (this.模拟循环.当前时间 >= this.下次攻击时间) {
      this.登记伤害('天隼击', 48)
      // 沿用分山劲按序号哈希的固定随机方式，重新计算时保持同一条攻击时间线。
      let 哈希 = (987654321 ^ Math.imul(++this.攻击次数, 2654435761)) >>> 0
      哈希 = Math.imul(哈希 ^ (哈希 >>> 15), 2246822519) >>> 0
      哈希 = Math.imul(哈希 ^ (哈希 >>> 13), 3266489917) >>> 0
      哈希 = (哈希 ^ (哈希 >>> 16)) >>> 0
      const 随机值 = 哈希 / 4294967296
      this.下次攻击时间 = this.模拟循环.当前时间 + (随机值 < 0.2 ? 112 : 随机值 < 0.6 ? 176 : 240)
    }
    this.登记检查()
  }
}

export default 天隼击
