import { 获取倒读条实际帧数分布 } from '@/工具函数/data'
import 循环模拟技能基础数据 from '../../../constant/skill'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 待生效事件 } from '../../type'

class 玳弦急曲 extends 有CD技能通用类 {
  // 2707入口 -> 40207通道；消耗剑舞配方5787/5788。
  static 技能数据 = 循环模拟技能基础数据?.find((item) => item.技能名称 === '玳弦急曲')
  本次伤害段数 = 3
  本次完整伤害段数 = 3
  本次作用次数?: number
  本次流玉 = false

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  释放前初始化(额外信息) {
    super.释放前初始化(额外信息)
    this.本次作用次数 = 额外信息?.作用次数
    this.本次流玉 = false
  }

  获取读条参数() {
    const 新妆启用 = this.模拟循环.校验奇穴是否存在('新妆')
    const 霜降启用 = this.模拟循环.校验奇穴是否存在('霜降')
    const 剑舞 = this.模拟循环.角色状态信息.剑舞
    const 消耗剑舞数 = 霜降启用 ? 剑舞 : Math.min(剑舞, 1)
    return {
      新妆启用,
      霜降启用,
      作用间隔帧: 消耗剑舞数 > 0 ? (新妆启用 ? 7 : 9) : 新妆启用 ? 12 : 15,
      消耗剑舞数,
      完整跳数: 3 + (霜降启用 ? 消耗剑舞数 : 0),
    }
  }

  获取作用分布() {
    const { 作用间隔帧, 完整跳数 } = this.获取读条参数()
    return 获取倒读条实际帧数分布(
      作用间隔帧 * 完整跳数,
      作用间隔帧,
      this.模拟循环.获取实际加速值(),
    ).slice(0, this.本次作用次数 ?? 完整跳数)
  }

  获取读条时间() {
    return this.获取作用分布().reduce((总时间, 间隔) => 总时间 + 间隔, 0)
  }

  读条(读条开始时间) {
    this.读条玳弦急曲(读条开始时间)
    this.保存释放记录('玳弦急曲')
  }

  读条玳弦急曲(读条开始时间) {
    const { 消耗剑舞数, 新妆启用, 霜降启用, 完整跳数 } = this.获取读条参数()
    const 作用分布 = this.获取作用分布()
    this.本次伤害段数 = 作用分布.length
    this.本次完整伤害段数 = 完整跳数
    const 流玉 = this.模拟循环.当前自身buff列表.流玉
    this.本次流玉 = !!流玉?.当前层数
    if (this.本次流玉) {
      this.模拟循环.卸除buff({
        名称: '流玉',
        对象: '自身',
        buff刷新时间: 流玉.刷新时间,
      })
    }
    this.新增钗燕层数('玳弦急曲')
    if (this.模拟循环.当前自身buff列表.芳姿畅音?.当前层数) {
      this.模拟循环.添加buff({ 名称: '仙姿玳弦', 对象: '自身' })
      this.模拟循环.卸除buff({ 名称: '芳姿畅音', 对象: '自身' })
    }
    const 待生效事件队列: 待生效事件[] = []
    let 已读条时间 = 0
    for (let i = 0; i < 作用分布.length; i++) {
      待生效事件队列.push({
        事件名称: '技能读条',
        事件时间: 读条开始时间 + 已读条时间 + 作用分布[i],
        事件备注: {
          技能名称: '玳弦急曲',
          是否完整结束: i === 完整跳数 - 1,
          新妆启用,
          霜降启用,
          消耗剑舞数,
          流玉启用: this.本次流玉,
        },
      })
      已读条时间 = 已读条时间 + 作用分布[i]
    }
    this.模拟循环.添加待生效事件队列(待生效事件队列)
    const 是否有仙姿玳弦 = this.模拟循环.当前自身buff列表['仙姿玳弦']?.当前层数
    this.模拟循环.角色状态信息.剑舞 -= 消耗剑舞数
    if (是否有仙姿玳弦) {
      this.回复剑舞(1)
    }
  }

  // 顺序不可随意更改
  读条命中(事件备注) {
    const { 新妆启用, 霜降启用, 消耗剑舞数, 流玉启用 } = 事件备注
    const 霜降增益 = 霜降启用 ? [`${新妆启用 ? '霜降' : '霜降普通'}·${消耗剑舞数 + 1}`] : []
    const 本次玳弦增益 = 霜降增益.concat(流玉启用 ? ['流玉'] : [])
    const 命中前急曲层数 = this.模拟循环.技能类实例集合.急曲.获取急曲数据().当前层数 || 0
    if (this.模拟循环.校验奇穴是否存在('化冰') && this.模拟循环.当前自身buff列表.化冰?.当前层数) {
      this.触发伤害行为('化冰')
      this.模拟循环.卸除buff({ 名称: '满堂', 对象: '自身', 卸除层数: 1 })
    }
    if (新妆启用) {
      this.触发伤害行为('玳弦急曲·1', 1, 本次玳弦增益, undefined, 1, ['流玉'])
    }
    this.触发伤害行为('玳弦急曲·2', 1, 本次玳弦增益, undefined, 1, ['流玉'])
    this.模拟循环.卸除buff({ 名称: '满堂', 对象: '自身', 卸除层数: 新妆启用 ? 2 : 1 })

    if (this.模拟循环.校验奇穴是否存在('盈袖')) {
      // 按一个读条跳处理一次，不按本体、额外伤害的条数重复叠层。
      if (命中前急曲层数 === 6) {
        this.模拟循环.添加buff({ 名称: '盈袖', 对象: '目标', 新增层数: 1 })
      }
      this.模拟循环.技能类实例集合?.急曲?.获得和刷新急曲?.('剑破虚空')
    }
    if (this.模拟循环.当前自身buff列表['仙姿玳弦']?.当前层数) {
      this.触发伤害行为('留芳仙姿·玳弦')
      this.新增钗燕层数('留芳仙姿·玳弦')
    }
    if (
      this.模拟循环.校验奇穴是否存在('钗燕') &&
      this.模拟循环.当前自身buff列表.玳弦钗燕?.当前层数
    ) {
      this.结算钗燕伤害()
      this.模拟循环.卸除buff({ 名称: '玳弦钗燕', 对象: '自身' })
    }

    if (事件备注.是否完整结束) {
      if (霜降启用) {
        this.触发伤害行为('破·霜降', 3, [], undefined, 消耗剑舞数 + 1)
      }
      if (!新妆启用) {
        this.模拟循环.技能类实例集合.急曲.获得和刷新急曲('玳弦急曲')
      }
    }
    this.结算枕上触发()
  }

  保存释放记录(名称) {
    this.本次释放记录 = {
      实际伤害技能: 名称,
      重要buff列表: this.获取当前重要buff列表(['繁音急节', '仙姿玳弦']).concat(
        this.本次流玉 ? ['流玉'] : [],
      ),
      伤害段数: this.本次伤害段数,
      完整伤害段数: this.本次完整伤害段数,
    }
  }
}

export default 玳弦急曲

export const 玳弦急曲类型 = typeof 玳弦急曲
