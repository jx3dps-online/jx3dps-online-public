import type 循环主类 from '../../main'
import { 每秒郭氏帧 } from '@/数据/常量'
import type { 循环基础技能数据类型 } from '../../type'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 大扇子P2动作时刻, 大扇子P2技能数据 } from '../../../constant/大扇子'
import { 结算P2技能, 结算P2终结技 } from './P2'

class 大扇子 extends 有CD技能通用类 {
  技能名称: string

  constructor(模拟循环: 循环主类, 技能名称: string) {
    super(模拟循环)
    this.技能名称 = 技能名称
    this.初始化技能运行数据()
  }

  检查GCD(索引: number, 当前技能?: 循环基础技能数据类型) {
    if (this.技能名称 === '退出大扇子') return super.检查GCD(索引, 当前技能) + 1
    const P1 = this.模拟循环.当前自身buff列表.大扇子
    if (this.技能名称 === '绫罗红波' && P1?.当前层数) {
      this.本次释放延迟 = 0
      return Math.max(0, P1.刷新时间! + 11 * 每秒郭氏帧 - this.模拟循环.当前时间)
    }
    const P2 = this.模拟循环.当前自身buff列表['大扇子·P2']
    const 已完成次数 = this.模拟循环.角色状态信息.大扇子P2技能序列.length
    if (
      当前技能?.大扇子阶段 === 'P2' &&
      this.技能名称 !== '云肩转腰' &&
      P2?.当前层数 &&
      已完成次数 < 4
    ) {
      this.本次释放延迟 = 0
      return Math.max(0, P2.刷新时间! + 大扇子P2动作时刻[已完成次数] - this.模拟循环.当前时间)
    }
    return super.检查GCD(索引, 当前技能)
  }

  命中() {
    if (大扇子P2技能数据.some((技能) => 技能.技能名称 === this.技能名称)) {
      this.结算P2动作()
      return
    }
    if (this.技能名称 === '使用大扇子') {
      delete this.模拟循环.角色状态信息.大扇子前一个技能
      delete this.模拟循环.角色状态信息.大扇子分支
      this.模拟循环.角色状态信息.大扇子P2技能序列 = []
      this.模拟循环.GCD组.大扇子 = 0
      this.模拟循环.添加buff({ 名称: '大扇子', 对象: '自身' })
      return
    }
    if (this.技能名称 === '退出大扇子') {
      this.模拟循环.卸除buff({ 名称: '大扇子', 对象: '自身' })
      this.模拟循环.卸除buff({ 名称: '大扇子·P2', 对象: '自身' })
      return
    }
    if (this.技能名称 === '绫罗红波') {
      const 分支映射 = { 倾: '25', 拧: '35', 仰: '45' } as const
      const 分支 = 分支映射[this.模拟循环.角色状态信息.大扇子前一个技能!]
      this.模拟循环.卸除buff({ 名称: '大扇子', 对象: '自身' })
      this.模拟循环.添加buff({ 名称: '大扇子·P2', 对象: '自身' })
      this.模拟循环.角色状态信息.大扇子分支 = 分支
      this.模拟循环.添加战斗日志({
        日志: `大扇子以${分支}判定进入P2，四次QTE固定在2.5、5.5、8.5、11.5秒`,
        日志类型: '技能释放结果',
        日志时间: this.模拟循环.当前时间,
      })
      return
    }
    if (this.技能名称 === '倾' || this.技能名称 === '拧' || this.技能名称 === '仰') {
      this.模拟循环.角色状态信息.大扇子前一个技能 = this.技能名称
    }
    if (this.技能名称 === '倾') {
      this.模拟循环.添加buff({ 名称: '醉心', 对象: '自身' })
    } else {
      this.模拟循环.卸除buff({ 名称: '满堂', 对象: '自身', 卸除层数: 1 })
    }
    if (this.技能名称 === '拧') {
      // TODO: 拧23186为阴性直伤，待补系数、基础/浮动伤害及武器对应技能等级；用户授权先占位。
      this.模拟循环.添加战斗日志({
        日志: '拧伤害系数待补，本次不计入伤害',
        日志类型: '技能释放结果',
        日志时间: this.模拟循环.当前时间,
      })
    }
  }

  结算P2动作() {
    结算P2技能(this.模拟循环, this.技能名称)
    if (this.技能名称 === '云肩转腰') return
    const 状态 = this.模拟循环.角色状态信息
    状态.大扇子P2技能序列.push(this.技能名称)
    if (状态.大扇子P2技能序列.length === 4) {
      结算P2终结技(this.模拟循环)
    }
  }

  释放后() {
    this.本次释放记录 = {
      实际伤害技能: this.技能名称,
      重要buff列表: this.获取当前重要buff列表(
        ['大扇子', '大扇子·P2', '醉心', '出云', '梅雨', '傲雪暗香'],
        ['奈落', '穿林·1', '穿林·2', '红蝶'],
      ),
    }
  }
}

export default 大扇子
