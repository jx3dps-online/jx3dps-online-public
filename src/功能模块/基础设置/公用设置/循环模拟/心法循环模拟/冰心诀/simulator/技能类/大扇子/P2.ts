import type 循环主类 from '../../main'

function 记录伤害占位(模拟循环: 循环主类, 技能名称: string) {
  模拟循环.添加战斗日志({
    日志: `${技能名称}伤害数值待补，本次不计入伤害`,
    日志类型: '技能释放结果',
    日志时间: 模拟循环.当前时间,
  })
}

export function 结算P2技能(模拟循环: 循环主类, 技能名称: string) {
  const 自身 = 模拟循环.当前自身buff列表
  const 目标 = 模拟循环.当前目标buff列表
  switch (技能名称) {
    case '提':
      if (自身.颂曲?.当前层数) 模拟循环.添加buff({ 名称: '颂曲', 对象: '自身' })
      break
    case '沉':
      模拟循环.添加buff({ 名称: '颂曲', 对象: '自身' })
      break
    case '冲':
      模拟循环.添加buff({ 名称: '醉心', 对象: '自身' })
      break
    case '含':
      // TODO: 炫目23215、追加生辉23224均为阴性直伤，待补系数、基础/浮动伤害及武器对应技能等级。
      记录伤害占位(模拟循环, '炫目')
      if (目标.奈落?.当前层数) 记录伤害占位(模拟循环, '生辉')
      break
    case '靠':
      // TODO: 幻蝶23216为外功直伤，待补系数、基础/浮动伤害及等级；红蝶Buff 16331待补实际等级与每跳伤害。
      记录伤害占位(模拟循环, '幻蝶、红蝶')
      模拟循环.添加buff({ 名称: '红蝶', 对象: '目标' })
      break
    case '腆':
      if (自身.鸾息?.当前层数) 模拟循环.添加buff({ 名称: '鸾息', 对象: '自身' })
      break
    case '移':
      // TODO: 那美23218为阴性直伤，待补系数、基础/浮动伤害及武器对应技能等级。
      记录伤害占位(模拟循环, '那美')
      模拟循环.添加buff({ 名称: '出云', 对象: '自身' })
      模拟循环.添加buff({ 名称: '奈落', 对象: '目标' })
      break
    case '鹓动鸾飞':
      模拟循环.添加buff({ 名称: '鸾息', 对象: '自身' })
      自身.鸾息.备注 = `受到各类伤害降低约${自身.醉心?.当前层数 ? '14.94' : '9.96'}%。`
      break
    case '扇舞蝶红':
      // TODO: 扇舞蝶红23208为外功直伤、血扇公主23295为阴性直伤，分别补系数、基础/浮动伤害及等级。
      记录伤害占位(模拟循环, '扇舞蝶红、血扇公主')
      if (目标.奈落?.当前层数) {
        模拟循环.卸除buff({ 名称: '穿林·2', 对象: '目标' })
        模拟循环.添加buff({ 名称: '穿林·1', 对象: '目标' })
      }
      break
  }
  if (['提', '含', '靠', '腆', '移', '扇舞蝶红'].includes(技能名称)) {
    模拟循环.卸除buff({ 名称: '满堂', 对象: '自身', 卸除层数: 1 })
  }
}

export function 结算P2终结技(模拟循环: 循环主类) {
  const 分支 = 模拟循环.角色状态信息.大扇子分支
  if (分支 === '35') {
    // TODO: 冷月葬花23211为阴性直伤，待补系数、基础/浮动伤害及武器对应技能等级。
    记录伤害占位(模拟循环, '冷月葬花')
    const 目标 = 模拟循环.当前目标buff列表
    if (目标['穿林·1']?.当前层数 || 目标['穿林·2']?.当前层数) {
      模拟循环.卸除buff({ 名称: '穿林·1', 对象: '目标' })
      模拟循环.添加buff({ 名称: '穿林·2', 对象: '目标' })
    }
    模拟循环.卸除buff({ 名称: '满堂', 对象: '自身', 卸除层数: 1 })
  } else if (分支 === '45') {
    模拟循环.添加buff({ 名称: '梅雨', 对象: '自身' })
    模拟循环.添加buff({ 名称: '傲雪暗香', 对象: '自身' })
    模拟循环.添加战斗日志({
      日志: '梅雨归途生效，傲雪暗香按满血NPC计算',
      日志类型: '技能释放结果',
      日志时间: 模拟循环.当前时间,
    })
  }
}
