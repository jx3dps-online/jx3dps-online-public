import 技能统一类 from '../../通用类/技能统一类'

class 卸除飞剑 extends 技能统一类 {
  等待前有飞剑 = false

  释放前初始化(额外信息) {
    super.释放前初始化(额外信息)
    this.等待前有飞剑 = !!this.模拟循环.当前自身buff列表.飞剑
    this.本次释放延迟 = 额外信息?.延迟 ?? 1
  }

  命中() {
    if (this.等待前有飞剑 || this.模拟循环.当前自身buff列表.飞剑) {
      this.本次释放记录.卸除飞剑序号 =
        this.模拟循环.技能类实例集合.万世不竭.技能运行数据.最后飞剑序号
    }
    this.模拟循环.卸除buff({ 名称: '飞剑', 对象: '自身', 卸除层数: 5 })
  }
}

export default 卸除飞剑
