import { 每秒郭氏帧 } from '@/数据/常量'
import { 获取倒读条实际帧数分布 } from '@/工具函数/data'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 获取当前破苍穹 } from '../../utils'

const 飞剑伤害 = ['飞剑·一', '飞剑·二', '飞剑·三', '飞剑·四', '飞剑·五']
const 轮内时间 = [0, 0.1875, 0.5, 0.75, 1].map((秒) => 秒 * 每秒郭氏帧)

class 万世不竭 extends 有CD技能通用类 {
  飞剑批次 = 0

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  释放() {
    const Buff = this.模拟循环.当前自身buff列表
    return Buff.飞剑 || Buff.破势二段 || Buff.橙武
      ? { 可以释放: false, 异常信息: '已有飞剑、破势二段资格或橙武效果，不能重新蓄剑' }
      : { 可以释放: true }
  }

  获取读条时间() {
    return 获取倒读条实际帧数分布(
      每秒郭氏帧 * 1.25,
      每秒郭氏帧 * 0.25,
      this.模拟循环.加速值,
      0,
      0,
      5,
    ).reduce((总时间, 间隔) => 总时间 + 间隔, 0)
  }

  读条(开始时间: number) {
    let 事件时间 = 开始时间
    const 分布 = 获取倒读条实际帧数分布(
      每秒郭氏帧 * 1.25,
      每秒郭氏帧 * 0.25,
      this.模拟循环.加速值,
      0,
      0,
      5,
    )
    this.模拟循环.添加待生效事件队列(
      分布.map((间隔, 序号) => {
        事件时间 += 间隔
        return { 事件名称: '技能读条', 事件时间, 事件备注: { 技能名称: '万世不竭', 序号 } }
      }),
    )
  }

  读条命中({ 序号 }) {
    if (序号 === 4) this.获得飞剑()
  }

  获得飞剑(持续时间 = 每秒郭氏帧 * 26.5) {
    const 已有飞剑 = this.模拟循环.当前自身buff列表.飞剑
    if (已有飞剑) {
      this.修改飞剑余时(持续时间)
      return
    }
    this.模拟循环.添加buff({ 名称: '飞剑', 对象: '自身', 覆盖层数: 5 })
    this.模拟循环.当前自身buff列表.飞剑.最大持续时间 = 持续时间
    this.恢复起手效果()
  }

  恢复起手效果() {
    const Buff = this.模拟循环.当前自身buff列表.飞剑
    if (!Buff) return
    this.飞剑批次 += 1
    const 首轮 = Buff.刷新时间! + 每秒郭氏帧 * 3
    let 轮次 = Math.max(0, Math.floor((this.模拟循环.当前时间 - 首轮) / (每秒郭氏帧 * 3)))
    let 序号 = 轮内时间.findIndex(
      (偏移) => 首轮 + 轮次 * 每秒郭氏帧 * 3 + 偏移 >= this.模拟循环.当前时间,
    )
    if (序号 < 0) {
      轮次 += 1
      序号 = 0
    }
    this.技能运行数据.最后飞剑序号 = 序号 === 0 ? (轮次 > 0 ? 5 : 0) : 序号
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '飞剑攻击',
        事件时间: 首轮 + 轮次 * 每秒郭氏帧 * 3 + 轮内时间[序号],
        事件备注: { 批次: this.飞剑批次, 序号 },
      },
    ])
  }

  飞剑攻击({ 批次, 序号 }) {
    if (批次 !== this.飞剑批次 || !this.模拟循环.当前自身buff列表.飞剑) return
    this.触发伤害行为(飞剑伤害[序号])
    this.技能运行数据.最后飞剑序号 = 序号 + 1
    const 间隔 = 序号 === 4 ? 每秒郭氏帧 * 2 : 轮内时间[序号 + 1] - 轮内时间[序号]
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '飞剑攻击',
        事件时间: this.模拟循环.当前时间 + 间隔,
        事件备注: { 批次, 序号: (序号 + 1) % 5 },
      },
    ])
  }

  获取飞剑余时() {
    const Buff = this.模拟循环.当前自身buff列表.飞剑
    return Buff ? Math.max(0, Buff.刷新时间! + Buff.最大持续时间! - this.模拟循环.当前时间) : 0
  }

  修改飞剑余时(变化: number) {
    const Buff = this.模拟循环.当前自身buff列表.飞剑
    if (!Buff) return
    const 余时 = Math.min(每秒郭氏帧 * 50, this.获取飞剑余时() + 变化)
    if (余时 <= 0) {
      this.模拟循环.卸除buff({ 名称: '飞剑', 对象: '自身', 卸除层数: 5 })
      return
    }
    Buff.最大持续时间 = this.模拟循环.当前时间 + 余时 - Buff.刷新时间!
    this.模拟循环.添加战斗日志({
      日志: `飞剑剩余时间变为${余时 / 每秒郭氏帧}秒`,
      日志类型: '自身buff变动',
    })
  }

  抱阳续剑() {
    const Buff = this.模拟循环.当前自身buff列表
    if (
      this.模拟循环.校验奇穴是否存在('抱阳') &&
      获取当前破苍穹(Buff).length &&
      Buff.飞剑 &&
      !Buff.破势二段
    ) {
      const 余时 = this.获取飞剑余时()
      const 续时 =
        余时 >= 每秒郭氏帧 * 42 && 余时 <= 每秒郭氏帧 * 43
          ? 每秒郭氏帧 * 49.6 - 余时
          : 每秒郭氏帧 * 6
      this.修改飞剑余时(续时)
    }
  }
}

export default 万世不竭
