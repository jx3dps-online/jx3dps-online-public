import { 每秒郭氏帧 } from '@/数据/常量'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'
import { 获取当前破苍穹 } from '../../utils'

class 五方行尽 extends 有CD技能通用类 {
  颠越批次 = 0
  颠越额外已用次数 = 0

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  释放() {
    return this.模拟循环.角色状态信息.气点 > 0
      ? { 可以释放: true }
      : { 可以释放: false, 异常信息: '本期暂不支持零气释放五方行尽' }
  }

  命中() {
    const 气点 = this.模拟循环.角色状态信息.气点
    const 档位 = ['一', '二', '三', '四', '五', '六', '七', '八', '九', '十'][气点 - 1]
    const 伤害名称 = '五方行尽·' + 档位
    this.本次释放记录 = { 实际伤害技能: 伤害名称 }
    this.模拟循环.改变气点(-气点, '五方行尽消耗')
    this.触发伤害行为(伤害名称)
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '会神生效',
        事件时间: this.模拟循环.当前时间 + 每秒郭氏帧 * 0.25,
        事件备注: { 持续时间: (5 + Math.ceil(气点 / 2)) * 每秒郭氏帧 },
      },
    ])
    if (this.模拟循环.校验奇穴是否存在('正气')) {
      const 气场 = 获取当前破苍穹(this.模拟循环.当前自身buff列表).sort(
        (甲, 乙) => 甲.刷新时间! + 甲.最大持续时间! - 乙.刷新时间! - 乙.最大持续时间!,
      )[0]
      if (气场) {
        this.模拟循环.卸除buff({ 名称: 气场.名称, 对象: '自身' })
        this.模拟循环.添加buff({ 名称: '颠越苍穹', 对象: '目标' })
        this.恢复起手效果()
      }
      this.触发颠越额外伤害('五方行尽')
    }
  }

  会神生效({ 持续时间 }) {
    this.模拟循环.添加buff({ 名称: '会神', 对象: '自身' })
    this.模拟循环.当前自身buff列表.会神.最大持续时间 = 持续时间
  }

  恢复起手效果() {
    const Buff = this.模拟循环.当前目标buff列表.颠越苍穹
    if (!Buff) return
    this.颠越批次 += 1
    this.颠越额外已用次数 = 0
    const 次数 = Math.max(1, Math.ceil((this.模拟循环.当前时间 - Buff.刷新时间!) / 每秒郭氏帧))
    if (次数 > 6) return
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '颠越周期伤害',
        事件时间: Buff.刷新时间! + 次数 * 每秒郭氏帧,
        事件备注: { 批次: this.颠越批次, 次数 },
      },
    ])
  }

  颠越周期伤害({ 批次, 次数 }) {
    if (批次 !== this.颠越批次 || !this.模拟循环.当前目标buff列表.颠越苍穹) return
    this.触发伤害行为('颠越苍穹击')
    this.模拟循环.添加战斗日志({ 日志: `颠越周期伤害第${次数}次`, 日志类型: '技能释放结果' })
    if (次数 < 6) {
      this.模拟循环.添加待生效事件队列([
        {
          事件名称: '颠越周期伤害',
          事件时间: this.模拟循环.当前时间 + 每秒郭氏帧,
          事件备注: { 批次, 次数: 次数 + 1 },
        },
      ])
    }
  }

  触发颠越额外伤害(来源: string) {
    if (
      !this.模拟循环.校验奇穴是否存在('正气') ||
      !this.模拟循环.当前目标buff列表.颠越苍穹 ||
      this.颠越额外已用次数 >= 5
    )
      return
    this.颠越额外已用次数 += 1
    this.触发伤害行为('颠越苍穹击')
    this.模拟循环.添加战斗日志({
      日志: `${来源}触发颠越额外伤害，已用${this.颠越额外已用次数}/5次`,
      日志类型: '技能释放结果',
    })
  }
}

export default 五方行尽
