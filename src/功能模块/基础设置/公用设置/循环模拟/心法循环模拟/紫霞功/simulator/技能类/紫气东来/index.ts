import { 每秒郭氏帧 } from '@/数据/常量'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 紫气东来 extends 有CD技能通用类 {
  紫气批次 = 0

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  命中() {
    this.模拟循环.改变气点(10, '紫气东来')
    this.模拟循环.添加buff({ 名称: '紫气东来·3', 对象: '自身' })
    this.恢复起手效果()
    if (!this.模拟循环.当前自身buff列表.破势二段) {
      this.模拟循环.技能类实例集合.万世不竭.获得飞剑(每秒郭氏帧 * 25)
    }
  }

  恢复起手效果() {
    const Buff = this.模拟循环.当前自身buff列表['紫气东来·3']
    if (!Buff) return
    this.紫气批次 += 1
    const 次数 = Math.max(1, Math.ceil((this.模拟循环.当前时间 - Buff.刷新时间!) / 每秒郭氏帧))
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '紫气回气',
        事件时间: Buff.刷新时间! + 次数 * 每秒郭氏帧,
        事件备注: { 批次: this.紫气批次 },
      },
    ])
  }

  紫气回气({ 批次 }) {
    if (批次 !== this.紫气批次 || !this.模拟循环.当前自身buff列表['紫气东来·3']) return
    this.模拟循环.改变气点(2, '紫气回气')
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '紫气回气',
        事件时间: this.模拟循环.当前时间 + 每秒郭氏帧,
        事件备注: { 批次 },
      },
    ])
  }
}

export default 紫气东来
