import { 每秒郭氏帧 } from '@/数据/常量'
import { 获取实际帧数 } from '@/工具函数/data'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

const 同尘增益 = ['同尘·1', '同尘·2', '同尘·3', '同尘·4']

class 六合独尊 extends 有CD技能通用类 {
  剑域批次 = 0

  constructor(模拟循环) {
    super(模拟循环)
    this.初始化技能运行数据()
  }

  获取读条时间() {
    return 获取实际帧数(每秒郭氏帧 * 1.5, this.模拟循环.加速值)
  }

  读条(开始时间: number) {
    this.模拟循环.添加待生效事件队列([
      {
        事件名称: '技能读条',
        事件时间: 开始时间 + this.获取读条时间(),
        事件备注: { 技能名称: '六合独尊' },
      },
    ])
  }

  读条命中() {
    const 技能 = this.模拟循环.技能基础数据.find((技能) => 技能.技能名称 === '六合独尊')!
    this.模拟循环.技能释放后更新运行数据(技能, this)
    this.模拟循环.添加buff({ 名称: '八方剑域', 对象: '目标' })
    this.本次释放记录 = { 实际伤害技能: '六合独尊' }
    this.恢复起手效果()
  }

  恢复起手效果() {
    const Buff = this.模拟循环.当前目标buff列表.八方剑域
    if (!Buff) return
    this.剑域批次 += 1
    const 事件 = [0, 1, 2, 3, 4]
      .map((序号) => ({
        事件名称: '六合攻击',
        事件时间: Buff.刷新时间! + 序号 * 每秒郭氏帧 * 0.625,
        事件备注: { 批次: this.剑域批次, 序号 },
      }))
      .filter((事件) => 事件.事件时间 >= this.模拟循环.当前时间)
    this.模拟循环.添加待生效事件队列(事件)
  }

  六合攻击({ 批次, 序号 }) {
    if (批次 !== this.剑域批次 || !this.模拟循环.当前目标buff列表.八方剑域) return
    this.触发伤害行为('六合独尊', 1, 序号 ? [同尘增益[序号 - 1]] : [], undefined, 1, 同尘增益)
    this.模拟循环.技能类实例集合.五方行尽.触发颠越额外伤害('六合独尊')
  }
}

export default 六合独尊
