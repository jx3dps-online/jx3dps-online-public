  改变气点(变化: number, 来源: string) {
    const 原气点 = this.角色状态信息.气点
    this.角色状态信息.气点 = Math.max(0, Math.min(10, 原气点 + 变化))
    if (原气点 !== this.角色状态信息.气点) {
      this.添加战斗日志({
        日志: 来源 + '：气点 ' + 原气点 / 2 + ' → ' + this.角色状态信息.气点 / 2,
        日志类型: '技能释放结果',
      })
    }
  }
