  // 初始化创建
  constructor(props: SimulatorCycleProps) {
    const 起手Buff配置 = 转换起手Buff配置(props.起手Buff配置)
    // 模拟开始后不会变动的数据
    this.测试循环 = props.测试循环
    this.大橙武模拟 = props.大橙武模拟
    this.会心回豆 = props.会心回豆 ?? false
    this.奇穴 = props.奇穴
    this.秘籍 = props.秘籍
    this.加速值 = props.加速值
    this.网络延迟 = props.网络延迟
    this.忽略延迟技能 = props.忽略延迟技能 || []
    this.周期性忽略延迟 = props.周期性忽略延迟 || 0
    this.启用团队增益快照 = !!props.启用团队增益快照
    this.团队增益轴 = props.团队增益轴 ? props.团队增益轴 : {}
    this.副本事件实例列表 = props.副本事件实例列表 ? props.副本事件实例列表 : []
    // 根据奇穴和装备情况修改buff的数据
    this.Buff和Dot数据 = 根据奇穴修改buff数据(this.奇穴)
    // 根据奇穴和装备情况修改技能的数据
    this.技能基础数据 = 根据奇穴秘籍修改技能数据(this.奇穴, this.秘籍)

    this.当前自身buff列表 = {
      ...获取起手Buff配置(起手Buff配置, this.Buff和Dot数据, '自身'),
    }
    this.当前目标buff列表 = { ...获取起手Buff配置(起手Buff配置, this.Buff和Dot数据, '目标') }

    this.角色状态信息 = {
      气点: (props.起手气点 ?? 5) * 2,
    }
    this.待生效事件队列 = []
    // 模拟初始化
    this.初始化技能实例类()
    if (
      !Number.isInteger(this.角色状态信息.气点) ||
      this.角色状态信息.气点 < 0 ||
      this.角色状态信息.气点 > 10
    ) {
      this.初始配置异常 = '起手气点应为0至5之间的半点数值'
    }
    for (const [名称, 配置] of Object.entries(起手Buff配置 || {})) {
      const 数据 = this.Buff和Dot数据[名称]
      if (!配置 || typeof 配置 !== 'object' || Array.isArray(配置)) {
        this.初始配置异常 = `起手Buff配置无效：${名称}`
        continue
      }
      if (
        !数据 ||
        配置.类型 !== 数据.类型 ||
        typeof 配置.层数 !== 'number' ||
        !Number.isInteger(配置.层数) ||
        配置.层数 < 1 ||
        配置.层数 > 数据.最大层数 ||
        typeof 配置.获得时间 !== 'number' ||
        !Number.isInteger(配置.获得时间) ||
        配置.获得时间 > 0
      ) {
        this.初始配置异常 = `起手Buff配置无效：${名称}`
      }
      if (名称 === '飞剑' && 配置.层数 !== 5) this.初始配置异常 = '本期起手飞剑仅支持完整5层'
    }
    if (this.当前自身buff列表.橙武 && !props.大橙武模拟) {
      this.初始配置异常 = '起手橙武需要装备启用大橙武特效'
    }
    this.添加待生效事件队列([{ 事件名称: '自然回气', 事件时间: 每秒郭氏帧 }])
    if (!this.初始配置异常) {
      this.清空已经消失的buff()
      for (const [对象, 列表] of [
        ['自身', this.当前自身buff列表],
        ['目标', this.当前目标buff列表],
      ] as const) {
        for (const 名称 of Object.keys(列表)) {
          this.添加战斗日志({
            日志: `${对象}获得${名称}`,
            日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
            日志时间: 0,
          })
        }
      }
      Object.values(this.技能类实例集合).forEach((技能) => 技能.恢复起手效果?.())
    }
    this.重置循环执行结果()
  }

  重置循环执行结果() {
    this.循环执行结果 = '成功'
    this.循环异常信息 = { 异常索引: 0, 异常信息: '' }
  }

  添加buff({
    名称,
    对象 = '目标',
    事件时间 = this.当前时间,
    新增层数 = 1,
    覆盖层数 = 0,
    只添加日志 = false,
  }) {
    const 当前层数 =
      对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数

    const 新buff对象 = {
      ...this.Buff和Dot数据[名称],
      当前层数: 覆盖层数
        ? 覆盖层数
        : Math.min((当前层数 || 0) + 新增层数, this.Buff和Dot数据[名称].最大层数 || 1),
      刷新时间: 事件时间,
    }
    if (当前层数 && 新buff对象.当前层数 !== 当前层数 && 新buff对象.当前层数 !== 1) {
      this.添加战斗日志({
        日志: `${名称}层数变为【${新buff对象.当前层数}】`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    } else {
      this.添加战斗日志({
        日志: `${对象}获得${名称}`,
        日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
        日志时间: 事件时间,
      })
    }

    if (!只添加日志) {
      if (对象 === '自身') {
        this.当前自身buff列表[名称] = { ...新buff对象 }
      } else {
        this.当前目标buff列表[名称] = { ...新buff对象 }
      }
    }
  }

  卸除buff({
    名称,
    对象 = '目标',
    事件时间 = this.当前时间,
    buff刷新时间 = 事件时间,
    卸除层数 = 1,
    只添加日志 = false,
  }) {
    const 当前层数 =
      (对象 === '自身'
        ? this.当前自身buff列表[名称]?.当前层数
        : this.当前目标buff列表[名称]?.当前层数) || 0

    if ((当前层数 && 当前层数 >= 0) || 只添加日志) {
      if (当前层数 - 卸除层数 > 0) {
        this.添加战斗日志({
          日志: `${名称}层数变为【${当前层数 - 卸除层数}】`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 事件时间,
        })
        if (!只添加日志) {
          const 新buff对象 = {
            ...this.Buff和Dot数据[名称],
            当前层数: 当前层数 - 卸除层数,
            刷新时间: buff刷新时间,
          }
          if (对象 === '自身') {
            this.当前自身buff列表[名称] = { ...新buff对象 }
          } else {
            this.当前目标buff列表[名称] = { ...新buff对象 }
          }
        }
      } else {
        this.添加战斗日志({
          日志: `${对象}失去${名称}`,
          日志类型: 对象 === '自身' ? '自身buff变动' : '目标buff变动',
          日志时间: 事件时间,
        })
        if (!只添加日志) {
          if (对象 === '自身') {
            delete this.当前自身buff列表[名称]
          } else {
            delete this.当前目标buff列表[名称]
          }
        }
      }
    }
  }

