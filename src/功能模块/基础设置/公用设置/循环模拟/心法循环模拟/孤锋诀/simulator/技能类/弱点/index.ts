/**
 * 经过测试的弱点规
 * 弱点自身原始间隔为24帧
 * 实际应用满足 24-N+1 N为加速档位 既计算加速后额外添加1帧
 * 浮游、物化期间间隔变化远离经过对比JCL得
 * 浮游期间加速间隔激素继续计算，遇到间隔校验是否处于浮游状态，若处于浮游状态则不尽兴弱点，但是会记录弱点记时点
 * 释放物化后，刷新加速快照，按上一次弱点记时点按新间隔生成新的弱点轴
 * 在失去物化后，刷新加速快照，按上一次弱点记时点按新间隔生成新的弱点轴
 */

