  static 原始间隔 = 16 * 10
  // static 单位间隔 = 16
  static 最大事件次数 = 500
  static 弱点记时点 = 8

  constructor(模拟循环) {
    super(模拟循环)
    弱点.弱点记时点 = 8

    const 循环加速值 = this.模拟循环?.加速值
    // 用8计算加速。然后*20
    const 加速后帧数 = 获取实际帧数(160, 循环加速值)
    弱点.原始间隔 = 加速后帧数
    // 弱点.单位间隔 = 加速后帧数
  }

