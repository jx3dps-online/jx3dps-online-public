  // }

  初始化弱点() {
    // 立即造成第一次弱点伤害，然后添加序列
    // this.弱点造成伤害()
    弱点.弱点记时点 = 8
    this.刷新弱点序列()
  }

  立即获得并刷新弱点() {
    this.弱点检查()
    this.刷新弱点序列((this.模拟循环?.当前时间 || 0) + 弱点.原始间隔)
  }

  // 降低寻隙Buff时间(降低跳数 = 0) {
