import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 破穴 extends 有CD技能通用类 {
  命中() {
    const 循环 = this.模拟循环
    const 经脉循行 = 循环.技能类实例集合.经脉循行
    const 消耗任脉 = 经脉循行.经脉循行状态校验() ? 循环.判断消耗能量值('任脉') : 0
    const 消耗督脉 = 经脉循行.经脉循行状态校验() ? 循环.判断消耗能量值('督脉') : 0
    const 返还风徊 = !!循环.当前目标buff列表.风徊絮转?.当前层数

    if (经脉循行.经脉循行状态校验()) {
      循环.角色状态信息.能量信息.任脉 -= 消耗任脉
      循环.角色状态信息.能量信息.督脉 -= 消耗督脉
      this.触发伤害行为('破', 1, [], undefined, Math.floor((消耗任脉 + 消耗督脉) / 2) + 1)
    } else {
      循环.回复能量(15, '任脉', false)
      循环.回复能量(15, '督脉', false)
    }

    this.触发伤害行为('破穴')
    循环.技能类实例集合.蛰微.累计消耗督脉(消耗督脉)
    if (循环.校验奇穴是否存在('神封') && (消耗任脉 === 40 || 消耗督脉 === 40)) {
      循环.神封触发()
    }
    if (返还风徊) {
      循环.卸除buff({ 名称: '风徊絮转', 对象: '目标', 卸除层数: 1 })
      循环.回复能量(消耗任脉, '任脉')
      循环.回复能量(消耗督脉, '督脉')
    }
    // 源脚本先返还调息，再按结算后的能量更新经脉循行。
    if (循环.校验奇穴是否存在('蛰微') && 经脉循行.经脉循行状态校验()) {
      this.更新技能运行数据({ 待充能时间点: [] })
    }
    this.橙武回能()
    经脉循行.经脉循行添加校验()
    经脉循行.经脉循行卸除校验()
    this.本次释放记录 = { 伤害段数: 经脉循行.经脉循行状态校验() ? 1 : 2 }
  }
}

export default 破穴
export const 破穴类型 = typeof 破穴
