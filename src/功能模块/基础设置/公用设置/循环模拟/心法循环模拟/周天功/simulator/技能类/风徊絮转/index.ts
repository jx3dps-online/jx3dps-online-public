import { 获取实际帧数 } from '@/工具函数/data'
import { 每秒郭氏帧 } from '@/数据/常量'
import 有CD技能通用类 from '../../通用类/有CD技能通用类'

class 风徊絮转 extends 有CD技能通用类 {
  constructor(模拟循环) {
    super(模拟循环)
    const 技能数据 = this.模拟循环.技能基础数据.find((技能) => 技能.技能名称 === '风徊絮转')
    if (技能数据) 技能数据.技能CD = 获取实际帧数(每秒郭氏帧 * 23, 模拟循环.加速值)
  }

  命中() {
    this.触发伤害行为('风徊絮转')
    this.模拟循环.添加buff({ 名称: '风徊絮转', 对象: '目标' })
  }

  抟风触发() {
    if (!this.模拟循环.当前目标buff列表.风徊絮转?.当前层数) return
    this.模拟循环.卸除buff({ 名称: '风徊絮转', 对象: '目标' })
    // 固定 PVE 目标不进入拉拽状态，源脚本在拉拽判定失败时直接结算附伤。
    this.触发伤害行为('风徊絮转·抟')
  }
}

export default 风徊絮转
