  获取实际加速帧数(原始帧数, 加速等级) {
    const 是否处于降厄加速状态 = !!this.当前自身buff列表?.['降厄']?.当前层数
    const 是否处于狂暴加速状态 = !!this.当前自身buff列表?.['蛊虫狂暴']?.当前层数
    const 降厄加速值 = 512
    const 狂暴加速值 = 102
    const 生效加速值 =
      (是否处于降厄加速状态 ? 降厄加速值 : 0) + (是否处于狂暴加速状态 ? 狂暴加速值 : 0)

    return 获取实际帧数(原始帧数, 加速等级, 0, 生效加速值)
  }
