import { 计算局部秒伤 } from '@/计算容器'
import { 在指定心法数据下执行 } from '@/数据/数据工具/获取当前数据'
import { 获取加速等级分界 } from '@/工具函数/data'
import type { 循环数据 } from '@/@types/循环'

const 比较数值 = (左: number, 右: number) => (左 < 右 ? -1 : 左 > 右 ? 1 : 0)

export const 获取对比列 = (心法数据: 数据类型, 循环列表: 循环数据[]): 对比列[] => {
  const 分界 = 在指定心法数据下执行(心法数据, 获取加速等级分界)
  return 循环列表
    .flatMap((循环, 循环索引) =>
      循环.循环详情.map((详情, 详情索引) => {
        const 档位 = Number(详情.循环加速等级)
        const 范围 = 详情.循环加速值范围
        const 未限定加速 = !范围?.length && 详情.循环加速等级 === undefined
        const 加速范围: [number, number] = 范围?.length
          ? [Number(范围[0]), Number(范围[1])]
          : 未限定加速
            ? [-Infinity, Infinity]
            : [
                档位 === 0 ? -Infinity : 分界[档位 - 1],
                档位 === 分界.length ? Infinity : 分界[档位],
              ]
        const 加速说明 = 范围?.length
          ? `[${范围[0]}, ${范围[1]}) 加速`
          : 未限定加速
            ? '未限定加速'
            : `${详情.循环加速等级} 档加速`
        const 延迟说明 =
          详情.循环延迟要求 === undefined ? '未限定延迟' : `${详情.循环延迟要求} 延迟`
        return {
          id: `${循环索引}:${详情索引}`,
          循环,
          详情,
          加速范围,
          标题: `${加速说明} · ${延迟说明}`,
          加速说明,
          延迟说明,
          简易标题: `${范围?.length ? `[${范围[0]},${范围[1]})` : 未限定加速 ? '不限' : 详情.循环加速等级} | ${详情.循环延迟要求 ?? '不限'}`,
          原因: 未限定加速 && 循环.强制加速要求 ? '循环缺少加速要求' : undefined,
          排序: { 循环索引, 详情索引 },
        }
      }),
    )
    .sort((左, 右) => {
      const 左延迟 = 左.详情.循环延迟要求
      const 右延迟 = 右.详情.循环延迟要求
      return (
        比较数值(左.排序.循环索引, 右.排序.循环索引) ||
        比较数值(左.加速范围[0], 右.加速范围[0]) ||
        比较数值(左.加速范围[1], 右.加速范围[1]) ||
        比较数值(
          左延迟 === undefined ? Infinity : Number(左延迟),
          右延迟 === undefined ? Infinity : Number(右延迟),
        ) ||
        比较数值(左.排序.详情索引, 右.排序.详情索引)
      )
    })
    .map(({ 排序, ...列 }) => 列)
}

export const 列符合筛选 = (列: 对比列, 筛选: 对比筛选) => {
  if (
    (筛选.最低加速 ?? 0) > (筛选.最高加速 ?? Infinity) ||
    (筛选.最低延迟 ?? 0) > (筛选.最高延迟 ?? Infinity)
  )
    return false
  const [下限, 上限] = 列.加速范围
  const 最低加速 = 筛选.最低加速
  const 最高加速 = 筛选.最高加速
  if (最低加速 !== null && 最高加速 !== null && 最低加速 === 最高加速) {
    if (!(下限 <= 最低加速 && 最低加速 < 上限)) return false
  } else if (下限 >= (最高加速 ?? Infinity) || 上限 <= (最低加速 ?? -Infinity)) {
    return false
  }
  if (列.详情.循环延迟要求 === undefined) return 筛选.未限定延迟
  const 延迟 = Number(列.详情.循环延迟要求)
  return 延迟 >= (筛选.最低延迟 ?? 0) && 延迟 <= (筛选.最高延迟 ?? Infinity)
}

export const 计算对比格子 = (心法数据: 数据类型, 行: 对比行, 列: 对比列): 对比结果 => {
  if (行.原因 || !行.状态) return { 原因: 行.原因 || '角色数据不可读' }
  if (列.原因) return { 原因: 列.原因 }
  const [下限, 上限] = 列.加速范围
  if (!(行.加速值 >= 下限 && 行.加速值 < 上限)) return { 原因: '该加速延迟下无法计算该循环' }
  if (['橙武', '特效'].includes(列.循环.标记 || '') && 行.武器标记 !== 列.循环.标记) {
    return { 原因: 行.武器标记 ? '武器不匹配' : '无法确认专用武器' }
  }
  if (!列.详情.技能详情.length || !(列.详情.战斗时间 > 0)) return { 原因: '循环缺少技能或战斗时间' }
  const 结果 = 计算局部秒伤(
    心法数据,
    {
      ...行.状态,
      当前计算循环名称: 列.循环.名称,
      当前奇穴信息: 列.循环.奇穴,
      当前秘籍信息: 列.详情.秘籍 || 列.循环.秘籍 || 行.状态.当前秘籍信息,
      网络延迟:
        列.详情.循环延迟要求 === undefined ? 行.状态.网络延迟 : Number(列.详情.循环延迟要求),
    },
    列.详情,
  )
  return Number.isFinite(结果.秒伤) ? { 秒伤: 结果.秒伤 } : { 原因: '计算结果无效' }
}
