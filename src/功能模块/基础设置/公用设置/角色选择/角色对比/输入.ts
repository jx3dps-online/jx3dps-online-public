const 读取心法配置 = (心法: string) => {
  const 映射 = 获取缓存映射(心法)
  const 特殊配置 = JSON.parse(localStorage.getItem(映射.特殊配置) || '{}')
  const 自定义循环 = JSON.parse(localStorage.getItem(映射.自定义循环) || '{}')
  if (!是对象(特殊配置) || !是对象(自定义循环)) throw new Error('心法配置格式错误，原数据未改动。')
  const 自定义循环列表 = Object.values(自定义循环)
  if (
    !自定义循环列表.every(
      (项) =>
        是对象(项) &&
        typeof 项.名称 === 'string' &&
        Array.isArray(项.奇穴) &&
        项.奇穴.every((奇穴) => typeof 奇穴 === 'string') &&
        Array.isArray(项.循环详情) &&
        项.循环详情.every(
          (详情) =>
            是对象(详情) &&
            Number.isFinite(详情.战斗时间) &&
            详情.战斗时间 > 0 &&
            Array.isArray(详情.技能详情) &&
            详情.技能详情.every(
              (技能) =>
                是对象(技能) && typeof 技能.技能名称 === 'string' && Number.isFinite(技能.技能数量),
            ),
        ),
    )
  )
    throw new Error('自定义循环格式错误，请在对应心法中检查；原数据未改动。')
  return { 特殊配置, 自定义循环列表: 自定义循环列表 as 循环数据[] }
}

export const 准备对比数据 = async ({ 角色, 页面数据 }: 对比输入): Promise<对比数据> => {
  const 心法 = 角色[0].心法
  const 页面同心法 = 页面数据.当前角色?.心法 === 心法
  const 配置 = 页面同心法
    ? { 特殊配置: 页面数据.特殊配置, 自定义循环列表: 页面数据.自定义循环列表 }
    : 读取心法配置(心法)
  const 目标存储 = 创建目标池存储(心法)
  const 目标池 = 目标存储.读取()
  const 读取错误 = 目标存储.读取错误()
  if (读取错误) throw new Error(读取错误)
  const 角色行 = 角色.map((项) => ({
    id: `角色:${项.id}`,
    角色id: 项.id,
    名称: 项.名称,
    来源: '角色' as const,
    状态:
      项.id === 页面数据.当前角色?.id
        ? {
            ...页面数据,
            角色增益: { 阵眼: 页面数据.增益数据.阵眼, 小吃: 页面数据.增益数据.小吃 },
            更新时间: 页面数据.角色更新时间,
          }
        : 读取原始角色状态(项.id),
  }))
  const 原始行 = 角色行.flatMap((角色) => [
    角色,
    ...目标池.目标.map((目标) => ({
      id: `目标:${角色.角色id}:${目标.id}`,
      角色id: 角色.角色id,
      目标id: 目标.id,
      名称: 目标.名称,
      来源: '目标' as const,
      状态: 角色.状态
        ? {
            ...角色.状态,
            装备信息: 目标.装备,
            当前计算循环名称: 目标.循环?.名称 || '',
            当前奇穴信息: 目标.循环?.奇穴 || [],
            当前秘籍信息: 目标.循环?.秘籍 || 角色.状态.当前秘籍信息,
            更新时间: 目标.时间,
          }
        : undefined,
    })),
  ])
  const 心法数据 = await 确保心法数据已加载(心法)
  const 行 = 在指定心法数据下执行(心法数据, () =>
    原始行.map((项): 对比行 => {
      const 空行: 对比行 = {
        id: 项.id,
        角色id: 项.角色id,
        目标id: '目标id' in 项 ? 项.目标id : undefined,
        名称: 项.名称,
        来源: 项.来源,
        加速值: 0,
        武器标记: '',
      }
      if (!项.状态) return { ...空行, 原因: '角色尚未保存或保存数据不可读' }
      const 原始 = deepClone(项.状态) as 角色状态数据类型
      const 装备信息 = 原始.装备信息.装备列表?.length
        ? 根据装备信息获取基础属性(原始.装备信息)
        : 原始.装备信息
      const 增益数据 = {
        ...原始.角色增益,
        团队增益: 页面数据.增益数据.团队增益.filter((增益) =>
          心法数据.团队增益.some((可用) => 可用.增益名称 === 增益.增益名称),
        ),
      }
      const 加速值 =
        (装备信息.装备基础属性.加速等级 || 0) +
        (页面数据.增益启用 ? 计算增益数据中加速值(增益数据) : 0)
      const 加速装备: string[] = []
      const 加速附魔: string[] = []
      for (const 装备 of 装备信息.装备列表 || []) {
        const 数据 = 心法数据.装备数据[装备.装备部位]?.find((数据) => 数据.id === 装备.id)
        if (数据?.装备增益.some((增益) => 增益.属性 === 属性类型.加速等级 && 增益.值 > 0)) {
          加速装备.push(装备.装备部位)
        }
        const 附魔 = 心法数据.附魔.find((数据) => 数据.id === 装备.附魔)
        if (附魔?.增益集合.some((增益) => 增益.属性 === 属性类型.加速等级 && 增益.值 > 0)) {
          加速附魔.push(装备.装备部位)
        }
      }
      const 加速小吃 = 页面数据.增益启用
        ? 增益数据.小吃
            .map((名称) => 心法数据.小药小吃.find((项) => 项.小吃名称 === 名称))
            .filter((小吃) =>
              小吃?.增益集合.some((增益) => 增益.属性 === 属性类型.加速等级 && 增益.值 > 0),
            )
        : []
      const 酒数量 = 加速小吃.filter((项) => 项?.小吃部位 === 小吃类型枚举.家园酒品).length
      const 武器 = 装备信息.装备列表?.find((装备) => 装备.装备部位 === '武器')
      const 武器数据 = 心法数据.装备数据.武器?.find((装备) => 装备.id === 武器?.id)
      const 武器标记 =
        武器数据?.装备特效 === 装备特效枚举.大橙武特效
          ? '橙武'
          : 武器数据?.装备特效 === 装备特效枚举.门派特效武器
            ? '特效'
            : 武器数据
              ? '紫武'
              : ''
      return {
        ...空行,
        加速值,
        武器标记,
        加速概要: {
          装备: 加速装备.length >= 3 ? `${加速装备.length} 件` : 加速装备.join('、') || '无',
          附魔: 加速附魔.join('、'),
          小药: 加速小吃.length - 酒数量,
          酒: 酒数量,
        },
        状态: {
          装备信息,
          增益数据,
          增益启用: 页面数据.增益启用,
          当前输出计算目标名称: 页面数据.当前输出计算目标名称,
          当前计算循环名称: 原始.当前计算循环名称,
          当前奇穴信息: 原始.当前奇穴信息,
          当前秘籍信息: 原始.当前秘籍信息,
          网络延迟: 页面数据.网络延迟,
          团队增益轴: 页面数据.团队增益轴,
          ...配置,
        },
      }
    }),
  )
  return {
    心法数据,
    行,
    目标: 目标池.目标.map(({ id, 名称 }) => ({ id, 名称 })),
    循环: [...心法数据.计算循环, ...配置.自定义循环列表],
  }
}
