import type { 引导界面状态 } from './界面状态'

export interface 引导步骤 {
  标识: string
  标题: string
  说明: string
  选择器: string
  等待操作?: boolean
  开放界面?: boolean
  位置?: 'rightTop' | 'top' | 'bottom'
}

export function 获取引导步骤(
  界面: 引导界面状态,
  有计算结果: boolean,
  增益打开: boolean,
  增益启用: boolean,
  目标编辑: boolean,
): 引导步骤[] {
  let 目标提示 = {
    标题: '设定配装目标',
    说明: 界面.登阶显示
      ? '打开「目标管理」新建目标，规划想获得的装备与循环，持续辅助角色成长和对比。'
      : '点击这个页签返回配装目标区域，再打开「目标管理」。',
    选择器: 界面.登阶显示 ? '#Guide_目标管理' : '#Guide_登阶页签',
  }
  if (目标编辑) {
    目标提示 = {
      标题: '完成目标配装并保存',
      说明: '选择目标装备并核对目标循环，再点击「保存目标」或「更新目标」。保存成功后继续；直接关闭不算完成。目标与角色装备分别保存。',
      选择器: '#Guide_保存目标',
    }
  } else if (界面.目标命名打开) {
    目标提示 = {
      标题: '命名并选择目标循环',
      说明: '填写目标名称，确认循环后点击创建，进入目标配装。创建时目标已加入列表，之后取消编辑也会保留，可在目标管理中继续编辑。',
      选择器: '.guide-new-goal-modal .ant-modal-content',
    }
  } else if (界面.目标管理打开) {
    目标提示 = {
      标题: '新建或编辑目标',
      说明: '点击「新增目标」。也可以编辑已有目标，完成配装后保存。',
      选择器: '.dragon-manager .ant-modal-content',
    }
  }
  return [
    {
      标识: '打开配装器',
      标题: '打开配装器',
      说明: '点击「配装器」开始了解装备设置。',
      选择器: '#Guide_1',
      等待操作: true,
    },
    {
      标识: '保存角色',
      标题: '配装并保存角色',
      说明: '这里可以选择装备并设置精炼、镶嵌和附魔，工具菜单提供导入入口。完成后点击「保存角色」保存并重新计算；直接关闭会放弃未保存的修改。首页「角色」入口可切换和管理你的多个实际角色。',
      选择器: '#Guide_7',
      等待操作: true,
    },
    {
      标识: '预设循环',
      标题: '预设循环',
      说明: '这里选择计算使用的预设循环。注意武器类型与循环说明，切换循环可能同时更新奇穴和秘籍。支持模拟器的心法可通过「循环模拟」研究循环，首次打开会有单独的基础引导。',
      选择器: '#Guide_预设循环',
    },
    {
      标识: '心法阈值',
      标题: '查看心法加速阈值',
      说明: '悬停或点击加速数值，可查看当前档位与下一档；「查看阈值」可以展开本心法的详细档位。配装应结合所选循环的加速要求，不是越高越好。这一步无需修改数值。',
      选择器: '#Guide_加速阈值',
      开放界面: true,
    },
    {
      标识: '增益设置',
      标题: 增益启用 ? '增益已启用' : 增益打开 ? '启用增益' : '打开增益详情',
      说明: 增益启用
        ? '小吃小药、阵眼和团队增益当前已参与计算。计算属性收益时建议保持启用，否则木桩环境下部分属性收益和实战会有较大差距。点击「已了解」继续。'
        : 增益打开
          ? '增益详情包含小吃小药、阵眼和团队增益。点击「启用增益」开关，启用后会自动继续；只有启用后才参与增益计算。'
          : '点击「增益详情」，查看角色增益和团队增益设置。',
      选择器: 增益打开 ? '#Guide_14' : '#Guide_12',
      等待操作: !增益启用,
    },
    {
      标识: '技能图表',
      标题: '查看技能数量与伤害分布',
      说明: 有计算结果
        ? '悬停可看总伤、会心期望和伤害比例。想查看更详细的秒伤统计，再点击秒伤旁的「技能详情」即可。'
        : '当前没有可用计算结果。请先检查循环要求的加速、延迟和装备，结果恢复后继续。也可以结束引导后调整。',
      选择器: 有计算结果 ? '#skill-chart' : '#Guide_计算结果',
      位置: 'top',
      开放界面: true,
    },
    {
      标识: '目标设置',
      ...目标提示,
      等待操作: true,
      开放界面: 目标编辑 || 界面.目标命名打开 || 界面.目标管理打开,
    },
    ...(界面.桌宠挂载
      ? [
          {
            标识: '桌宠',
            标题: 界面.桌宠问题状态 === '问题列表' ? '用桌宠查找帮助' : '认识桌宠',
            说明:
              界面.桌宠问题状态 === '问题列表'
                ? '搜索问题或关键词，例如「加速」或「保存循环」，选择问题后结束引导，阅读简答或打开对应工具。完整功能说明可以从右下角齿轮打开。'
                : 界面.桌宠显示
                  ? '点击桌宠打开问题列表。也可以拖动调整位置，右键隐藏。'
                  : 界面.桌宠可用
                    ? '桌宠当前已隐藏。点击「显示桌宠并继续」后，再点击桌宠；之后可在网页设置的外观设置中调整显示。'
                    : '桌宠暂未就绪。可以稍后重放引导；右下角齿轮中的「功能说明」也提供完整帮助。',
            选择器:
              界面.桌宠问题状态 === '问题列表'
                ? '#Guide_桌宠问题'
                : 界面.桌宠显示
                  ? '#Guide_桌宠'
                  : '#Guide_15',
            等待操作: 界面.桌宠问题状态 !== '问题列表',
            开放界面: 界面.桌宠问题状态 === '问题列表',
          },
        ]
      : []),
  ]
}
