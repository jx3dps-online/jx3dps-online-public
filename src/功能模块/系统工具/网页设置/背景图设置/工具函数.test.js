import { 校准背景图选择 } from './校准背景图选择'

describe('校准背景图选择', () => {
  it('内置图片更新后只保留仍然存在的用户选择', () => {
    expect(校准背景图选择(['已删除.jpg', '仍存在.jpg'], ['仍存在.jpg', '新图片.jpg'])).toEqual([
      '仍存在.jpg',
    ])
  })

  it('用户选择全部失效时回退到当前可用图片', () => {
    expect(校准背景图选择(['已删除.jpg'], ['新图片一.jpg', '新图片二.jpg'])).toEqual([
      '新图片一.jpg',
      '新图片二.jpg',
    ])
  })

  it('保留仍然可用的自定义图片并去重', () => {
    expect(
      校准背景图选择(
        ['local:用户图片', 'local:用户图片'],
        ['内置.jpg', 'local:用户图片', 'local:用户图片'],
      ),
    ).toEqual(['local:用户图片'])
  })
})
