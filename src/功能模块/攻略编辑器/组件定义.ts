const 拆分 = (值: unknown) =>
  String(值 || '')
    .split(/[,，、\s]+/)
    .map((项) => 项.trim())
    .filter(Boolean)
export const 节点 = (
  标签: string,
  属性: Record<string, unknown> = {},
  子: (内容节点 | string)[] = [],
): 内容节点 => ({ 标签, 属性, 子 })
const 富文块 = (名称: string): 组件定义 => ({
  名称,
  分类: '文字',
  默认值: { 内容: '' },
  字段: [{ 键: '内容', 名称: '内容', 类型: '富文本' }],
  构建: (块) => 节点('div', { 'data-guide-kind': 名称 }, 富文本节点(块.内容)),
})

