const 克隆 = <T>(值: T): T => JSON.parse(JSON.stringify(值))

/** 附魔按部位通用：按附魔 ID 解析，数据中存在且支持当前部位即可套用。 */
const 附魔可用于部位 = (附魔ID?: number, 部位?: string) =>
  !!附魔ID && !!根据附魔ID获取附魔数据(附魔ID, 部位)
const 获取装备 = (装备?: 选择装备数据类型) =>
  装备?.id
    ? 获取当前数据().装备数据?.[装备.装备部位]?.find((条目) => 条目.id === 装备.id)
    : undefined
const 装备名称 = (装备: 选择装备数据类型 | undefined, 文案: 登阶文案) =>
  装备?.id
    ? 获取装备(装备)?.装备名称 || 填充文案(文案['计算.装备名称.兜底'], { ID: 装备.id })
    : 文案['通用.未装备']
export const 装备相同 = (甲?: 选择装备数据类型, 乙?: 选择装备数据类型) =>
  !!甲?.id &&
  !!乙?.id &&
  (获取装备(甲)?.重复装备id || 甲.id) === (获取装备(乙)?.重复装备id || 乙.id)

/** 只保留用户选择的大附魔；套装、特效和五彩石郭氏增益必须由装备重新派生。 */
export const 重建登阶装备 = (装备: 装备信息数据类型): 装备信息数据类型 => {
  const 拷贝 = 克隆(装备)
  const 装备增益: 装备增益类型 = {}
  大附魔键.forEach((键) => {
    装备增益[键] = 拷贝.装备增益?.[键] || 0
  })
  return 根据装备信息获取基础属性({ ...拷贝, 装备增益 })
}

/** 两个戒指不因左右互换产生虚假的换装任务，优先对齐同一件装备。 */
export const 配对装备 = (当前: 装备信息数据类型, 目标: 装备信息数据类型) => {
  const 已用 = new Set<number>()
  const 分配 = new Map<number, number>()
  const 目标列表 = 目标.装备列表 || []
  目标列表.forEach((目标装备, 索引) => {
    if (!目标装备?.id) return
    const 可匹配 = (装备: 选择装备数据类型, 位置: number) =>
      !已用.has(位置) && 装备?.装备部位 === 目标装备.装备部位 && 装备相同(装备, 目标装备)
    // 同 id 双戒指优先匹配养成也一致的那件，避免左右交换产生虚假缺口。
    const 养成签名 = (装备: 选择装备数据类型) =>
      JSON.stringify([
        装备.当前精炼等级 || 0,
        装备.附魔 || '',
        (装备.镶嵌孔数组 || []).map((孔) => [孔.镶嵌类型, 孔.镶嵌宝石等级 || 0]),
      ])
    const 精确索引 = 当前.装备列表.findIndex(
      (装备, 位置) => 可匹配(装备, 位置) && 养成签名(装备) === 养成签名(目标装备),
    )
    const 当前索引 = 精确索引 >= 0 ? 精确索引 : 当前.装备列表.findIndex(可匹配)
    if (当前索引 >= 0) {
      已用.add(当前索引)
      分配.set(索引, 当前索引)
    }
  })
  return 目标列表.flatMap((目标装备, 索引) => {
    if (!目标装备?.id) return []
    let 当前索引 = 分配.get(索引)
    if (当前索引 === undefined) {
      当前索引 = 当前.装备列表.findIndex(
        (装备, 位置) => !已用.has(位置) && 装备?.装备部位 === 目标装备.装备部位,
      )
      if (当前索引 >= 0) 已用.add(当前索引)
    }
    const 同部位序号 = 目标列表
      .slice(0, 索引 + 1)
      .filter((装备) => 装备.装备部位 === 目标装备.装备部位).length
    return [
      {
        当前索引,
        当前装备: 当前.装备列表[当前索引],
        目标装备,
        部位: 目标装备.装备部位 + (目标装备.装备部位 === '戒指' ? ' ' + 同部位序号 : ''),
      },
    ]
  })
}

/** 用当前身装的配对部位整体替换目标对应槽位；装备、精炼、镶嵌、附魔原样保留。 */
export const 替换目标部位 = (
  目标: 装备信息数据类型,
  当前: 装备信息数据类型,
  部位: string,
  文案: 登阶文案,
): 装备信息数据类型 => {
  const 配对 = 配对装备(当前, 目标).find((项) => 项.部位 === 部位)
  if (!配对?.当前装备?.id) throw new Error(文案['计算.错误.身装无部位'])
  const 目标索引 = 目标.装备列表.indexOf(配对.目标装备)
  if (目标索引 < 0) throw new Error(文案['计算.错误.目标已变化'])
  const 新目标 = 克隆(目标)
  新目标.装备列表[目标索引] = 克隆(配对.当前装备)
  return 新目标
}

/** 按差异项用当前身装替换目标：部位整体替换，大附魔与五彩石只替换对应事项。 */
export const 替换目标项 = (
  目标: 装备信息数据类型,
  当前: 装备信息数据类型,
  项: Pick<登阶差异, '类别' | '部位'>,
  文案: 登阶文案,
): 装备信息数据类型 => {
  if (项.类别 === '大附魔') {
    const i = 大附魔部位.indexOf(项.部位)
    if (i < 0) throw new Error(文案['计算.错误.大附魔已变化'])
    const 新目标 = 克隆(目标)
    新目标.装备增益 = { ...新目标.装备增益, [大附魔键[i]]: 当前.装备增益?.[大附魔键[i]] || 0 }
    return 新目标
  }
  if (项.类别 === '五彩石') return { ...克隆(目标), 五彩石: 当前.五彩石 || '' }
  return 替换目标部位(目标, 当前, 项.部位, 文案)
}

export const 安全计算登阶秒伤 = (
  装备: 装备信息数据类型,
  计算: (装备: 装备信息数据类型) => number | undefined,
): number | undefined => {
  try {
    // 引擎会忽略已下架/不属于当前心法的 id；不能把缺失装备的结果当成真实差距。
    if (!装备.装备列表?.some((项) => 项?.id) || 装备.装备列表.some((项) => 项?.id && !获取装备(项)))
      return undefined
    const 秒伤 = 计算(重建登阶装备(装备))
    return typeof 秒伤 === 'number' && Number.isFinite(秒伤) && 秒伤 > 0 ? 秒伤 : undefined
  } catch {
    return undefined
  }
}

export const 生成登阶分析 = (
  当前: 装备信息数据类型,
  目标: 装备信息数据类型,
  计算: (装备: 装备信息数据类型) => number | undefined,
  文案: 登阶文案,
): 登阶分析 => {
  const 分类进度: 登阶分析['分类进度'] = (
    ['装备', '精炼', '镶嵌', '附魔', '大附魔', '五彩石'] as 登阶类别[]
  ).map((名称) => ({ 名称, 完成数: 0, 总数: 0 }))
  const 差异: 登阶分析['差异'] = []
  const 建议: 登阶建议[] = []
  const 部位进度: 登阶部位进度[] = []
  const 配对列表 = 配对装备(当前, 目标)
  const 记进度 = (
    类别: 登阶类别,
    已完成: boolean,
    部位: string,
    现状: string,
    期望: string,
    展示: Partial<
      Pick<登阶差异, '当前装备' | '目标装备' | '当前等级' | '目标等级' | '目标孔索引'>
    > = {},
  ) => {
    const 分类 = 分类进度.find((项) => 项.名称 === 类别)!
    分类.总数++
    if (已完成) 分类.完成数++
    else 差异.push({ 类别, 部位, 当前: 现状, 目标: 期望, ...展示 })
  }
  const 安全计算 = (装备: 装备信息数据类型) => 安全计算登阶秒伤(装备, 计算)
  const 当前秒伤 = 安全计算(当前)
  const 目标秒伤 = 安全计算(目标)
  const 添加建议 = (
    id: string,
    标题: string,
    说明: string,
    类别: 登阶类别,
    装备: 装备信息数据类型,
  ) => {
    let 装备信息 = 装备
    try {
      装备信息 = 重建登阶装备(装备)
    } catch {
      /* 过期数据仍可展示任务，但不编造收益。 */
    }
    const 秒伤 = 安全计算(装备信息)
    const 条目: 登阶建议 = {
      id,
      标题,
      说明,
      类别,
      装备信息,
      秒伤,
      提升: 秒伤 !== undefined && 当前秒伤 !== undefined ? 秒伤 - 当前秒伤 : undefined,
    }
    建议.push(条目)
    return 条目
  }
  const 精炼方案 = 克隆(当前)
  const 镶嵌方案 = 克隆(当前)
  const 附魔方案 = 克隆(当前)
  let 精炼件数 = 0
  let 镶嵌孔数 = 0
  let 附魔件数 = 0

  配对列表.forEach(({ 当前索引, 当前装备, 目标装备, 部位 }) => {
    const 相同 = 装备相同(当前装备, 目标装备)
    // 部位达成按「装备 + 精炼 + 镶嵌 + 附魔」四合一；目标没有的养成项视为满足。
    let 槽位达成 = 相同
    记进度('装备', 相同, 部位, 装备名称(当前装备, 文案), 装备名称(目标装备, 文案), {
      当前装备,
      目标装备,
    })
    if (!相同) {
      const 替换方案 = 克隆(当前)
      if (当前索引 >= 0) 替换方案.装备列表[当前索引] = 克隆(目标装备)
      else 替换方案.装备列表.push(克隆(目标装备))
      添加建议(
        'equip-' + 部位,
        填充文案(文案['计算.建议.换装.标题'], {
          部位,
          装备: 装备名称(目标装备, 文案),
        }),
        填充文案(文案['计算.建议.换装.说明'], {
          当前: 装备名称(当前装备, 文案),
          目标: 装备名称(目标装备, 文案),
        }),
        目标装备.装备部位 === '武器' ? '武器' : '装备',
        替换方案,
      )
    }
    const 当前精炼 = 当前装备?.当前精炼等级 || 0
    const 目标精炼 = 目标装备.当前精炼等级 || 0
    if (目标精炼 > 0) {
      const 精炼达标 = !!当前装备?.id && 当前精炼 >= 目标精炼
      if (!精炼达标) 槽位达成 = false
      记进度(
        '精炼',
        精炼达标,
        部位,
        填充文案(文案['计算.精炼.值'], { 等级: 当前精炼 }),
        填充文案(文案['计算.精炼.值'], { 等级: 目标精炼 }),
        {
          当前装备,
          目标装备,
          当前等级: Number(当前精炼),
          目标等级: Number(目标精炼),
        },
      )
      const 当前数据 = 获取装备(当前装备)
      // 与配装器保持一致：橙武 8 级，其余装备 6 级；不把目标橙武的 8 精炼套到普通武器。
      const 上限 = 当前数据?.装备类型 === 装备类型枚举.橙武 ? 8 : 6
      const 可提升至 = Math.min(目标精炼, 上限)
      if (当前数据 && 当前精炼 < 可提升至) {
        精炼方案.装备列表[当前索引].当前精炼等级 = 可提升至
        精炼件数++
      }
    }
    // 镶嵌孔按第 1/2/3 孔顺序对齐，属性类型不参与匹配；换同部位装备后原等级按顺序保留。
    const 当前装备数据 = 获取装备(当前装备)
    const 当前孔位 = (索引: number) => {
      const 已存 = 当前装备?.镶嵌孔数组?.[索引]
      if (已存) return 已存
      const 数据孔 = 当前装备数据?.镶嵌孔数组?.[索引]
      return 数据孔 ? { ...数据孔, 镶嵌宝石等级: 0 } : undefined
    }
    ;(目标装备.镶嵌孔数组 || []).forEach((目标孔, 目标孔索引) => {
      const 等级 = 目标孔.镶嵌宝石等级 || 0
      if (!等级) return
      const 当前孔 = 当前孔位(目标孔索引)
      // 当前孔数少于目标孔数：多出的目标孔不影响对比与达成，也不生成阻止性提示。
      if (!当前孔) return
      const 当前等级 = 当前孔.镶嵌宝石等级 || 0
      const 镶嵌达标 = 当前等级 >= 等级
      if (!镶嵌达标) 槽位达成 = false
      记进度(
        '镶嵌',
        镶嵌达标,
        部位,
        填充文案(文案['计算.镶嵌.值'], {
          属性: 属性简写枚举[当前孔.镶嵌类型 || ''] || 文案['计算.镶嵌.属性兜底'],
          等级: 当前等级,
        }),
        填充文案(文案['计算.镶嵌.值'], {
          属性: 属性简写枚举[目标孔.镶嵌类型 || ''] || 文案['计算.镶嵌.属性兜底'],
          等级,
        }),
        { 当前装备, 目标装备, 当前等级, 目标等级: 等级, 目标孔索引 },
      )
      if (当前装备数据 && 当前等级 < 等级 && 等级 <= 8) {
        const 方案装备 = 镶嵌方案.装备列表[当前索引]
        const 方案孔列表 = 方案装备.镶嵌孔数组 || []
        if (方案孔列表[目标孔索引]) 方案孔列表[目标孔索引].镶嵌宝石等级 = 等级
        else 方案孔列表[目标孔索引] = { ...当前孔, 镶嵌宝石等级: 等级 }
        方案装备.镶嵌孔数组 = 方案孔列表
        镶嵌孔数++
      }
    })
    if (目标装备.附魔) {
      const 附魔达标 = !!当前装备?.附魔 && 当前装备.附魔 === 目标装备.附魔
      if (!附魔达标) 槽位达成 = false
      记进度(
        '附魔',
        附魔达标,
        部位,
        获取附魔显示名称(当前装备?.附魔) || 文案['通用.未附魔'],
        获取附魔显示名称(目标装备.附魔),
      )
      if (
        当前装备数据 &&
        当前装备.附魔 !== 目标装备.附魔 &&
        附魔可用于部位(目标装备.附魔, 当前装备.装备部位)
      ) {
        附魔方案.装备列表[当前索引].附魔 = 目标装备.附魔
        附魔件数++
      }
    }
    部位进度.push({ 部位, 已达成: 槽位达成 })
  })
  if (精炼件数)
    添加建议(
      'refine',
      文案['计算.建议.精炼.标题'],
      填充文案(文案['计算.建议.精炼.说明'], { 件数: 精炼件数 }),
      '精炼',
      精炼方案,
    )
  if (镶嵌孔数)
    添加建议(
      'gems',
      文案['计算.建议.镶嵌.标题'],
      填充文案(文案['计算.建议.镶嵌.说明'], { 孔数: 镶嵌孔数 }),
      '镶嵌',
      镶嵌方案,
    )
  if (附魔件数)
    添加建议(
      'enchants',
      文案['计算.建议.附魔.标题'],
      填充文案(文案['计算.建议.附魔.说明'], { 件数: 附魔件数 }),
      '附魔',
      附魔方案,
    )

  const 大附魔方案 = 克隆(当前)
  let 大附魔数 = 0
  大附魔键.forEach((键, 索引) => {
    const 目标值 = 目标.装备增益?.[键] || 0
    if (!目标值) return
    const 当前值 = 当前.装备增益?.[键] || 0
    const 部位已装备 = 当前.装备列表.some((项) => 项?.id && 项.装备部位 === 大附魔部位[索引])
    记进度(
      '大附魔',
      部位已装备 && 当前值 >= 目标值,
      大附魔部位[索引],
      大附魔档位名称(文案, 当前值),
      大附魔档位名称(文案, 目标值),
    )
    if (部位已装备 && 当前值 < 目标值) {
      大附魔方案.装备增益 = { ...大附魔方案.装备增益, [键]: 目标值 }
      大附魔数++
    }
  })
  if (大附魔数)
    添加建议(
      'major-enchants',
      文案['计算.建议.大附魔.标题'],
      填充文案(文案['计算.建议.大附魔.说明'], { 数量: 大附魔数 }),
      '大附魔',
      大附魔方案,
    )
  if (目标.五彩石) {
    记进度(
      '五彩石',
      当前.五彩石 === 目标.五彩石,
      '五彩石',
      当前.五彩石 || 文案['通用.未设置'],
      目标.五彩石,
    )
    if (当前.五彩石 !== 目标.五彩石)
      添加建议(
        'stone',
        文案['计算.建议.五彩石.标题'],
        填充文案(文案['计算.建议.五彩石.说明'], { 五彩石: 目标.五彩石 }),
        '五彩石',
        { ...克隆(当前), 五彩石: 目标.五彩石 },
      )
  }

  // 组合只围绕目标套装枚举，不再按单件 DPS 前几名凑组合。
  // 普通/英雄切糕分别计数，不能混成一套；武器始终独立。
  const 已生成组合 = new Set<string>()
  ;[
    { 特效: 装备特效枚举.门派套装, 名称: 文案['计算.组合.门派'], 件数: [2, 4] },
    { 特效: 装备特效枚举.切糕_普通, 名称: 文案['计算.组合.普通切糕'], 件数: [2] },
    { 特效: 装备特效枚举.切糕_英雄, 名称: 文案['计算.组合.英雄切糕'], 件数: [2] },
  ].forEach(({ 特效, 名称, 件数 }) => {
    const 套装 = 配对列表.filter(
      (项) => 项.目标装备.装备部位 !== '武器' && 获取装备(项.目标装备)?.装备特效 === 特效,
    )
    件数.forEach((数量) => {
      if (套装.length < 数量) return
      const 枚举 = (起始: number, 已选: typeof 套装) => {
        if (已选.length < 数量) {
          for (let i = 起始; i <= 套装.length - (数量 - 已选.length); i++) {
            枚举(i + 1, [...已选, 套装[i]])
          }
          return
        }
        const 待换 = 已选.filter((项) => !装备相同(项.当前装备, 项.目标装备))
        // 只缺一件时，已有单件换装建议会计入套装触发；不重复占据建议列表。
        if (待换.length < 2) return
        const 标识 = 待换
          .map((项) => 项.部位 + ':' + 项.目标装备.id)
          .sort()
          .join('|')
        if (已生成组合.has(标识)) return
        已生成组合.add(标识)
        const 组合方案 = 克隆(当前)
        待换.forEach((项) => {
          if (项.当前索引 >= 0) 组合方案.装备列表[项.当前索引] = 克隆(项.目标装备)
          else 组合方案.装备列表.push(克隆(项.目标装备))
        })
        添加建议(
          'set-' + 特效 + '-' + 数量 + '-' + 标识,
          填充文案(文案['计算.建议.组合.标题'], {
            名称,
            数量,
            部位: 待换.map((项) => 项.部位).join('＋'),
          }),
          填充文案(文案['计算.建议.组合.说明'], {
            装备: 待换.map((项) => 装备名称(项.目标装备, 文案)).join('、'),
          }),
          '组合',
          组合方案,
        )
      }
      枚举(0, [])
    })
  })
  建议.sort((甲, 乙) => (乙.提升 ?? -Infinity) - (甲.提升 ?? -Infinity))
  return {
    当前秒伤,
    目标秒伤,
    分类进度,
    部位进度,
    差异,
    建议,
    完成数: 分类进度.reduce((和, 项) => 和 + 项.完成数, 0),
    总数: 分类进度.reduce((和, 项) => 和 + 项.总数, 0),
  }
}

/** 快速记下一项实际取得的结果，不能把其他部位或其他养成一并覆盖。 */
export const 拿下登阶差异 = (
  当前: 装备信息数据类型,
  目标: 装备信息数据类型,
  项: 登阶差异,
  文案: 登阶文案,
) => {
  const 新装备 = 克隆(当前)
  if (项.类别 === '五彩石') {
    新装备.五彩石 = 目标.五彩石
    return 重建登阶装备(新装备)
  }
  if (项.类别 === '大附魔') {
    const i = 大附魔部位.indexOf(项.部位)
    if (i < 0 || !当前.装备列表.some((x) => x.id && x.装备部位 === 项.部位))
      throw new Error(文案['计算.错误.先取得大附魔部位'])
    const 键 = 大附魔键[i]
    新装备.装备增益 = { ...新装备.装备增益, [键]: 目标.装备增益?.[键] || 0 }
    return 重建登阶装备(新装备)
  }
  const 配对 = 配对装备(当前, 目标).find((x) => x.部位 === 项.部位)
  if (!配对) throw new Error(文案['计算.错误.目标装备已变化'])
  const { 当前索引, 当前装备, 目标装备 } = 配对
  if (项.类别 === '装备') {
    if (当前索引 >= 0) 新装备.装备列表[当前索引] = 克隆(目标装备)
    else 新装备.装备列表.push(克隆(目标装备))
  } else {
    const 数据 = 获取装备(当前装备)
    if (!数据) throw new Error(文案['计算.错误.先取得养成部位'])
    const 装备 = 新装备.装备列表[当前索引]
    if (项.类别 === '精炼') {
      const 等级 = Number(目标装备.当前精炼等级) || 0
      const 上限 = 数据.装备类型 === 装备类型枚举.橙武 ? 8 : 6
      if (等级 > 上限) throw new Error(文案['计算.错误.精炼上限'])
      装备.当前精炼等级 = Math.max(Number(装备.当前精炼等级) || 0, 等级)
    } else if (项.类别 === '附魔') {
      if (!附魔可用于部位(目标装备.附魔, 装备.装备部位))
        throw new Error(文案['计算.错误.附魔不适用'])
      装备.附魔 = 目标装备.附魔
    } else if (项.类别 === '镶嵌') {
      // 与分析阶段相同：按第 1/2/3 孔顺序对齐，不按属性类型匹配。
      const 目标孔索引 = 项.目标孔索引 ?? -1
      const 目标孔 = 目标孔索引 >= 0 ? 目标装备.镶嵌孔数组?.[目标孔索引] : undefined
      const 当前孔列表 = 装备.镶嵌孔数组 || []
      const 当前孔 =
        当前孔列表[目标孔索引] ||
        (数据.镶嵌孔数组?.[目标孔索引]
          ? { ...数据.镶嵌孔数组[目标孔索引], 镶嵌宝石等级: 0 }
          : undefined)
      if (!目标孔 || !当前孔) throw new Error(文案['计算.错误.孔位已变化'])
      const 等级 = Math.max(当前孔.镶嵌宝石等级 || 0, 目标孔.镶嵌宝石等级 || 0)
      if (当前孔列表[目标孔索引]) 当前孔列表[目标孔索引].镶嵌宝石等级 = 等级
      else {
        当前孔列表[目标孔索引] = { ...当前孔, 镶嵌宝石等级: 等级 }
        装备.镶嵌孔数组 = 当前孔列表
      }
    } else throw new Error(文案['计算.错误.不支持更新'])
  }
  return 重建登阶装备(新装备)
}
