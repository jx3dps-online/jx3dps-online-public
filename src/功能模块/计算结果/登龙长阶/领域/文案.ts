import type { 登阶文案, 文案键 } from '../文案'

/** 大附魔只有普通（1）与英雄（2）两档，界面统一展示档位名称。 */
export const 大附魔档位名称 = (文案: 登阶文案, 值?: number) =>
  值
    ? 值 >= 2
      ? 文案['登阶.大附魔档位.英雄']
      : 文案['登阶.大附魔档位.普通']
    : 文案['登阶.大附魔档位.未启用']

/** 踏天进度不可用/已到终点时的状态，文案在默认字典中按心法覆盖。 */
export type 踏天进度状态 =
  | '参考配置无效'
  | '已达参考终点'
  | '门槛不可算'
  | '终点不可算'
  | '目标不可算'

const 踏天进度状态键: Record<踏天进度状态, 文案键> = {
  参考配置无效: '踏天.进度状态.参考配置无效',
  已达参考终点: '踏天.进度状态.已达参考终点',
  门槛不可算: '踏天.进度状态.门槛不可算',
  终点不可算: '踏天.进度状态.终点不可算',
  目标不可算: '踏天.进度状态.目标不可算',
}

export const 获取踏天进度状态文案 = (文案: 登阶文案, 状态: 踏天进度状态) =>
  文案[踏天进度状态键[状态]]

/** 达成区单行文案：以页面现有文案为基准，按踏天状态取词。 */
export const 获取达成文案 = (
  文案: 登阶文案,
  输入: {
    踏天中: boolean
    踏天达标: boolean
    踏天未满: boolean
    踏天原因?: string
  },
) => {
  if (输入.踏天中) return 文案['登阶.达成文案.踏天中']
  if (输入.踏天达标) return 文案['登阶.达成文案.踏天达标']
  if (输入.踏天未满) return 文案['登阶.达成文案.踏天未满']
  return 输入.踏天原因 || 文案['登阶.达成文案.达成']
}
