export interface 足迹摘要 {
  标题: string
  摘要: string[]
  变更数: number
}

export interface 足迹收益 {
  /** 对应传入历史数组的位置，避免同一毫秒记录发生键冲突。 */
  索引: number
  快照: 配装快照
  秒伤?: number
  提升?: number
}

const 装备数据 = (装备?: 选择装备数据类型) =>
  装备?.id ? 获取当前数据().装备数据?.[装备.装备部位]?.find((项) => 项.id === 装备.id) : undefined
const 装备标识 = (装备?: 选择装备数据类型) => 装备数据(装备)?.重复装备id || 装备?.id || 0
const 装备名 = (装备: 选择装备数据类型 | undefined, 文案: 登阶文案) =>
  装备?.id
    ? 装备数据(装备)?.装备名称 || 填充文案(文案['计算.装备名称.兜底'], { ID: 装备.id })
    : 文案['通用.未装备']
const 镶嵌签名 = (装备?: 选择装备数据类型) =>
  (装备?.镶嵌孔数组 || [])
    .map((孔) => [孔.镶嵌类型 || '', 孔.镶嵌宝石等级 || 0])
    .sort((甲, 乙) => String(甲[0]).localeCompare(String(乙[0])) || Number(甲[1]) - Number(乙[1]))
const 养成签名 = (装备?: 选择装备数据类型) =>
  JSON.stringify([装备?.当前精炼等级 || 0, 装备?.附魔 || '', 镶嵌签名(装备)])

/** 同部位先匹配完全一致的装备，再匹配同 id；双戒交换不构成成长变更。 */
const 对齐装备 = (旧装备: 选择装备数据类型[], 新装备: 选择装备数据类型[]) => {
  const 旧列表 = 旧装备.filter((项) => 项?.id)
  const 新列表 = 新装备.filter((项) => 项?.id)
  const 已用 = new Set<number>()
  const 配对 = new Map<number, number>()
  for (const 精确 of [true, false]) {
    新列表.forEach((新, 索引) => {
      if (配对.has(索引)) return
      const 旧索引 = 旧列表.findIndex(
        (旧, 位置) =>
          !已用.has(位置) &&
          旧.装备部位 === 新.装备部位 &&
          装备标识(旧) === 装备标识(新) &&
          (!精确 || 养成签名(旧) === 养成签名(新)),
      )
      if (旧索引 >= 0) {
        已用.add(旧索引)
        配对.set(索引, 旧索引)
      }
    })
  }
  const 结果: { 旧?: 选择装备数据类型; 新?: 选择装备数据类型; 部位: string }[] = []
  新列表.forEach((新, 索引) => {
    let 旧索引 = 配对.get(索引)
    if (旧索引 === undefined) {
      旧索引 = 旧列表.findIndex((旧, 位置) => !已用.has(位置) && 旧.装备部位 === 新.装备部位)
      if (旧索引 >= 0) 已用.add(旧索引)
    }
    const 同部位序号 = 新列表.slice(0, 索引 + 1).filter((项) => 项.装备部位 === 新.装备部位).length
    结果.push({
      旧: 旧列表[旧索引],
      新,
      部位: 新.装备部位 + (新.装备部位 === '戒指' ? ' ' + 同部位序号 : ''),
    })
  })
  旧列表.forEach((旧, 索引) => {
    if (!已用.has(索引)) 结果.push({ 旧, 部位: 旧.装备部位 })
  })
  return 结果
}

export const 生成足迹摘要 = (
  上一份: 装备信息数据类型 | undefined,
  本次: 装备信息数据类型,
  文案: 登阶文案,
): 足迹摘要 => {
  if (!上一份)
    return {
      标题: 文案['足迹.启程.标题'],
      摘要: [
        填充文案(文案['足迹.启程.说明'], {
          数量: 本次.装备列表.filter((项) => 项?.id).length,
        }),
      ],
      变更数: 0,
    }
  const 分类: { 名称: string; 变更: string[] }[] = [
    文案['足迹.分类.换装'],
    文案['足迹.分类.精炼'],
    文案['足迹.分类.镶嵌'],
    文案['足迹.分类.小附魔'],
    文案['足迹.分类.大附魔'],
    文案['足迹.分类.五彩石'],
  ].map((名称) => ({ 名称, 变更: [] }))
  const 记录 = (索引: number, 内容: string) => 分类[索引].变更.push(内容)
  对齐装备(上一份.装备列表, 本次.装备列表).forEach(({ 旧, 新, 部位 }) => {
    if (装备标识(旧) !== 装备标识(新))
      记录(
        0,
        填充文案(文案['足迹.记录.换装'], { 部位, 旧: 装备名(旧, 文案), 新: 装备名(新, 文案) }),
      )
    // 装备取得或卸下归入换装；不把空槽自动展开为多条养成操作。
    if (!旧 || !新) return
    const 旧精炼 = 旧.当前精炼等级 || 0
    const 新精炼 = 新.当前精炼等级 || 0
    if (旧精炼 !== 新精炼)
      记录(1, 填充文案(文案['足迹.记录.精炼'], { 部位, 旧: 旧精炼, 新: 新精炼 }))
    const 旧孔 = 镶嵌签名(旧)
    const 新孔 = 镶嵌签名(新)
    const 已用孔 = new Set<number>()
    const 孔配对 = new Map<number, number>()
    // 同属性、同等级优先，孔位顺序变化不会误报升级。
    for (const 精确 of [true, false]) {
      新孔.forEach((孔, 索引) => {
        if (孔配对.has(索引)) return
        const 旧索引 = 旧孔.findIndex(
          (项, 位置) => !已用孔.has(位置) && 项[0] === 孔[0] && (!精确 || 项[1] === 孔[1]),
        )
        if (旧索引 >= 0) {
          已用孔.add(旧索引)
          孔配对.set(索引, 旧索引)
        }
      })
    }
    新孔.forEach((孔, 索引) => {
      const 旧索引 = 孔配对.get(索引)
      const 旧等级 = 旧索引 === undefined ? undefined : Number(旧孔[旧索引][1])
      if (旧等级 !== Number(孔[1]))
        记录(
          2,
          填充文案(文案['足迹.记录.镶嵌'], {
            部位,
            属性: 属性简写枚举[String(孔[0])] || 文案['足迹.镶嵌.属性兜底'],
            旧: 旧等级 === undefined ? 文案['通用.无'] : 旧等级,
            新: 孔[1],
          }),
        )
    })
    旧孔.forEach((孔, 索引) => {
      if (!已用孔.has(索引))
        记录(
          2,
          填充文案(文案['足迹.记录.镶嵌卸下'], {
            部位,
            属性: 属性简写枚举[String(孔[0])] || 文案['足迹.镶嵌.属性兜底'],
            旧: 孔[1],
          }),
        )
    })
    if (旧.附魔 !== 新.附魔)
      记录(
        3,
        填充文案(文案['足迹.记录.附魔'], {
          部位,
          旧: 获取附魔显示名称(旧.附魔) || 文案['通用.未附魔'],
          新: 获取附魔显示名称(新.附魔) || 文案['通用.未附魔'],
        }),
      )
  })
  const 大附魔 = [
    ['大附魔_伤帽', '帽子'],
    ['大附魔_伤衣', '衣服'],
    ['大附魔_伤腰', '腰带'],
    ['大附魔_伤腕', '护腕'],
    ['大附魔_伤鞋', '鞋子'],
  ] as const
  大附魔.forEach(([键, 部位]) => {
    const 旧值 = 上一份.装备增益?.[键] || 0
    const 新值 = 本次.装备增益?.[键] || 0
    if (旧值 !== 新值)
      记录(
        4,
        填充文案(文案['足迹.记录.大附魔'], {
          部位,
          旧: 大附魔档位名称(文案, 旧值),
          新: 大附魔档位名称(文案, 新值),
        }),
      )
  })
  if ((上一份.五彩石 || '') !== (本次.五彩石 || ''))
    记录(
      5,
      填充文案(文案['足迹.记录.五彩石'], {
        旧: 上一份.五彩石 || 文案['通用.未设置'],
        新: 本次.五彩石 || 文案['通用.未设置'],
      }),
    )
  const 有变更 = 分类.filter((项) => 项.变更.length)
  const 变更数 = 有变更.reduce((和, 项) => 和 + 项.变更.length, 0)
  if (!变更数)
    return { 标题: 文案['足迹.配装未变.标题'], 摘要: [文案['足迹.配装未变.说明']], 变更数: 0 }
  const 展示分类 = 有变更.slice(0, 有变更.length > 3 ? 2 : 3)
  const 摘要 = 展示分类.map(
    (项) =>
      填充文案(文案['足迹.摘要.分类'], {
        名称: 项.名称,
        变更: 项.变更.slice(0, 2).join('；'),
      }) + (项.变更.length > 2 ? 填充文案(文案['足迹.摘要.更多'], { 数量: 项.变更.length }) : ''),
  )
  if (有变更.length > 3) {
    const 隐藏 = 有变更.slice(2)
    摘要.push(
      填充文案(文案['足迹.摘要.另有'], {
        数量: 隐藏.reduce((和, 项) => 和 + 项.变更.length, 0),
        分类: 隐藏.map((项) => 项.名称).join('、'),
      }),
    )
  }
  return { 标题: 填充文案(文案['足迹.标题.更新'], { 次数: 变更数 }), 摘要, 变更数 }
}

/** 每份快照都在调用方提供的同一当前环境下重算，不使用过去存储的 DPS。 */
export const 计算足迹收益 = (
  历史: 配装快照[],
  计算: (装备: 装备信息数据类型, 快照: 配装快照) => number | undefined,
): 足迹收益[] => {
  const 起始索引 = Math.max(0, 历史.length - 30)
  let 上次秒伤: number | undefined
  return 历史.slice(起始索引).map((快照, 位置) => {
    const 秒伤 = 安全计算登阶秒伤(快照.装备, (装备) => 计算(装备, 快照))
    const 提升 = 秒伤 !== undefined && 上次秒伤 !== undefined ? 秒伤 - 上次秒伤 : undefined
    上次秒伤 = 秒伤
    return { 索引: 起始索引 + 位置, 快照, 秒伤, 提升 }
  })
}
