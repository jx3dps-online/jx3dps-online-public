/**
 * 完成度权重数组：[部位达成, 容量, 秒伤]。
 * 权重之和作为分母，方便后续直接调整比例而不用改公式结构。
 */
export const 完成度权重 = [0, 40, 60]

export interface 完成度环境 {
  /** 附魔基准系数表；不传则按当前心法数据计算 */
  系数表?: Record<string, number>
  /** 装备增益数据（含功法特殊增益）；不传则按当前心法数据取 */
  装备增益数据?: 装备增益数据类型
  /** 角色默认基础属性；不传则按当前心法取 */
  默认属性?: Partial<角色基础属性类型>
}

const clamp100 = (值: number) => Math.max(0, Math.min(100, 值))

/** 容量统计的属性字段 -> 属性类型（用于查附魔基准） */
const 容量字段映射: [keyof 角色基础属性类型, 属性类型][] = [
  ['基础攻击', 属性类型.全基础攻击],
  ['会心等级', 属性类型.全会心等级],
  ['会心效果等级', 属性类型.全会心效果等级],
  ['破防等级', 属性类型.全破防等级],
  ['无双等级', 属性类型.无双等级],
  ['全能等级', 属性类型.全能等级],
  ['加速等级', 属性类型.加速等级],
  ['力道', 属性类型.力道],
  ['身法', 属性类型.身法],
  ['元气', 属性类型.元气],
  ['根骨', 属性类型.根骨],
]

/** 有属性、参与容量的大附魔；伤腰/腕/鞋只有技能效果，不参与容量 */
const 大附魔容量键 = ['大附魔_伤帽', '大附魔_伤衣'] as const

/**
 * 整套配装的「附魔基准容量」分数：
 * 装备基础属性（含精炼、镶嵌、附魔、五彩石，扣除心法默认基础属性）
 * + 大附魔_伤帽/伤衣属性。
 * 不含套装/切糕/冬至与装备特效，这部分由秒伤比例体现。
 */
export const 计算容量分数 = (
  装备信息?: 装备信息数据类型,
  环境?: 完成度环境,
): number | undefined => {
  if (!装备信息?.装备基础属性) return undefined
  const 系数表 = 环境?.系数表 || 获取容量系数表()
  const 装备增益数据 = 环境?.装备增益数据 || 获取当前数据().装备增益数据
  const 默认属性 = 环境?.默认属性 || 获取角色默认基础属性()
  const 基础 = 装备信息.装备基础属性
  let 分数 = 0

  容量字段映射.forEach(([字段, 属性键]) => {
    const 基准 = 系数表[属性键] || 0
    if (!基准) return
    const 差值 = (基础[字段] || 0) - (默认属性[字段] || 0)
    if (差值 > 0) 分数 += (差值 / 基准) * 分数放大系数
  })

  // 武器伤害按平均武伤与武伤附魔基准折算；内功心法没有武伤附魔时不参与
  const 武伤基准 = 系数表[属性类型.武器伤害] || 0
  if (武伤基准) {
    const 平均武伤 = ((基础.武器伤害_最小值 || 0) + (基础.武器伤害_最大值 || 0)) / 2
    if (平均武伤 > 0) 分数 += (平均武伤 / 武伤基准) * 分数放大系数
  }

  大附魔容量键.forEach((键) => {
    const 档位 = 装备信息.装备增益?.[键] || 0
    if (!档位) return
    const 增益列表 = 获取装备特效增益数据(键, 档位, 装备增益数据) || []
    增益列表.forEach((项) => {
      const 属性 = 装备和附魔属性转换(项.属性)
      const 基准 = 系数表[属性] || 0
      if (基准) 分数 += ((项.值 || 0) / 基准) * 分数放大系数
    })
  })

  return 分数
}

/** 部位达成比例：目标已配置槽位中，装备/精炼/镶嵌/附魔全部达成的槽位占比 */
export const 计算部位达成比例 = (部位进度: 登阶部位进度[] = []) => {
  if (!部位进度.length) return 0
  const 达成数 = 部位进度.filter((项) => 项.已达成).length
  return clamp100((达成数 / 部位进度.length) * 100)
}

export interface 比例结果 {
  比例?: number
  估算: boolean
}

/**
 * 进度比例：有起点且目标高于起点时，按「起点区间」计算；
 * 起点缺失或分母 <= 0 时退化为「当前 / 目标」，并用 估算 标记。
 */
export const 计算比例 = (当前?: number, 目标?: number, 起点?: number): 比例结果 => {
  if (当前 === undefined || 目标 === undefined || 目标 <= 0) return { 估算: false }
  if (起点 !== undefined && 目标 - 起点 > 0) {
    return { 比例: clamp100(((当前 - 起点) / (目标 - 起点)) * 100), 估算: false }
  }
  return { 比例: clamp100((当前 / 目标) * 100), 估算: true }
}

export const 计算容量比例 = 计算比例
export const 计算秒伤比例 = 计算比例

export interface 完成度输入 {
  部位进度?: 登阶部位进度[]
  当前容量?: number
  目标容量?: number
  起点容量?: number
  当前DPS?: number
  目标DPS?: number
  起点DPS?: number
}

export interface 完成度结果 {
  完成度?: number
  待评估原因?: string
  部位比例: number
  容量比例?: number
  容量估算?: boolean
  秒伤比例?: number
  秒伤估算?: boolean
}

/** 加权完成度：三项比例各自的缺失都会让整体待评估，不按剩余项归一 */
export const 计算完成度 = (输入: 完成度输入, 文案: 登阶文案): 完成度结果 => {
  const 部位比例 = 计算部位达成比例(输入.部位进度 || [])
  const 容量 = 计算比例(输入.当前容量, 输入.目标容量, 输入.起点容量)
  const 秒伤 = 计算比例(输入.当前DPS, 输入.目标DPS, 输入.起点DPS)

  if (容量.比例 === undefined) {
    const 待评估原因 =
      输入.目标容量 === undefined
        ? 文案['完成度.目标容量不可用']
        : 输入.目标容量 <= 0
          ? 文案['完成度.目标容量为零']
          : 文案['完成度.当前容量不可用']
    return { 部位比例, 待评估原因 }
  }

  if (秒伤.比例 === undefined) {
    return {
      部位比例,
      容量比例: 容量.比例,
      容量估算: 容量.估算,
      待评估原因: 文案['完成度.DPS不可比'],
    }
  }

  const 权重和 = 完成度权重.reduce((和, 项) => 和 + 项, 0) || 1
  const 加权 = 部位比例 * 完成度权重[0] + 容量.比例 * 完成度权重[1] + 秒伤.比例 * 完成度权重[2]
  return {
    完成度: clamp100(加权 / 权重和),
    部位比例,
    容量比例: 容量.比例,
    容量估算: 容量.估算,
    秒伤比例: 秒伤.比例,
    秒伤估算: 秒伤.估算,
  }
}
