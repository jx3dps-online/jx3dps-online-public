import type { ReactNode } from 'react'
import type { 选择装备数据类型 } from '@/@types/装备'
import { 装备位置部位枚举 } from '@/@types/装备'
import { 获取角色需要展示的面板数据 } from '@/功能模块/基础设置/面板信息/工具'
import { 获取面板显示数据 } from '@/功能模块/基础设置/面板信息'
import type use登阶页面 from '../../hooks/use登阶页面'
import { 配对装备, 重建登阶装备 } from '../../领域/计算'
import type { 配装快照 } from '@/角色/类型'

export type 登阶页面 = ReturnType<typeof use登阶页面>
export type 部位状态 = '已达成' | '已认可' | '未达成' | '未设目标'
export interface 分享装备对 {
  部位: string
  当前?: 选择装备数据类型
  目标?: 选择装备数据类型
  状态: 部位状态
}
export interface 分享配置 {
  背景: string
  背景横向位置: number
  蒙层: number
  署名: string
  寄语: string
  养成: boolean
  属性: boolean
  显示署名: boolean
  二维码: boolean
  清晰度: number
}

export const 分享不可用原因 = (页面: 登阶页面) =>
  页面.读取错误 ||
  页面.目标池读取错误 ||
  页面.错误 ||
  页面.不匹配原因 ||
  页面.待评估原因 ||
  (!页面.结果匹配 || 页面.忙碌 || !页面.分析 ? '分享.等待分析' : '')

export const 获取分享标识 = (页面: 登阶页面) =>
  JSON.stringify([
    页面.名称,
    页面.数据.当前角色?.id,
    页面.结果?.key,
    页面.当前?.名称,
    页面.目标?.名称,
    页面.展示达成,
  ])

export function 生成分享数据(页面: 登阶页面) {
  const 当前 = { ...页面.当前!, 装备: 重建登阶装备(页面.当前!.装备) }
  const 目标 = { ...页面.目标!, 装备: 重建登阶装备(页面.目标!.装备) }
  const 分析 = 页面.分析!
  const 配对 = 配对装备(当前.装备, 目标.装备)
  const 已用 = new Set(配对.map((项) => 项.当前索引))
  let 戒指序号 = 0
  const 装备对: 分享装备对[] = Object.values(装备位置部位枚举).map((部位) => {
    const 名称 = 部位 === '戒指' ? `${部位} ${++戒指序号}` : 部位
    const 项 = 配对.find((项) => 项.部位 === 名称)
    const 进度 = 分析.部位进度.find((项) => 项.部位 === 名称)
    const 有认可 =
      页面.踏天中 &&
      页面.结果?.有效认可?.includes(`部位:${名称}`) &&
      页面.结果.原始差异?.some(
        (差异) => 差异.部位 === 名称 && ['装备', '精炼', '镶嵌', '附魔'].includes(差异.类别),
      )
    let 身装 = 项?.当前装备
    if (!项) {
      const 索引 = 当前.装备.装备列表.findIndex((装备, i) => 装备.装备部位 === 部位 && !已用.has(i))
      if (索引 >= 0) {
        身装 = 当前.装备.装备列表[索引]
        已用.add(索引)
      }
    }
    return {
      部位: 名称,
      当前: 身装,
      目标: 项?.目标装备,
      状态: !项 ? '未设目标' : 有认可 ? '已认可' : 进度?.已达成 ? '已达成' : '未达成',
    }
  })
  const 生成属性 = (快照: 配装快照): { 名称: string; 值: ReactNode }[] | undefined => {
    if (!快照.循环) return undefined
    const 面板 = 获取角色需要展示的面板数据({
      装备信息: 快照.装备,
      当前奇穴信息: 快照.循环.奇穴,
      增益数据: 页面.数据.增益数据,
      增益启用: false,
      显示增益后面板: false,
    })
    return ['攻击', '会心', '会效', '破防', '无双', '加速'].map((名称) => ({
      名称,
      值: 获取面板显示数据(名称, 面板),
    }))
  }
  const 五彩进度 = 分析.分类进度.find((项) => 项.名称 === '五彩石')
  const 五彩认可 =
    页面.踏天中 &&
    页面.结果?.有效认可?.includes('五彩石:五彩石') &&
    页面.结果.原始差异?.some((项) => 项.类别 === '五彩石')
  const 五彩状态: 部位状态 = !五彩进度?.总数
    ? '未设目标'
    : 五彩认可
      ? '已认可'
      : 五彩进度.完成数 === 五彩进度.总数
        ? '已达成'
        : '未达成'
  return {
    心法: 页面.名称,
    当前,
    目标,
    装备对,
    五彩状态,
    完成度: 页面.展示完成度,
    已达成: 页面.展示达成,
    完成数: 分析.完成数,
    总数: 分析.总数,
    踏天中: 页面.踏天中,
    当前属性: 生成属性(当前),
    目标属性: 生成属性(目标),
    日期: new Date().toLocaleDateString('zh-CN'),
  }
}

export type 分享数据 = ReturnType<typeof 生成分享数据>
