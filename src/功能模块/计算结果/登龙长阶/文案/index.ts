import { 默认文案 } from './默认'
import 分山劲文案 from './心法/分山劲'
import type { 登阶文案 } from './默认'

export type { 登阶文案, 文案键 } from './默认'

/**
 * 心法覆盖注册表：key 是心法数据里的 `名称`。
 * 新增定制只需在 `心法/` 下建文件并在这里登记；未登记的心法使用默认文案。
 */
const 心法覆盖: Record<string, Partial<登阶文案>> = {
  分山劲: 分山劲文案,
  // 分山劲_悟 与分山劲共用同一份文案
  分山劲_悟: 分山劲文案,
}

const 文案缓存 = new Map<string, 登阶文案>()

/** 取合并后的文案表；同一心法返回同一对象引用，可直接用于依赖比较。 */
export const 获取文案 = (心法名称?: string): 登阶文案 => {
  const 缓存键 = 心法名称 || ''
  if (!文案缓存.has(缓存键)) 文案缓存.set(缓存键, { ...默认文案, ...心法覆盖[缓存键] })
  return 文案缓存.get(缓存键)!
}

/** 替换 `{占位符}`；未传的占位符原样保留，便于定位漏传。 */
export const 填充文案 = (模板: string, 参数: Record<string, string | number>) =>
  模板.replace(/\{([^{}]+)\}/g, (整体, 键: string) =>
    参数[键] === undefined ? 整体 : String(参数[键]),
  )

/** 武器类型/循环标记的显示名；未知值原样返回。 */
export const 武器类型显示 = (文案: 登阶文案, 类型?: string) =>
  类型 === '橙武'
    ? 文案['武器类型.橙武']
    : 类型 === '紫武'
      ? 文案['武器类型.紫武']
      : 类型 === '特效'
        ? 文案['武器类型.特效']
        : 类型 || ''
