import { useEffect, useState } from 'react'
import { 装备信息数据类型 } from '@/@types/装备'
import { 登阶武器类型 } from '../领域/循环'
import { 生成登阶分析, 重建登阶装备, 安全计算登阶秒伤 } from '../领域/计算'
import { 计算完成度, 计算容量分数 } from '../领域/完成度'
import { 应用踏天认可, 计算踏天完成度, 有效秒伤 } from '../踏天/计算'
import { 获取文案 } from '../文案'
import type { 登阶差异 } from '../领域/类型'
import type { 踏天进度状态 } from '../领域/文案'
import type { 配装快照, 配装目标, 配装循环, 角色计划 } from '@/角色/类型'
import type { use踏天参考 } from '../踏天/配置'

interface 登阶分析输入 {
  名称: string
  当前?: 配装快照
  目标?: 配装目标
  起点?: 装备信息数据类型
  目标循环?: 配装循环
  参考: ReturnType<typeof use踏天参考>['参考']
  计划: 角色计划
  踏天中: boolean
  跨大橙武: boolean
  计算key: string
  结果范围: string
  按循环计算: (装备: 装备信息数据类型, 配置?: 配装循环) => number | undefined
}
type 分析类型 = ReturnType<typeof 生成登阶分析>
/** 按快照与环境键重算；保留上一份同范围结果，避免展示闪烁。 */
export default function use登阶分析({
  名称,
  当前,
  目标,
  起点,
  目标循环,
  参考,
  计划,
  踏天中,
  跨大橙武,
  计算key,
  结果范围,
  按循环计算,
}: 登阶分析输入) {
  const 文案 = 获取文案(名称)
  const [结果, 设置结果] = useState<{
    key: string
    分析?: 分析类型
    范围: string
    原始差异?: 登阶差异[]
    起点秒伤?: number
    门槛秒伤?: number
    开启进度?: number
    踏天进度状态?: 踏天进度状态
    有效认可?: string[]
    完成度?: ReturnType<typeof 计算完成度>
    错误?: string
  }>()
  useEffect(() => {
    设置结果(undefined)
  }, [名称])
  useEffect(() => {
    if (!当前 || !目标) return
    const 定时器 = window.setTimeout(() => {
      try {
        // 差异与建议只依赖装备对比，不依赖 DPS：目标循环缺失/失效/不满足时也照常生成；
        // 只有 DPS 与综合完成度进入待评估。
        const 计算 = (装备: 装备信息数据类型) => 按循环计算(装备, 目标循环)
        const 原分析 = 生成登阶分析(当前.装备, 目标.装备, 计算, 文案)
        const 认可结果 = 踏天中
          ? 应用踏天认可(原分析, 当前.装备, 目标.装备, 计划.踏天?.替代认可)
          : undefined
        const 分析 = 认可结果?.分析 || 原分析
        let 门槛秒伤: number | undefined
        let 开启进度: number | undefined
        let 进度状态: 踏天进度状态 | undefined
        if (参考 && (踏天中 || (分析.总数 > 0 && 分析.完成数 === 分析.总数))) {
          门槛秒伤 = 安全计算登阶秒伤(参考.门槛.装备, (装备) => 按循环计算(装备, 参考.门槛.循环))
          if (!踏天中 && !跨大橙武 && 登阶武器类型(当前.装备) === 登阶武器类型(参考.目标.装备)) {
            const 终点 = 安全计算登阶秒伤(参考.目标.装备, (装备) =>
              按循环计算(装备, 参考.目标.循环),
            )
            const 起程 = 安全计算登阶秒伤(目标.装备, (装备) => 按循环计算(装备, 参考.目标.循环))
            if (有效秒伤(门槛秒伤) && 有效秒伤(终点) && 有效秒伤(起程)) {
              if (终点 > 门槛秒伤 && 终点 > 起程) 开启进度 = (起程 - 门槛秒伤) / (终点 - 门槛秒伤)
              else if (终点 <= 门槛秒伤) 进度状态 = '参考配置无效'
              else 进度状态 = '已达参考终点'
            } else if (!有效秒伤(门槛秒伤)) 进度状态 = '门槛不可算'
            else if (!有效秒伤(终点)) 进度状态 = '终点不可算'
            else 进度状态 = '目标不可算'
          }
        }
        const 起点秒伤 = 起点 ? 安全计算登阶秒伤(起点, 计算) : undefined
        const 当前容量 = 计算容量分数(重建登阶装备(当前.装备))
        const 目标容量 = 计算容量分数(重建登阶装备(目标.装备))
        const 起点容量 = 起点 ? 计算容量分数(重建登阶装备(起点)) : undefined
        const 完成度输入 = {
          部位进度: 分析.部位进度,
          当前容量,
          目标容量,
          起点容量,
          当前DPS: 分析.当前秒伤,
          目标DPS: 分析.目标秒伤,
          起点DPS: 起点秒伤,
        }
        const 完成度 = 踏天中
          ? 计算踏天完成度(完成度输入, 门槛秒伤, 文案)
          : 计算完成度(完成度输入, 文案)
        设置结果({
          key: 计算key,
          范围: 结果范围,
          原始差异: 原分析.差异,
          分析,
          起点秒伤,
          完成度,
          门槛秒伤,
          开启进度,
          踏天进度状态: 进度状态,
          有效认可: 认可结果?.有效,
        })
      } catch {
        设置结果({
          key: 计算key,
          范围: 结果范围,
          错误: 文案['分析.错误.装备不可用'],
        })
      }
    }, 60)
    return () => window.clearTimeout(定时器)
  }, [计算key])
  return 结果
}
