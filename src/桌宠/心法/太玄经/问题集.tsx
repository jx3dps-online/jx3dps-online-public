const 转换气泡问题 = (问题: 经典问题): 经典问题 => {
  const 行为 = 问题.行为
  if (行为.类型 === '自定义') {
    return {
      ...问题,
      回答方式: '气泡',
      行为: {
        类型: '弹窗',
        内容: (
          <>
            <p>{操作说明[行为.名称]}</p>
            <Button size='small' onClick={() => 执行行为(行为.名称, 行为.参数)}>
              {行为.名称}
            </Button>
          </>
        ),
      },
    }
  }
  return { ...问题, 回答方式: '气泡' }
}

