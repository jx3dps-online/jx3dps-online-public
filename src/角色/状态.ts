export const 获取循环配套数据 = (
  名称: string,
  数据: Pick<数据模块类型, '装备信息' | '增益数据' | '增益启用' | '网络延迟' | '自定义循环列表'>,
) => {
  const { 当前循环信息, 计算循环详情 } = useCycle({
    使用内存数据: false,
    覆盖数据: { ...数据, 当前计算循环名称: 名称 },
  })
  const { 默认数据 = {}, 奇穴数据 = [] } = 获取当前数据()
  return {
    当前计算循环名称: 当前循环信息?.名称 || '',
    当前奇穴信息:
      当前循环信息?.奇穴 || 默认数据.奇穴 || 奇穴数据.map((项) => 项.奇穴列表[0].奇穴名称),
    当前秘籍信息: 计算循环详情?.秘籍 || 当前循环信息?.秘籍 || 默认数据.秘籍 || {},
  }
}

export const 角色状态存储键 = (角色id: string) => 'jx3dps:角色状态:v1:' + encodeURIComponent(角色id)

const 校验角色状态 = (值: unknown): 值 is 角色状态数据类型 => {
  if (!是对象(值)) return false
  return (
    有效配装装备(值.装备信息) &&
    typeof 值.当前计算循环名称 === 'string' &&
    Array.isArray(值.当前奇穴信息) &&
    值.当前奇穴信息.every((项) => typeof 项 === 'string') &&
    是对象(值.当前秘籍信息) &&
    Object.values(值.当前秘籍信息).every(
      (项) => Array.isArray(项) && 项.every((秘籍) => typeof 秘籍 === 'string'),
    ) &&
    是对象(值.角色增益) &&
    typeof 值.角色增益.阵眼 === 'string' &&
    Array.isArray(值.角色增益.小吃) &&
    值.角色增益.小吃.every((项) => typeof 项 === 'string') &&
    Number.isFinite(值.更新时间)
  )
}

export const 创建角色状态存储 = (角色id: string, 默认状态: 角色状态数据类型) =>
  创建本地存储<角色状态数据类型>(角色状态存储键(角色id), 默认状态, 校验角色状态)

/** 按当前心法的默认数据创建一个角色的初始状态。 */
export const 创建默认角色状态 = (): 角色状态数据类型 => {
  const { 默认数据 = {}, 奇穴数据 = [] } = 获取当前数据()
  const { 全部循环 } = useCycle({ 使用内存数据: false })
  const 默认秘籍 = 默认数据?.秘籍 || {}
  const 默认装备信息 = 默认数据?.配装 || {}
  const 当前计算循环名称 = 全部循环[0]?.名称 || ''
  const 当前循环信息 = 全部循环?.find((项) => 项?.名称 === 当前计算循环名称)
  const 默认奇穴 =
    默认数据?.奇穴 ||
    奇穴数据.map((项) => {
      return 项?.奇穴列表?.[0]?.奇穴名称
    })

  let 装备信息: 装备信息数据类型 = {
    装备基础属性: 获取角色默认基础属性(),
    装备列表: [],
    五彩石: '',
    装备增益: {},
    ...默认装备信息,
  }
  if (装备信息.装备列表?.length) {
    装备信息 = 根据装备信息获取基础属性(装备信息)
  }

  return {
    装备信息,
    当前计算循环名称,
    当前奇穴信息: 当前循环信息?.奇穴 || 默认奇穴,
    当前秘籍信息: 当前循环信息?.秘籍 || 默认秘籍,
    角色增益: { 阵眼: '', 小吃: [] },
    更新时间: Date.now(),
  }
}

export const 读取角色状态 = (角色: 角色元数据) => {
  const 存储 = 创建角色状态存储(角色.id, 创建默认角色状态())
  const 状态 = 存储.读取()
  // 载入时重算装备基础属性：游戏/附魔数据更新后，已保存的配装也按最新数据生效
  const 最新状态 = 状态.装备信息?.装备列表?.length
    ? { ...状态, 装备信息: 根据装备信息获取基础属性(状态.装备信息) }
    : 状态
  const 读取错误 = 存储.读取错误()
  if (读取错误) return { 状态: 最新状态, 读取错误 }
  const 自定义循环列表 = 加载缓存自定义循环数据()
  const 全部循环 = [...(获取当前数据().计算循环 || []), ...自定义循环列表]
  if (全部循环.some((项) => 项.名称 === 状态.当前计算循环名称)) {
    return { 状态: 最新状态, 读取错误 }
  }
  const 循环配置 = 获取循环配套数据(全部循环[0]?.名称 || '', {
    装备信息: 最新状态.装备信息,
    增益数据: 合成增益数据(状态.角色增益),
    增益启用: 加载缓存增益启用(),
    网络延迟: 加载缓存网络延迟(),
    自定义循环列表,
  })
  const 修正状态 = { ...最新状态, ...循环配置, 更新时间: Date.now() }
  if (状态.当前计算循环名称 !== 修正状态.当前计算循环名称) {
    try {
      存储.保存({ ...状态, ...循环配置, 更新时间: 修正状态.更新时间 })
    } catch (错误) {
      return { 状态: 修正状态, 读取错误: `循环已回退，但未能保存：${(错误 as Error).message}` }
    }
  }
  return { 状态: 修正状态, 读取错误 }
}

/** 按存储原文校验读取，不按当前心法重算；从未保存或数据损坏时返回 undefined。用于复制角色。 */
export const 读取原始角色状态 = (角色id: string): 角色状态数据类型 | undefined => {
  try {
    const 原文 = localStorage.getItem(角色状态存储键(角色id))
    if (原文 === null) return undefined
    const 值 = JSON.parse(原文)
    return 校验角色状态(值) ? 值 : undefined
  } catch {
    return undefined
  }
}

/** 「保存角色」：写角色状态，再记录成长足迹；足迹失败不回滚配装。 */
export const 保存角色配装 = (角色: 角色元数据, 状态: 角色状态数据类型) => {
  const 新状态 = { ...状态, 更新时间: Date.now() }
  创建角色状态存储(角色.id, 新状态).保存(新状态)
  let 警告: string | undefined
  try {
    创建角色计划存储(角色.id).记录配装(新状态.装备信息, 角色.名称, 提取配装循环(新状态))
  } catch (错误) {
    警告 = '配装已保存，但成长足迹未写入：' + (错误 as Error).message
  }
  return { 状态: 新状态, 警告 }
}
