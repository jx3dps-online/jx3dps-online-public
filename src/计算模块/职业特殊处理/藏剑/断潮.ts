import { 目标属性类型 } from '@/@types/常量'
import { 循环技能详情, 技能增益列表数据 } from '@/@types/循环'
import { 快照类型, 技能基础数据模型, 技能计算增益数据列表 } from '@/@types/技能'
import { 装备增益类型 } from '@/@types/装备'
import { 最终计算属性类型 } from '@/@types/计算'
import { 自身属性系数 } from '@/数据/常量'
import 获取技能等级信息 from '@/数据/数据工具/获取技能等级信息'
import {
  获取增益实际数据集合,
  计算该技能下多个增益的增益集合,
} from '@/计算模块/统一工具函数/增益计算函数'
import { 计算增益加成后最终计算属性 } from '@/计算模块/统一工具函数/计算增益加成后最终计算属性'

const 触发断潮技能 = ['听雷', '夕照雷峰', '云飞玉皇']
const 触发断潮概率 = 0.3

/**
 * 断潮动态函数 - 计算断潮技能的触发情况
 * 通过依次计算触发技能的每一个增益组合，判定当增益组的的实际会心期望
 * 根据会心期望计算该增益组xx个技能触发的断潮数量期望
 * 合并返回
 */
export const 断潮动态函数 = (
  最终循环: 循环技能详情[],
  人物属性: 最终计算属性类型,
  技能数据映射: Map<string, 技能基础数据模型>,
  装备增益: 装备增益类型,
  快照计算: 快照类型[],
  团队增益结合: string[],
  计算目标: 目标属性类型,
) => {
  // 初始化断潮技能数据
  const 断潮最终数据: 循环技能详情 = {
    技能名称: '断潮',
    技能数量: 0,
    技能增益列表: [],
  }

  // 遍历循环技能，计算断潮触发，和计算公式相同，但是这里只计算属性
  最终循环
    .filter((循环) => 触发断潮技能.includes(循环.技能名称))
    .forEach((循环) => {
      // 获取技能基础数据
      const 完整技能属性 = 技能数据映射.get(循环.技能名称)
      const 当前技能属性 = 获取技能等级信息(完整技能属性, 循环.技能等级)

      // 获取全局增益
      const 全局增益集合 = 获取全局增益集合(当前技能属性)

      // 处理有增益的技能部分
      let 无增益技能数 = 循环.技能数量
      if (循环.技能增益列表?.length) {
        const 增益处理结果 = 处理技能增益(
          循环,
          当前技能属性,
          人物属性,
          装备增益,
          快照计算,
          团队增益结合,
          计算目标,
          全局增益集合,
        )
        //console.log(
        //  `[断潮触发-增益] 技能: ${循环.技能名称}, 处理技能数: ${增益处理结果.已处理技能数}, ` +
        //  `触发数量: ${增益处理结果.触发数量}`,
        //)
        //console.log(`[断潮触发-增益列表]`, 增益处理结果.增益列表)
        // 更新断潮数据
        断潮最终数据.技能数量 += 增益处理结果.触发数量
        断潮最终数据.技能增益列表 && 断潮最终数据.技能增益列表.push(...增益处理结果.增益列表)
        无增益技能数 -= 增益处理结果.已处理技能数
      }

      // 处理无增益的技能部分
      if (无增益技能数 > 0) {
        const 计算技能全局增益后数据 = 计算增益加成后最终计算属性({
          传入计算属性: 人物属性,
          增益集合: 全局增益集合,
          当前目标: 计算目标,
        })

        const 触发数量期望 = 根据面板获取断潮概率(计算技能全局增益后数据)
        const 触发数量 = 触发数量期望 * 无增益技能数
        //console.log(
        //  `[断潮触发-无增益] 技能: ${循环.技能名称}, 技能数: ${无增益技能数}, ` +
        //  `触发期望: ${触发数量期望}, 触发数量: ${触发数量}`,
        //)
        断潮最终数据.技能数量 += 触发数量
      }
    })
  //console.log(`最终断潮数量: `, 断潮最终数据.技能数量)
  //console.log(`断潮 Buff 来源列表:`, 断潮最终数据.技能增益列表)
  return [...最终循环, 断潮最终数据]
}

/**
 * 获取全局增益集合
 */
const 获取全局增益集合 = (当前技能属性): 技能计算增益数据列表[] => {
  if (!当前技能属性?.技能增益列表?.length) return []

  return 当前技能属性.技能增益列表
    .filter((增益) => 增益.增益启用 && 增益.增益类型 === '全局启用')
    .flatMap((增益) =>
      (增益.增益集合 || []).map((item) => ({
        ...item,
        增益来源: 增益.增益名称,
      })),
    )
}

/**
 * 处理技能增益
 */
const 处理技能增益 = (
  循环: 循环技能详情,
  当前技能属性,
  人物属性: 最终计算属性类型,
  装备增益: 装备增益类型,
  快照计算: 快照类型[],
  团队增益结合: string[],
  计算目标: 目标属性类型,
  全局增益集合: 技能计算增益数据列表[],
) => {
  let 总触发数量 = 0
  const 增益列表: 技能增益列表数据[] = []
  let 已处理技能数 = 0

  // 计算所有增益名称列表
  const 该技能循环内增益名称列表 =
    循环?.技能增益列表?.map((增益) =>
      计算该技能下多个增益的增益集合(增益, 当前技能属性, 装备增益, 快照计算, 团队增益结合),
    ) || []

  // 处理每个增益实例
  循环?.技能增益列表?.forEach((增益, 索引) => {
    if (!增益.增益技能数) return

    已处理技能数 += 增益.增益技能数

    // 获取当前增益的实际数据
    const 技能独立增益集合列表 = 获取增益实际数据集合(该技能循环内增益名称列表[索引], 当前技能属性)

    // 计算增益后的最终属性
    const 技能最终计算数据 = 计算增益加成后最终计算属性({
      传入计算属性: 人物属性,
      增益集合: [...全局增益集合, ...技能独立增益集合列表],
      当前目标: 计算目标,
    })

    // 计算断潮触发数量
    const 触发数量期望 = 根据面板获取断潮概率(技能最终计算数据)
    if (触发数量期望) {
      const 触发数量 = 触发数量期望 * 增益.增益技能数
      总触发数量 += 触发数量

      增益列表.push({
        增益名称: 增益.增益名称,
        增益技能数: 触发数量,
      })
    }
  })

  return {
    触发数量: 总触发数量,
    增益列表,
    已处理技能数,
  }
}

/**
 * 根据面板属性计算断潮触发数量
 */
const 根据面板获取断潮概率 = (技能最终计算数据) => {
  if (!技能最终计算数据) return 0

  const 当前触发时会心 =
    (技能最终计算数据.最终人物属性?.会心等级 || 0) / 自身属性系数.会心 +
    (技能最终计算数据.额外会心率 || 0)

  return 当前触发时会心 + 触发断潮概率
}
