// 计算技能循环总输出
export const 循环秒伤计算 = (props: 技能总伤害计算入参类型) => {
  const {
    计算循环,
    装备信息,
    当前目标,
    技能数据映射,
    增益启用,
    增益数据,
    战斗时间,
    是否郭氏计算,
    快照计算 = [],
    计算循环详情,
    奇穴数据 = [],
    计算技能详情,
  } = props
  // 总dps
  let 循环总伤 = 0
  // 每个技能的dps总和列表
  const 计算结果技能列表: 计算结果技能列表类型[] = []
  const 计算目标 = 当前目标

  // 获取装备增益等带来的最终增益集合
  let 总增益集合: 技能计算增益数据列表[] = 获取装备增益(装备信息, 快照计算, 计算循环详情?.覆盖率)
  const 团队增益结合: string[] = []

  // 根据增益信息修改最终循环内容
  let 最终循环: 循环技能详情[] = [...计算循环]

  if (增益启用 && 增益数据) {
    const 团队增益增益集合 = 根据增益选项获取增益集合(增益数据, undefined, 快照计算)
    总增益集合 = 总增益集合.concat(团队增益增益集合)

    // 塞入团队增益
    增益数据?.团队增益?.forEach((增益) => {
      if (增益?.启用) {
        团队增益结合.push(增益?.增益名称)
      }
    })

    if (增益数据?.阵眼) {
      团队增益结合.push(增益数据?.阵眼)
    }

    const 飘黄数据 = 增益数据?.团队增益.find((item) => item.增益名称 === '飘黄')
    if (飘黄数据?.启用) {
      最终循环.push({
        技能名称: '逐云寒蕊',
        技能数量: Math.floor((战斗时间 / 60) * 12), // CD60
        技能等级: 飘黄数据?.层数,
        技能增益列表: [],
      })
    }

    // 气纯阵眼特殊处理
    if (增益数据?.阵眼 === '气纯阵(阵眼)') {
      最终循环 = 气纯阵眼动态函数(最终循环)
    }

    // 天罗阵眼特殊处理
    // if (增益数据?.阵眼 === '天罗阵(阵眼)') {
    //   天罗阵眼动态函数(技能数据映射)
    // }
  }

  /**
   * 第一次计算增益、包含：
   * 团队增益（小药、团辅、阵眼等）
   * 装备增益（套装双会、风水特效、大附魔、切糕等）
   * 这里不会包含特定技能的增益
   *
   * */

  const 计算团辅和装备后属性 = 计算增益加成后最终计算属性({
    装备基础属性: 装备信息?.装备基础属性,
    增益集合: 总增益集合,
    当前目标,
  })

  最终循环 = 根据增益修改最终循环(装备信息, 最终循环, 战斗时间, 计算团辅和装备后属性)

  // 遍历循环，获取每一个技能的总输出
  最终循环.forEach((循环技能) => {
    // 获取循环内某个技能的总dps
    const { 总伤, 总会心数量, 当前技能属性, 计算数量, 技能最终详情 } = 计算循环内某技能总伤害(
      循环技能,
      装备信息?.装备增益,
      计算目标,
      技能数据映射,
      是否郭氏计算,
      快照计算,
      计算团辅和装备后属性,
      战斗时间,
      团队增益结合,
      计算技能详情,
    )
    计算结果技能列表.push(
      去除对象中的无效值({
        统计名称: 当前技能属性?.统计名称,
        技能ID: 当前技能属性?.技能ID,
        技能名称: 循环技能.技能名称,
        技能等级: 循环技能.技能等级,
        伤害层数: 循环技能.伤害层数,
        DOT跳数: 循环技能.DOT跳数,
        技能总输出: 总伤,
        技能数量: 计算数量,
        会心几率: 总会心数量 / 计算数量,
        技能最终详情: 技能最终详情,
      }),
    )
    循环总伤 = 循环总伤 + 总伤
  })

  return { 总伤: 循环总伤, 计算结果技能列表 }
}

const 获取所有技能通用的增益集合 = (该技能增益集合: string[][]) => {
  const 共同增益 = new Set(该技能增益集合[0])
  该技能增益集合.forEach((增益) => {
    const currentSet = new Set(增益)
    for (const key of 共同增益) {
      if (!currentSet.has(key)) {
        共同增益.delete(key)
      }
    }
  })

  const 全部共用增益数据 = Array.from(共同增益)
  const 共用增益数据集合 = 该技能增益集合[0].filter((item) => 全部共用增益数据?.includes(item))

  return 共用增益数据集合
}

