import 获取当前数据 from '@/数据/数据工具/获取当前数据'
import { 内容缓存 } from '@/工具函数/cache'
import { 根据秘籍格式化技能基础数据 } from './技能秘籍计算'
import { 根据奇穴格式化技能基础数据 } from './技能奇穴计算'
import { 根据团队增益格式化技能基础数据, 根据装备格式化技能基础数据 } from './技能装备计算'

/**
 * 计算由装备、秘籍、奇穴等影响的技能基础的增益启用情况
 * 结果按入参内容缓存（内容相等即命中），key 前缀心法名：技能系数按心法缓存，
 * 加入心法标识可避免切换心法后命中脏缓存。
 */
export const 获取判断增益后技能系数 = 内容缓存(
  ({
    秘籍信息,
    奇穴数据,
    装备增益,
    团队增益,
    团队快照计算列表,
    排除技能增益 = [],
  }: {
    秘籍信息: any
    奇穴数据: any
    装备增益: any
    团队增益: any
    团队快照计算列表: any
    排除技能增益?: string[]
  }) => {
    const { 技能系数 } = 获取当前数据()
    const 秘籍格式化后技能基础数据 = 根据秘籍格式化技能基础数据(技能系数, 秘籍信息)
    const 奇穴格式化后技能基础数据 = 根据奇穴格式化技能基础数据(秘籍格式化后技能基础数据, 奇穴数据)
    const 装备格式化后技能基础数据 = 根据装备格式化技能基础数据(奇穴格式化后技能基础数据, 装备增益)
    const 计算后技能基础数据 = 根据团队增益格式化技能基础数据(
      装备格式化后技能基础数据,
      团队增益,
      团队快照计算列表,
    )
    if (!排除技能增益.length) return 计算后技能基础数据
    return 计算后技能基础数据.map((技能) => {
      const 数据 = {
        ...技能,
        技能增益列表: 技能.技能增益列表?.filter((增益) => !排除技能增益.includes(增益.增益名称)),
      }
      if (技能.技能等级数据) {
        数据.技能等级数据 = { ...技能.技能等级数据 }
        for (const 等级 in 数据.技能等级数据) {
          const 等级数据 = 数据.技能等级数据[等级]
          数据.技能等级数据[等级] = {
            ...等级数据,
            技能增益列表: 等级数据.技能增益列表?.filter(
              (增益) => !排除技能增益.includes(增益.增益名称),
            ),
          }
        }
      }
      return 数据
    })
  },
  {
    maxSize: 200,
    keyFn: ({ 秘籍信息, 奇穴数据, 装备增益, 团队增益, 团队快照计算列表, 排除技能增益 = [] }) => {
      return `${获取当前数据()?.名称 || ''}|${JSON.stringify([
        秘籍信息,
        奇穴数据,
        装备增益,
        团队增益,
        团队快照计算列表,
        排除技能增益,
      ])}`
    },
  },
)
