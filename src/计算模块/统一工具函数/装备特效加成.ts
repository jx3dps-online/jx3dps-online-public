const 装备特效加成 = (
  人物面板: 角色基础属性类型,
  装备增益: 装备增益类型,
  最终计算属性: 最终计算属性类型,
): { 计算人物面板: 角色基础属性类型; 最终计算属性: 最终计算属性类型 } => {
  let 实际面板 = { ...人物面板 }
  // 试炼之地
  if (装备增益?.特效_38934) {
    实际面板 = 适应算法(实际面板, 装备增益?.特效_38934)
  }
  if (装备增益?.特效_38946) {
    实际面板 = 项链破防转攻击算法(实际面板, 装备增益?.特效_38946)
  }
  if (装备增益?.特效_38945) {
    实际面板 = 项链会心转无双算法(实际面板, 装备增益?.特效_38945)
  }
  if (装备增益?.特效_46727) {
    实际面板 = 暗器攻击算法(实际面板, 装备增益.特效_46727)
  }
  // 副本特效
  if (装备增益?.特效_40791) {
    实际面板 = 特效_40791算法(实际面板, 装备增益?.特效_40791)
  }

  return { 计算人物面板: 实际面板, 最终计算属性 }
}

// BuffId：30743
const 特效_40791算法 = (人物面板: 角色基础属性类型, 加成等级: number): 角色基础属性类型 => {
  const 等级加成数值 = 装备特效数据.特效_40791?.算法参数?.加成数值 || {}

  const 加成数值 = 等级加成数值?.[加成等级] || 0
  // 新等级效果改了
  if (加成等级 > 2) {
    if (人物面板?.破防等级 < 人物面板?.会心等级) {
      return {
        ...人物面板,
        破防等级: (人物面板?.破防等级 || 0) + 加成数值,
      }
    } else {
      return {
        ...人物面板,
        会心等级: (人物面板?.会心等级 || 0) + 加成数值,
      }
    }
  } else {
    const 实际平均数值 = INT(加成数值 / 3)
    // 效果为随机三个属性其中一个，这里做均摊计算
    return {
      ...人物面板,
      破防等级: (人物面板?.破防等级 || 0) + 实际平均数值,
      会心等级: (人物面板?.会心等级 || 0) + 实际平均数值,
      无双等级: (人物面板?.无双等级 || 0) + 实际平均数值,
    }
  }
}

// BuffID: 29529
const 项链破防转攻击算法 = (人物面板: 角色基础属性类型, 加成等级: number): 角色基础属性类型 => {
  const 破防等级 = 人物面板?.破防等级
  const 算法参数 = 装备特效数据.特效_38946?.算法参数
  const 每层所需破防 = 算法参数?.每层所需属性?.[加成等级] || 1
  const 每层数值 = 算法参数?.加成数值?.[加成等级] || 0
  const 最大层数 = 算法参数?.最大层数?.[加成等级] || 0

  const 加成层数 = Math.min(最大层数, Math.max(0, Math.floor(破防等级 / 每层所需破防)))
  const 加成攻击数值 = 加成层数 * 每层数值
  return {
    ...人物面板,
    基础攻击: (人物面板?.基础攻击 || 0) + 加成攻击数值,
    面板攻击: (人物面板?.面板攻击 || 0) + 加成攻击数值,
  }
}

// BuffID: 29528
const 项链会心转无双算法 = (人物面板: 角色基础属性类型, 加成等级: number): 角色基础属性类型 => {
  const 会心等级 = 人物面板?.会心等级
  const 算法参数 = 装备特效数据.特效_38945?.算法参数
  const 每层所需会心 = 算法参数?.每层所需属性?.[加成等级] || 1
  const 每层数值 = 算法参数?.加成数值?.[加成等级] || 0
  const 最大层数 = 算法参数?.最大层数?.[加成等级] || 0

  const 加成层数 = Math.min(最大层数, Math.max(0, Math.floor(会心等级 / 每层所需会心)))
  const 加成无双数值 = 加成层数 * 每层数值
  return {
    ...人物面板,
    无双等级: 人物面板.无双等级 + 加成无双数值,
  }
}

const 暗器攻击算法 = (人物面板: 角色基础属性类型, 加成等级: number): 角色基础属性类型 => {
  const { 加成数值, 冷却帧数, 持续时间分段 } = 装备特效数据.特效_46727!.加速增益!
  const 加速等级 = Math.max(0, Math.floor(人物面板.加速等级))
  let 持续帧数 = 持续时间分段[持续时间分段.length - 1].持续帧数
  // 试炼纯加速暗器_攻击.lua：基础加速分段插值，持续帧数向下取整。
  for (let i = 1; i < 持续时间分段.length; i++) {
    const 前段 = 持续时间分段[i - 1]
    const 后段 = 持续时间分段[i]
    if (加速等级 < 后段.加速等级) {
      持续帧数 = Math.floor(
        前段.持续帧数 +
          ((加速等级 - 前段.加速等级) * (后段.持续帧数 - 前段.持续帧数)) /
            (后段.加速等级 - 前段.加速等级),
      )
      break
    }
  }
  // 静态期望计算按持续命中的覆盖率均摊，不将触发加攻视为全程常驻。
  const 加成攻击数值 = ((加成数值[加成等级] || 0) * 持续帧数) / 冷却帧数
  return {
    ...人物面板,
    基础攻击: 人物面板.基础攻击 + 加成攻击数值,
    面板攻击: (人物面板.面板攻击 || 0) + 加成攻击数值,
  }
}

// 取会心破防的最大值再进行加成的算法
const 适应算法 = (人物面板: 角色基础属性类型, 加成等级: number): 角色基础属性类型 => {
  let 最终面板 = { ...人物面板 }
  const 等级加成数值 = 装备特效数据.特效_38934?.算法参数?.加成数值 || {}
  const 加成数值 = 等级加成数值?.[加成等级] || 0
  const 会心等级 = 人物面板?.会心等级
  const 破防等级 = 人物面板?.破防等级
  const 最大值 = Math.max(会心等级, 破防等级)

  if (最大值 === 破防等级) {
    最终面板 = {
      ...最终面板,
      破防等级: 最终面板.破防等级 + 加成数值,
    }
  } else if (最大值 === 会心等级) {
    最终面板 = {
      ...最终面板,
      会心等级: 最终面板.会心等级 + 加成数值,
    }
  }

  return 最终面板
}

