// 统计增益，获取增益的集合
export const 获取装备增益 = (
  装备信息: 装备信息数据类型,
  快照计算: 快照类型[],
  循环覆盖率?: { [key: string]: number },
): 属性加成[] => {
  const { 装备增益数据, 覆盖率 } = 获取当前数据()
  let 总增益集合: 属性加成[] = []
  // 如果是快照计算，不计算套装、水特效、风腰椎的加成。放到最后的增益数量里计算
  if (!快照计算?.includes('套装会心会效')) {
    if (装备信息?.装备增益?.套装会心会效) {
      // 判断套装覆盖率
      const 套装覆盖率 = 循环覆盖率?.套装会心会效 || 覆盖率?.套装会心会效 || 0.6
      const 装备特效增益效果 = 获取装备特效增益数据('套装会心会效', 1, 装备增益数据, 套装覆盖率)
      if (装备特效增益效果) {
        总增益集合 = 总增益集合.concat(装备特效增益效果)
      }
    }
  }
  if (!快照计算?.includes('风特效')) {
    if (装备信息?.装备增益?.风特效腰坠) {
      const 增益等级 = 装备信息?.装备增益?.风特效腰坠
      // 判断套装覆盖率
      const 套装覆盖率 = 覆盖率?.风特效腰坠 || 15 / 180
      const 装备特效增益效果 = 获取装备特效增益数据(
        '风特效腰坠',
        增益等级,
        装备增益数据,
        套装覆盖率,
      )
      if (装备特效增益效果) {
        总增益集合 = 总增益集合.concat(装备特效增益效果)
      }
    }
  }
  if (!快照计算?.includes('大附魔_伤腰')) {
    if (装备信息?.装备增益?.大附魔_伤腰) {
      const 装备特效增益效果 = 获取装备特效增益数据('大附魔_伤腰', 1, 装备增益数据)
      if (装备特效增益效果) {
        总增益集合 = 总增益集合.concat(装备特效增益效果)
      }
    }
  }
  if (装备信息?.装备增益?.切糕会心) {
    const 装备特效增益效果 = 获取装备特效增益数据('切糕会心', 1, 装备增益数据)
    if (装备特效增益效果) {
      总增益集合 = 总增益集合.concat(装备特效增益效果)
    }
  }
  if (装备信息?.装备增益?.切糕无双) {
    const 装备特效增益效果 = 获取装备特效增益数据('切糕无双', 1, 装备增益数据)
    if (装备特效增益效果) {
      总增益集合 = 总增益集合.concat(装备特效增益效果)
    }
  }
  if (装备信息?.装备增益?.切糕会心_英雄) {
    const 装备特效增益效果 = 获取装备特效增益数据('切糕会心', 2, 装备增益数据)
    if (装备特效增益效果) {
      总增益集合 = 总增益集合.concat(装备特效增益效果)
    }
  }
  if (装备信息?.装备增益?.切糕无双_英雄) {
    const 装备特效增益效果 = 获取装备特效增益数据('切糕无双', 1, 装备增益数据)
    if (装备特效增益效果) {
      总增益集合 = 总增益集合.concat(装备特效增益效果)
    }
  }
  /**
   * 装备特效计算
   * 常驻增益、大橙武无双、试炼之地常驻、精简常驻
   */
  总增益集合 = 获取装备特效增益(总增益集合, 装备信息?.装备增益)

  if (装备信息?.装备增益?.郭氏力道) {
    总增益集合 = 总增益集合.concat([
      { 属性: 属性类型.郭氏力道, 值: 装备信息?.装备增益?.郭氏力道 || 0 },
    ])
  }
  if (装备信息?.装备增益?.郭氏身法) {
    总增益集合 = 总增益集合.concat([
      { 属性: 属性类型.郭氏身法, 值: 装备信息?.装备增益?.郭氏身法 || 0 },
    ])
  }
  if (装备信息?.装备增益?.郭氏根骨) {
    总增益集合 = 总增益集合.concat([
      { 属性: 属性类型.郭氏根骨, 值: 装备信息?.装备增益?.郭氏根骨 || 0 },
    ])
  }
  if (装备信息?.装备增益?.郭氏元气) {
    总增益集合 = 总增益集合.concat([
      { 属性: 属性类型.郭氏元气, 值: 装备信息?.装备增益?.郭氏元气 || 0 },
    ])
  }

  return 总增益集合
}

/**
 * @name 获取装备特效增益
 */
const 获取装备特效增益 = (总增益集合: 属性加成[], 装备增益: 装备增益类型) => {
  const { 装备增益数据 } = 获取当前数据()
  let 最终增益集合 = [...总增益集合]
  常驻面板类装备特效?.forEach((增益类型) => {
    if (装备增益?.[增益类型]) {
      const 装备特效增益效果 = 获取装备特效增益数据(增益类型, 装备增益?.[增益类型], 装备增益数据)
      if (装备特效增益效果) {
        最终增益集合 = 最终增益集合.concat(装备特效增益效果)
      }
    }
  })
  return 最终增益集合
}

const 获取触发技能名称列表 = (触发技能?: 装备特效触发技能) =>
  Object.values(触发技能?.技能 || {}).map((技能) => 技能.技能名称)

/**
 * 应用装备特效的触发技能：
 * 未装备（档位无对应技能）时移除循环内已有技能，已存在时不重复添加
 */
const 应用触发技能 = (
  循环: 循环技能详情[],
  触发技能: 装备特效触发技能 | undefined,
  档位: number,
  计算技能数量: (间隔: number) => number,
): 循环技能详情[] => {
  const 名称列表 = 获取触发技能名称列表(触发技能)
  const 实际档位 = 触发技能?.档位映射?.[档位] ?? 档位
  const 技能数据 = 触发技能?.技能?.[实际档位]
  if (!技能数据 || !触发技能) {
    return 循环.filter((item) => !名称列表.some((名称) => item.技能名称?.includes(名称)))
  }
  if (循环.some((item) => 名称列表.some((名称) => item.技能名称?.includes(名称)))) {
    return 循环
  }
  return [
    ...循环,
    {
      技能名称: 技能数据.技能名称,
      技能数量: 计算技能数量(触发技能.间隔),
    },
  ]
}

// 根据增益信息修改最终循环内容
export const 根据增益修改最终循环 = (
  装备信息: 装备信息数据类型,
  计算循环,
  战斗时间,
  计算团辅和装备后属性: 最终计算属性类型,
): 循环技能详情[] => {
  const 装备增益 = 装备信息?.装备增益
  let 最终循环: 循环技能详情[] = [...计算循环]
  const 按间隔计算数量 = (间隔: number) => Math.floor(战斗时间 / 间隔)

  最终循环 = 应用触发技能(
    最终循环,
    装备特效数据.大附魔_伤腕?.触发技能,
    装备增益?.大附魔_伤腕 || 0,
    按间隔计算数量,
  )
  最终循环 = 应用触发技能(
    最终循环,
    装备特效数据.大附魔_伤鞋?.触发技能,
    装备增益?.大附魔_伤鞋 || 0,
    按间隔计算数量,
  )
  最终循环 = 应用触发技能(
    最终循环,
    装备特效数据.特效_38950?.触发技能,
    装备增益?.特效_38950 || 0,
    按间隔计算数量,
  )
  最终循环 = 应用触发技能(
    最终循环,
    装备特效数据.特效_42767?.触发技能,
    装备增益?.特效_42767 || 0,
    (间隔) => Math.floor((战斗时间 / 间隔) * 速震特效跳数(计算团辅和装备后属性)),
  )
  最终循环 = 应用触发技能(
    最终循环,
    装备特效数据.特效_40788?.触发技能,
    装备增益?.特效_40788 || 0,
    按间隔计算数量,
  )

  if (装备增益?.龙门飞剑武器) {
    最终循环.push({
      技能名称: '剑风',
      技能数量: Math.floor((战斗时间 * 6) / 30),
    })
  }

  return 最终循环
}

// 属性类型在枚举中的序号，用于排序时 O(1) 查下标（避免每次 indexOf 遍历约 80 个元素）
const 属性类型序号 = new Map<属性类型, number>(
  Object.values(属性类型).map((值, 序号) => [值, 序号]),
)

const 获取属性序号 = (属性: 属性类型): number => 属性类型序号.get(属性) ?? 0

// 对增益进行排序
export const 增益排序 = (list: 属性加成[]): 属性加成[] => {
  const newList = [...list]

  newList.sort((a, b) => {
    return 获取属性序号(a.属性) - 获取属性序号(b.属性)
  })

  return newList.filter((item) => !!item)
}

// 对增益进行同类合并，然后再排序返回
export const 增益合并并排序 = (list: 属性加成[]): 属性加成[] => {
  const obj = {}
  const skillCoefficientList: 属性加成[] = []
  list.forEach((item) => {
    if (item) {
      if (obj[item.属性]) {
        // 系数增伤不合并排序，否则多次计算会遗漏 目前只有系数增伤是乘算，其他的都为加算，若存在其他加算，这里也要过滤
        if (item.属性 !== 属性类型.系数增伤) {
          obj[item.属性] += item.值
        } else {
          skillCoefficientList.push(item)
        }
      } else {
        obj[item.属性] = item.值
      }
    }
  })

  const newList: any[] = Object.keys(obj).map((key) => {
    return { 属性: key, 值: obj[key] }
  })

  newList.sort((a, b) => {
    return 获取属性序号(a.属性) - 获取属性序号(b.属性)
  })

  return newList.filter((item) => !!item).concat(skillCoefficientList || [])
}

/**
 * 计算增益选项带来的增益。获取增益集合
 */
export const 根据增益选项获取增益集合 = (
  增益数据: 增益选项数据类型,
  过滤阵眼触发类增益?: boolean,
  快照计算?: string[],
): 属性加成[] => {
  const { 小药小吃, 团队增益, 阵眼 } = 获取当前数据()
  let 增益集合: 属性加成[] = []

  if (增益数据?.小吃) {
    const 小吃数据集合 = 小药小吃.filter((item) => 增益数据?.小吃?.includes(item.小吃名称))
    if (小吃数据集合?.length) {
      小吃数据集合.forEach((a) => {
        if (a?.增益集合?.length) {
          增益集合 = 增益集合.concat(a?.增益集合)
        }
      })
    }
  }

  if (增益数据?.团队增益?.length) {
    const 团队增益集合 = 增益数据?.团队增益
      ?.filter((item) => item.启用 && !快照计算?.includes(item.增益名称))
      .map((item) => {
        const data: any = 团队增益.find((a) => a.增益名称 === item.增益名称)
        return {
          ...data,
          增益集合: data?.增益集合.map((c) => {
            return {
              ...c,
              值: (c?.值 * item?.层数 * item?.覆盖率) / 100,
            }
          }),
        }
      })

    if (团队增益集合?.length) {
      团队增益集合.forEach((item) => {
        增益集合 = 增益集合.concat(item.增益集合)
      })
    }
  }

  if (增益数据?.阵眼) {
    const 增益阵眼 = 阵眼.find((item) => item.阵眼名称 === 增益数据?.阵眼)
    if (增益阵眼 && 增益阵眼?.增益集合?.length) {
      if (过滤阵眼触发类增益) {
        增益集合 = 增益集合.concat(增益阵眼.增益集合.filter((增益) => !增益?.触发型增益))
      } else {
        增益集合 = 增益集合.concat(增益阵眼.增益集合)
      }
    }
  }

  return 增益集合
}

/**
 * @name 该技能数量下同时计算的多个增益的增益集合
 * getGainList
 */
export const 计算该技能下多个增益的增益集合 = (
  增益: 技能增益列表数据,
  当前技能属性: 技能基础数据模型,
  装备增益: 装备增益类型,
  快照计算: 快照类型[],
  团队增益结合: string[],
) => {
  // 将该数量下同时计算的多个增益转为数组
  const 该技能增益列表 = 增益.增益名称.split(',')

  // 该技能数量下同时计算的多个增益的增益集合
  const 增益名称列表: string[] = []

  该技能增益列表.forEach((i) => {
    const 该技能增益 = (当前技能属性?.技能增益列表 || [])?.find((item) => {
      if (item.增益名称 === i && item.增益类型 === '部分启用') {
        if (item?.增益所在位置 === '奇穴') {
          return item?.增益启用
        } else if (item?.依赖装备增益) {
          if (item?.快照类型) {
            // 风特效腰坠：普通档为 1，当前英雄档为 36；档位变化时同步这里与 快照增益.ts 的数值
            if (item?.依赖装备增益?.includes('风特效腰坠')) {
              if (item?.依赖装备增益 === '风特效腰坠_英雄') {
                const 判断增益: any = { ...装备增益 }
                if (判断增益?.风特效腰坠_英雄 || 判断增益?.风特效腰坠 === 36) {
                  判断增益.风特效腰坠 = 36
                }
                return 判断增益?.['风特效腰坠'] === 36 && 快照计算?.includes(item?.快照类型)
              } else {
                return 装备增益?.['风特效腰坠'] === 1 && 快照计算?.includes(item?.快照类型)
              }
            } else {
              return !!装备增益?.[item?.依赖装备增益] && 快照计算?.includes(item?.快照类型)
            }
          } else {
            return !!装备增益?.[item?.依赖装备增益]
          }
        } else if (item?.依赖团队增益) {
          if (item?.快照类型) {
            return 快照计算?.includes(item?.快照类型) && item?.增益启用
          } else {
            return 团队增益结合?.includes(item?.依赖团队增益) && item?.增益启用
          }
        } else if (item?.依赖阵眼增益) {
          return 团队增益结合?.includes(item?.依赖阵眼增益)
        } else {
          return true
        }
      }
      return false
    })

    if (该技能增益) {
      增益名称列表.push(i)
    }
  })

  return 增益名称列表
}

export const 获取增益实际数据集合 = (增益名称列表: string[], 当前技能属性: 技能基础数据模型) => {
  let 增益集合列表: 技能计算增益数据列表[] = []
  增益名称列表.forEach((增益名称) => {
    const 该技能增益 = 当前技能属性?.技能增益列表?.find((item) => item?.增益名称 === 增益名称)
    const 该技能增益列表: 技能计算增益数据列表[] = (该技能增益?.增益集合 || []).map((item) => {
      return {
        ...item,
        增益启用: true,
        增益来源: 该技能增益?.增益名称,
      }
    })
    增益集合列表 = 增益集合列表.concat(该技能增益列表)
  })
  return 增益集合列表
}

export const 根据循环判断快照计算列表 = (循环技能数据: 循环技能详情[] | undefined): any[] => {
  const { 技能增益 } = 获取当前数据()
  if (!循环技能数据?.length) {
    return []
  }
  const 快照计算列表: string[] = []
  const 字符数据 = JSON.stringify(循环技能数据)
  快照类型数据.forEach((item) => {
    if (字符数据?.includes(item) && item !== '套装会心会效') {
      快照计算列表.push(item)
    }
  })

  // 判断套装双会
  if (技能增益?.通用增益?.length) {
    const 套装增益名称 = 技能增益?.通用增益?.find(
      (a) => a?.增益所在位置 === '装备' && a?.快照类型 === '套装会心会效',
    )?.增益名称

    if (套装增益名称) {
      const 存在套装Buff = 循环技能数据?.some((a) =>
        a?.技能增益列表?.some((b) => b?.增益名称?.includes(套装增益名称)),
      )
      if (存在套装Buff) {
        快照计算列表.push('套装会心会效')
      }
    }
  }

  return 快照计算列表
}

